"""
977. 有序数组的平方（Squares of a Sorted Array）

题目描述：
给你一个按非递减顺序排序的整数数组 nums，返回每个数字的平方组成的新数组，
要求也按非递减顺序排序。

输入描述：
一个非递减排序的整数数组 nums。
1 <= nums.length <= 10^4，-10^4 <= nums[i] <= 10^4。

输出描述：
返回平方后按非递减顺序排列的新数组。注意：需要返回新数组，不是原地修改。

输入示例 1：
nums = [-4, -1, 0, 3, 10]
输出示例 1：
[0, 1, 9, 16, 100]
解释：平方后分别是 [16, 1, 0, 9, 100]，排序后得到结果。

输入示例 2：
nums = [-7, -3, 2, 3, 11]
输出示例 2：
[4, 9, 9, 49, 121]

════════════════════════════════════════════════════════════════════════
核心概念：有序数组的平方，最大值一定在两端
════════════════════════════════════════════════════════════════════════

观察：
    原数组有序，平方后的数组有什么特点？
    - 非负数的平方保持递增（0 → 3 → 10，平方 0 → 9 → 100）
    - 负数的平方保持递减（-4 → -1，平方 16 → 1）

    所以平方后的数组是"中间小、两端大"的形状（双调数组）。
    最大值一定在最左或最右端，不可能在中间。

核心思路：从两端向中间填充 result 数组
    用双指针从两端比较，较大的平方值先填入 result 的末尾。
    这样就不需要额外排序，直接得到有序结果。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
暴力平方 + 排序               O(n log n)      O(n)            ⭐ 一行代码
双指针（从两端填尾）           O(n)            O(n)            ⭐⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力平方 + 排序
# ══════════════════════════════════════════════════════════


def sortedSquares_bruteforce(nums: list[int]) -> list[int]:
    """暴力平方 + 排序 ⭐

    核心思想：
    ────────────────────────────────────────────────────────
    先对每个元素求平方，再对结果排序。

    时间复杂度：O(n log n) — 排序占主导。
    空间复杂度：O(n) — 存新数组。

    代码量最小，一行搞定，但没有利用原数组有序的条件。
    """
    return sorted(num ** 2 for num in nums)


# ══════════════════════════════════════════════════════════
# 解法二：双指针（从两端填尾）⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def sortedSquares(nums: list[int]) -> list[int]:
    """双指针（从两端填尾）⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    原数组有序，平方后的最大值一定在两端。
    用 left 和 right 指向两端，比较两端平方值，把较大者放入 result 末尾。

    算法步骤：
    1. 初始化 result = [0] * n（预分配空间），k = n - 1（指向末尾）。
    2. left = 0（最左端），right = n - 1（最右端）。
    3. while left <= right：
       a. 比较 nums[left]² 和 nums[right]²：
          - 若 left 侧大：result[k] = nums[left]²，left += 1。
          - 若 right 侧大或相等：result[k] = nums[right]²，right -= 1。
       b. k -= 1。
    4. 返回 result。

    时间复杂度：O(n) — 双指针各移动最多 n 步。
    空间复杂度：O(n) — 需要存结果数组（题目要求返回新数组，无法避免）。

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [-4, -1, 0, 3, 10], n = 5

    步骤  left  right  nums[left]²  nums[right]²  较大者   result[k]  k
    ──────────────────────────────────────────────────────────────────────
    1      0     4        16            100        right    100       4→3
    2      0     3        16             9         left     16        3→2
    3      1     3         1             9         right     9        2→1
    4      1     2         1             0         left      1        1→0
    5      2     2         0             0         right     0        0→-1

    result = [0, 1, 9, 16, 100] ✓
    """
    n = len(nums)
    result = [0] * n
    k = n - 1  # 从末尾向前填充

    left, right = 0, n - 1
    while left <= right:
        if nums[left] ** 2 >= nums[right] ** 2:
            result[k] = nums[left] ** 2
            left += 1
        else:
            result[k] = nums[right] ** 2
            right -= 1
        k -= 1

    return result


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、双指针解法的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：双指针法能正确得到平方后有序的数组。
#
# 证明：
# （1）最大值一定在两端：
#     设 a <= b 是原数组中任意两个元素。
#     - 若 a, b 都 >= 0：a² <= b²，右侧大。
#     - 若 a, b 都 < 0：|a| >= |b|，a² >= b²，左侧大。
#     - 若 a < 0 <= b：比较 |a| 和 b 即可。
#     总之，平方数组的最大值一定出现在当前 [left, right] 区间的两端。
#
# （2）每次选择正确：
#     比较两端后，把较大的平方值放入 result[k]。
#     由于 k 从 n-1 递减到 0，我们按从大到小的顺序填充 result。
#     每次选走的都是当前剩余元素中的最大值，不会有遗漏或重复。
#
# （3）终止条件：
#     left 和 right 相遇后，所有元素都被处理过，result 填满。
#     此时 k = -1，循环结束。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. k 的初始值和更新方向：
#    k 必须从 n-1 开始递减。如果 k 从 0 开始递增，
#    就变成了从小到大填充，但我们每次选的是最大值，会得到反向结果。
#
# 2. 比较条件搞反：
#    if nums[left]² >= nums[right]² 时填左侧。
#    如果条件反了，较大的值被跳过，较小的值先填入，结果错误。
#
# 3. 忘记预分配 result 数组：
#    用 result.append(...) 然后反转也可以，
#    但预分配 result = [0] * n 更高效，避免动态扩容。
#
# 4. 空数组处理：
#    空数组时 n=0，result=[0]*0=[], 循环不执行，直接返回 []。
#    虽然代码可以自然处理，但显式判断更安全。
#
# 5. 误以为需要原地修改：
#    题目要求返回新数组，不是原地修改。
#    Python 列表切片 nums[:] = result 可以原地更新，但没有必要。
# ══════════════════════════════════════════════════════════
