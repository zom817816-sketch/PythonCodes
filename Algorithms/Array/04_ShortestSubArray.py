"""
209. 长度最小的子数组（Minimum Size Subarray Sum）

题目描述：
给定一个含有 n 个正整数的数组和一个正整数 target，找出该数组中
满足其和 >= target 的长度最小的连续子数组，并返回其长度。
如果不存在符合条件的子数组，返回 0。

输入描述：
一个正整数数组 nums 和一个正整数 target。
1 <= target <= 10^9，1 <= nums.length <= 10^5，1 <= nums[i] <= 10^5。

输出描述：
返回满足和 >= target 的最短连续子数组的长度，不存在则返回 0。

输入示例 1：
target = 7, nums = [2, 3, 1, 2, 4, 3]
输出示例 1：
2
解释：子数组 [4, 3] 的和为 7，长度为 2。

输入示例 2：
target = 4, nums = [1, 4, 4]
输出示例 2：
1
解释：子数组 [4] 的和为 4，长度为 1。

输入示例 3：
target = 11, nums = [1, 1, 1, 1, 1, 1, 1, 1]
输出示例 3：
0
解释：所有元素之和为 8 < 11，不存在符合条件的子数组。

════════════════════════════════════════════════════════════════════════
核心概念：滑动窗口（双指针）
════════════════════════════════════════════════════════════════════════

什么是滑动窗口？
    滑动窗口是一种特殊的双指针技巧，用于解决"连续子数组"问题。
    它维护一个窗口 [left, right]，通过移动左右边界来调整窗口大小，
    并在过程中维护窗口内的某种性质（如和、最大值、最小值等）。

滑动窗口的两种类型：
    - 固定长度窗口：窗口大小固定，每次整体向右移动一格。
    - 可变长度窗口：窗口大小可变，本题属于这种。

本题的窗口维护：
    - 扩大窗口：right 右移，累加 nums[right] 到 cur_sum。
    - 缩小窗口：当 cur_sum >= target 时，尝试左移 left 缩短窗口，
      同时更新最小长度。因为所有元素都是正整数，左移一定会让和变小，
      所以可以放心缩。

为什么正整数是关键前提？
    如果数组中有负数，窗口缩小时 cur_sum 不一定变小，
    滑动窗口就失效了。此时需要用前缀和 + 有序集合等方法。

与"子数组最小值之和"的对比：
────────────────────────────────────────────────────────────────────────
维度                长度最小的子数组          子数组最小值之和 (LC 907)
────────────────────────────────────────────────────────────────────────
窗口性质            维护窗口和               维护单调递增栈
窗口操作            扩大→缩小                弹栈→入栈
目标                最短长度                 所有子数组的最小值之和
数据结构            双指针 + 变量            单调栈 + 边界数组
────────────────────────────────────────────────────────────────────────

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
暴力双重循环                  O(n²)           O(1)            ⭐ 枚举所有子数组
前缀和 + 二分查找             O(n log n)      O(n)            ⭐⭐⭐ 适配有负数情况
滑动窗口（双指针）             O(n)            O(1)            ⭐⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力双重循环
# ══════════════════════════════════════════════════════════


def minSubArrayLen_bruteforce(target: int, nums: list[int]) -> int:
    """暴力双重循环 ⭐

    核心思想：
    ────────────────────────────────────────────────────────
    枚举所有子数组的起点 i 和终点 j，计算每个子数组的和，
    找到满足条件的最短长度。

    时间复杂度：O(n²) — 共有 O(n²) 个子数组。
    空间复杂度：O(1) — 只用常数个变量。

    优化：一旦找到满足条件的子数组就 break（继续扩大只会更长）。
    """
    n = len(nums)
    min_len = n + 1

    for i in range(n):
        cur_sum = 0
        for j in range(i, n):
            cur_sum += nums[j]
            if cur_sum >= target:
                min_len = min(min_len, j - i + 1)
                break  # 继续扩大只会更长，break

    return 0 if min_len == n + 1 else min_len


# ══════════════════════════════════════════════════════════
# 解法二：前缀和 + 二分查找
# ══════════════════════════════════════════════════════════


def minSubArrayLen_prefix_binary(target: int, nums: list[int]) -> int:
    """前缀和 + 二分查找 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    构建前缀和数组 prefix，prefix[k] = nums[0] + ... + nums[k-1]。
    子数组 nums[i..j] 的和 = prefix[j+1] - prefix[i]。
    要找和 >= target，即 prefix[i] <= prefix[j+1] - target。
    因为 nums 都是正整数，prefix 单调递增，可以用二分查找快速定位最大的 i
    （i 越大，子数组越短）。

    算法步骤：
    1. 构建前缀和数组 prefix，长度 n+1，prefix[0] = 0。
    2. 对每个右端点 j（0 到 n-1）：
       a. threshold = prefix[j+1] - target。
       b. 在 prefix[0..j] 中二分查找最大的 i，使 prefix[i] <= threshold。
       c. 若找到（i >= 0），min_len = min(min_len, j - i + 1)。
    3. 返回 min_len 或 0。

    时间复杂度：O(n log n) — 遍历 n 个右端点，每次二分查找 O(log n)。
    空间复杂度：O(n) — 前缀和数组。

    图解示例：
    ────────────────────────────────────────────────────────
    target = 7, nums = [2, 3, 1, 2, 4, 3]
    prefix = [0, 2, 5, 6, 8, 12, 15]  （长度 7）

     j   prefix[j+1]  threshold   搜索范围 prefix[0..j]   最大的 i (prefix[i]<=threshold)   长度 j-i+1
    ────────────────────────────────────────────────────────────────────────────────────────────────────
     0        2          -5         [0]                    无（0 > -5）                      -
     1        5          -2         [0, 2]                 无                                -
     2        6          -1         [0, 2, 5]              无                                -
     3        8           1         [0, 2, 5, 6]           i=0 (prefix[0]=0 ≤ 1)             4
     4       12           5         [0, 2, 5, 6, 8]        i=2 (prefix[2]=5 ≤ 5)             3
     5       15           8         [0, 2, 5, 6, 8, 12]    i=4 (prefix[4]=8 ≤ 8)             2

    返回 min_len = 2 ✓（子数组 [4, 3]）

    为什么能适配含负数的数组？
        滑动窗口依赖"正整数保证 cur_sum 单调递增"这一前提。
        前缀和 + 二分查找只要 prefix 单调递增就能二分。
        但若 nums 含负数，prefix 不再单调，此时需用有序集合（如 SortedList）
        替代 bisect 来维护"已见过的 prefix 值"，复杂度仍为 O(n log n)。
    """
    import bisect

    n = len(nums)
    # 构建前缀和：prefix[k] = nums[0] + ... + nums[k-1]，prefix[0] = 0
    prefix = [0] * (n + 1)
    for k in range(n):
        prefix[k + 1] = prefix[k] + nums[k]

    min_len = n + 1

    for j in range(n):
        # 子数组 nums[i..j] 的和 = prefix[j+1] - prefix[i] >= target
        # 即 prefix[i] <= prefix[j+1] - target
        threshold = prefix[j + 1] - target
        # 在 prefix[0..j] 中找最大的 i 使 prefix[i] <= threshold
        # bisect_right 返回第一个 > threshold 的位置，减 1 得到最右 <= threshold 的位置
        # 搜索范围限定为 prefix[0..j]（hi=j+1），因为左端点 i 不能超过 j
        i = bisect.bisect_right(prefix, threshold, 0, j + 1) - 1
        if i >= 0:  # 找到满足条件的左端点
            min_len = min(min_len, j - i + 1)

    return 0 if min_len == n + 1 else min_len


# ══════════════════════════════════════════════════════════
# 解法三：滑动窗口（双指针）⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def minSubArrayLen(target: int, nums: list[int]) -> int:
    """滑动窗口（双指针）⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    用 [left, right] 表示当前窗口，cur_sum 维护窗口内元素之和。

    扩大窗口：right 右移，cur_sum += nums[right]。
    缩小窗口：当 cur_sum >= target 时，记录当前长度后，
              left 右移，cur_sum -= nums[left]。

    为什么可以 while 缩？
        因为所有元素都是正整数，cur_sum 随 left 右移单调递减。
        所以只要 cur_sum >= target，就可以不断缩小直到 cur_sum < target，
        期间经过的每个窗口都是合法的，取最短即可。

    算法步骤：
    1. left = 0, cur_sum = 0, min_len = n + 1。
    2. right 从 0 到 n-1：
       a. cur_sum += nums[right]（扩大窗口）。
       b. while cur_sum >= target：
          - min_len = min(min_len, right - left + 1)。
          - cur_sum -= nums[left]。
          - left += 1（缩小窗口）。
    3. 返回 min_len（如果被更新过）或 0。

    时间复杂度：O(n) — left 和 right 各移动最多 n 步。
    空间复杂度：O(1) — 只用常数个变量。

    图解示例：
    ────────────────────────────────────────────────────────
    target = 7, nums = [2, 3, 1, 2, 4, 3]

    步骤  right  nums[r]  cur_sum  left  窗口和>=7?  操作                  min_len
    ────────────────────────────────────────────────────────────────────────────
    初始    -      -        0       0       -        -                     7
    1       0      2        2       0       ✗        right++               7
    2       1      3        5       0       ✗        right++               7
    3       2      1        6       0       ✗        right++               7
    4       3      2        8       0       ✓        cur-=2, left=1        min(7,4)=4
                                                  cur=6 < 7, 跳出
    5       4      4       10       1       ✓        cur-=3, left=2        min(4,4)=4
                                                  cur=7 >= 7 ✓
                                                  min(4,3)=3
                                                  cur-=1, left=3
                                                  cur=6 < 7, 跳出
    6       5      3        9       3       ✓        cur-=2, left=4        min(3,3)=3
                                                  cur=7 >= 7 ✓
                                                  min(3,2)=2
                                                  cur-=4, left=5
                                                  cur=3 < 7, 跳出

    返回 min_len = 2 ✓（子数组 [4, 3]）
    """
    n = len(nums)
    left = 0
    cur_sum = 0
    min_len = n + 1

    for right in range(n):
        # 扩大窗口：加入 nums[right]
        cur_sum += nums[right]

        # 缩小窗口：尝试左移，直到 cur_sum < target
        while cur_sum >= target:
            # 当前窗口 [left, right] 满足条件，更新最短长度
            window_len = right - left + 1
            min_len = min(min_len, window_len)
            # 移出左边界
            cur_sum -= nums[left]
            left += 1

    return 0 if min_len == n + 1 else min_len


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、滑动窗口的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：滑动窗口能找到满足和 >= target 的最短子数组。
#
# 证明：
# （1）正确性源于单调性：
#     因为所有 nums[i] 都是正整数，cur_sum 随窗口扩大单调递增，
#     随窗口缩小单调递减。这保证了：
#     - 当 cur_sum < target 时，必须扩大窗口（右移 right）。
#     - 当 cur_sum >= target 时，可以尝试缩小窗口（右移 left）来寻找更短的合法子数组。
#
# （2）每个合法子数组都被考虑：
#     对于任意一个满足条件的子数组 [i, j]，
#     当 right 移动到 j 时，窗口扩大到包含 j。
#     然后 while 循环会不断右移 left，直到 cur_sum < target。
#     在这个过程中，left = i 时的窗口 [i, j] 会被检查到，
#     此时 min_len 会尝试更新。
#
# （3）不会遗漏：
#     一旦 left 超过 i，后续的 [i', j]（i' > i）长度更短。
#     如果它们也合法，自然会在后续的 while 中被检查。
#     如果它们不合法，说明 [i, j] 是以 j 结尾的最短合法子数组，
#     已经被记录过了。
#
# （4）时间复杂度 O(n)：
#     left 和 right 都只增不减，每个最多移动 n 步。
#     总步数不超过 2n，即 O(n)。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. min_len 初始值太小：
#    如果 min_len 初始为 0，min(0, x) 永远是 0，结果错误。
#    正确初始值是 n + 1（比任何可能的长度都大），最后检查是否被更新过。
#
# 2. while 写成 if：
#    当 cur_sum 远大于 target 时，可能需要连续缩小多次。
#    用 if 只能缩小一次，漏掉更短的合法窗口。
#
# 3. 忘记处理"不存在"的情况：
#    如果所有子数组都不满足条件，min_len 保持为 n+1。
#    必须返回 0 而不是 n+1。
#
# 4. 窗口长度计算错误：
#    必须是 right - left + 1（闭区间）。
#    写成 right - left 会少算 1。
#
# 5. 数组中有负数：
#    滑动窗口要求元素非负。如果有负数，窗口缩小时 cur_sum 不一定变小，
#    while 循环可能漏掉合法子数组。此时需要用前缀和 + 有序集合。
# ══════════════════════════════════════════════════════════
