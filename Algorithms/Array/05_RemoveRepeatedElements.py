"""
26. 删除有序数组中的重复项（Remove Duplicates from Sorted Array）

题目描述：
给你一个非严格递增排列的数组 nums，请你原地删除重复出现的元素，
使每个元素只出现一次，返回删除后数组的新长度。
元素的相对顺序应该保持一致。

输入描述：
一个非递减排序的整数数组 nums。
0 <= nums.length <= 3 * 10^4，-10^4 <= nums[i] <= 10^4。

输出描述：
返回唯一元素的个数 k，nums 的前 k 个元素应包含去重后的唯一元素（保持顺序）。
判题系统会检查前 k 个元素是否正确。

输入示例 1：
nums = [1, 1, 2]
输出示例 1：
2
解释：nums 前两个元素为 [1, 2]，返回 2。

输入示例 2：
nums = [0, 0, 1, 1, 1, 2, 2, 3, 3, 4]
输出示例 2：
5
解释：nums 前五个元素为 [0, 1, 2, 3, 4]，返回 5。

════════════════════════════════════════════════════════════════════════
核心概念：双指针（快慢指针）在有序数组去重中的应用
════════════════════════════════════════════════════════════════════════

为什么有序数组去重容易？
    因为重复的元素一定是相邻的。遍历数组时，只要比较当前元素和"最后一个保留的元素"，
    就能判断是否需要保留当前元素。

双指针思想：
    slow：慢指针，指向"已去重部分的最后一个元素"。
    fast：快指针，遍历整个数组。

    当 nums[fast] != nums[slow] 时，
    说明 fast 找到了一个新的唯一元素，把它放到 slow 的下一个位置。

与"移除元素"(LC 27) 的对比：
────────────────────────────────────────────────────────────────────────
维度                移除元素 (LC 27)          删除重复项 (LC 26)
────────────────────────────────────────────────────────────────────────
删除条件            值 == val（任意值）        值 == 前一个保留值
数组是否有序        否                        是
比较对象            nums[fast] != val        nums[fast] != nums[slow]
slow 含义           下一个填入位置            已保留最后一个元素
slow 初始值         0                         0（但返回 slow+1）
slow 更新时机       每次 fast 匹配成功时      每次 fast 发现新元素时
────────────────────────────────────────────────────────────────────────
两题模板几乎相同，核心都是"快慢指针 + 不匹配时写入"。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
pop 逐个删除                  O(n²)           O(1)            ⭐ list.pop 是 O(n)
快慢指针                      O(n)            O(1)            ⭐⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────
"""


# ══════════════════════════════════════════════════════════
# 解法一：pop 逐个删除
# ══════════════════════════════════════════════════════════


def removeDuplicates_pop(nums: list[int]) -> int:
    """pop 逐个删除 ⭐

    核心思想：
    ────────────────────────────────────────────────────────
    遍历数组，如果当前元素等于前一个元素（重复），就 pop 删除。

    时间复杂度：O(n²) — list.pop(i) 是 O(n)，最坏情况（所有元素相同）
    需要 pop n-1 次，总复杂度 O(n²)。
    空间复杂度：O(1) — 原地修改。

    注意：pop 后数组长度变了，i 不能增加（否则会跳过新的 i 位置）。
    """
    if not nums:
        return 0

    i = 1
    while i < len(nums):
        if nums[i] == nums[i - 1]:
            nums.pop(i)
        else:
            i += 1

    return len(nums)


# ══════════════════════════════════════════════════════════
# 解法二：快慢指针 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def removeDuplicates(nums: list[int]) -> int:
    """快慢指针 ⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    slow 指向已去重部分的最后一个元素。
    fast 遍历整个数组，当发现与 slow 不同的新元素时，
    把它复制到 slow 的下一个位置，slow 前进。

    算法步骤：
    1. 如果数组为空，返回 0。
    2. slow = 0（第一个元素一定保留）。
    3. fast 从 1 到 n-1 遍历：
       a. 如果 nums[fast] != nums[slow]：
          - slow += 1
          - nums[slow] = nums[fast]
    4. 返回 slow + 1（slow 是最后唯一元素的下标，数量要 +1）。

    时间复杂度：O(n) — fast 指针遍历一遍。
    空间复杂度：O(1) — 只用常数个变量。

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [0, 0, 1, 1, 1, 2, 2, 3, 3, 4]

    步骤  fast  slow  nums[fast]  nums[slow]  相等?  操作
    ────────────────────────────────────────────────────────────────
    初始   -     0      -           0          -     -
    1      1     0      0           0          ✓     跳过
    2      2     0      1           0          ✗     slow=1, nums[1]=1
    3      3     1      1           1          ✓     跳过
    4      4     1      1           1          ✓     跳过
    5      5     1      2           1          ✗     slow=2, nums[2]=2
    6      6     2      2           2          ✓     跳过
    7      7     2      3           2          ✗     slow=3, nums[3]=3
    8      8     3      3           3          ✓     跳过
    9      9     3      4           3          ✗     slow=4, nums[4]=4

    返回 slow + 1 = 5 ✓
    nums 前 5 个元素 = [0, 1, 2, 3, 4] ✓
    """
    if not nums:
        return 0

    slow = 0

    for fast in range(1, len(nums)):
        # 发现新的唯一元素
        if nums[fast] != nums[slow]:
            slow += 1
            nums[slow] = nums[fast]

    return slow + 1


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、快慢指针的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：快慢指针能正确删除有序数组中的重复项，返回唯一元素个数。
#
# 证明：
# （1）循环不变量：在每次 fast 循环开始时，
#     nums[0..slow] 包含从 nums[0] 到当前 nums[fast-1] 中
#     所有唯一元素，且保持原顺序。
#     初始 slow=0，nums[0] 是第一个唯一元素，成立。
#
# （2）维护不变量：
#     - 若 nums[fast] == nums[slow]：与最后一个保留元素重复，跳过。
#       nums[0..slow] 不变，不变量保持。
#     - 若 nums[fast] != nums[slow]：新的唯一元素。
#       slow += 1，nums[slow] = nums[fast]。
#       由于数组有序，nums[fast] 不可能出现在 nums[0..slow-1] 中
#       （否则它应该等于某个之前的元素），所以它是新的唯一元素。
#       不变量保持。
#
# （3）终止：fast 遍历完后，nums[0..slow] 包含所有唯一元素。
#     slow 是下标，元素数量 = slow + 1。
#
#
# 二、与 LC 27 移除元素的对比记忆：
# ────────────────────────────────────────────────────────
#
# 两题都是"快慢指针 + 覆盖"的模板，区别只有比较条件：
#
#     LC 27：if nums[fast] != val → 写入
#     LC 26：if nums[fast] != nums[slow] → 写入
#
# 共同点：
#     - 都是 fast 找"需要保留"的元素，slow 指向下一个写入位置
#     - 都不需要额外空间，原地修改
#     - 时间复杂度都是 O(n)
#
# 记忆口诀：有序去重比邻居，无序移除比目标。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 返回 slow 而不是 slow + 1：
#    slow 是最后一个唯一元素的下标（从 0 开始）。
#    元素数量 = 下标 + 1。返回 slow 会少算一个。
#
# 2. 数组为空的边界处理：
#    空数组时 slow = 0 但没有元素，slow + 1 = 1 是错误答案。
#    必须在函数开头显式判断 if not nums: return 0。
#
# 3. 比较条件写错：
#    写成 nums[fast] == nums[slow] 时写入，结果完全反了——
#    保留的是重复元素，去掉的是唯一元素。
#
# 4. pop 解法中忘记 i 不变：
#    pop(i) 后，原来的 nums[i+1] 变成了新的 nums[i]。
#    如果此时 i += 1，新的 nums[i] 就被跳过了。
#    正确：pop 后 i 不变，else 时 i += 1。
#
# 5. slow 从 1 开始：
#    slow 应该从 0 开始。第一个元素一定保留，作为比较基准。
#    如果从 1 开始，第一个元素会被跳过。
# ══════════════════════════════════════════════════════════
