"""
704. 二分查找（Binary Search）

题目描述：
给定一个 n 个元素有序的（升序）整型数组 nums 和一个目标值 target，
写一个函数搜索 nums 中的 target，如果目标值存在返回下标，否则返回 -1。

输入描述：
一个有序数组 nums（升序，无重复元素）和一个目标值 target。
1 <= nums.length <= 10^4，-10^4 < nums[i], target < 10^4。

输出描述：
返回 target 在 nums 中的下标，若不存在返回 -1。

输入示例 1：
nums = [-1, 0, 3, 5, 9, 12], target = 9
输出示例 1：
4
解释：9 出现在 nums 中并且下标为 4。

输入示例 2：
nums = [-1, 0, 3, 5, 9, 12], target = 2
输出示例 2：
-1
解释：2 不存在 nums 中因此返回 -1。

════════════════════════════════════════════════════════════════════════
核心概念：二分查找的区间定义（循环不变量）
════════════════════════════════════════════════════════════════════════

二分查找的本质是"每次排除一半的可能性"。但"排除"的前提是：
你必须明确知道当前搜索区间的边界含义——这就是**循环不变量**。

两种常见的区间定义：

  [left, right] — 左闭右闭
      - while left <= right（left 和 right 都在有效范围内）
      - right = mid - 1（mid 已被检查过，新区间不包含 mid）
      - left = mid + 1（同理）

  [left, right) — 左闭右开
      - while left < right（right 不在有效范围内）
      - right = mid（新区间依然左闭右开，right 本身不被检查）
      - left = mid + 1（mid 已被检查过）

循环不变量规则：
    区间的定义就是不变量。要在循环中坚持根据查找区间的定义来做边界处理，
    就是循环不变量规则。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
暴力遍历                      O(n)            O(1)            ⭐ 线性扫描
二分查找（左闭右闭）           O(log n)        O(1)            ⭐⭐⭐⭐ 推荐
二分查找（左闭右开）           O(log n)        O(1)            ⭐⭐⭐⭐ 等价写法
────────────────────────────────────────────────────────────────────────

核心思想（二分查找）：
────────────────────────────────────────────────────────────────────────
每次取区间中点 mid，比较 nums[mid] 和 target：
  - 相等 → 找到，返回 mid
  - nums[mid] > target → 目标在左半边，右边界左移
  - nums[mid] < target → 目标在右半边，左边界右移

关键前提：数组必须**有序**且**无重复元素**。
有重复元素时，返回的下标可能不唯一（取决于 mid 恰好落到哪个重复值上）。
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力遍历
# ══════════════════════════════════════════════════════════


def search_bruteforce(nums: list[int], target: int) -> int:
    """暴力遍历 ⭐

    核心思想：
    ────────────────────────────────────────────────────────
    逐个检查每个元素是否等于 target。

    时间复杂度：O(n) — 最坏情况需要遍历整个数组。
    空间复杂度：O(1) — 只用常数个变量。
    """
    for i, num in enumerate(nums):
        if num == target:
            return i
    return -1


# ══════════════════════════════════════════════════════════
# 解法二：二分查找（左闭右闭）⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def search(nums: list[int], target: int) -> int:
    """二分查找（左闭右闭）⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    搜索区间定义为 [left, right]，左闭右闭，包含左右端点。

    循环条件：left <= right
        因为当 left == right 时，区间仍然有效（只有一个元素需要检查）。

    边界更新：
        nums[mid] > target → right = mid - 1（mid 已经不等于 target，排除）
        nums[mid] < target → left = mid + 1（同理排除）

    算法步骤：
    1. 初始化 left = 0, right = len(nums) - 1。
    2. while left <= right：
       a. mid = (left + right) // 2（向下取整）。
       b. 如果 nums[mid] == target：返回 mid。
       c. 如果 nums[mid] > target：right = mid - 1。
       d. 如果 nums[mid] < target：left = mid + 1。
    3. 循环结束仍未找到：返回 -1。

    时间复杂度：O(log n) — 每次区间长度减半。
    空间复杂度：O(1) — 只用常数个变量。

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [-1, 0, 3, 5, 9, 12], target = 9

    步骤  left  right  mid  nums[mid]  比较结果       操作
    ────────────────────────────────────────────────────────
    1      0     5      2      3       3 < 9         left = 3
    2      3     5      4      9       9 == 9 ✓      返回 4

    结果：4 ✓

    查找不存在的 target = 2：
    ────────────────────────────────────────────────────────
    步骤  left  right  mid  nums[mid]  比较结果       操作
    ────────────────────────────────────────────────────────
    1      0     5      2      3       3 > 2         right = 1
    2      0     1      0     -1       -1 < 2        left = 1
    3      1     1      1      0       0 < 2         left = 2
    4      2 > 1 → 循环结束，返回 -1

    结果：-1 ✓
    """
    left, right = 0, len(nums) - 1

    while left <= right:
        mid = (left + right) // 2
        if nums[mid] == target:
            return mid
        elif nums[mid] > target:
            right = mid - 1
        else:
            left = mid + 1

    return -1


# ══════════════════════════════════════════════════════════
# 解法三：二分查找（左闭右开）
# ══════════════════════════════════════════════════════════


def search_left_closed_right_open(nums: list[int], target: int) -> int:
    """二分查找（左闭右开）⭐⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    搜索区间定义为 [left, right)，左闭右开，不包含右端点。

    循环条件：left < right
        因为 right 不在有效范围内，left == right 时区间为空。

    边界更新：
        nums[mid] > target → right = mid（新区间 [left, mid) 依然左闭右开）
        nums[mid] < target → left = mid + 1（mid 已被检查过，排除）

    算法步骤：
    1. 初始化 left = 0, right = len(nums)。
       注意：right 是 len(nums)，不是 len(nums) - 1！
       因为右开区间，right 表示"右边界之后"。
    2. while left < right：
       a. mid = (left + right) // 2。
       b. 如果 nums[mid] == target：返回 mid。
       c. 如果 nums[mid] > target：right = mid。
       d. 如果 nums[mid] < target：left = mid + 1。
    3. 循环结束仍未找到：返回 -1。

    时间复杂度：O(log n) — 同左闭右闭版本。
    空间复杂度：O(1) — 同左闭右闭版本。

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [-1, 0, 3, 5, 9, 12], target = 9

    步骤  left  right  mid  nums[mid]  比较结果       操作
    ────────────────────────────────────────────────────────
    1      0     6      3      5       5 < 9         left = 4
    2      4     6      5     12       12 > 9        right = 5
    3      4     5      4      9       9 == 9 ✓      返回 4

    结果：4 ✓
    """
    left, right = 0, len(nums)

    while left < right:
        mid = (left + right) // 2
        if nums[mid] == target:
            return mid
        elif nums[mid] > target:
            right = mid
        else:
            left = mid + 1

    return -1


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、二分查找的正确性证明（左闭右闭版本）：
# ────────────────────────────────────────────────────────
#
# 定理：如果 target 存在于有序数组 nums 中，左闭右闭版二分查找会找到它。
#
# 证明：
# （1）循环不变量：在每次 while 循环开始时，
#     若 target 存在，则它一定在 [left, right] 范围内。
#     初始 left=0, right=n-1，整个数组在范围内，成立。
#
# （2）每次循环后，不变量仍然成立：
#     - 若 nums[mid] == target：直接返回，结束。
#     - 若 nums[mid] > target：因为数组有序，target 不可能在 mid 或 mid 之后，
#       所以 target 一定在 [left, mid-1] 中，right = mid - 1 保持不变量。
#     - 若 nums[mid] < target：同理，target 一定在 [mid+1, right] 中，
#       left = mid + 1 保持不变量。
#
# （3）循环终止：
#     当 left > right 时，区间 [left, right] 为空。
#     由不变量逆否命题：若 target 存在，它一定在 [left, right] 中；
#     现在区间为空，说明 target 不存在，返回 -1 正确。
#
# （4）时间复杂度 O(log n)：
#     每次循环区间长度减半，长度从 n 变为 1 需要 log₂n 次迭代。
#
#
# 二、两种写法的对比：
# ────────────────────────────────────────────────────────
#
# 维度              左闭右闭 [left, right]      左闭右开 [left, right)
# ────────────────────────────────────────────────────────
# right 初始值      len(nums) - 1               len(nums)
# while 条件        left <= right              left < right
# nums[mid] > t     right = mid - 1            right = mid
# nums[mid] < t     left = mid + 1              left = mid + 1
# mid 被检查后      从新区间中排除              从新区间中排除
# 代码风格          更对称、更常用               某些语言更自然
# ────────────────────────────────────────────────────────
#
# 本质上两种写法是等价的。选哪种都可以，但要注意始终坚持同一套规则，
# 不要混用（比如 while left <= right 但 right 又更新为 mid）。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. while 条件写错：
#    左闭右闭版本写成 while left < right → 当只剩一个元素时跳过检查，
#    可能漏掉目标。左闭右开版本写成 while left <= right → 死循环
#    （left == right 时仍然进入循环，但 mid == left == right，
#    若 nums[mid] != target，更新后区间不变）。
#
# 2. right 初始值写错：
#    左闭右开版本写成 right = len(nums) - 1。
#    此时区间 [left, right) 实际是 [left, len(nums)-1)，漏掉了最后一个元素。
#
# 3. 边界更新方向反了：
#    nums[mid] > target 时写成 left = mid + 1。
#    此时 target 明明在左边，却把左边界推到右边，永远找不到。
#
# 4. 整数溢出：
#    在某些语言中 (left + right) 可能溢出。
#    Python 不用关心这个，但经典写法是 mid = left + (right - left) // 2。
#
# 5. 数组无序：
#    二分查找的前提是数组有序。对无序数组使用二分查找，结果完全不可靠。
#
# 6. 数组有重复元素：
#    有重复元素时，返回的下标取决于 mid 落到哪个重复值上。
#    如果需要返回"第一个出现的位置"或"最后一个出现的位置"，
#    需要改造边界条件（见 LeetCode 34）。
