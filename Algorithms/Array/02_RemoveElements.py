"""
27. 移除元素（Remove Element）

题目描述：
给你一个数组 nums 和一个值 val，你需要原地移除所有数值等于 val 的元素，
并返回移除后数组的新长度。元素的相对顺序可能会改变。

不要使用额外的数组空间，你必须仅使用 O(1) 额外空间并原地修改输入数组。

输入描述：
一个整数数组 nums 和一个整数 val。
0 <= nums.length <= 100，0 <= nums[i] <= 50，0 <= val <= 100。

输出描述：
返回移除 val 后数组的新长度 k，nums 的前 k 个元素应包含所有不等于 val 的元素。
剩余元素可以忽略。

判题标准：
系统会用以下代码测试：
    k = removeElement(nums, val)
    assert k == expected_length
    for i in range(k):
        assert nums[i] != val

输入示例 1：
nums = [3, 2, 2, 3], val = 3
输出示例 1：
2
解释：nums 为 [2, 2, _, _]，返回 2。

输入示例 2：
nums = [0, 1, 2, 2, 3, 0, 4, 2], val = 2
输出示例 2：
5
解释：nums 为 [0, 1, 4, 0, 3, _, _, _]，返回 5。
     注意元素顺序可以改变，只要前 k 个元素都不等于 val 即可。

════════════════════════════════════════════════════════════════════════
核心概念：数组无法原地删除，只能覆盖
════════════════════════════════════════════════════════════════════════

为什么不能"真正删除"？
    在 Python 列表中，list.remove(x) 或 list.pop(i) 会触发元素移动，
    时间复杂度为 O(n)。如果对 n 个元素各删一次，总复杂度 O(n²)。

原地删除的本质：
    不是"删除"，而是用后面的有效元素**覆盖**前面的待删元素。
    双指针法就是实现这个覆盖的标准技巧。

与"删除有序数组中的重复项"(LC 26) 的对比：
────────────────────────────────────────────────────────────────────────
维度                移除元素 (LC 27)          删除重复项 (LC 26)
────────────────────────────────────────────────────────────────────────
删除条件            值 == val（任意值）        值 == 前一个值（重复）
数组是否有序        否                        是
相对顺序            可以改变                  必须保持
双指针条件          nums[fast] != val          nums[fast] != nums[slow]
核心思想            覆盖（无序可交换）         覆盖（有序需保持顺序）
────────────────────────────────────────────────────────────────────────

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
暴力双重循环                  O(n²)           O(1)            ⭐ 每删一次整体前移
快慢指针                      O(n)            O(1)            ⭐⭐⭐⭐⭐ 推荐
双向指针（交换法）             O(n)            O(1)            ⭐⭐⭐ 顺序会改变
────────────────────────────────────────────────────────────────────────
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力双重循环
# ══════════════════════════════════════════════════════════


def removeElement_bruteforce(nums: list[int], val: int) -> int:
    """暴力双重循环 ⭐

    核心思想：
    ────────────────────────────────────────────────────────
    外层循环查找 val，找到后用内层循环把后面所有元素前移一位。

    算法步骤：
    1. i 从 0 到 n-1 遍历：
       a. 如果 nums[i] == val：
          - 把 nums[i+1:] 的所有元素向前移一位
          - 数组长度减 1（逻辑上，实际不修改 len）
          - i 保持不变（因为新的 nums[i] 还没检查过）
       b. 否则 i += 1

    时间复杂度：O(n²) — 最坏情况所有元素都是 val，每次删除需要 O(n) 前移。
    空间复杂度：O(1) — 只用常数个变量。
    """
    i = 0
    n = len(nums)
    while i < n:
        if nums[i] == val:
            # 把后面所有元素向前移动一位
            for j in range(i, n - 1):
                nums[j] = nums[j + 1]
            n -= 1  # 逻辑长度减 1
            # 注意：i 不增加，因为新的 nums[i] 是原来的 nums[i+1]，还没检查过
        else:
            i += 1

    return n


# ══════════════════════════════════════════════════════════
# 解法二：快慢指针 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def removeElement(nums: list[int], val: int) -> int:
    """快慢指针 ⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    定义两个指针：
    - fast：快指针，负责遍历数组，寻找"不需要删除"的元素。
    - slow：慢指针，指向下一个要填入"有效元素"的位置。

    当 fast 找到一个不等于 val 的元素时，把它赋给 nums[slow]，
    然后 slow += 1。这样 slow 始终指向有效区域的末尾之后。

    算法步骤：
    1. slow = 0（有效区域初始为空）。
    2. fast 从 0 到 n-1 遍历：
       a. 如果 nums[fast] != val：
          - nums[slow] = nums[fast]（有效元素填入有效区域）
          - slow += 1（有效区域扩大）
       b. fast 始终 += 1
    3. 返回 slow（有效区域长度）。

    时间复杂度：O(n) — fast 指针最多遍历一遍数组。
    空间复杂度：O(1) — 只用常数个变量。

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [0, 1, 2, 2, 3, 0, 4, 2], val = 2

    步骤  fast  slow  nums[fast]  != 2?  操作                  nums (前 slow 位)
    ──────────────────────────────────────────────────────────────────────────────
    1      0     0      0        ✓     nums[0]=0, slow=1      [0]
    2      1     1      1        ✓     nums[1]=1, slow=2      [0, 1]
    3      2     2      2        ✗     跳过                   [0, 1]
    4      3     2      2        ✗     跳过                   [0, 1]
    5      4     2      3        ✓     nums[2]=3, slow=3      [0, 1, 3]
    6      5     3      0        ✓     nums[3]=0, slow=4      [0, 1, 3, 0]
    7      6     4      4        ✓     nums[4]=4, slow=5      [0, 1, 3, 0, 4]
    8      7     5      2        ✗     跳过                   [0, 1, 3, 0, 4]

    返回 slow = 5 ✓
    """
    slow = 0

    for fast in range(len(nums)):
        if nums[fast] != val:
            nums[slow] = nums[fast]
            slow += 1

    return slow


# ══════════════════════════════════════════════════════════
# 解法三：双向指针（交换法）
# ══════════════════════════════════════════════════════════


def removeElement_swap(nums: list[int], val: int) -> int:
    """双向指针（交换法）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    用左指针找待删元素，右指针找有效元素，找到后交换。
    这样可以减少写入次数（快慢指针对每个有效元素都要写入一次，
    交换法只对需要交换的元素写入）。

    算法步骤：
    1. left = 0, right = len(nums) - 1。
    2. while left <= right：
       a. 左指针右移，直到找到 val 或越界。
       b. 右指针左移，直到找到非 val 元素或越界。
       c. 如果 left < right：交换 nums[left] 和 nums[right]。
    3. 返回 left（左指针最终位置就是有效长度）。

    时间复杂度：O(n) — 两指针各移动最多 n 步。
    空间复杂度：O(1) — 只用常数个变量。

    注意：此方法会改变元素相对顺序（因为交换了），但题目允许。
    """
    left, right = 0, len(nums) - 1

    while left <= right:
        # 左指针找待删元素
        while left <= right and nums[left] != val:
            left += 1
        # 右指针找有效元素
        while left <= right and nums[right] == val:
            right -= 1
        # 交换
        if left < right:
            nums[left], nums[right] = nums[right], nums[left]

    return left


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、快慢指针的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：快慢指针能正确移除所有等于 val 的元素，返回新长度。
#
# 证明：
# （1）循环不变量：在每次循环开始时，nums[0..slow-1] 中所有元素都不等于 val。
#     初始 slow=0，区间为空，成立。
#
# （2）每次迭代后不变量仍成立：
#     - 若 nums[fast] == val：不执行写入，slow 不变，不变量保持。
#     - 若 nums[fast] != val：执行 nums[slow] = nums[fast]，
#       由于 nums[fast] != val，新的 nums[slow] 也 != val。
#       slow += 1 后，nums[0..slow-1] 仍然全部 != val，不变量保持。
#
# （3）终止条件：fast 遍历完所有元素。
#     此时所有不等于 val 的元素都被复制到了 nums[0..slow-1]，
#     slow 就是有效长度。
#
# （4）没有遗漏：每个元素要么被 fast 检查时跳过（等于 val），
#     要么被复制到有效区域。不存在第三种情况。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 暴力解法中 i 忘记保持不变：
#    删除元素后，后面的元素前移了一位。如果此时 i += 1，
#    新的 nums[i]（原来的 nums[i+1]）就被跳过了。
#    正确做法：删除后 i 不变，下次循环继续检查新的 nums[i]。
#
# 2. 快慢指针中 slow 的更新位置：
#    slow 必须在 nums[fast] != val 时才增加。
#    如果写在 if 外面每次都增加，slow 就失去了"有效区域边界"的含义。
#
# 3. 交换法中 while 条件写错：
#    内层 while 条件必须有 left <= right 的保护。
#    否则当数组中全是 val 或全不是 val 时，指针会越界。
#
# 4. 返回 left 还是 right：
#    交换法中返回 left（左指针最终位置），不是 right + 1。
#    当 left > right 时，有效区域是 [0, left-1]，长度为 left。
#
# 5. 误以为需要"物理删除"：
#    题目要求原地，但不要求真的把 val 从数组中删掉。
#    只需要保证前 k 个元素都是有效值即可，后面的元素可以是任何值。
# ══════════════════════════════════════════════════════════
