"""
42. 接雨水（Trapping Rain Water）

题目描述：
给定 n 个非负整数表示每个宽度为 1 的柱子的高度图，计算按此排列的柱子下雨之后能接多少雨水。

输入描述：
height[i] 表示第 i 根柱子的高度，每根柱子的宽度均为 1。

输出描述：
返回柱子之间能够接住的雨水总量。

输入示例 1：
height = [0, 1, 0, 2, 1, 0, 1, 3, 2, 1, 2, 1]
输出示例 1：
6

输入示例 2：
height = [4, 2, 0, 3, 2, 5]
输出示例 2：
9

════════════════════════════════════════════════════════════════════════
核心概念：每个位置的积水量
════════════════════════════════════════════════════════════════════════

对于下标 i，左侧最高柱子和右侧最高柱子共同决定该位置的水面高度：

    water[i] = min(left_max[i], right_max[i]) - height[i]

如果结果小于等于 0，说明该位置无法接水。

解法总览：
────────────────────────────────────────────────────────────────────────
解法                         时间复杂度       空间复杂度       适用场景
────────────────────────────────────────────────────────────────────────
暴力枚举左右最高柱子           O(n²)            O(1)             直观理解
前缀最大值                     O(n)             O(n)             容易实现
单调递减栈                     O(n)             O(n)             学习单调栈
双指针                         O(n)             O(1)             ⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

本文件中的 trap 使用单调栈，符合当前目录的主题；如果只关注空间复杂度，
可以使用 trap_two_pointers。
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力枚举左右最高柱子
# ══════════════════════════════════════════════════════════


def trap_bruteforce(height: list[int]) -> int:
    """暴力解法 ⭐⭐

    核心思想：
    对每个位置 i，分别扫描它左边和右边的最高柱子，然后计算当前位置的积水量。

    算法步骤：
    1. 枚举每个位置 i。
    2. 找出 [0, i] 中的最高柱子和 [i, n - 1] 中的最高柱子。
    3. 将 min(left_max, right_max) - height[i] 加入答案。

    时间复杂度：O(n²) — 每个位置都需要再次扫描左右区间。
    空间复杂度：O(1) — 只使用常数个变量。

    示例：[4, 2, 0, 3, 2, 5]
    位置 2 的左右最高高度分别为 4 和 5，因此可以接 4 格水。
    所有位置累加后结果为 9 ✓
    """
    water = 0
    n = len(height)

    for i, current_height in enumerate(height):
        # 包含当前位置也不会影响最大值，因为当前位置最终会被减掉。
        left_max = max(height[: i + 1])
        right_max = max(height[i:n])
        water += max(0, min(left_max, right_max) - current_height)

    return water


# ══════════════════════════════════════════════════════════
# 解法二：前缀最大值和后缀最大值
# ══════════════════════════════════════════════════════════


def trap_prefix_max(height: list[int]) -> int:
    """前缀最大值解法 ⭐⭐⭐

    核心思想：
    预先计算每个位置左侧和右侧的最高柱子，避免暴力解法中的重复扫描。

    算法步骤：
    1. left_max[i] 保存下标 i 左侧（包含 i）的最高高度。
    2. right_max[i] 保存下标 i 右侧（包含 i）的最高高度。
    3. 根据水面公式逐个位置计算积水量。

    时间复杂度：O(n) — 三次线性遍历。
    空间复杂度：O(n) — 保存两个最大值数组。

    示例：[0, 1, 0, 2] 的 left_max 为 [0, 1, 1, 2]；
    right_max 为 [2, 2, 2, 2]，中间低洼位置的水量可以直接计算。 ✓
    """
    n = len(height)
    if n < 3:
        return 0

    left_max = [0] * n
    right_max = [0] * n

    # 计算每个位置左侧的最高柱子。
    left_max[0] = height[0]
    for i in range(1, n):
        left_max[i] = max(left_max[i - 1], height[i])

    # 计算每个位置右侧的最高柱子。
    right_max[n - 1] = height[n - 1]
    for i in range(n - 2, -1, -1):
        right_max[i] = max(right_max[i + 1], height[i])

    water = 0
    for i, current_height in enumerate(height):
        water += min(left_max[i], right_max[i]) - current_height

    return water


# ══════════════════════════════════════════════════════════
# 解法三：单调递减栈（本目录的主解法）
# ══════════════════════════════════════════════════════════


def trap(height: list[int]) -> int:
    """单调递减栈解法 ⭐⭐⭐⭐

    核心思想：
    栈中保存柱子的下标，并保证这些下标对应的高度从栈底到栈顶递减。
    当遇到更高的柱子时，栈顶柱子可能成为一个凹槽的底部：

        左边界 | 凹槽底部 | 右边界（当前柱子）

    算法步骤：
    1. 遍历每根柱子，并将其下标放入栈中。
    2. 如果当前柱子高于栈顶柱子，弹出栈顶，作为凹槽底部 bottom。
    3. 弹出后新的栈顶是左边界 left，当前柱子是右边界 right。
    4. 使用宽度乘高度计算这一层的积水，并继续处理可能更深的凹槽。

    计算公式：
        width = right - left - 1
        bounded_height = min(height[left], height[right]) - height[bottom]
        water += width * bounded_height

    时间复杂度：O(n) — 每个下标最多入栈和出栈一次。
    空间复杂度：O(n) — 栈最多保存 n 个下标。

    示例：[4, 2, 0, 3, 2, 5]
    遇到 3 时，0 找到左边界 2，形成 2 格水；
    遇到 5 时，继续结算由 4 和 5 形成的更大凹槽，最终结果为 9 ✓
    """
    stack: list[int] = []
    water = 0

    for right, right_height in enumerate(height):
        # 当前柱子作为右边界，结算所有比它低的凹槽底部。
        while stack and right_height > height[stack[-1]]:
            bottom = stack.pop()

            # 没有左边界，无法形成完整凹槽。
            if not stack:
                break

            left = stack[-1]
            width = right - left - 1
            bounded_height = min(height[left], right_height) - height[bottom]
            water += width * bounded_height

        stack.append(right)

    return water


# ══════════════════════════════════════════════════════════
# 解法四：双指针（空间复杂度最优）
# ══════════════════════════════════════════════════════════


def trap_two_pointers(height: list[int]) -> int:
    """双指针解法 ⭐⭐⭐⭐ 推荐

    核心思想：
    使用 left 和 right 从两端向中间移动，并维护两侧已经见过的最高柱子。
    哪一侧的最高柱子更低，就先结算哪一侧，因为该侧的积水高度已经被确定。

    算法步骤：
    1. 初始化 left_max 和 right_max，分别表示两侧已遍历部分的最高高度。
    2. 若 height[left] <= height[right]，左侧水量由 left_max 决定，处理 left 后右移。
    3. 否则右侧水量由 right_max 决定，处理 right 后左移。
    4. 两个指针相遇时，所有位置都已处理。

    时间复杂度：O(n) — 每个位置只访问一次。
    空间复杂度：O(1) — 只使用几个变量。

    示例：[4, 2, 0, 3, 2, 5]
    右边界高度 5 足够高，因此左侧可以逐步根据 left_max 结算；
    当处理到右侧时，再根据 right_max 结算剩余位置，结果为 9 ✓
    """
    left = 0
    right = len(height) - 1
    left_max = 0
    right_max = 0
    water = 0

    while left < right:
        if height[left] <= height[right]:
            # 左侧较低，左位置的水面高度由 left_max 决定。
            left_max = max(left_max, height[left])
            water += left_max - height[left]
            left += 1
        else:
            # 右侧较低，右位置的水面高度由 right_max 决定。
            right_max = max(right_max, height[right])
            water += right_max - height[right]
            right -= 1

    return water


# ══════════════════════════════════════════════════════════
# 正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明：
# ─────────────────────────────────────────────────────────
# 定理：上述四种方法都能正确计算柱状图能够接住的雨水总量。
#
# 证明：
# （1）对于任意位置 i，水面不可能高于左侧最高柱子或右侧最高柱子，
#      因此该位置的水面高度必然是 min(left_max[i], right_max[i])。
# （2）前缀最大值方法直接保存这两个最高值，所以每个位置计算出的水量正确。
# （3）暴力方法通过扫描得到同样的两个最高值，因此结果正确。
# （4）单调栈方法在弹出 bottom 时，栈顶是左边界，当前下标是右边界，
#      它们之间新增的水层恰好是由这两个边界确定的，且每个水层只结算一次。
# （5）双指针方法总是先处理较低的一侧。由于另一侧当前存在不低于它的边界，
#      较低侧的积水高度已经确定，因此移动并结算该侧不会遗漏或重复计算。
#
# 常见错误：
# ─────────────────────────────────────────────────────────
# 1. 宽度应为 right - left - 1，而不是 right - left，
#    因为左右边界柱子本身不存水。
# 2. 高度应为 min(左边界高度, 右边界高度) - 底部高度，
#    不能直接使用两边高度的差值。
# 3. 单调栈弹出底部后，如果栈为空，说明没有左边界，不能计算积水。
# 4. 使用双指针时，必须维护 left_max 和 right_max，不能只比较当前两根柱子。
# 5. 长度小于 3 的数组不可能形成凹槽，答案一定是 0。
# ══════════════════════════════════════════════════════════
