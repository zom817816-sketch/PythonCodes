"""
下一个更大元素 I（Next Greater Element I）

题目描述：
nums1 中数字 x 的 下一个更大元素 是指 x 在 nums2 中对应位置 右侧 的 第一个 比 x 大的元素。
给你两个 没有重复元素 的数组 nums1 和 nums2 ，下标从 0 开始计数，其中 nums1 是 nums2 的子集。
对于每个 0 <= i < nums1.length，找出满足 nums1[i] == nums2[j] 的下标 j，
并且在 nums2 中确定 nums2[j] 的 下一个更大元素。如果不存在下一个更大元素，本次查询的答案是 -1。
返回一个长度为 nums1.length 的数组 ans 作为答案，满足 ans[i] 是如上所述的 下一个更大元素。

输入描述：
两个整数数组 nums1 和 nums2，1 <= nums1.length <= nums2.length <= 1000，
0 <= nums1[i], nums2[i] <= 10^4，所有整数互不相同。

输出描述：
一个整数数组 ans，ans[i] 是 nums1[i] 在 nums2 中的下一个更大元素，不存在则为 -1。

输入示例：
示例 1：
nums1 = [4,1,2], nums2 = [1,3,4,2]
输出示例：[-1,3,-1]
解释：
- nums1[0]=4，在 nums2 中位置为 2，右侧没有比 4 大的元素 → -1
- nums1[1]=1，在 nums2 中位置为 0，右侧第一个比 1 大的是 3 → 3
- nums1[2]=2，在 nums2 中位置为 3，右侧没有元素 → -1

示例 2：
nums1 = [2,4], nums2 = [1,2,3,4]
输出示例：[3,-1]
解释：
- nums1[0]=2，在 nums2 中位置为 1，右侧第一个比 2 大的是 3 → 3
- nums1[1]=4，在 nums2 中位置为 3，右侧没有元素 → -1

════════════════════════════════════════════════════════════════════════
核心概念：单调栈（Monotonic Stack）+ 哈希表映射
════════════════════════════════════════════════════════════════════════

与上一题（每日温度）的对比：
────────────────────────────────────────────────────────────────────────
维度                每日温度（739）              下一个更大元素 I（496）
────────────────────────────────────────────────────────────────────────
输入                单数组 temperatures           双数组 nums1, nums2
输出                间隔天数（int）               元素值（int）
核心操作            找右边第一个更大的元素的距离     找右边第一个更大的元素的值
数据结构            单调栈存下标                   单调栈存值 + 哈希表存映射
额外处理            无                            需要哈希表建立值→下一个更大元素的映射
本质                相同！都是"下一个更大元素"问题  相同！只是多了一步：先在 nums2 预处理所有答案
────────────────────────────────────────────────────────────────────────

关键洞察：
    虽然题目有两个数组，但真正需要处理的只有 nums2。
    nums2 中每个元素的"下一个更大元素"是固定的，与 nums1 无关。
    所以策略是：
    1. 对 nums2 用单调栈预处理，算出每个元素的"下一个更大元素"，存入哈希表
    2. 遍历 nums1，直接从哈希表中查找答案

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
暴力解法                      O(n²)           O(1)            ⭐ 双重循环，小规模可用
哈希表 + 单调栈               O(m + n)        O(n)            ⭐⭐⭐⭐⭐ 推荐，最优解
────────────────────────────────────────────────────────────────────────

核心思想（哈希表 + 单调栈）：
────────────────────────────────────────────────────────────────────────
第一步：对 nums2 用单调递减栈，求出每个元素的"下一个更大元素"
    - 栈中存储"还没找到答案的元素的值"
    - 当前元素来临时，弹走所有比它小的栈顶 → 当前元素就是它们的答案
    - 将弹栈元素和当前元素的映射存入哈希表
    - 当前元素入栈（等待未来某个更大的元素来匹配它）

第二步：遍历 nums1，从哈希表中直接查表得到答案
    - 哈希表中存在对应值 → 返回对应的下一个更大元素
    - 哈希表中不存在 → 返回 -1（说明该元素后面没有更大的）

为什么栈里存值而不是下标？
    因为我们需要用"值"作为哈希表的 key。
    在每日温度中需要存下标是因为要计算距离（i - top）。
    这里只需要元素的值作为答案，存值更直观。

图解示例（nums2 = [1,3,4,2]）：
────────────────────────────────────────────────────────────────────────
单调递减栈，栈中存值。弹栈时记录映射表 mapping[弹栈值] = 当前值。

步骤      i   num   栈状态       操作                          mapping 更新
──────────────────────────────────────────────────────────────────────────
初始      -    -    []           -                            {}
1         0    1    [1]          栈空，1 入栈                  {}
2         1    3    [3]          3 > 1，弹栈1 → mapping[1]=3   {1:3}
                                3 入栈
3         2    4    [4]          4 > 3，弹栈3 → mapping[3]=4   {1:3, 3:4}
                                4 入栈
4         3    2    [4,2]        2 < 4，入栈                   {1:3, 3:4}
遍历结束，栈中剩余元素（4, 2）后面没有更大的，不加入 mapping

最终 mapping = {1: 3, 3: 4}
对 nums1 = [4,1,2] 查表：
    4 → 不在 mapping 中 → -1
    1 → mapping[1] = 3 → 3
    2 → 不在 mapping 中 → -1

结果：[-1, 3, -1] ✓
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力解法
# ══════════════════════════════════════════════════════════


def nextGreaterElement_brute(nums1: list[int], nums2: list[int]) -> list[int]:
    """
    暴力解法 ⭐

    核心思想：
    ────────────────────────────────────────────────────────
    对 nums1 中每个元素，先在 nums2 中找到它的位置，
    然后从该位置向右扫描，找到第一个比它大的元素。

    算法步骤：
    1. 外层循环遍历 nums1 中每个元素
    2. 在 nums2 中找到该元素的下标 pos
    3. 从 pos+1 开始向右扫描 nums2，找到第一个更大的元素
    4. 找到则记录答案，找不到则为 -1

    时间复杂度：O(m × n) — 对每个 nums1 元素，在 nums2 中线性查找 + 线性扫描
    空间复杂度：O(1)     — 不计输出数组

    图解示例：
    ────────────────────────────────────────────────────────
    nums1 = [4,1,2], nums2 = [1,3,4,2]
    i=0: nums1[0]=4 → 在 nums2 中位置 2 → 向右找：nums2[3]=2 < 4 → -1
    i=1: nums1[1]=1 → 在 nums2 中位置 0 → 向右找：nums2[1]=3 > 1 → 3
    i=2: nums1[2]=2 → 在 nums2 中位置 3 → 向右无元素 → -1

    结果：[-1, 3, -1] ✓

    ⚠️ 注意：原始版本存在 bug，内层循环 j 从 i+1 开始，
    但 i 是 nums1 的下标而非 nums2 的下标，导致查找位置错误。
    正确做法是先找到 nums1[i] 在 nums2 中的位置 pos，再从 pos+1 开始扫描。
    """
    m, n = len(nums1), len(nums2)
    answer = [-1] * m

    for i in range(m):
        target = nums1[i]
        # 先找到 target 在 nums2 中的位置
        pos = -1
        for j in range(n):
            if nums2[j] == target:
                pos = j
                break
        # 从 pos+1 开始向右查找第一个更大的元素
        for j in range(pos + 1, n):
            if nums2[j] > target:
                answer[i] = nums2[j]
                break

    return answer


# ══════════════════════════════════════════════════════════
# 解法二：哈希表 + 单调栈 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def nextGreaterElement(nums1: list[int], nums2: list[int]) -> list[int]:
    """
    哈希表 + 单调栈 ⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    先对 nums2 用单调栈预处理，建立"值 → 下一个更大元素"的映射，
    然后遍历 nums1 直接查表得到答案。

    单调栈处理过程：
        维护单调递减栈（栈底到栈顶递减），栈中存元素的值。
        遍历 nums2 时，对每个当前值 num：
        - 所有比 num 小的栈顶都要弹出，num 就是它们的"下一个更大元素"
        - 将 mapping[弹出值] = num 记录下来
        - 将 num 入栈（等待未来某个更大的值来匹配它）

    为什么是"递减"栈？
        栈中元素都是在"等待更大元素"的。
        如果栈保持递减，新元素来时：
        - 比栈顶大 → 弹栈（匹配成功），继续看新栈顶
        - 比栈顶小 → 入栈（继续等待）
        弹栈时当前元素一定是弹栈元素"最近的"更大的。

    算法步骤：
    1. 初始化空栈 stack 和空哈希表 mapping
    2. 正序遍历 nums2 中每个元素 num：
       a. while 栈非空 且 num > stack[-1]：
           top = stack.pop()
           apping[top] = num    # num 是 top 的下一个更大元素
       b. stack.append(num)       # num 入栈等待匹配
    3. 遍历 nums1，从 mapping 中查表：
       a. 存在 → mapping[nums1[i]]
       b. 不存在 → -1

    时间复杂度：O(m + n) — nums2 遍历 O(n)（每个元素入栈出栈各一次），
                           nums1 遍历 O(m)，哈希表查找 O(1)
    空间复杂度：O(n)     — 栈和哈希表各 O(n)

    图解示例：
    ────────────────────────────────────────────────────────
    nums2 = [1,3,4,2]

    步骤  num   操作                                        栈       mapping
    ────────────────────────────────────────────────────────────────────────
    初始   -    -                                          []       {}
    1      1    栈空，1 入栈                               [1]      {}
    2      3    3 > 1，弹栈1, mapping[1]=3, 3 入栈         [3]      {1:3}
    3      4    4 > 3，弹栈3, mapping[3]=4, 4 入栈         [4]      {1:3,3:4}
    4      2    2 < 4，入栈                                 [4,2]    {1:3,3:4}

    栈中剩余 4, 2 后面没有更大元素，不记录 mapping

    对 nums1 = [4,1,2] 查表：
        4 → mapping 中无 → -1
        1 → mapping[1] = 3 → 3
        2 → mapping 中无 → -1

    结果：[-1, 3, -1] ✓

    与"每日温度"的代码对比：
        每日温度：answer[top] = i - top  (存下标，算距离)
        本题：    mapping[top] = num     (存值，记元素)
        单调栈的弹栈逻辑完全一样，区别只在于：
        - 栈中存什么（下标 vs 值）
        - 弹栈时记录什么（距离 vs 映射关系）
    """
    stack = []        # 单调递减栈，存储元素的值
    mapping = {}      # 值 → 下一个更大元素的映射

    # 第一步：对 nums2 用单调栈预处理
    for num in nums2:
        # 当前 num 比栈顶大 → num 就是栈顶元素的"下一个更大元素"
        while stack and num > stack[-1]:
            top = stack.pop()
            mapping[top] = num
        # 当前元素入栈，等待未来某个更大的值来匹配
        stack.append(num)

    # 第二步：遍历 nums1，直接查表得到答案
    return [mapping.get(x, -1) for x in nums1]


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、单调栈 + 哈希表的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：上述算法能正确求出 nums2 中每个元素的"下一个更大元素"。
#
# 证明：
# （1）栈的单调性保持：
#     入栈前，所有比当前元素小的栈顶都会被弹出。
#     因此新元素入栈后，栈中值仍保持递减。
#     归纳可证，每次入栈后栈都是递减的。
#
# （2）弹栈的及时性（保证"第一个"更大）：
#     当 num 到来且 num > stack[-1] 时，
#     因为是正序遍历，num 是 stack[-1] 之后第一个比它大的元素。
#     假设存在某个元素 x 在 stack[-1] 和 num 之间也比它大，
#     那么 x 应该在 num 之前就已经弹出了 stack[-1]（矛盾）。
#     所以 num 确实是栈顶元素的"下一个更大元素"。
#
# （3）未弹栈元素的答案：
#     遍历结束后，栈中剩余的元素没有被弹过，
#     说明它们之后没有任何元素比它们大，
#     因此不在 mapping 中，查表时返回默认值 -1，正确。
#
# （4）每个元素最多入栈出栈各一次：
#     值 v 入栈后，要么在某个更大值到来时被弹出（mapping[v] 确定），
#     要么遍历结束留在栈中（mapping 中不存在）。不存在重复入栈。
#     因此总时间复杂度 O(n)。
#
# （5）哈希表查找的正确性：
#     因为 nums1 是 nums2 的子集，nums1 中所有值都在 nums2 中出现过，
#     但并非所有值都有"下一个更大元素"。
#     mapping.get(x, -1) 能正确处理这两种情况。
#
#
# 二、与"每日温度"的统一视角：
# ────────────────────────────────────────────────────────
#
# 两道题本质相同，都是"右边第一个更大元素"问题。
# 代码框架完全一致，区别只有两个细节：
#
#              每日温度 (739)              下一个更大元素 I (496)
# ────────────────────────────────────────────────────────────────
# 栈中存什么？  下标（需要算距离）           值（需要做哈希表 key）
# 弹栈记录什么？answer[top] = i - top        mapping[top] = num
# 最终输出？    answer 数组直接返回          查表后返回
# ────────────────────────────────────────────────────────────────
#
# 统一模板：
#     stack = []
#     for cur in array:
#         while stack and cur > stack[-1]:
#             top = stack.pop()
#             record[top] = cur      # 区别只在这行
#         stack.append(cur)
#
# 记忆口诀：
#   - 找"右边第一个更大" → 单调递减栈
#   - 栈里存什么决定了记录什么（存下标算距离，存值记映射）
#
#
# 三、单调栈的四种变体速查：
# ────────────────────────────────────────────────────────
#
# 变体              栈类型          比较条件              解决的问题
# ────────────────────────────────────────────────────────────────────
# 右边第一个更大     单调递减栈      cur > 栈顶            本题 / 每日温度
# 右边第一个更小     单调递增栈      cur < 栈顶            找右边最小
# 左边第一个更大     单调递减栈      正序遍历 + 弹栈前查询  找左边最大
# 左边第一个更小     单调递增栈      正序遍历 + 弹栈前查询  找左边最小
# ────────────────────────────────────────────────────────────────────
#
# 规律：
#   - "更大" → 递减栈（小的被弹走，大的留下）
#   - "更小" → 递增栈（大的被弹走，小的留下）
#   - "右边" → 正序遍历（当前元素是前面元素的答案）
#   - "左边" → 正序遍历，但弹栈前先查询栈内（栈内就是左边的元素）
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 暴力解法中 j 从 i+1 开始（原代码 bug）：
#    i 是 nums1 的下标，不是 nums2 中的位置。
#    必须先找到 nums1[i] 在 nums2 中的位置 pos，
#    然后 j 从 pos+1 开始扫描。
#    例如 nums1=[4], nums2=[4,1,2]，i=0 时 pos=0，应从 j=1 开始找。
#    如果 j 从 i+1=1 开始，碰巧能找到，但逻辑错误。
#
# 2. 搞反栈的单调性：
#    找"更大"，用单调递减栈。
#    如果用单调递增栈，弹栈条件反过来，会得到完全错误的答案。
#
# 3. 忘记 while 循环，只用 if：
#    当前元素可能同时匹配多个栈顶。
#    例如 num=5 来临时，栈里压着 [3,2,1]，三个都要弹。
#    用 if 只能弹一个，会漏掉 mapping。
#
# 4. 哈希表查找用 mapping[x] 而不是 mapping.get(x, -1)：
#    栈中剩余元素没有"下一个更大元素"，不会加入 mapping。
#    直接 mapping[x] 会 KeyError。
#    必须用 .get(x, -1) 提供默认值 -1。
#
# 5. 混淆存下标和存值：
#    每日温度需要存下标（算距离 i - top）。
#    本题存值更自然（做哈希表的 key）。
#    如果在本题中存下标，哈希表的 key 就需要额外转换。
#
# 6. 对 nums2 逆序遍历：
#    逆序遍历也能做（从后往前维护"已经见过的更大元素"），
#    但需要用单调递增栈，比较条件也不同。
#    正序遍历 + 单调递减栈是更通用的模板，建议先掌握正序版本。
# ══════════════════════════════════════════════════════════
