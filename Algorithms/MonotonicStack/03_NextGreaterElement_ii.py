"""
下一个更大元素 II（Next Greater Element II）

题目描述：
给定一个循环数组 nums （nums[n-1] 的下一个元素是 nums[0]），
返回 nums 中每个元素的下一个更大元素。
数字 x 的下一个更大的元素是按数组遍历顺序，这个数字之后的第一个比它更大的数，
这意味着你应该循环地搜索它的下一个更大的数。如果不存在，则输出 -1。

输入描述：
一个循环整数数组 nums，1 <= nums.length <= 10^4，-10^9 <= nums[i] <= 10^9。

输出描述：
一个整数数组 result，result[i] 是 nums[i] 的下一个更大元素（循环搜索）。

输入示例：
示例 1：
nums = [1,2,1]
输出：[2,-1,2]
解释：
第一个 1 的下一个更大的数是 2；
数字 2 找不到下一个更大的数；
第二个 1 的下一个更大的数需要循环搜索，结果也是 2。

示例 2：
nums = [1,2,3,4,3]
输出：[2,3,4,-1,4]
解释：
索引 0 (1) → 更大的 2 at 索引 1
索引 1 (2) → 更大的 3 at 索引 2
索引 2 (3) → 更大的 4 at 索引 3
索引 3 (4) → 没有更大的（3,1,2,3 都 ≤ 4）→ -1
索引 4 (3) → 循环搜索，4 at 索引 3（通过 2*n 遍历可找到）

════════════════════════════════════════════════════════════════════════
核心概念：循环数组 + 单调栈
════════════════════════════════════════════════════════════════════════

什么是循环数组？
    循环数组的末尾和开头相连，形成一个环。
    查找"下一个更大元素"时，需要考虑从当前位置到数组末尾，
    再从头开始直到当前位置之前的所有元素。

如何处理循环数组？
    核心技巧：将数组"展开"为两倍长度，用取模访问原数组。
    例如 nums = [1,2,1]，展开后相当于 [1,2,1,1,2,1]。
    遍历 i = 0..2n-1，实际访问 nums[i % n]。
    这样就能覆盖"从每个元素出发，绕一圈回来"的所有情况。

    为什么遍历 2n 就够了？
        对元素 i，只需要考虑它后面的 n-1 个元素（绕一圈）。
        遍历到 i + n - 1 就能覆盖所有需要的元素。
        当遍历完 2n 次，所有元素都已经被当作"当前元素"处理过了。

与"每日温度"的对比：
────────────────────────────────────────────────────────────────────────
维度                每日温度（I）              下一个更大元素（II）
────────────────────────────────────────────────────────────────────────
数组类型            普通数组                  循环数组
遍历次数            n 次                      2n 次（展开两倍）
栈中存储            下标                      下标
弹栈条件            temperatures[i] > 栈顶    nums[i] > 栈顶
结果数组            answer[top] = i - top     result[top] = nums[i]
答案默认值          0（间隔天数）              -1（不存在更大元素）
核心区别            算距离                     算值
────────────────────────────────────────────────────────────────────────

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
暴力解法                      O(n²)           O(1)            ⭐ 对每个元素循环查找
单调栈（2n 遍历）             O(n)            O(n)            ⭐⭐⭐⭐⭐ 推荐，最经典
────────────────────────────────────────────────────────────────────────

核心思想（单调栈 + 循环展开）：
────────────────────────────────────────────────────────────────────────
1. 将循环数组展开为 2n 长度的虚拟数组，遍历 2n 次
2. 维护一个单调递减栈，栈中存储下标（而非值）
3. result[i] 初始化为 -1（默认没有更大元素）
4. 正序遍历 i = 0..2n-1：
   a. cur = nums[i % n]（实际当前值）
   b. while 栈非空 且 cur > nums[栈顶下标]：
       top = 栈顶下标
       result[top] = cur    ← cur 就是 top 的下一个更大元素
       弹栈
   c. 如果 i < n（只把前 n 个下标入栈，后半段只是用来匹配）：
       栈中只存 0..n-1 的下标
       因为后半段（n..2n-1）是虚拟展开的，不需要入栈

为什么只入栈前 n 个？
    栈里存的是"等待被匹配的原始下标"。
    后半段是虚拟展开，它们的下标超出了 0..n-1 的范围，
    存进去没有意义（result 数组只有 n 个位置）。
    但后半段的值仍然可以用来弹栈匹配前半段的元素。

图解示例（nums = [1,2,1]，n=3，遍历 0..5）：
────────────────────────────────────────────────────────────────────────
result = [-1, -1, -1]

步骤  i  i%3  cur  栈顶(下标/值)     操作                    栈        result
───────────────────────────────────────────────────────────────────────────────
初始  -   -    -       -              -                     []        [-1,-1,-1]
1     0   0    1       -              入栈(i<3)             [0]       -
2     1   1    2      0/1<2          弹0, res[0]=2         [1]       [2,-1,-1]
3     2   2    1      1/2>1           入栈(i<3)             [1,2]     -
4     3   0    1      2/1=1 不弹     i>=3 不入栈            [1,2]     -
5     4   1    2      2/1<2          弹2, res[2]=2
                      1/2=2 不弹      i>=3 不入栈            [1]       [2,-1,2]
6     5   2    1      1/2>1           i>=3 不入栈            [1]       -

最终：result = [2, -1, 2] ✓
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力解法
# ══════════════════════════════════════════════════════════


def nextGreaterElements_brute(nums: list[int]) -> list[int]:
    """
    暴力解法 ⭐

    核心思想：
    ────────────────────────────────────────────────────────
    对每个元素 nums[i]，从 i+1 开始循环查找下一个更大的元素。
    通过 (i + j) % n 实现循环访问。

    算法步骤：
    1. 外层循环遍历每个位置 i
    2. 内层循环 j = 1..n，检查 nums[(i+j) % n] 是否 > nums[i]
    3. 找到第一个就记录并跳出；否则保持 -1

    时间复杂度：O(n²) — 最坏情况（严格递减），内层循环走遍 n-1 个元素
    空间复杂度：O(1)   — 不计输出数组

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [1,2,1]
    i=0, val=1: 查 (0+1)%3=1 → nums[1]=2>1 → res[0]=2
    i=1, val=2: 查 2→nums[2]=1, 查 0→nums[0]=1, 查 1→nums[1]=2 都 ≤ 2 → res[1]=-1
    i=2, val=1: 查 0→nums[0]=1, 查 1→nums[1]=2>1 → res[2]=2

    结果：[2,-1,2] ✓
    """
    n = len(nums)
    result = [-1] * n

    for i in range(n):
        # 从 i+1 开始，最多查 n-1 个（绕一圈）
        for j in range(1, n):
            next_idx = (i + j) % n
            if nums[next_idx] > nums[i]:
                result[i] = nums[next_idx]
                break

    return result


# ══════════════════════════════════════════════════════════
# 解法二：单调栈（循环展开）⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def nextGreaterElements(nums: list[int]) -> list[int]:
    """
    单调栈（循环展开）⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    将循环数组展开为 2n 长度，用单调递减栈找出每个元素的下一个更大值。

    与"每日温度"的区别：
    - 每日温度：result[top] = i - top（距离）
    - 本题：result[top] = nums[i % n]（值）
    - 需要遍历 2n 次以覆盖循环搜索

    关键细节：
    - 栈中存下标（不是值），result 数组按下标回填
    - 只把 i < n 的下标入栈（后半段是虚拟展开，不入栈）
    - 后半段的值可以弹栈，用来匹配前半段还没找到答案的元素
    - 比较条件用 > 不用 >=：题目要"严格大于"

    算法步骤：
    1. 初始化 result[n] = [-1] * n（默认找不到更大元素）
    2. 初始化空栈 stack
    3. 遍历 i = 0..2n-1：
       a. cur = nums[i % n]
       b. while 栈非空 且 cur > nums[stack[-1]]：
           top = stack.pop()
           result[top] = cur   # cur 就是 top 的下一个更大元素
       c. 如果 i < n：stack.append(i)  # 只入栈前 n 个真实下标

    时间复杂度：O(n) — 每个下标最多入栈一次、出栈一次，共 n 次
    空间复杂度：O(n) — 栈最多存 n 个下标

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [1,2,3,4,3]（n=5）

    步骤  i  i%5  cur   栈顶(下标/值)    操作                    栈         result
    ───────────────────────────────────────────────────────────────────────────────────
    初始  -   -    -        -             -                     []         [-1,-1,-1,-1,-1]
    1     0   0    1        -             入栈                  [0]        -
    2     1   1    2       0/1<2          弹0, res[0]=2        [1]        [2,-1,-1,-1,-1]
    3     2   2    3       1/2<3          弹1, res[1]=3        [2]        [2,3,-1,-1,-1]
    4     3   3    4       2/3<4          弹2, res[2]=4        [3]        [2,3,4,-1,-1]
    5     4   4    3       3/4>3          入栈                  [3,4]      -
    6     5   0    1       4/3>1          i>=5 不入栈          [3,4]      -
    7     6   1    2       4/3>2          i>=6 不入栈          [3,4]      -
    8     7   2    3       4/3=3 不弹     i>=7 不入栈          [3,4]      -
    9     8   3    4       4/3<4          弹4, res[4]=4        [3]        [2,3,4,-1,4]
                          3/4=4 不弹      i>=8 不入栈          [3]        -
    10    9   4    3       3/4>3          i>=9 不入栈          [3]        -

    最终：result = [2,3,4,-1,4] ✓
    """
    n = len(nums)
    if n == 0:
        return []

    result = [-1] * n
    stack = []  # 存储下标，对应值单调递减

    # 遍历 2n 次，展开循环数组
    for i in range(2 * n):
        cur = nums[i % n]
        # 当前值比栈顶下标对应的值大 → 当前值就是栈顶的下一个更大元素
        while stack and cur > nums[stack[-1]]:
            top = stack.pop()
            result[top] = cur  # 记录值（不是距离）
        # 只把前 n 个真实下标入栈
        # 后半段 n..2n-1 是虚拟展开，不入栈
        if i < n:
            stack.append(i)

    return result


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、单调栈（2n 遍历）的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：算法能正确找出循环数组中每个元素的下一个更大元素。
#
# 证明：
# （1）循环展开的等价性：
#     对元素 nums[i]（0 <= i < n），它的循环搜索范围是
#     nums[i+1], nums[i+2], ..., nums[n-1], nums[0], nums[1], ..., nums[i-1]。
#     遍历 2n 次时，当 k = i+1, i+2, ..., i+n-1，nums[k % n] 恰好覆盖这个范围。
#     因此 2n 次遍历足以覆盖每个元素的完整搜索空间。
#
# （2）弹栈的及时性：
#     当 cur = nums[k % n] 大于栈顶下标 top 对应的值时，
#     由于 k 是递增的，cur 是 top 之后（循环意义上）遇到的第一个更大的值。
#     如果存在某个 j 在 top 和 k 之间也比 top 大，
#     那么 j 对应的元素应该在 k 之前就已经弹出了 top（矛盾）。
#     所以 cur 确实是 top 的"下一个更大元素"。
#
# （3）只入栈前 n 个的正确性：
#     栈中只存 0..n-1 的下标，它们都在 result 数组中有对应位置。
#     后半段 n..2n-1 的虚拟下标，即使入栈也没有 result 位置可以回填。
#     而它们的值仍然可以通过 cur 参与弹栈匹配，所以不入栈不影响正确性。
#
# （4）每个下标最多入栈出栈各一次：
#     下标 i 在 i < n 时入栈（恰好一次）。
#     之后要么在某个 k > i 时被弹出（result[i] 确定），
#     要么遍历结束留在栈中（result[i] 保持 -1）。
#     不存在重复入栈。总时间复杂度 O(2n) = O(n)。
#
#
# 二、原代码的 Bug 分析：
# ────────────────────────────────────────────────────────
#
# Bug 1：用值作为 key，而非下标
# ────────────────────────────────────────────────────────
# 原代码使用 mapping = {}，弹栈时 mapping[top] = nums[i % n]，
# 这里 top 是栈中的值（stack.append(nums[i % n])），
# 所以 mapping 的 key 是元素值而不是下标。
#
# 问题：当数组中有重复值且它们的下一个更大元素不同时，
# mapping 只能存一个，导致后面的结果被覆盖。
#
# 反例：nums = [1, 2, 1, 3]
#   索引 0 的 1 → 下一个更大是 2
#   索引 2 的 1 → 下一个更大是 3
#   mapping[1] 只能存一个值！存了 2 就放不下 3。
#
# 正确做法：栈中存下标，result 数组按下标回填。
#   每个下标独立记录答案，互不干扰。
#
# Bug 2：if not mapping.get(top) 逻辑不严谨
# ────────────────────────────────────────────────────────
# `mapping.get(top)` 返回值或 None。
# `not None` = True，所以不存在时会设置；
# `not 2` = False，所以已存在时不会覆盖。
# 这个逻辑恰好能工作（仅因为 Python 的真值规则），但非常脆弱，
# 完全依赖"不覆盖已有值"的语义，而非"按下标记录"。
#
# Bug 3：栈中存值导致无法计算距离（虽然本题不需要距离）
# ────────────────────────────────────────────────────────
# 与"每日温度"不同，本题不需要距离，但存值仍然是错误习惯。
# 当需要距离时，必须存下标才能做 i - top 计算。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 用值做 key，而非下标：
#    数组中可以有重复值，每个值可能有不同的下一个更大元素。
#    必须用下标做 key（result 数组按下标索引）。
#
# 2. 忘记只入栈前 n 个：
#    如果把 i >= n 的虚拟下标也入栈，栈中会存无效下标，
#    而 result 数组只有 n 个位置（访问 result[虚拟下标] 会越界或错误）。
#
# 3. 遍历次数写错：
#    必须遍历 2n 次，不能只遍历 n 次。
#    只遍历 n 次就变成了普通数组的"下一个更大元素 I"，
#    循环搜索的后半段（绕回来的部分）被漏掉了。
#
# 4. 比较条件写错：
#    必须用 cur > nums[stack[-1]]（严格大于）。
#    如果写成 >=，相等的元素也会触发弹栈，导致错误答案。
#    题目要的是"比它更大"，不是"大于等于"。
#
# 5. result 初始值写错：
#    必须初始化为 -1（找不到更大元素时的默认值）。
#    不能初始化为 0 或其他值，会被误认为有效答案。
#
# 6. 混淆 LeetCode 496 和 503：
#    - LeetCode 496：下一个更大元素 I（两个数组，用哈希表）
#    - LeetCode 503：下一个更大元素 II（循环数组，2n 遍历）
#    本题是 II 型，关键区别在循环 + 2n 遍历。
