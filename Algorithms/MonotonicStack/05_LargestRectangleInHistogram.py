# 解法二：分治递归
# ══════════════════════════════════════════════════════════


def largestRectangleArea_divide_conquer(heights: list[int]) -> int:
    """分治递归 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    找到区间 [left, right] 中最矮的柱子，它将矩形分为三种可能：
    1. 完全在最矮柱子左边的最大矩形（递归左半部分）。
    2. 完全在最矮柱子右边的最大矩形（递归右半部分）。
    3. 包含最矮柱子本身的矩形，高度就是最矮柱子的高度，宽度为整个区间。
    三者取最大值即可。

    算法步骤：
    1. 递归函数 solve(left, right) 返回区间内的最大矩形面积。
    2. 找到 [left, right] 中最矮柱子的下标 min_idx。
    3. 跨 min_idx 的面积 = heights[min_idx] * (right - left + 1)。
    4. 分别递归 solve(left, min_idx - 1) 和 solve(min_idx + 1, right)。
    5. 三者取最大值。

    时间复杂度：O(n log n) — 每次递归将区间从最矮处切开，
    平均每次分成大小相近的两部分，递归深度 log n，每层处理 n 个元素。
    最坏情况 O(n²)（柱子高度有序，每次只切掉一个柱子）。
    空间复杂度：O(log n) — 递归栈深度，最坏 O(n)。

    图解示例：
    ────────────────────────────────────────────────────────
    heights = [2, 1, 5, 6, 2, 3]

    solve(0, 5): 最矮 h=1 at idx=1
        跨区间面积 = 1 × 6 = 6
        solve(0, 0): 单根柱子 → 2
        solve(2, 5): 最矮 h=2 at idx=4
            跨区间面积 = 2 × 4 = 8
            solve(2, 3): 最矮 h=5 at idx=2
                跨区间面积 = 5 × 2 = 10
                solve(2, 1): 空区间 → 0
                solve(3, 3): 6
                → max = 10
            solve(5, 5): 3
            → max(8, 10, 3) = 10
        → max(6, 2, 10) = 10

    最大面积：10 ✓
    """
    n = len(heights)

    def solve(left: int, right: int) -> int:
        if left > right:
            return 0

        # 找区间内最矮的柱子
        min_idx = left
        for i in range(left, right + 1):
            if heights[i] < heights[min_idx]:
                min_idx = i

        # 方案 3：包含最矮柱子的矩形
        cross_area = heights[min_idx] * (right - left + 1)
        # 方案 1：左半部分
        left_area = solve(left, min_idx - 1)
        # 方案 2：右半部分
        right_area = solve(min_idx + 1, right)

        return max(cross_area, left_area, right_area)

    return solve(0, n - 1)


