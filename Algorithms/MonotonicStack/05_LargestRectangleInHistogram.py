# 解法三：单调栈（预计算边界数组）
# ══════════════════════════════════════════════════════════


def largestRectangleArea_stack_boundary(heights: list[int]) -> int:
    """单调栈（预计算边界数组）⭐⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    用单调栈分别计算每根柱子的左边界和右边界，
    然后代入面积公式。这是理解单调栈解法的好起点。

    左边界 left_boundary[i]：
        下标 i 左边第一个比 heights[i] 小的柱子下标，
        若不存在则为 -1（表示可以延伸到最左边）。

    右边界 right_boundary[i]：
        下标 i 右边第一个比 heights[i] 小的柱子下标，
        若不存在则为 n（表示可以延伸到最右边）。

    算法步骤：
    1. 正序遍历，用单调递增栈计算 left_boundary。
       栈中存下标，保证 heights 值递增。
       当前元素比栈顶小 → 弹栈（栈顶的右边界确定）。
    2. 逆序遍历，用单调递增栈计算 right_boundary。
       同理，当前元素比栈顶小 → 弹栈（栈顶的左边界确定）。
    3. 逐根柱子计算面积，取最大值。

    时间复杂度：O(n) — 每个下标入栈出栈各两次（左右各一次）。
    空间复杂度：O(n) — 两个边界数组 + 栈。

    图解示例：
    ────────────────────────────────────────────────────────
    heights = [2, 1, 5, 6, 2, 3], n = 6

    计算 left_boundary（正序遍历，单调递增栈）：
        i=0, h=2: 栈空 → left_boundary[0]=-1, 入栈 0  栈:[0]
        i=1, h=1: 1 < 2(栈顶)，弹栈 0；栈空 → left_boundary[1]=-1, 入栈 1  栈:[1]
        i=2, h=5: 5 > 1(栈顶) → left_boundary[2]=1, 入栈 2  栈:[1,2]
        i=3, h=6: 6 > 5(栈顶) → left_boundary[3]=2, 入栈 3  栈:[1,2,3]
        i=4, h=2: 2 < 6(栈顶)，弹栈 3；2 < 5(栈顶)，弹栈 2；
                  2 > 1(栈顶) → left_boundary[4]=1, 入栈 4  栈:[1,4]
        i=5, h=3: 3 > 2(栈顶) → left_boundary[5]=4, 入栈 5  栈:[1,4,5]
        left_boundary = [-1, -1, 1, 2, 1, 4]

    计算 right_boundary（逆序遍历，单调递增栈）：
        i=5, h=3: 栈空 → right_boundary[5]=6, 入栈 5  栈:[5]
        i=4, h=2: 2 < 3(栈顶)，弹栈 5；栈空 → right_boundary[4]=6, 入栈 4  栈:[4]
        i=3, h=6: 6 > 2(栈顶) → right_boundary[3]=4, 入栈 3  栈:[3,4]
        i=2, h=5: 5 < 6(栈顶)，弹栈 3；5 > 2(栈顶) → right_boundary[2]=4, 入栈 2  栈:[2,4]
        i=1, h=1: 1 < 5(栈顶)，弹栈 2；1 < 2(栈顶)，弹栈 4；
                  栈空 → right_boundary[1]=6, 入栈 1  栈:[1]
        i=0, h=2: 2 > 1(栈顶) → right_boundary[0]=1, 入栈 0  栈:[0,1]
        right_boundary = [1, 6, 4, 4, 6, 6]

    面积计算：
        i=0: 2 × (1-(-1)-1) = 2 × 1 = 2
        i=1: 1 × (6-(-1)-1) = 1 × 6 = 6
        i=2: 5 × (4-1-1) = 5 × 2 = 10 ← 最大
        i=3: 6 × (4-2-1) = 6 × 1 = 6
        i=4: 2 × (6-1-1) = 2 × 4 = 8
        i=5: 3 × (6-4-1) = 3 × 1 = 3

    最大面积：10 ✓
    """
    n = len(heights)
    if n == 0:
        return 0

    left_boundary = [-1] * n
    right_boundary = [n] * n

    # 正序遍历，计算左边界（左边第一个比它小的）
    stack = []
    for i in range(n):
        # 弹出所有 >= heights[i] 的栈顶，因为它们不可能成为任何后续元素的左边界
        while stack and heights[stack[-1]] >= heights[i]:
            stack.pop()
        # 此时栈顶就是左边第一个比 heights[i] 小的下标
        left_boundary[i] = stack[-1] if stack else -1
        stack.append(i)

    # 逆序遍历，计算右边界（右边第一个比它小的）
    stack = []
    for i in range(n - 1, -1, -1):
        # 弹出所有 >= heights[i] 的栈顶
        while stack and heights[stack[-1]] >= heights[i]:
            stack.pop()
        # 此时栈顶就是右边第一个比 heights[i] 小的下标
        right_boundary[i] = stack[-1] if stack else n
        stack.append(i)

    result = 0
    for i in range(n):
        area = heights[i] * (right_boundary[i] - left_boundary[i] - 1)
        if area > result:
            result = area

    return result


# ══════════════════════════════════════════════════════════
# 解法四：单调栈（哨兵一次遍历）⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def largestRectangleArea(heights: list[int]) -> int:
    """单调栈（哨兵一次遍历）⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    在 heights 两端各插入一个 0 作为哨兵，保证最后所有柱子都能被弹栈结算。
    只需一次遍历，就能同时确定每根柱子的左边界和右边界。

    为什么哨兵是 0？
        哨兵 0 比任何柱子都矮，当遍历到它时，
        栈中所有剩余柱子都会被弹出来结算，
        且哨兵本身不会影响面积（0 × 宽度 = 0）。

    为什么一次遍历就够了？
        当栈顶 top 被弹出时：
        - 当前下标 i 就是 top 的右边界（右边第一个比它小的）
        - 弹出后的新栈顶就是 top 的左边界（左边第一个比它小的）
        所以弹栈时，top 的左右边界同时确定，可以直接算面积。

    算法步骤：
    1. 在 heights 末尾追加 0 作为右哨兵。
    2. 初始化栈，先放 -1 作为左哨兵（简化栈空判断）。
    3. 遍历 i = 0..n（包含追加的哨兵）：
       a. while heights[i] < heights[stack[-1]]：
           top = stack.pop()
           area = heights[top] * (i - stack[-1] - 1)
           更新最大值
       b. stack.append(i)
    4. 返回最大面积。

    时间复杂度：O(n) — 每个下标最多入栈一次、出栈一次。
    空间复杂度：O(n) — 栈最多保存 n+2 个下标（含哨兵）。

    图解示例：
    ────────────────────────────────────────────────────────
    heights = [2, 1, 5, 6, 2, 3]，追加哨兵后 = [2, 1, 5, 6, 2, 3, 0]

    步骤    i    h[i]   栈顶(top)  弹栈?  面积计算                       栈状态         result
    ───────────────────────────────────────────────────────────────────────────────────────────
    初始    -     -       -          -      -                            [-1]           0
    1       0     2      -1         否      -                            [-1, 0]        0
    2       1     1      0/h=2>1    是      top=0, area=2×(1-(-1)-1)=2   [-1]           2
                1     1      -1         否      -                            [-1, 1]        2
    3       2     5      1/h=1<5    否      -                            [-1, 1, 2]     2
    4       3     6      2/h=5<6    否      -                            [-1, 1, 2, 3]  2
    5       4     2      3/h=6>2    是      top=3, area=6×(4-2-1)=6      [-1, 1, 2]     6
                4     2      2/h=5>2    是      top=2, area=5×(4-1-1)=10   [-1, 1]        10
                4     2      1/h=1<2    否      -                            [-1, 1, 4]     10
    6       5     3      4/h=2<3    否      -                            [-1, 1, 4, 5]  10
    7       6     0      5/h=3>0    是      top=5, area=3×(6-4-1)=3      [-1, 1, 4]     10
                6     0      4/h=2>0    是      top=4, area=2×(6-1-1)=6      [-1, 1]        10
                6     0      1/h=1>0    是      top=1, area=1×(6-(-1)-1)=5   [-1]           10
                6     0      -1         否      -                            [-1, 6]        10

    最大面积：10 ✓
    """
    # 追加 0 作为右哨兵，保证所有柱子最终都会被弹栈结算
    heights_with_sentinel = heights + [0]
    n = len(heights_with_sentinel)
    if len(heights) == 0:
        return 0

    result = 0
    # 栈中先放 -1 作为左哨兵，简化"栈空"判断
    stack = [-1]

    for i in range(n):
        # 当前柱子比栈顶矮 → 栈顶柱子找到了右边界 i，进行结算
        while stack[-1] != -1 and heights_with_sentinel[i] < heights_with_sentinel[stack[-1]]:
            top = stack.pop()
            # 弹出 top 后，新的栈顶就是 top 的左边界
            width = i - stack[-1] - 1
            area = heights_with_sentinel[top] * width
            if area > result:
                result = area

        # 当前下标入栈，等待未来某个更矮的柱子来结算它
        stack.append(i)

    return result


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、单调栈（哨兵版）的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：哨兵单调栈算法能正确计算柱状图的最大矩形面积。
#
# 证明：
# （1）弹栈时左右边界确定：
#     当 top 因 heights[i] < heights[top] 被弹出时，
#     i 是 top 右边第一个比它矮的柱子（因为栈内保持递增，
#     i 之前没有任何比 heights[top] 矮的元素触发弹栈），
#     弹出 top 后的新栈顶 left 是 top 左边第一个比它矮的柱子
#     （同样因为栈内递增，left 和 top 之间没有更矮的柱子）。
#     所以 top 的左右边界同时确定，面积计算正确。
#
# （2）每个柱子都被结算一次：
#     右哨兵 0 保证最后所有柱子都会被弹栈。
#     左哨兵 -1 保证弹栈后栈永远不会空，left 始终有值。
#     每个下标入栈一次、出栈一次，不会重复计算或遗漏。
#
# （3）不会多算或少算：
#     面积公式 width = i - left - 1 恰好覆盖了 [left+1, i-1] 之间
#     所有 >= heights[top] 的柱子，这正是以 heights[top] 为高度的
#     最大矩形能延伸的范围。多一根太少，少一根也太少。
#
# （4）时间复杂度 O(n)：
#     虽然有 while 嵌套循环，但每个下标最多入栈一次、出栈一次，
#     总弹栈次数不超过 n，总操作次数 O(n)。
#
#
# 二、三种解法的对比与选择：
# ────────────────────────────────────────────────────────
#
# 维度              暴力              分治              单调栈
# ────────────────────────────────────────────────────────
# 时间复杂度        O(n²)            O(n log n)       O(n)
# 空间复杂度        O(1)             O(log n)          O(n)
# 代码简洁度        ⭐⭐⭐⭐⭐          ⭐⭐⭐             ⭐⭐
# 可扩展性          低               中               高
# 适用场景          教学入门          理解分治思想       工业级，单调栈经典
#
# 什么时候用哪个？
# - 学习单调栈：从"预计算边界数组"版本开始，再过渡到哨兵版。
# - 面试答题：直接上哨兵版，代码短、复杂度最优、逻辑清晰。
# - 遇到类似问题（如接雨水）：单调栈的核心思想是一致的——
#   利用栈维护一个有序序列，遇到破坏有序性的元素时结算历史。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 忘记加哨兵：
#    没有右哨兵，遍历结束后栈中还剩柱子没被结算。
#    要么手动再清理栈中剩余元素，要么直接加哨兵。
#    没有左哨兵，弹栈后栈为空时需要额外判断 left 是否存在。
#
# 2. 搞反比较条件：
#    要找"更小的"作为边界 → while heights[i] < heights[stack[-1]]。
#    如果写成 >，栈的单调性就反了，计算结果完全错误。
#    记忆口诀：找更小 → 递增栈，找更大 → 递减栈。
#
# 3. 宽度公式写错：
#    width = i - stack[-1] - 1，不是 i - top - 1 也不是 i - stack[-1]。
#    参考接雨水问题中的同款坑：左右边界柱子本身不计入宽度。
#
# 4. 弹栈后没有更新栈顶：
#    top = stack.pop() 之后，left = stack[-1]。
#    不要在 pop 之前取 left，也不要漏取导致用了旧的栈顶。
#
# 5. 边界数组版本中比较符号方向搞混：
#    计算 left_boundary 时弹栈条件是 heights[栈顶] >= heights[i]。
#    这里用 >= 是为了保证"严格更小"才成为边界。
#    如果用 >，高度相同的柱子会互相成为边界，导致面积算小。
#
# 6. 哨兵版本修改了原数组：
#    用 heights + [0] 创建新数组，而不是直接 append 修改原数组。
#    否则调用者的原始输入会被意外改变。
