"""
84. 柱状图中最大的矩形（Largest Rectangle in Histogram）

题目描述：
给定 n 个非负整数，用来表示柱状图中各个柱子的高度。每个柱子彼此相邻，且宽度为 1。
求在该柱状图中，能够勾勒出来的矩形的最大面积。

输入描述：
heights[i] 表示第 i 根柱子的高度，每根柱子的宽度均为 1。

输出描述：
返回能够勾勒出来的最大矩形面积。

输入示例 1：
heights = [2, 1, 5, 6, 2, 3]
输出示例 1：
10
解释：最大的矩形由柱子 5 和 6 组成，高度为 min(5,6)=5，宽度为 2，面积 = 5 × 2 = 10。

输入示例 2：
heights = [2, 4]
输出示例 2：
4
解释：选任意一根柱子，面积为 2 × 2 = 4。

输入示例 3：
heights = [2, 1, 2]
输出示例 3：
3
解释：以高度 1 跨越三根柱子，面积 = 1 × 3 = 3。

════════════════════════════════════════════════════════════════════════
核心概念：以每根柱子为高度，向两边扩展
════════════════════════════════════════════════════════════════════════

对于每根柱子 i，如果以它的高度 heights[i] 作为矩形的高度，
那么矩形的宽度最多能延伸到哪里？

    左边界 left_boundary[i]：左边第一个比 heights[i] 小的柱子的下标
    右边界 right_boundary[i]：右边第一个比 heights[i] 小的柱子的下标

    以 heights[i] 为高度的最大矩形面积：
        area[i] = heights[i] * (right_boundary[i] - left_boundary[i] - 1)

    最终答案 = max(area[0], area[1], ..., area[n-1])

为什么找"第一个更小"的柱子？
    因为以 heights[i] 为高度的矩形，必须跨越所有 >= heights[i] 的相邻柱子。
    一旦遇到比 heights[i] 小的柱子，就无法继续延伸了。
    所以边界就是"第一个比它小"的柱子。

与接雨水问题的对比：
────────────────────────────────────────────────────────────────────────
维度                接雨水 (LeetCode 42)          柱状图矩形 (LeetCode 84)
────────────────────────────────────────────────────────────────────────
核心问题            找凹槽 → 计算积水体积          找边界 → 计算矩形面积
边界条件            min(左边界, 右边界) - 底部     高度 × (右边界 - 左边界 - 1)
单调栈方向          单调递减栈（找更大的）          单调递增栈（找更小的）
弹栈时机            遇到更大的柱子                  遇到更小的柱子
弹栈含义            当前柱子 = 弹栈元素的右边界     当前柱子 = 弹栈元素的右边界
────────────────────────────────────────────────────────────────────────

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
暴力枚举左右边界               O(n²)           O(1)            ⭐ 双重循环
分治递归                      O(n log n)      O(log n)        ⭐⭐⭐ 递归栈
单调栈（预计算边界数组）       O(n)            O(n)            ⭐⭐⭐⭐ 思路清晰
单调栈（哨兵一次遍历）         O(n)            O(n)            ⭐⭐⭐⭐⭐ 推荐，最优
────────────────────────────────────────────────────────────────────────

核心思想（单调栈）：
────────────────────────────────────────────────────────────────────────
维护一个单调递增栈（栈底到栈顶的高度递增），栈中存储下标。

为什么是"递增"栈？
    我们要找"右边第一个比当前柱子小"的柱子作为右边界。
    当新元素比栈顶元素小时，栈顶元素的右边界就是当前元素。
    所以保持栈内高度递增，遇到更小的元素就弹栈结算。

算法步骤（哨兵版）：
    1. 在 heights 两端各插入一个哨兵高度 0，简化边界判断。
    2. 遍历每个下标 i：
       a. while heights[i] < heights[stack[-1]]：弹栈 top。
          top 的右边界 = i，左边界 = 新栈顶。
          area = heights[top] * (i - stack[-1] - 1)。
       b. 将 i 入栈。
    3. 返回最大面积。

图解示例：heights = [2, 1, 5, 6, 2, 3]
────────────────────────────────────────────────────────────────────────
完整流程见"解法四"的逐步推演表格。
关键步骤：
    i=4 (height=2) 时弹栈 3 (height=6)：area = 6×1 = 6
                   弹栈 2 (height=5)：area = 5×2 = 10 ← 最大值
    i=6 (height=0) 时弹栈 5 (height=3)：area = 3×1 = 3
                   弹栈 4 (height=2)：area = 2×3 = 6
                   弹栈 1 (height=1)：area = 1×5 = 5

结果：10 ✓
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力枚举左右边界
# ══════════════════════════════════════════════════════════


def largestRectangleArea_brute(heights: list[int]) -> int:
    """暴力枚举左右边界 ⭐

    核心思想：
    ────────────────────────────────────────────────────────
    对每根柱子 i，向左右扩展，找到第一个比它矮的柱子，
    以它的高度为矩形高度，扩展的宽度为矩形宽度，计算面积。

    算法步骤：
    1. 外层循环遍历每根柱子 i。
    2. left 向左扩展，直到遇到比 heights[i] 矮的柱子。
    3. right 向右扩展，直到遇到比 heights[i] 矮的柱子。
    4. 面积 = heights[i] * (right - left - 1)，更新最大值。

    时间复杂度：O(n²) — 最坏情况（柱子高度单调递增），
    第 i 根柱子需要向左扩展 i 步、向右扩展 n-1-i 步，总步数 O(n²)。
    空间复杂度：O(1) — 只用常数个变量。

    图解示例：
    ────────────────────────────────────────────────────────
    heights = [2, 1, 5, 6, 2, 3]

    i=0, h=2: 左边界=-1, 右边界=1(heights[1]=1<2)
              area = 2 × (1-(-1)-1) = 2 × 1 = 2
    i=1, h=1: 左边界=-1, 右边界=6(到末尾都 >=1)
              area = 1 × (6-(-1)-1) = 1 × 6 = 6
    i=2, h=5: 左边界=1(heights[1]=1<5), 右边界=4(heights[4]=2<5)
              area = 5 × (4-1-1) = 5 × 2 = 10 ← 目前最大
    i=3, h=6: 左边界=2(heights[2]=5<6), 右边界=4(heights[4]=2<6)
              area = 6 × (4-2-1) = 6 × 1 = 6
    i=4, h=2: 左边界=1(heights[1]=1<2), 右边界=6
              area = 2 × (6-1-1) = 2 × 4 = 8
    i=5, h=3: 左边界=4(heights[4]=2<3), 右边界=6
              area = 3 × (6-4-1) = 3 × 1 = 3

    最大面积：10 ✓
    """
    result = 0
    n = len(heights)

    for i in range(n):
        # 向左找第一个比 heights[i] 小的位置
        left = i
        while left >= 0 and heights[left] >= heights[i]:
            left -= 1

        # 向右找第一个比 heights[i] 小的位置
        right = i
        while right < n and heights[right] >= heights[i]:
            right += 1

        result = max(result, heights[i] * (right - left - 1))

    return result


