"""
两数相加（Add Two Numbers）

题目描述：
给你两个 非空 的链表，表示两个非负的整数。它们每位数字都是按照 逆序 的方式存储的，
并且每个节点只能存储 一位 数字。请你将两个数相加，并以相同形式返回一个表示和的链表。
你可以假设除了数字 0 之外，这两个数都不会以 0 开头。

输入描述：
两个非空链表 l1 和 l2，分别表示两个非负整数（逆序存储）

输出描述：
一个链表，表示两数之和（逆序存储）

输入示例：
l1 = [2,4,3], l2 = [5,6,4]
输出示例：
[7,0,8]
解释：342 + 465 = 807

════════════════════════════════════════════════════════════════════════
核心概念：链表模拟手工加法 + 进位处理
════════════════════════════════════════════════════════════════════════

核心思想类似于手工竖式加法：
    从低位到高位逐位相加，维护一个"进位"变量。
    链表本身是逆序存储，所以从头遍历就是从低位到高位，
    天然符合加法从低位算起的规则。

    逆序链表表示：
    [2→4→3] 表示数字 342（个位→十位→百位）
    [5→6→4] 表示数字 465

    竖式模拟：
        3 4 2   (l1，从左到右是个位、十位、百位)
    +   4 6 5   (l2)
    ─────────
        8 0 7   (结果链表 [7→0→8])

    关键点：
    1. 进位 carry：当某位之和 ≥ 10 时，进位为 1，当前位值为 sum % 10
    2. 链表长度不同时，短链表"走完后"补 0 继续算
    3. 两个链表都走完后，如果还有进位，需要额外补一个节点（值为 1）

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
多分支迭代法                    O(max(m,n))     O(max(m,n))     ⭐⭐⭐
统一迭代法（补0合并）             O(max(m,n))     O(max(m,n))     ⭐⭐⭐⭐ 推荐
递归法                          O(max(m,n))     O(max(m,n))     ⭐⭐⭐
────────────────────────────────────────────────────────────────────────

其中 m, n 分别为两个链表的长度。

核心思想（统一迭代法）：
────────────────────────────────────────────────────────────────────────
用一个循环统一处理所有情况：
    每轮取 l1 当前值（l1 为空则取 0），取 l2 当前值（l2 为空则取 0），
    加上进位 carry，计算当前位值和新的进位。
    循环条件为 l1 或 l2 或 carry 还有值。

初始条件：
    carry = 0（初始无进位）
    dummy_head 哑节点作为结果链表头部哨兵

最终答案：
    dummy_head.next 即为结果链表的头节点
"""

from typing import Optional


class ListNode:
    """链表节点定义"""
    def __init__(self, val=0, next=None):
        self.val = val      # 当前节点存储的数字（0-9）
        self.next = next    # 指向下一个节点的指针


# ══════════════════════════════════════════════════════════
# 解法一：多分支迭代法（原代码修复版）
# ══════════════════════════════════════════════════════════


def addTwoNumbers_multiBranch(l1: Optional[ListNode], l2: Optional[ListNode]) -> Optional[ListNode]:
    """
    多分支迭代法 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    根据两个链表是否还有节点，分三种情况处理：
    - 两个链表都有节点：两个值 + 进位 相加
    - 只有一个链表有节点：单个值 + 进位 相加
    - 两个链表都走完但仍有进位：补一个进位节点

    算法步骤：
    1. 创建哑节点 dummy_head 和游标 prev
    2. 循环遍历，根据 l1/l2 是否存在分三种情况处理
    3. 每次计算当前位值（sum % 10）和进位（sum // 10）
    4. 创建新节点，链接到结果链表
    5. 若循环结束后仍有进位，补一个节点

    时间复杂度：O(max(m,n)) — 遍历较长链表的所有节点
    空间复杂度：O(max(m,n)) — 结果链表最多 max(m,n)+1 个节点

    图解示例：
    ────────────────────────────────────────────────────────
    l1 = [2→4→3], l2 = [5→6→4], carry = 0

    第1轮: l1.val=2, l2.val=5, carry=0 → sum=7,  cur=7, carry=0
           结果: [7]        l1→4, l2→6

    第2轮: l1.val=4, l2.val=6, carry=0 → sum=10, cur=0, carry=1
           结果: [7→0]      l1→3, l2→4

    第3轮: l1.val=3, l2.val=4, carry=1 → sum=8,  cur=8, carry=0
           结果: [7→0→8]    l1→None, l2→None

    循环结束，carry=0，无需补节点。

    结果：[7→0→8] ✓
    """
    carry = 0                           # 进位值，初始为0
    dummy_head = ListNode(0)            # 哑节点，简化头节点处理
    prev = dummy_head                   # prev 指向结果链表的最后一个节点

    while l1 or l2:
        if l1 and l2:
            # 两个链表都有节点：两个值 + 进位 相加
            total = l1.val + l2.val + carry
            carry, cur_val = total // 10, total % 10   # 计算进位和当前位
            cur = ListNode(cur_val)                     # 创建新节点
            prev.next = cur                             # 链接到结果链表
            prev = cur                                  # 移动 prev
            l1 = l1.next                                # 移动 l1
            l2 = l2.next                                # 移动 l2
        elif l1:
            # 只有 l1 有节点
            total = l1.val + carry
            carry, cur_val = total // 10, total % 10
            cur = ListNode(cur_val)
            prev.next = cur
            prev = cur
            l1 = l1.next                                # 只移动 l1
        elif l2:
            # 只有 l2 有节点
            total = l2.val + carry
            carry, cur_val = total // 10, total % 10
            cur = ListNode(cur_val)
            prev.next = cur
            prev = cur
            l2 = l2.next  # ✅ 注意：是 l2 = l2.next，不是 l2.next = l2

    # 循环结束后，如果还有进位，需要额外补一个节点
    if carry:
        prev.next = ListNode(carry)

    return dummy_head.next


# ══════════════════════════════════════════════════════════
# 解法二：统一迭代法（补0合并分支）
# ══════════════════════════════════════════════════════════


def addTwoNumbers(l1: Optional[ListNode], l2: Optional[ListNode]) -> Optional[ListNode]:
    """
    统一迭代法 ⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    将三种分支情况统一为一种：当链表走完时，将其值视为 0。
    这样每轮循环的逻辑完全一致，代码更简洁，不易出错。

    关键洞察：
    - 链表为空时 val 取 0，等价于"补零"
    - 循环条件加上 carry，确保最后剩余进位也能被处理
    - 不再需要循环后的额外进位判断

    算法步骤：
    1. 创建哑节点和游标
    2. 循环条件：l1 或 l2 或 carry 任一非零
    3. 取 l1 当前值（空则取 0），取 l2 当前值（空则取 0）
    4. 三者相加，计算当前位值和进位
    5. 创建新节点并链接，移动 l1、l2 指针（非空时才移动）

    时间复杂度：O(max(m,n)) — 最多遍历 max(m,n)+1 轮
    空间复杂度：O(max(m,n)) — 结果链表最多 max(m,n)+1 个节点

    图解示例：
    ────────────────────────────────────────────────────────
    l1 = [2→4→3], l2 = [5→6→4], carry = 0

    第1轮: v1=2, v2=5, carry=0 → total=7,  cur=7, carry=0
           l1→4, l2→6          结果: [7]

    第2轮: v1=4, v2=6, carry=0 → total=10, cur=0, carry=1
           l1→3, l2→4          结果: [7→0]

    第3轮: v1=3, v2=4, carry=1 → total=8,  cur=8, carry=0
           l1→None, l2→None    结果: [7→0→8]

    第4轮: v1=0, v2=0, carry=0 → 循环条件不满足，退出

    结果：[7→0→8] ✓

    图解示例2（有进位溢出）：
    ────────────────────────────────────────────────────────
    l1 = [9→9→9→9→9→9→9], l2 = [9→9→9→9], carry = 0

    前4轮: 逐位相加，carry 累积
    第5-7轮: l2 走完，v2=0，l1 继续加 carry
    第8轮: l1 走完，v1=0, v2=0, carry=1 → total=1, cur=1, carry=0
           补一个节点 [1]

    结果：[8→9→9→9→0→0→0→1] ✓
    """
    carry = 0                           # 进位
    dummy_head = ListNode(0)            # 哑节点
    prev = dummy_head                   # 结果链表游标

    # 循环条件：l1 或 l2 或 carry 任一非零
    # ✅ 加上 carry 条件，循环内自动处理最后进位，无需循环后再判断
    while l1 or l2 or carry:
        # 取当前位的值，链表走完则取 0（等价于补零）
        v1 = l1.val if l1 else 0
        v2 = l2.val if l2 else 0

        # 三者相加：当前位值 + 进位
        total = v1 + v2 + carry

        # 计算当前位值和新的进位
        carry = total // 10             # 进位（0 或 1）
        cur_val = total % 10            # 当前位值（0-9）

        # 创建新节点并链接
        cur = ListNode(cur_val)
        prev.next = cur
        prev = cur

        # 移动链表指针（非空时才移动）
        l1 = l1.next if l1 else None
        l2 = l2.next if l2 else None

    return dummy_head.next


# ══════════════════════════════════════════════════════════
# 解法三：递归法
# ══════════════════════════════════════════════════════════


def addTwoNumbers_recursive(l1: Optional[ListNode], l2: Optional[ListNode]) -> Optional[ListNode]:
    """
    递归法 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    将"逐位相加"转化为递归问题：每次只处理当前位，
    然后对 next 指针递归调用，把进位传递下去。

    递归结构：
    addTwoNumbers(l1, l2, carry) =
        当前位节点(ListNode((l1.val + l2.val + carry) % 10))
        → next = addTwoNumbers(l1.next, l2.next, 新进位)

    算法步骤：
    1. 基本情况：l1、l2 都为空且 carry=0 → 返回 None
    2. 取当前位值（空则取 0），计算和、进位
    3. 创建当前位节点
    4. 递归处理 next，传入新的进位
    5. 将递归结果接到当前节点后面

    时间复杂度：O(max(m,n)) — 递归深度为 max(m,n)+1
    空间复杂度：O(max(m,n)) — 递归栈深度 + 结果链表

    图解示例：
    ────────────────────────────────────────────────────────
    l1 = [2→4→3], l2 = [5→6→4]

    递归展开：
    add(2→4→3, 5→6→4, carry=0)
      → total=7, cur=7, carry=0
      → next = add(4→3, 6→4, 0)
        → total=10, cur=0, carry=1
        → next = add(3, 4, 1)
          → total=8, cur=8, carry=0
          → next = add(None, None, 0) → None（基本情况）
          → 返回 [8]
        → 返回 [0→8]
      → 返回 [7→0→8]

    结果：[7→0→8] ✓
    """

    def helper(l1: Optional[ListNode], l2: Optional[ListNode], carry: int) -> Optional[ListNode]:
        """递归辅助函数，额外传入进位参数"""
        # 基本情况：两个链表都走完且无进位
        if not l1 and not l2 and carry == 0:
            return None

        # 取当前位值（空则取 0）
        v1 = l1.val if l1 else 0
        v2 = l2.val if l2 else 0

        # 计算和、当前位值、进位
        total = v1 + v2 + carry
        carry = total // 10
        cur_val = total % 10

        # 创建当前位节点
        cur = ListNode(cur_val)

        # 递归处理下一位，将进位传递下去
        next_l1 = l1.next if l1 else None
        next_l2 = l2.next if l2 else None
        cur.next = helper(next_l1, next_l2, carry)

        return cur

    return helper(l1, l2, 0)


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：给定两个逆序存储的非负整数链表 l1 和 l2，
# 上述算法能正确返回表示两数之和的逆序链表。
#
# 证明：
# （1）循环不变量：每轮循环开始时，carry 保存的是低位向当前位的进位
#     （0 或 1），prev 指向结果链表的最后一个已处理节点。
# （2）完备性：循环条件 while l1 or l2 or carry 确保所有位都被处理：
#     - l1 有剩余 → 继续处理 l1 的位
#     - l2 有剩余 → 继续处理 l2 的位
#     - carry=1 且链表都走完 → 补一个进位节点
# （3）正确性：每轮 total = v1 + v2 + carry，
#     由于 v1, v2 ∈ [0,9], carry ∈ {0,1}，total ∈ [0,19]，
#     cur_val = total % 10 ∈ [0,9]（合法的一位数字），
#     新 carry = total // 10 ∈ {0,1}（进位只能是 0 或 1），逻辑正确。
#
#
# 三种解法对比：
# ────────────────────────────────────────────────────────
#
# 维度          多分支迭代法          统一迭代法           递归法
# ───────────────────────────────────────────────────────────
# 代码长度       较长（3个分支）       简洁（1个分支）      简洁
# 可读性         一般                  高 ⭐               高
# 分支逻辑       l1&l2 / 仅l1 / 仅l2  统一处理             统一处理
# 进位处理       循环后单独判断         循环内自动处理       递归参数传递
# 栈空间         O(1)                  O(1)                 O(max(m,n))
# 适用场景       理解原理              推荐，最实用          理解递归思维
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. ❌ l2.next = l2  →  ✅ l2 = l2.next
#    错误原因：l2.next = l2 是把 l2 的 next 指向自己（自引用死循环），
#    正确做法是 l2 = l2.next（移动游标到下一个节点）。
#
# 2. ❌ 循环条件 while l1 or l2，循环内用 elif plus == 1 处理进位
#    →  ✅ 循环条件 while l1 or l2 or carry，或循环后单独判断 if carry
#    错误原因：当 l1、l2 都为 None 时，while l1 or l2 为 False，
#    elif plus == 1 分支永远不可达，最后的进位会丢失。
#    示例 3 中 [9,9,9,9,9,9,9] + [9,9,9,9] 的最高位进位 1 会丢失。
#
# 3. ❌ 忽略链表长度不同的情况
#    →  ✅ 短链表走完后，取值补 0 继续计算
#    错误原因：如果只在 l1 and l2 时循环，长的链表剩余位会丢失。
# ══════════════════════════════════════════════════════════
