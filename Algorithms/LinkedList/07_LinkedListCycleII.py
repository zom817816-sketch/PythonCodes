"""
142. 环形链表 II（Linked List Cycle II）

题目描述：
给定一个链表的头节点 head，返回链表开始入环的第一个节点。
如果链表无环，则返回 None。

如果链表中有某个节点，可以通过连续跟踪 next 指针再次到达该节点，
则链表中存在环。pos 是链表尾连接到链表中的位置（0-indexed）。
pos 不作为参数传递，仅用于标识环的存在。

注意：不允许修改链表。

输入描述：
一个链表头节点 head。
链表中节点数目范围 [0, 10^4]，-10^5 <= Node.val <= 10^5。

输出描述：
返回入环节点，无环返回 None。

输入示例 1：
head = [3, 2, 0, -4], pos = 1（尾节点 -4 连接到节点 2）
输出示例 1：
节点 2（值为 2 的节点）

输入示例 2：
head = [1, 2], pos = 0（尾节点 2 连接到节点 1）
输出示例 2：
节点 1

输入示例 3：
head = [1], pos = -1（无环）
输出示例 3：
null

════════════════════════════════════════════════════════════════════════
核心概念：快慢指针 + 数学推导
════════════════════════════════════════════════════════════════════════

分两步：① 判断是否有环  ② 找到入环节点

第一步：快慢指针判断有环
    slow 每次走 1 步，fast 每次走 2 步。
    如果有环，fast 一定会追上 slow（在环内相遇）。
    如果无环，fast 到达 None。

    ┌──────────────────────────────────────────────┐
    │  head → ... → 入环节点 → ... → 相遇点         │
    │         a        │←────── 环 ──────→│        │
    └──────────────────────────────────────────────┘
         a = 入口前距离    b = 入口到相遇点    c = 相遇点到入口

第二步：找入环节点（数学推导）
    相遇时：
        slow 走了 a + b 步
        fast 走了 a + b + n(b+c) 步（n 是圈数，至少 1）
    fast 速度是 slow 两倍：
        2(a + b) = a + b + n(b + c)
        a + b = n(b + c)
        a = n(b + c) - b = (n-1)(b + c) + c

    结论：a = (n-1) × 环长 + c
    即：从 head 走 a 步 = 从相遇点走 c 步 + 绕 (n-1) 圈
    所以让两个指针分别从 head 和相遇点出发，每次各走 1 步，
    它们一定在入环节点相遇！

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
哈希集合                      O(n)            O(n)            ⭐⭐ 直观
快慢指针                      O(n)            O(1)            ⭐⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想（快慢指针）：
────────────────────────────────────────────────────────────────────────
第一阶段：slow 和 fast 从 head 出发，slow 走 1 步，fast 走 2 步。
    有环则一定在环内某点相遇。
第二阶段：一个指针从 head 出发，另一个从相遇点出发，各走 1 步。
    它们相遇的位置就是入环节点。
"""


class ListNode:
    """链表节点定义"""

    def __init__(self, val: int = 0, next: "ListNode | None" = None):
        self.val = val
        self.next = next


# ══════════════════════════════════════════════════════════
# 解法一：哈希集合
# ══════════════════════════════════════════════════════════


def detectCycle_hashset(head: ListNode | None) -> ListNode | None:
    """哈希集合 ⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    遍历链表，用集合记录已访问的节点。
    第一次遇到已在集合中的节点就是入环节点。

    算法步骤：
    1. visited = set()。
    2. cur = head，遍历链表。
    3. 如果 cur 已在 visited 中，返回 cur（入环节点）。
    4. 否则 visited.add(cur)，cur = cur.next。
    5. 遍历结束（cur == None）返回 None（无环）。

    时间复杂度：O(n) — 每个节点访问一次。
    空间复杂度：O(n) — 哈希集合存储所有节点。

    图解示例：
    ────────────────────────────────────────────────────────
    head = 3 → 2 → 0 → -4 → (回到 2)

    visited: {3}
    visited: {3, 2}
    visited: {3, 2, 0}
    visited: {3, 2, 0, -4}
    cur = 2, 2 在 visited 中 → 返回节点 2 ✓
    """
    visited: set[ListNode] = set()
    cur = head

    while cur:
        if cur in visited:
            return cur  # 入环节点
        visited.add(cur)
        cur = cur.next

    return None  # 无环


# ══════════════════════════════════════════════════════════
# 解法二：快慢指针 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def detectCycle(head: ListNode | None) -> ListNode | None:
    """快慢指针 ⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    第一阶段：slow 走 1 步，fast 走 2 步，有环则在环内相遇。
    第二阶段：从 head 和相遇点各出发一个指针，每次走 1 步，
    相遇位置就是入环节点。

    数学推导：
        设 a = 入口前距离，b = 入口到相遇点距离，c = 相遇点到入口距离。
        相遇时 slow 走 a+b，fast 走 a+b+n(b+c)。
        2(a+b) = a+b+n(b+c) → a = (n-1)(b+c) + c。
        即从 head 走 a 步 = 从相遇点走 c 步再绕 (n-1) 圈。
        两个指针同步走 1 步，一定在入口相遇。

    算法步骤：
    1. slow = fast = head。
    2. while fast and fast.next:
       slow = slow.next, fast = fast.next.next。
       if slow == fast: 找到相遇点，跳出。
    3. 如果没有相遇（fast 到达 None），返回 None。
    4. p1 = head, p2 = slow（相遇点）。
    5. while p1 != p2: p1 = p1.next, p2 = p2.next。
    6. 返回 p1（入环节点）。

    时间复杂度：O(n) — 两阶段总步数不超过 3n。
    空间复杂度：O(1) — 只用常数指针。

    图解示例：
    ────────────────────────────────────────────────────────
    head = 3 → 2 → 0 → -4 → (回到 2)，pos = 1

    链表结构：
         3 → 2 → 0 → -4
             ↑__________|
        a=1  |b=1  |  c=2  |（环长 b+c=3）

    第一阶段（找相遇点）：
    步骤  slow  fast
    初始   3     3
    1      2     0
    2      0     2
    3     -4     -4  ← 相遇！

    第二阶段（找入口）：
    p1 = head = 3, p2 = -4
    p1=2, p2=2  ← 相遇在节点 2！

    返回节点 2 ✓
    """
    # ── 第一阶段：判断是否有环，找相遇点 ──
    slow = head
    fast = head

    while fast and fast.next:
        slow = slow.next  # 慢指针走 1 步
        fast = fast.next.next  # 快指针走 2 步

        if slow is fast:
            # 有环，进入第二阶段
            # ── 第二阶段：找入环节点 ──
            p1 = head  # 从头出发
            p2 = slow  # 从相遇点出发

            while p1 is not p2:
                p1 = p1.next  # 各走 1 步
                p2 = p2.next

            return p1  # 相遇点 = 入环节点

    return None  # 无环


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、快慢指针法的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理1（有环必相遇）：
#     如果链表有环，slow 和 fast 一定在环内相遇。
# 证明：
# （1）fast 比 slow 每轮多走 1 步。进入环后，两者的距离每轮缩小 1。
# （2）环的长度有限，距离一定会缩小到 0（相遇）。
#     不会"跳过"：距离从 d 变到 d-1，每次减 1，不会从 1 直接到 -1。
#
# 定理2（相遇点找入口）：
#     从 head 和相遇点各走 1 步，一定在入环节点相遇。
# 证明：
# （1）设 a = 入口前距离，b = 入口到相遇点，c = 相遇点到入口。
#     环长 = b + c。
# （2）相遇时：
#     slow 走了 a + b 步。
#     fast 走了 a + b + n(b + c) 步（n ≥ 1，fast 至少多绕一圈）。
# （3）fast 速度是 slow 的 2 倍：
#     2(a + b) = a + b + n(b + c)
#     a + b = n(b + c)
#     a = n(b + c) - b = (n-1)(b + c) + c
# （4）a = (n-1) × 环长 + c
#     即从 head 走 a 步 = 从相遇点走 c 步再绕 (n-1) 圈。
#     两个指针同步走 1 步，走 a 步后：
#     - p1 从 head 到入口（走了 a 步）。
#     - p2 从相遇点走 c 步到入口，再绕 (n-1) 圈回到入口。
#     两者在入口相遇。✓
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. slow 和 fast 初始都指向 head，第一次循环后就比较：
#    初始 slow == fast == head，但这是起点不是相遇点。
#    必须先各走一步再比较（while 内先走再 if）。
#
# 2. 忘记检查 fast 和 fast.next：
#    fast = fast.next.next 要求 fast 和 fast.next 都不为 None。
#    否则无环链表会空指针异常。
#
# 3. 第二阶段用 fast 而不是 slow：
#    相遇后 fast 可能已经被修改（如果循环后还有代码）。
#    应保存相遇点 slow，用新的 p1/p2 指针。
#
# 4. 原始 md 代码中的赋值错误：
#    if slow = fast: 应为 if slow == fast:（== 是比较，= 是赋值）。
# ══════════════════════════════════════════════════════════
