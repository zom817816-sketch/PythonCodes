"""
160. 相交链表（Intersection of Two Linked Lists）

题目描述：
给你两个单链表的头节点 headA 和 headB，请你找出并返回两个单链表相交的起始节点。
如果两个链表不存在相交节点，返回 None。

注意：相交是指从某个节点开始，两条链表共享同一段后缀。
题目保证整个链式结构中不存在环。函数返回结果后，链表必须保持其原始结构。

输入描述：
两个链表头节点 headA 和 headB。
listA 中节点数目为 m，listB 中节点数目为 n，0 <= m, n <= 3 * 10^4。

输出描述：
返回相交节点，不相交返回 None。

输入示例 1：
headA = [4, 1, 8, 4, 5], headB = [5, 6, 1, 8, 4, 5]
（节点 8 开始相交，共享 8 -> 4 -> 5）
输出示例 1：
Intersected at '8'

输入示例 2：
headA = [1, 9, 1, 2, 4], headB = [3, 2, 4]
（节点 2 开始相交，共享 2 -> 4）
输出示例 2：
Intersected at '2'

输入示例 3：
headA = [2, 6, 4], headB = [1, 5]
（不相交）
输出示例 3：
null

════════════════════════════════════════════════════════════════════════
核心概念：路径等长法
════════════════════════════════════════════════════════════════════════

相交链表的特点：从交点开始，两条链表共享同一段后缀。
    listA: a1 → a2 → a3 ↘
                          c1 → c2 → c3 → None
    listB: b1 → b2 ↗

    交点之前：listA 有 a 个节点，listB 有 b 个节点（a ≠ b）。
    交点之后：共享 c 个节点。

核心洞察：
    如果 pA 走完 listA 后切换到 listB，pB 走完 listB 后切换到 listA，
    两者走过的总路程都是 a + b + c，因此一定在交点同步相遇！

    pA 路径: a1 → a2 → a3 → c1 → c2 → c3 → None → b1 → b2 → c1（相遇！）
    pB 路径: b1 → b2 → c1 → c2 → c3 → None → a1 → a2 → a3 → c1（相遇！）

    如果不相交：pA 和 pB 都走 a + b 步后同时到达 None，循环结束返回 None。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
哈希集合                      O(m+n)          O(m)            ⭐⭐ 直观
长度差对齐                     O(m+n)          O(1)            ⭐⭐⭐⭐ 思路清晰
双指针路径等长                 O(m+n)          O(1)            ⭐⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想（双指针路径等长）：
────────────────────────────────────────────────────────────────────────
pA 和 pB 分别从 headA 和 headB 出发。
pA 到达 None 时切换到 headB，pB 到达 None 时切换到 headA。
两条路径长度相等（a+b+c），一定在交点相遇。
不相交时，都走 a+b 步同时到达 None，退出循环返回 None。
"""


class ListNode:
    """链表节点定义"""

    def __init__(self, val: int = 0, next: "ListNode | None" = None):
        self.val = val
        self.next = next


# ══════════════════════════════════════════════════════════
# 解法一：长度差对齐
# ══════════════════════════════════════════════════════════


def getIntersectionNode_len(
    headA: ListNode | None, headB: ListNode | None
) -> ListNode | None:
    """长度差对齐 ⭐⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    先分别计算两条链表的长度，让长链表先走差值步，
    然后两条链表同步前进，第一个相同的节点就是交点。

    算法步骤：
    1. 计算 lenA 和 lenB。
    2. 长链表先走 |lenA - lenB| 步。
    3. 同步前进，直到 pA == pB 或都为 None。

    时间复杂度：O(m+n) — 两趟遍历。
    空间复杂度：O(1)。

    图解示例：
    ────────────────────────────────────────────────────────
    listA: 4 → 1 ↘
                   8 → 4 → 5 → None
    listB: 5 → 6 → 1 ↗

    lenA = 5, lenB = 6, diff = 1
    headB 先走 1 步到 6

    对齐后同步前进:
      pA=4, pB=6 → pA=1, pB=1 → pA=8, pB=8（相遇！）
    返回节点 8 ✓
    """
    # 计算两条链表长度
    lenA, lenB = 0, 0
    pA, pB = headA, headB
    while pA:
        lenA += 1
        pA = pA.next
    while pB:
        lenB += 1
        pB = pB.next

    # 长链表先走差值步
    pA, pB = headA, headB
    diff = abs(lenA - lenB)
    if lenA > lenB:
        for _ in range(diff):
            pA = pA.next
    else:
        for _ in range(diff):
            pB = pB.next

    # 同步前进，找交点
    while pA and pB:
        if pA is pB:
            return pA
        pA = pA.next
        pB = pB.next

    return None


# ══════════════════════════════════════════════════════════
# 解法二：双指针路径等长 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def getIntersectionNode(
    headA: ListNode | None, headB: ListNode | None
) -> ListNode | None:
    """双指针路径等长 ⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    pA 从 headA 出发，走完 listA 后切换到 headB。
    pB 从 headB 出发，走完 listB 后切换到 headA。
    两者走过的总路程相同（a+b+c），一定在交点同步相遇。

    不相交时：pA 和 pB 都走 a+b 步后同时到达 None，退出返回 None。

    算法步骤：
    1. pA = headA, pB = headB。
    2. while pA != pB:
       a. pA = pA.next if pA else headB（pA 到末尾后切换到 headB）
       b. pB = pB.next if pB else headA（pB 到末尾后切换到 headA）
    3. 返回 pA（交点或 None）。

    时间复杂度：O(m+n) — 最多走两趟。
    空间复杂度：O(1)。

    图解示例：
    ────────────────────────────────────────────────────────
    listA: 4 → 1 ↘                    (a=2)
                   8 → 4 → 5 → None  (c=3)
    listB: 5 → 6 → 1 ↗               (b=3)

    pA 路径: 4 → 1 → 8 → 4 → 5 → None → 5 → 6 → 1 → 8（相遇！）
             |--  listA  --|          |-- listB 独有 --|
             共走 a+c+b = 2+3+3 = 8 步到交点

    pB 路径: 5 → 6 → 1 → 8 → 4 → 5 → None → 4 → 1 → 8（相遇！）
             |--  listB  --|          |-- listA 独有 --|
             共走 b+c+a = 3+3+2 = 8 步到交点

    两人在交点 8 相遇 ✓

    不相交的情况：
    pA: 2 → 6 → 4 → None → 1 → 5 → None（pA=None, pB=None, 退出）
    pB: 1 → 5 → None → 2 → 6 → 4 → None（同时到达 None）
    返回 None ✓
    """
    pA = headA
    pB = headB

    while pA is not pB:
        # pA 到末尾后切换到 headB，否则前进一步
        pA = pA.next if pA else headB
        # pB 到末尾后切换到 headA，否则前进一步
        pB = pB.next if pB else headA

    return pA


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、双指针路径等长法的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：双指针法在相交时返回交点，不相交时返回 None。
#
# 证明（相交情况）：
# （1）设 listA 独有 a 个节点，listB 独有 b 个节点，共享 c 个节点。
# （2）pA 路径：a 个独有 → c 个共享 → None → b 个独有 → 交点。
#     总步数 = a + c + 1 + b = a + b + c + 1 步到达交点。
# （3）pB 路径：b 个独有 → c 个共享 → None → a 个独有 → 交点。
#     总步数 = b + c + 1 + a = a + b + c + 1 步到达交点。
# （4）步数相同，pA 和 pB 同时到达交点，pA == pB，返回交点。✓
#
# 证明（不相交情况）：
# （1）listA 有 a 个节点，listB 有 b 个节点。
# （2）pA 路径：a → None → b → None，共 a + b + 1 步到 None。
# （3）pB 路径：b → None → a → None，共 b + a + 1 步到 None。
# （4）同时到达 None，pA == pB == None，返回 None。✓
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 用值比较而不是引用比较：
#    if pA.val == pB.val → 两个不同节点可能有相同值。
#    必须用 if pA is pB（引用相等）。
#
# 2. 长度差对齐法忘记处理不等长：
#    如果两条链表等长，diff = 0，不跳过任何节点，直接同步前进。正确。
#    但如果忘记对齐，同步前进会错过交点。
#
# 3. 哈希集合法的额外空间：
#    哈希集合法将 listA 所有节点存入 set，然后遍历 listB 查找。
#    时间 O(m+n) 但空间 O(m)，不如双指针法优。
#
# 4. 误解"相交"的含义：
#    相交不是"值相同"，而是"同一个节点对象"。
#    从交点开始，两条链表共享同一段后缀（包括 next 指针）。
# ══════════════════════════════════════════════════════════
