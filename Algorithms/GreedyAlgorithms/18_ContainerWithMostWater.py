"""
盛最多水的容器（Container With Most Water）

题目描述：
给定一个长度为 n 的整数数组 height 。有 n 条垂线，第 i 条线的两个端点是 (i, 0) 和 (i, height[i])。
找出其中的两条线，使得它们与 x 轴共同构成的容器可以容纳最多的水。
返回容器可以储存的最大水量。
说明：你不能倾斜容器。

输入描述：
    height：长度为 n 的整数数组，n >= 2，0 <= height[i] <= 10^4

输出描述：
    返回容器可以储存的最大水量（整数）。

输入示例：
    height = [1,8,6,2,5,4,8,3,7]
输出示例：
    49
    解释：选择第 2 条线（高度 8）和第 9 条线（高度 7），
    容器宽度 = 9 - 2 = 7，高度 = min(8, 7) = 7，面积 = 7 * 7 = 49。

════════════════════════════════════════════════════════════════════════
核心概念：本题 vs 接雨水（LeetCode 42）
════════════════════════════════════════════════════════════════════════

    维度            本题（盛最多水的容器）        接雨水（LeetCode 42）
    ────────────    ─────────────────────────    ─────────────────────────
    水的形态        两条线之间的"一整块"          每个位置上方的"累计水柱"
    水量决定因素    min(h[i], h[j]) * (j - i)     sum(min(左边最高, 右边最高) - h[i])
    关键洞察        宽度缩小 → 必须增高才有戏      每格水量由两侧最大值较小者决定
    最优解法        双指针（贪心收缩）             双指针 / 单调栈 / DP 预处理

    本题的关键洞察：
    面积 = min(h[left], h[right]) * (right - left)。
    初始时宽度最大，指针内移只会让宽度变小，
    因此想让面积变大，唯一希望是"短板变长"——
    这正是贪心的决策依据：每次移动较矮的那一侧。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
解法一：暴力枚举所有线对        O(n²)            O(1)            ⭐⭐⭐
解法二：双指针（贪心收缩）      O(n)             O(1)            ⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想（双指针 + 贪心）：
────────────────────────────────────────────────────────────────────────
    1. 初始 left = 0, right = n-1，此时容器宽度最大。
    2. 每轮记录当前面积，然后移动较矮一侧的指针：
       - 宽度必然减小，若想找到更大面积，必须让 min(高度) 增大；
       - 较矮一侧是短板，保留它并与更远的线配对不可能超过当前面积；
       - 只有移动短板，才可能遇到更高的线。
    3. 两指针相遇时结束，过程中记录的最大面积即答案。
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力枚举所有线对
# ══════════════════════════════════════════════════════════


def maxArea_bruteforce(height: list[int]) -> int:
    """
    暴力枚举⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    枚举每一对线 (i, j)，直接套用面积公式取最大值。

    算法步骤：
    1. 双重循环枚举所有线对 (i, j)，i < j。
    2. 面积 = min(height[i], height[j]) * (j - i)。
    3. 维护全局最大面积。

    时间复杂度：O(n²) — 所有可能的线对共 n(n-1)/2 个。
    空间复杂度：O(1) — 只用了常数个变量。

    图解示例：
    ────────────────────────────────────────────────────────
    height = [1,8,6,2,5,4,8,3,7]
    枚举部分关键线对：
        (0,8): min(1,7)*8 = 8
        (1,8): min(8,7)*7 = 49  ← 最大
        (1,6): min(8,8)*5 = 40
        (2,8): min(6,7)*6 = 36
    结果：49 ✓
    """
    n = len(height)
    if n < 2:
        return 0

    max_area = 0
    for i in range(n):
        for j in range(i + 1, n):
            # 高度由短板决定，宽度为下标之差
            area = min(height[i], height[j]) * (j - i)
            max_area = max(max_area, area)
    return max_area


# ══════════════════════════════════════════════════════════
# 解法二：双指针（贪心收缩）
# ══════════════════════════════════════════════════════════


def maxArea(height: list[int]) -> int:
    """
    双指针 + 贪心⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    从"最宽"的容器开始，每次移动较矮一侧的指针。
    内移使宽度减小，唯一可能让面积变大的方式是
    弥补短板——所以放弃短板一侧是安全的（贪心）。

    算法步骤：
    1. 初始化 left = 0，right = n - 1，max_area = 0。
    2. 循环直到两指针相遇：
       a. 计算当前面积并更新 max_area；
       b. 若 height[left] < height[right]，left 右移；
          否则 right 左移（移动较矮一侧）。
    3. 返回 max_area。

    时间复杂度：O(n) — 每轮恰好有一个指针内移，总共 n-1 轮。
    空间复杂度：O(1) — 只用了常数个变量。

    图解示例：
    ────────────────────────────────────────────────────────
    height = [1,8,6,2,5,4,8,3,7]（下标 0~8）

    轮次  left  right  面积 = min(h[l],h[r])*(r-l)   max_area  移动
    ──────────────────────────────────────────────────────────
     1     0(1)   8(7)   min(1,7)*8 =  8               8       h[0]<h[8]，left→1
     2     1(8)   8(7)   min(8,7)*7 = 49 ← 峰值       49       h[1]>h[8]，right→7
     3     1(8)   7(3)   min(8,3)*6 = 18              49       h[1]>h[7]，right→6
     4     1(8)   6(8)   min(8,8)*5 = 40              49       h[1]<=h[6]，right→5
     5     1(8)   5(4)   min(8,4)*4 = 16              49       right→4
     6     1(8)   4(5)   min(8,5)*3 = 15              49       right→3
     7     1(8)   3(2)   min(8,2)*2 =  4              49       right→2
     8     1(8)   2(6)   min(8,6)*1 =  6              49       right→1
    两指针相遇，结束。

    结果：49 ✓
    """
    n = len(height)
    if n < 2:
        return 0

    max_area = 0
    left, right = 0, n - 1  # 从最宽的容器开始

    while left < right:
        # 当前面积：高度取短板，宽度为两指针间距
        area = min(height[left], height[right]) * (right - left)
        max_area = max(max_area, area)

        # 贪心决策：移动较矮一侧，才有机会遇到更高的线
        if height[left] < height[right]:
            left += 1
        else:
            right -= 1

    return max_area


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：双指针算法能找到最大水量的容器。
#
# 证明（反证法 + 归纳）：
# （1）不失一般性，设最优解为线对 (i*, j*)，且 height[i*] <= height[j*]。
# （2）关键引理：若 height[left] < height[right]，则线 left 与任何
#      k ∈ (left, right] 配对的面积都不超过当前面积 area(left, right)。
#      因为宽度 (k - left) < (right - left)，且高度
#      min(height[left], height[k]) <= height[left] = min(height[left], height[right])，
#      宽度与高度都不占优，故 area(left, k) <= area(left, right)。
#      —— 所以移动 left 不会丢掉任何比当前更优的解。
# （3）因此每次移动只会排除"不可能优于当前记录值"的线对；
#      最优线对 (i*, j*) 在它某一侧被排除之前始终存活。
#      当指针首次到达 i*（或 j*）时，另一侧指针若尚未越过其配对端点，
#      按引理被跳过的都是劣解，指针不会跳过 (i*, j*) 这个组合；
#      于是算法必然枚举到 (i*, j*) 并更新 max_area。
# （4）综上，算法结束时 max_area 即为全局最大面积。∎
#
# 直观理解：宽度在收缩是"确定性损失"，短板高度是"唯一变量"，
# 贪心把每一次移动都花在"有可能改善短板"的方向上，不浪费任何机会。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 移动较高一侧的指针：
#    例如 [1, 100, 2, 100, 1]，若移动高侧可能错过
#    (1,3) 这对组合（面积 100 * 2 = 200）。
#    正确做法：始终移动较矮一侧。
# 2. 面积公式写错：
#    宽度是下标之差 (j - i)，不是 height 之差或 j - i + 1。
# 3. 先移动再记录面积：
#    若在更新 max_area 之前就移动指针，会漏掉当前这一轮的组合。
#    正确顺序：先计算并更新面积，再移动指针。
# 4. 两指针同时移动：
#    例如 h[left] == h[right] 时同时内移看似"更快"，
#    但 [2,3,4,4,3] 中 (0,4) 面积为 8，同时移动会错过 (1,3) 之后
#    的正确比较顺序，虽然该例答案不变，却破坏了正确性证明的前提，
#    在某些构造输入下会得到错误答案。
# 5. 与"接雨水"（LeetCode 42）混淆：
#    本题求两条线围成的最大矩形水量，接雨水求所有凹槽的累计水量，
#    二者的面积模型完全不同，解法不能混用。
# ══════════════════════════════════════════════════════════
