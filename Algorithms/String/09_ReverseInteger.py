"""
整数反转（Reverse Integer）

题目描述：
    给你一个 32 位的有符号整数 x ，返回将 x 中的数字部分反转后的结果。
    如果反转后整数超过 32 位的有符号整数的范围 [−2³¹,  2³¹ − 1] ，就返回 0。
    假设环境不允许存储 64 位整数（有符号或无符号）。

输入描述：
    一个 32 位有符号整数 x（取值范围 -2³¹ ≤ x ≤ 2³¹ - 1）

输出描述：
    反转后的整数；若反转结果溢出 32 位则返回 0

输入示例 1：
    x = 123
    输出：321

输入示例 2：
    x = -123
    输出：-321

输入示例 3：
    x = 120
    输出：21       （反转后前导零自动消失）

输入示例 4：
    x = 0
    输出：0

输入示例 5（边界溢出）：
    x = 1534236469  (反转后为 9646324351，超过 2³¹-1 = 2147483647)
    输出：0

════════════════════════════════════════════════════════════════════════
核心概念：32 位有符号整数的边界与"逐位反转 + 提前溢出检查"
════════════════════════════════════════════════════════════════════════

32 位有符号整数的范围（以 10 进制展示）：
    下界  INT_MIN = -2³¹ = -2147483648
    上界  INT_MAX =  2³¹ - 1 =  2147483647

    上界按位分解：   2  1  4  7  4  8  3  6  4  7
    各位数值：       2, 1, 4, 7, 4, 8, 3, 6, 4, 7

    关键事实：
    ┌─────────────────────────────────────────────────────────────┐
    │ INT_MAX // 10 =  214748364                                  │
    │ INT_MAX % 10  =  7                                         │
    │ INT_MIN // 10 = -214748364  （注意 Python "//" 向下取整）  │
    │ INT_MIN % 10  = -8                                         │
    └─────────────────────────────────────────────────────────────┘

    在反转过程中，若已累积的结果 rev 比 INT_MAX // 10 还大，或恰好
    相等但下一位 pop 出的数 > 7，则反转后必然溢出。同理对 INT_MIN。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
字符串法（转 str 反转）        O(log|x|)        O(log|x|)        最直观
数学法（pop/push + 提前溢出）  O(log|x|)        O(1)             ⭐⭐⭐⭐ 推荐
栈模拟法（用 list 做栈）       O(log|x|)        O(log|x|)        教学性
纯数学（事后溢出检查）         O(log|x|)        O(1)             不严格符合题意
────────────────────────────────────────────────────────────────────────

核心思想（数学 pop/push 法）：
────────────────────────────────────────────────────────────────────────
    反转十进制数 x 的本质是：反复从 x 末尾"弹出"一位（x % 10），
    然后"压入"到结果 rev 的末尾（rev = rev * 10 + pop）。

    算法：
        rev = 0
        while x != 0:
            pop = x % 10
            x //= 10
            if rev > INT_MAX // 10 or (rev == INT_MAX // 10 and pop > 7):
                return 0           # 即将溢出
            if rev < INT_MIN // 10 or (rev == INT_MIN // 10 and pop < -8):
                return 0           # 即将下溢
            rev = rev * 10 + pop
        return rev

    符号处理技巧：x 本身用 Python 的 // 和 % 时，负数会自然带符号
    进入 pop，所以不需要单独 sign 标志位。
"""
# ══════════════════════════════════════════════════════════
# 解法一：字符串法
# ══════════════════════════════════════════════════════════


def reverse_str(x: int) -> int:
    """
    字符串法 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    把整数转成字符串后用切片 [::-1] 反转，再转回整数。这种写法
    依赖 Python 的任意精度整数与字符串处理；可读性最好但不符合
    "不允许 64 位整数"的约束（Python 内部其实是任意精度）。

    算法步骤：
    1. 记录符号 sign
    2. abs(x) 转字符串 -> 反转 -> int() 自动去前导零
    3. 乘回符号
    4. 溢出检查（-2³¹, 2³¹-1）

    时间复杂度：O(log|x|) — 与位数成正比
    空间复杂度：O(log|x|) — 中间字符串

    图解示例（x = -123）：
    ────────────────────────────────────────────────────────
    sign = -1
    abs(-123) = 123
    str(123)   = "123"
    [::-1]     = "321"
    int("321") = 321
    321 * (-1) = -321  ✓

    边界示例（x = 120）：
    str(120) = "120"
    [::-1]   = "021"
    int("021") = 21  （int() 自动忽略前导零）✓

    注意：严格来说，本方法不满足"环境不允许 64 位整数"的约束，
    仅在 Python/JS 等有任意精度或大整数的语言中可写。面试中如
    题目强调此约束，请使用解法二。
    """
    # 边界：x == 0 直接返回 0
    if x == 0:
        return 0

    INT_MIN, INT_MAX = -2**31, 2**31 - 1

    sign = -1 if x < 0 else 1
    reversed_str = str(abs(x))[::-1]      # 字符串反转
    result = int(reversed_str) * sign     # int() 自动忽略前导零

    # 32 位有符号整数溢出检查
    if result < INT_MIN or result > INT_MAX:
        return 0
    return result


# ══════════════════════════════════════════════════════════
# 解法二：数学 pop/push 法（提前溢出检查）⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def reverse(x: int) -> int:
    """
    数学 pop/push 法（提前溢出检查）⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    模仿"出栈入栈"的过程，每一轮从 x 末尾弹出一位数字，追加到
    结果 rev 的末尾。在每次 push 之前判断 rev*10 + pop 是否会超
    出 32 位范围，从而不需要 64 位临时变量。

    算法步骤：
    1. rev = 0
    2. while x != 0：
       a. pop = x % 10           # 弹出末尾
       b. x  = x // 10            # 截掉末尾
       c. 溢出检查（见下）
       d. rev = rev * 10 + pop    # 推入末尾
    3. 返回 rev

    溢出检查的推导：
    设 INT_MAX = 2*10^9 + ...，它的前 9 位是 INT_MAX // 10 = 214748364。
    推入前若 rev > INT_MAX // 10，则 rev*10 必 ≥ 2147483650 > INT_MAX。
    推入前若 rev == INT_MAX // 10，只有当 pop ≤ 7 时才不会溢出。
    对 INT_MIN 同理：// 10 向下取整 = -214748364，% 10 = -8。

    时间复杂度：O(log|x|) — 循环次数 = 位数
    空间复杂度：O(1) — 仅用常数个变量

    图解示例（x = 123）：
    ────────────────────────────────────────────────────────
    sign = 1，x = 123
    轮次  x   pop  rev        溢出检查
    初始  123  -   0
    1     12   3   0*10+3=3   0 < 214748364 → OK
    2     1    2   3*10+2=32  3 < 214748364 → OK
    3     0    1   32*10+1=321 32 < 214748364 → OK
    返回 1 * 321 = 321 ✓

    图解示例（x = -123）：
    ────────────────────────────────────────────────────────
    sign = -1，x = 123
    轮次  x   pop  rev
    初始  123  -   0
    1     12   3   3
    2     1    2   32
    3     0    1   321
    返回 -1 * 321 = -321 ✓

    溢出示例（x = 1534236469）：
    ────────────────────────────────────────────────────────
    翻转过程中当 rev 累积到 964632435，再 pop = 1 时：
        rev > INT_MAX // 10 (214748364) → 触发上溢判断
    返回 0 ✓
    """
    INT_MIN, INT_MAX = -2**31, 2**31 - 1

    # 先用 sign 标志位记录符号，然后对 |x| 做 pop/push。
    # 之所以不直接对负数做，是因为 Python 的 // 和 % 是"向下取整"：
    #   -1 // 10 == -1,  -1 % 10 == 9
    # 这会导致循环无法终止（-1 永远除不尽 10）。统一用 |x| 处理
    # 可避开此陷阱，也更易读。
    sign = -1 if x < 0 else 1
    x = abs(x)
    rev = 0
    while x != 0:
        # 对正数做取模与整除，行为与 C/Java 一致
        pop = x % 10
        x //= 10

        # 提前溢出检查：判断 rev * 10 + pop 是否会超出 32 位
        # 上界检查
        if rev > INT_MAX // 10:
            return 0
        if rev == INT_MAX // 10 and pop > 7:
            return 0
        # 下界检查
        if rev < INT_MIN // 10:
            return 0
        if rev == INT_MIN // 10 and pop < -8:
            return 0

        rev = rev * 10 + pop

    return sign * rev


