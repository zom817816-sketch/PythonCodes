# 解法三：栈模拟法
# ══════════════════════════════════════════════════════════


def reverse_stack(x: int) -> int:
    """
    栈模拟法 ⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    把数字逐位"压栈"再"出栈"，直观对应反转过程。仍属于 O(log|x|)
    空间思路，适合作为教学示例，实际工程中更推荐解法二。

    算法步骤：
    1. 把 x 的每一位压入栈 digits（用 list）
    2. 依次弹出栈顶，按顺序组成新数
    3. 中途检测溢出

    时间复杂度：O(log|x|)
    空间复杂度：O(log|x|) — 栈空间

    图解示例（x = 123）：
    ────────────────────────────────────────────────────────
    压栈：digits = [1, 2, 3]  （注意先压高位，最后压低位）
          等价于 digits = [3, 2, 1]（如果一边压一边立即出栈）
    出栈顺序：3, 2, 1
    累加：0*10+3=3 → 3*10+2=32 → 32*10+1=321 ✓
    """
    INT_MIN, INT_MAX = -2**31, 2**31 - 1

    # 边界
    if x == 0:
        return 0

    sign = -1 if x < 0 else 1
    x = abs(x)

    # 压栈：低位先入栈（这样出栈时就是高位在前）
    digits = []
    while x > 0:
        digits.append(x % 10)
        x //= 10

    # 出栈重组
    rev = 0
    for d in digits:
        # 同样的提前溢出检查
        if rev > INT_MAX // 10:
            return 0
        if rev == INT_MAX // 10 and d > 7:
            return 0
        rev = rev * 10 + d

    return sign * rev


# ══════════════════════════════════════════════════════════
# 解法四：纯数学（事后溢出检查）
# ══════════════════════════════════════════════════════════


def reverse_post_check(x: int) -> int:
    """
    纯数学（事后溢出检查）⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    与解法二同样基于 pop/push，但只在循环结束后对 rev 做一次溢出
    判断。代码更短，但因为 rev 本身已经是 Python 任意精度整数，
    严格来说也没满足"不允许 64 位整数"的约束；只是写法上比字符
    串法更接近题意的"32 位限制"精神。

    算法步骤：
    1. 循环 pop/push 累加 rev
    2. 循环结束后判断 rev 是否在 [INT_MIN, INT_MAX] 内
    3. 溢出则返回 0，否则返回 rev

    时间复杂度：O(log|x|)
    空间复杂度：O(1)

    适用场景：当语言/环境允许任意精度整数时，可以用更简洁的写法
    替代字符串法，同时比解法二少几个分支。
    """
    INT_MIN, INT_MAX = -2**31, 2**31 - 1

    sign = -1 if x < 0 else 1
    x = abs(x)

    rev = 0
    while x != 0:
        rev = rev * 10 + x % 10
        x //= 10

    rev *= sign

    # 事后溢出检查
    if rev < INT_MIN or rev > INT_MAX:
        return 0
    return rev


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明（以解法二 pop/push 法为例）：
# ────────────────────────────────────────────────────────
#
# 定理：reverse(x) 返回 x 的十进制反转，且当结果溢出 32 位时返回 0。
#
# 证明：
# （1）循环不变式
#     设 inv = "x 剩余部分" + rev 拼接成的十进制数。
#     初始：x = x₀，rev = 0，inv = x₀ + 0 = x₀
#     迭代：取出 pop = x % 10（x 的最低位），x //= 10。
#         此时 "x 剩余部分" 比原 x 少一位最低位。
#         rev 变为 rev*10 + pop，相当于把 pop 拼到 rev 的右侧。
#         所以 inv 仍然保持不变。
#     终止：x == 0，inv = "" + rev = rev，输出 rev。
#
# （2）符号正确性
#     实现中我们先取 sign = -1 if x < 0 else 1，再令 x = abs(x)
#     之后才对正数 x 做 pop/push。Python 的 // 和 % 对正数与 C/Java
#     行为一致；对负数先用 abs 转为正数即可避开取整方向差异。
#     循环结束后返回 sign * rev，从而带正确的符号。
#     验证：x = -123 → sign = -1, |x| = 123, 内部反转为 321,
#     最终 -1 * 321 = -321 ✓
#
# （3）溢出判断的完备性
#     推入前 rev ∈ [INT_MIN // 10, INT_MAX // 10] 范围之外 → 必溢出
#     rev == INT_MAX // 10 时，只允许 pop ≤ 7，否则 10*rev+pop > INT_MAX
#     rev == INT_MIN // 10 时，只允许 pop ≥ -8，否则 10*rev+pop < INT_MIN
#     推入后 rev ∈ [INT_MIN, INT_MAX]，因为我们排除了所有溢出情况。
#
# 综合（1）~（3）：算法正确。证毕。
#
#
# Python 负数取模的注意点：
# ────────────────────────────────────────────────────────
#   Python 的 // 是向下取整（floor），% 总与除数同号：
#       7  //  2  ==  3,   7  %  2 ==  1
#      -7  //  2  == -4,  -7  %  2 ==  1   （商的负号决定）
#      -7  // -2  ==  3,  -7  % -2 == -1
#   关键恒等式：a == (a // b) * b + (a % b)
#
#   在本算法的 pop/push 循环中，这会带来一个严重问题：
#       -1 // 10 == -1   （不会变成 0）
#       -1 % 10  ==  9   （不是 -1）
#   因此若直接对负数 x 做 while x != 0: x //= 10，循环永远不会
#   终止（-1 → -1 → -1 → ...）。即使终止，累积的 rev 也会是错
#   误的正数（因为 pop 总是非负）。
#
#   解决方案：本文件解法二、四采用 "sign 标志位 + abs(x)" 的策
#   略，对正数做取模与整除（与 C/Java 行为一致），最后再乘回
#   符号。这是从 C/Java 迁移到 Python 时最容易踩的坑之一。
#   这一点在 C++/Java 等"截断取整"语言中行为不同（那里 pop 会
#   带负号、自然累积为负数），迁移时务必留意。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 0. 【Python 陷阱】直接对负数做 x % 10 与 x // 10：Python 的整除
#    是"向下取整"（floor），不是"截断取零"：
#        -1 // 10 == -1  （不是 0！循环不会终止）
#        -1 % 10  ==  9  （不是 -1！是 9）
#    这会让 x 一直停留在 -1，while x != 0 进入死循环。正确做法
#    是先取 abs(x) 并用 sign 标志位记下符号，最后再乘回去。
#    这一点在 C/C++/Java 中是相反的（截断取零：-1 / 10 == 0，
#    -1 % 10 == -1），迁移算法时务必留意。
#
# 1. 字符串法不满足"无 64 位整数"约束：在 C/C++/Java 等语言中
#    long long 是 64 位，long long rev = 0; rev = rev*10 + pop;
#    可以"暂时"用 64 位来存，最后再判断是否 > INT_MAX。但题目
#    显式说不允许，所以正确做法是解法二的"提前溢出检查"。
#
# 2. 溢出边界值算错：INT_MAX // 10 = 214748364，末位允许值是 7；
#    INT_MIN // 10 = -214748364（向下取整得到），末位允许值是
#    -8（不是 -7！）。常见错误是把 INT_MIN % 10 写成 -7。
#    实际上 Python 中 -2**31 // 10 == -214748364，
#    -2**31  % 10 == -8，验证：-214748364*10 + (-8) = -2147483648。
#
# 3. 忽略 x == 0 的情况：0 反转还是 0。如果不特判，字符串法会
#    得到 "-0" 等不必要的中间状态；数学法会直接退出循环返回 0，
#    无问题。
#
# 4. 前导零未处理：x = 120 应返回 21 不是 021。int("021") == 21
#    自动处理；用纯 pop/push 时由于我们按位运算，前导 0 不会
#    累积到 rev 中。
#
# 5. 负数处理遗漏符号：x = -123 必须返回 -321 而不是 321。
#    字符串法靠 sign 标志位；纯数学法靠 abs(x) + 末尾 sign*rev。
#    C++/Java 里如果用截断取整的语义，pop 会带负号，自然累积为
#    负数；Python 必须显式 sign。
#
# 6. 提前溢出检查的"等于"分支漏写：必须判断
#    "rev == INT_MAX // 10 且 pop > 7"这一情形；只判断
#    "rev > INT_MAX // 10"会漏掉恰好等于边界的情况。
# ══════════════════════════════════════════════════════════
