"""
字符串转换整数 (atoi)（String to Integer (atoi)）

题目描述：
请你来实现一个 myAtoi(string s) 函数，使其能将字符串转换成一个 32 位有符号整数。
函数 myAtoi(string s) 的算法如下：
1. 空格：读入字符串并丢弃无用的前导空格（" "）
2. 符号：检查下一个字符（假设还未到字符末尾）为 '-' 还是 '+'。
   如果两者都不存在，则假定结果为正。
3. 转换：读取整数，直到遇到非数字字符或到达字符串的结尾。
   如果没有读取数字，则结果为 0。
4. 舍入：如果整数超过 32 位有符号整数范围 [−2³¹, 2³¹ − 1]，
   需要截断这个整数，使其保持在这个范围内。
   具体来说，小于 −2³¹ 的整数应该被舍入为 −2³¹，
   大于 2³¹ − 1 的整数应该被舍入为 2³¹ − 1。
返回整数作为最终结果。

注意：
- 本题只处理前导空格 ' '，不处理制表符、换行符等其他空白字符
- 只允许一个符号位，符号位只能出现在数字之前（以及前导空格之后）

输入描述：
一个字符串 s，可能包含前导空格、符号位、数字、非数字字符

输出描述：
一个 32 位有符号整数

输入示例：
s = "42"
输出示例：
42

输入示例：
s = "   -042"
输出示例：
-42

输入示例：
s = "1337c0d3"
输出示例：
1337
解释：读到 'c' 时停止，返回 1337

输入示例：
s = "0-1"
输出示例：
0
解释：读到 '-' 时停止，返回 0（符号位只能出现在最前面）

════════════════════════════════════════════════════════════════════════
核心概念：逐字符状态机 + 溢出检查
════════════════════════════════════════════════════════════════════════

本题本质上是一个有限状态机（FSM）：
    状态：等待空格 → 等待符号 → 读取数字 → 结束
    字符类型：' '、'+/-'、'0-9'、其他字符

状态转换表：
────────────────────────────────────────────────────────────────
当前状态        ' '         +/-         0-9         其他
────────────────────────────────────────────────────────────────
等待空格        等待空格    等待数字    读取数字    结束
等待数字        结束        结束        读取数字    结束
读取数字        结束        结束        读取数字    结束
结束            结束        结束        结束        结束
────────────────────────────────────────────────────────────────

溢出检查原理：
    32 位有符号整数范围：[-2¹⁴⁷⁴⁸³⁶⁴⁸, 2¹⁴⁷⁴⁸³⁶⁴⁷]
    每次 result * 10 + digit 之前，先检查是否会溢出：

    正数溢出条件：
        result > INT_MAX // 10  → 乘10 必溢出
        result == INT_MAX // 10 且 digit > 7 → 加 digit 后溢出

    负数溢出条件：
        result < INT_MIN // 10  → 乘10 必溢出
        result == INT_MIN // 10 且 digit > 8 → 加 digit 后溢出

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
单指针顺序扫描法               O(n)            O(1)            ⭐⭐⭐⭐ 推荐
正则表达式提取法                O(n)            O(n)            ⭐⭐⭐
────────────────────────────────────────────────────────────────────────
其中 n 为字符串长度。

核心思想（单指针扫描）：
────────────────────────────────────────────────────────────────────────
用一个指针 i 逐字符扫描，依次经历三个阶段：
1. 跳过前导空格（仅 ' '）
2. 读取一个符号位（可选，只能有一个）
3. 逐位读取数字，每步检查溢出，遇到非数字立即停止
"""


# ══════════════════════════════════════════════════════════
# 解法一：单指针顺序扫描法（推荐）
# ══════════════════════════════════════════════════════════


def myAtoi(s: str) -> int:
    """
    单指针顺序扫描法 ⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    严格按题目算法四步走：
      跳前导空格 → 读符号位 → 读数字（每步溢出检查）→ 返回截断值
    不使用 strip、lstrip 等会跳过多个字符的函数，逐字符控制。

    为什么不先用 strip()？
      题目明确只处理前导空格 ' '，不处理 '\t'、'\n' 等其他空白，
      s.strip() 会把这些都去掉，不符合题意。
      另外，符号位 '+' '-' 必须出现在前导空格之后、数字之前，
      用 strip() + lstrip('0') 的组合很容易处理错顺序。

    算法步骤：
    1. i = 0 指向当前字符，跳过所有 s[i] == ' '
    2. 读符号位：s[i] 为 '+' 或 '-' 时记录 sign，i += 1
    3. 循环读取数字：
       - 非数字字符 break
       - 每步检查 *10 后是否溢出，溢出直接截断到边界
    4. 返回 sign * result

    时间复杂度：O(n) — 单次扫描
    空间复杂度：O(1) — 只用几个变量

    图解示例（s = "   -042"）：
    ────────────────────────────────────────────────────────
    i=0, ch=' ' → 跳过，i=1
    i=1, ch=' ' → 跳过，i=2
    i=2, ch=' ' → 跳过，i=3
    i=3, ch='-' → sign=-1, i=4
    i=4, ch='0' → result=0*10+0=0, i=5
    i=5, ch='4' → result=0*10+4=4, i=6
    i=6, ch='2' → result=4*10+2=42, i=7 → 结束
    返回 sign * result = -1 * 42 = -42 ✓

    图解示例（s = "1337c0d3"）：
    ────────────────────────────────────────────────────────
    i=0, ch='1' → sign=1, result=1
    i=1, ch='3' → result=13
    i=2, ch='3' → result=133
    i=3, ch='7' → result=1337
    i=4, ch='c' → 非数字，break
    返回 1 * 1337 = 1337 ✓

    图解示例（s = "0-1"）：
    ────────────────────────────────────────────────────────
    i=0, ch='0' → sign=1, result=0
    i=1, ch='-' → 非数字，break
    返回 1 * 0 = 0 ✓
    """
    n = len(s)
    i = 0                                    # 当前扫描下标

    # ── 第 1 步：跳过前导空格（只处理 ' '，不处理 \t \n 等）──
    while i < n and s[i] == ' ':
        i += 1

    # 如果已经到末尾，直接返回 0
    if i >= n:
        return 0

    # ── 第 2 步：读取符号位（只允许一个）──
    sign = 1                                 # 默认正数
    if s[i] == '+':
        sign = 1
        i += 1
    elif s[i] == '-':
        sign = -1
        i += 1

    # ── 第 3 步：读取数字，每步检查溢出 ──
    INT_MAX = 2 ** 31 - 1                    # 2147483647
    INT_MIN = -2 ** 31                       # -2147483648
    result = 0

    while i < n and s[i].isdigit():          # 只处理 ASCII 数字字符
        digit = int(s[i])

        # ⚠️ 溢出检查（正数和负数用同一套上界，因为 sign 最后统一乘）
        # 如果 result * 10 + digit > INT_MAX，则溢出
        if result > INT_MAX // 10 or (result == INT_MAX // 10 and digit > 7):
            # 溢出截断：正数截断到 INT_MAX，负数截断到 INT_MIN
            return INT_MAX if sign == 1 else INT_MIN

        result = result * 10 + digit
        i += 1

    # ── 第 4 步：返回结果 ──
    return sign * result


# ══════════════════════════════════════════════════════════
# 解法二：正则表达式提取法
# ══════════════════════════════════════════════════════════


def myAtoi_regex(s: str) -> int:
    """
    正则表达式提取法 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    用正则表达式一次性提取出符合规则的整数前缀，
    再 int() 转换并做范围截断。代码简洁，
    但需要理解正则匹配的贪心规则。

    正则规则：
        ^[\s]*        — 匹配开头 0 个或多个空白字符
        [+-]?         — 可选的符号位
        \d+           — 1 个或多个数字
        没有用 $，因为后面可以跟非数字字符（自动停止）

    为什么用 ^[\s]* 而不是严格按题目只匹配 ' '？
      Python 中 re.match 的 \s 会匹配 \t \n 等，但本题
      测试用例只出现空格，可通过所有用例。若严格区分，
      可改用 ^[ ]* 只匹配空格字符。

    算法步骤：
    1. 用正则提取匹配的前缀子串
    2. 如果没匹配到（没有任何数字），返回 0
    3. int() 转换后按 INT_MIN/MAX 截断返回

    时间复杂度：O(n) — 正则扫描 + int 转换
    空间复杂度：O(n) — 正则匹配产生中间子串

    图解示例（s = "   -042abc"）：
    ────────────────────────────────────────────────────────
    正则匹配 "   -042" → int → -42 → 在范围内
    返回 -42 ✓

    图解示例（s = "words and 987"）：
    ────────────────────────────────────────────────────────
    正则从开头开始匹配，'w' 既非空白也非符号也非数字
    没有匹配到 → 返回 0 ✓
    """
    import re

    INT_MAX = 2 ** 31 - 1
    INT_MIN = -2 ** 31

    # 匹配：开头任意空白 + 可选符号 + 连续数字
    # 用 match 从字符串开头匹配
    match = re.match(r'^[ ]*([+-]?\d+)', s)

    if not match:
        return 0                               # 没有匹配到合法数字

    num = int(match.group(1))                  # 提取并转换

    # 截断到 32 位有符号整数范围
    if num > INT_MAX:
        return INT_MAX
    if num < INT_MIN:
        return INT_MIN
    return num


