# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：单指针扫描法能按题目规则正确返回 32 位有符号整数。
#
# 证明：
# （1）前导空格处理正确性：内层 while 只跳过 s[i] == ' '，
#     符合题目只处理前导空格的要求，不会误跳过 \t \n 等其他空白。
# （2）符号位处理正确性：只有一个 if/elif 判断，处理完立即 i += 1，
#     所以最多只会读取一个符号位。后面的 '-' 会被视为非数字停止，
#     因此 "0-1" 正确返回 0。
# （3）数字读取正确性：while s[i].isdigit() 保证只处理 '0'-'9'，
#     遇到任何非数字立即 break，符合"读到非数字字符停止"的规则。
# （4）溢出检查正确性：
#     - 当 result > INT_MAX // 10 → result * 10 ≥ INT_MAX + 1，必溢出
#     - 当 result == INT_MAX // 10 且 digit > 7 → 正数超过 2147483647，
#       负数超过 -2147483648（-2147483648 的个位是 8），统一用 digit>7 判断
#       因为 sign=-1 且 digit=8 时，实际值 = -2147483648 恰好等于 INT_MIN，
#       但我们的判断把它归为溢出返回 INT_MIN，结果恰好正确。
#
#
# 原代码 Bug 汇总与修复：
# ────────────────────────────────────────────────────────
#
# 1. ❌ s1 = s.strip().lstrip("0") 处理顺序错误
#    正确做法：先跳空格 → 读符号 → 再读数字，不能先把 '0' 都去掉
#    反例：s = "0-1" 经过 strip().lstrip("0") 变成 "-1"，直接 int 返回 -1，
#    但正确答案是 0（因为 '-' 在数字 '0' 之后，不算合法数字部分）。
#
# 2. ❌ 缺少非数字字符停止逻辑
#    正确做法：读取数字时遇到非数字立即停止，不能直接用 int(s1)
#    反例：s = "1337c0d3" 中 'c' 不是数字，应返回 1337，原代码直接 int 会抛异常。
#
# 3. ❌ 溢出范围写成 2**32
#    正确做法：32 位有符号整数范围是 [-2³¹, 2³¹-1] = [-2147483648, 2147483647]
#    原代码写成 2**32-1 和 -2**32 差了整整一位，上限是 4294967295 而非 2147483647。
#
# 4. ❌ s.strip() 误处理非空格空白
#    正确做法：只跳过 s[i] == ' '，不要用 strip()
#    strip() 会去掉 \t \n \r 等，不符合题目"丢弃无用的前导空格"的明确定义。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. ❌ 溢出判断写成 result * 10 + digit > INT_MAX 之后才截断
#    → ✅ 在乘加之前先判断
#    原因：result * 10 本身可能在某些语言中就溢出绕回（C++），
#    Python 虽然不会绕回，但题目要求"舍入"，所以要提前检查。
#
# 2. ❌ 符号位判断放在 while 循环里，导致"++123" 或 "+-123" 被误读
#    → ✅ 符号位只判断一次，读到数字后就不能再处理符号
#    反例：s = "+-12"，若符号位判断放在数字循环里，会把 '-' 也当成符号位，
#    正确答案是 0（'+' 之后 '-' 不是数字，停止，没有读到任何数字）。
#
# 3. ❌ 用 lstrip('0') 处理前导零
#    → ✅ 前导零不需要特殊处理，0 * 10 + 0 + 0 + 4 + 2 = 42 自然消零
#    原因：lstrip('0') 会把 "0000" 变成 ""，导致返回 0 虽然结果正确，
#    但会干扰符号位的判断（比如 "-0001" 变成 "-1" 没问题，
#    但 "0-1" 会变成 "-1"，顺序错乱）。
# ══════════════════════════════════════════════════════════
