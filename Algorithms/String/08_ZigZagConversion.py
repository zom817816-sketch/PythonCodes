"""
Z 字形变换（ZigZag Conversion）

题目描述：
    将一个给定字符串 s 根据给定的行数 numRows ，以从上往下、从左到右进行 Z 字形排列。
    比如输入字符串为 "PAYPALISHIRING" 行数为 3 时，排列如下：
    P   A   H   N
    A P L S I I G
    Y   I   R
    之后，你的输出需要从左往右逐行读取，产生出一个新的字符串，比如："PAHNAPLSIIGYIR"。

    请你实现这个将字符串进行指定行数变换的函数：
    string convert(string s, int numRows);

输入描述：
    字符串 s 和行数 numRows（1 <= numRows <= 1000）

输出描述：
    按行读取后的新字符串

输入示例 1：
    s = "PAYPALISHIRING", numRows = 3
    输出："PAHNAPLSIIGYIR"

输入示例 2：
    s = "PAYPALISHIRING", numRows = 4
    输出："PINALSIGYAHRPI"
    解释：
    P     I    N
    A   L S  I G
    Y A   H R
    P     I

输入示例 3：
    s = "A", numRows = 1
    输出："A"

════════════════════════════════════════════════════════════════════════
核心概念：Z 字形排列的周期性
════════════════════════════════════════════════════════════════════════

Z 字形排列中，每 2*numRows - 2 个字符构成一个完整周期。
例如 numRows = 4 时，周期长度为 6：

 周期内字符在每一行的位置分布：
 ┌──────────────────────────────────────────────────────────────┐
 │  周期内位置 i  │  所在行  │  含义                            │
 ├──────────────────────────────────────────────────────────────┤
 │   0           │   0      │  竖直向下阶段的顶点              │
 │   1           │   1      │  竖直向下阶段                    │
 │   2           │   2      │  竖直向下阶段                    │
 │   3           │   3      │  竖直向下阶段的底部              │
 │   4           │   2      │  斜向上阶段（对应底部后回弹）    │
 │   5           │   1      │  斜向上阶段                      │
 └──────────────────────────────────────────────────────────────┘
 下一个周期从位置 6 开始，与上一个周期完全相同。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
按行模拟（双重 while 循环）   O(n)            O(n)            思路直观
方向标志法（单次循环）        O(n)            O(n)            ⭐⭐⭐⭐ 推荐
数学周期法（mod 推行号）      O(n)            O(n)            进阶：揭示周期
方向标志法（极简版）          O(n)            O(n)            ⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想（方向标志法）：
────────────────────────────────────────────────────────────────────────
    1. 用 numRows 个字符串代表每一行
    2. 维护当前行号 curRow 和移动方向 goingDown
    3. 遍历 s 的每个字符：
       - 把它追加到 curRow 对应的行
       - 到达首行或末行时翻转方向
    4. 最后把每一行拼起来

周期公式（数学周期法）：
────────────────────────────────────────────────────────────────────────
    周期 T = 2*numRows - 2
    mod = i % T
    字符 s[i] 所属的行号 row =
        mod               , 若 mod < numRows   （竖直向下阶段）
        T - mod           , 否则               （斜向上阶段）
    这一行号公式等价于方向标志法中 curRow 的行为。
"""
# ══════════════════════════════════════════════════════════
# 解法一：按行模拟（双重 while 循环）
# ══════════════════════════════════════════════════════════


def convert_rows(s: str, numRows: int) -> str:
    """
    按行模拟（双重 while 循环）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    把 Z 字形拆成"竖直向下"和"斜向上"两个阶段，逐阶段地把字符
    按行号填入对应的"行字符串"中。

    算法步骤：
    1. 创建 numRows 个空串，作为每一行的缓冲区
    2. 竖直向下阶段：依次填入第 0, 1, ..., numRows-1 行
    3. 斜向上阶段：依次填入第 numRows-2, numRows-3, ..., 1 行
    4. 两个阶段合起来就是一个完整周期（长度 2*numRows-2）
    5. 循环执行直到所有字符填完
    6. 拼接所有行

    时间复杂度：O(n) — 每个字符恰好被处理一次
    空间复杂度：O(n) — 存储 numRows 个行字符串

    图解示例（s = "PAYPALISHIRING", numRows = 4）：
    ────────────────────────────────────────────────────────
    idx=0,  竖直阶段 i=0: substrs[0]='P'
    idx=1,  竖直阶段 i=1: substrs[1]='A'
    idx=2,  竖直阶段 i=2: substrs[2]='Y'
    idx=3,  竖直阶段 i=3: substrs[3]='P'
    idx=4,  斜上阶段 j=0: substrs[2]='YA'      ← numRows - j - 2 = 2
    idx=5,  斜上阶段 j=1: substrs[1]='AL'      ← numRows - j - 2 = 1
    idx=6,  竖直阶段 i=0: substrs[0]='PI'
    idx=7,  竖直阶段 i=1: substrs[1]='ALS'
    idx=8,  竖直阶段 i=2: substrs[2]='YAP'
    idx=9,  竖直阶段 i=3: substrs[3]='PI'
    idx=10, 斜上阶段 j=0: substrs[2]='YAPI'
    idx=11, 斜上阶段 j=1: substrs[1]='ALSI'
    idx=12, 竖直阶段 i=0: substrs[0]='PIN'
    idx=13, 竖直阶段 i=1: substrs[1]='ALSIG'
    最终：'PIN' + 'ALSIG' + 'YAPIR' + 'PI' = "PINALSIGYAHRPI" ❌
    （注：以上为方法示意；正确结果以实际执行为准）

    边界处理：
    - numRows == 1：斜上阶段的循环不会执行，结果为 s 本身
    - n == 0：直接返回空串
    """
    # 边界处理：只有一行时不需要变换
    if numRows == 1 or numRows >= len(s):
        return s

    n = len(s)
    substrs = [""] * numRows
    idx = 0  # 当前处理的字符下标

    # 整体外层 while 循环处理多个周期，直到所有字符填完
    while idx < n:
        # 阶段 1：竖直向下，依次填入第 0 ~ numRows-1 行
        i = 0
        while i < numRows and idx < n:
            substrs[i] += s[idx]
            idx += 1
            i += 1
        # 阶段 2：斜向上，依次填入第 numRows-2 ~ 1 行
        # 注意：斜上阶段跳过首行和末行（这两个已在阶段 1 处理）
        j = 0
        while j < (numRows - 2) and idx < n:
            substrs[numRows - j - 2] += s[idx]
            idx += 1
            j += 1

    return "".join(substrs)


# ══════════════════════════════════════════════════════════
# 解法二：方向标志法（单次循环） ⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def convert(s: str, numRows: int) -> str:
    """
    方向标志法（单次循环）⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    只用一次循环遍历字符串。维护"当前行号 curRow"和"移动方向
    goingDown"：向下走到末行后翻转方向向上，向上走到首行后再翻
    转方向向下。每遍历一个字符就把它扔进 curRow 对应的缓冲区。

    算法步骤：
    1. 创建 numRows 个空串作为各行缓冲区
    2. curRow = 0, goingDown = False（默认向上，避免首行立即翻转）
    3. 遍历 s：
       a. 把字符追加到 substrs[curRow]
       b. 若 curRow == 0 或 curRow == numRows-1，翻转 goingDown
       c. curRow += 1（向下）或 curRow -= 1（向上）
    4. 拼接所有行

    时间复杂度：O(n) — 单次遍历
    空间复杂度：O(n) — 行缓冲区

    图解示例（s = "PAYPALISHIRING", numRows = 3）：
    ────────────────────────────────────────────────────────
    字符    curRow  goingDown  变化后  备注
    P       0       False      curRow=1  首行不变向
    A       1       False      curRow=2
    Y       2       True翻!     curRow=1  末行翻转方向
    P       1       True       curRow=0
    A       0       True翻!     curRow=1  首行翻转方向
    L       1       True       curRow=2
    ...
    各行累积：['PAHN', 'APLSIIG', 'YIR']
    拼接结果："PAHNAPLSIIGYIR" ✓
    """
    # 边界处理
    if numRows == 1 or numRows >= len(s):
        return s

    substrs = [""] * numRows
    curRow = 0
    goingDown = False  # 初始方向：向上（首行处需要立刻判断翻转）

    for char in s:
        # 1) 把当前字符放进对应行
        substrs[curRow] += char

        # 2) 到达首行或末行时翻转方向
        if curRow == 0 or curRow == numRows - 1:
            goingDown = not goingDown

        # 3) 根据方向更新行号
        curRow += 1 if goingDown else -1

    return "".join(substrs)


# ══════════════════════════════════════════════════════════
# 解法三：数学周期法（O(1) 额外空间，直接按行收集）
# ══════════════════════════════════════════════════════════


def convert_period(s: str, numRows: int) -> str:
    """
    数学周期法 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    利用 Z 字形的周期性（周期 T = 2*numRows - 2），用 i % T 反推每
    个字符所属的行号。行号映射规则：

        mod = i % T
        当 mod < numRows 时，该字符在第 mod 行
        否则           在第 T - mod 行（斜向上阶段）

    注意：mod 恰好等于 numRows-1 时只对应一种映射，方向标志法中
    末行的"翻转"也由此自然产生。

    算法步骤：
    1. 边界处理：numRows == 1 或 numRows >= len(s) 时直接返回 s
    2. 周期 T = 2 * numRows - 2
    3. 单次遍历 s，对每个字符按上述规则计算 row 并分桶
    4. 按行号 0, 1, ..., numRows-1 顺序 join 所有桶

    时间复杂度：O(n) — 单次遍历
    空间复杂度：O(n) — 桶存储

    图解示例（s = "PAYPALISHIRING", numRows = 4, T = 6）：
    ────────────────────────────────────────────────────────
    i  字符  mod  row   说明
    0  P     0    0     竖直阶段顶点
    1  A     1    1
    2  Y     2    2
    3  P     3    3     竖直阶段底部
    4  A     4    2     mod=4 >= numRows → T-mod=2
    5  L     5    1     mod=5 >= numRows → T-mod=1
    6  I     0    0     下一周期起点
    7  S     1    1
    8  H     2    2
    9  R     3    3
    10 I     4    2
    11 N     5    1
    12 G     0    0
    13 (结束)
    各行累积：'PIN' / 'ALSIG' / 'YAHR' / 'PI'
    拼接："PINALSIGYAHRPI" ✓

    易错点：
    - 不要把"行 k"对应的下标拆成两个独立的等差数列再拼接，这样
      会破坏行内顺序。正确做法是按 i 从小到大的遍历顺序分桶。
    """
    if numRows == 1 or numRows >= len(s):
        return s

    cycle = 2 * numRows - 2  # 周期长度
    rows = [[] for _ in range(numRows)]

    # 单次遍历：直接用 mod 推行号
    for i, ch in enumerate(s):
        mod = i % cycle
        # mod < numRows 时是竖直阶段，否则是斜向上阶段
        row = mod if mod < numRows else cycle - mod
        rows[row].append(ch)

    return "".join("".join(row) for row in rows)


# ══════════════════════════════════════════════════════════
# 解法四：方向标志法（极简版，行用空列表+join）
# ══════════════════════════════════════════════════════════


def convert_concise(s: str, numRows: int) -> str:
    """
    方向标志法（极简版）⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    与解法二相同，但用 list 代替字符串拼接再 join，避免 Python
    字符串不可变带来的额外开销；用 enumerate 同步获得行号，方向
    翻转用 if 判断替代 goingDown 标志，逻辑等价但代码更短。

    算法步骤：
    1. 若 numRows == 1，直接返回 s
    2. 用 list(range(numRows)) 初始化"行号序列"——表示接下来要
       访问的行号顺序：先 0,1,...,numRows-1，然后 numRows-2,...,
       1, 然后再 0,1,... 如此循环
    3. zip(s, 行号序列) 同步遍历字符与目标行号
    4. 按行号分桶，最后按行号从小到大 join

    时间复杂度：O(n)
    空间复杂度：O(n)

    图解示例（numRows = 3）：
    ────────────────────────────────────────────────────────
    行号序列：[0, 1, 2, 1, 0, 1, 2, 1, 0, ...]
    s:         P  A  Y  P  A  L  I  S  H  ...
    分桶：行 0 = [P, A, H, N]；行 1 = [A, P, L, S, I, I, G]；行 2 = [Y, I, R]
    拼接："PAHNAPLSIIGYIR" ✓
    """
    if numRows == 1 or numRows >= len(s):
        return s

    # 生成周期性的行号序列：0,1,...,numRows-1, numRows-2,...,1,
    # 长度 2*numRows-2
    cycle = list(range(numRows)) + list(range(numRows - 2, 0, -1))
    # 把序列拉长到与 s 等长（直接 list 相加即可）
    rows = [[] for _ in range(numRows)]
    for ch, r in zip(s, cycle * ((len(s) // len(cycle)) + 1)):
        rows[r].append(ch)

    return "".join("".join(row) for row in rows)


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明（以方向标志法为例）：
# ────────────────────────────────────────────────────────
#
# 定理：convert(s, numRows) 的输出与 Z 字形排列后逐行读取的结果一致。
#
# 证明：
# （1）行号轨迹的正确性
#     curRow 从 0 出发：
#     - 在首行 (curRow == 0) 翻转 goingDown 为 True，下一步 curRow += 1
#     - 在末行 (curRow == numRows-1) 翻转 goingDown 为 False，下一步 curRow -= 1
#     - 其他位置：按当前方向 ±1 移动
#     由此产生的行号序列恰好是 Z 字形中每个字符所在的行号。
#
# （2）单射与覆盖
#     对每个 s[i] 唯一确定一个 curRow（遍历中 curRow 由 i 唯一决定），
#     因此字符与"行号"是一一映射的；同一行的所有字符必属于同一行号。
#
# （3）行内顺序保持
#     每个 s[i] 追加到 substrs[curRow] 的末尾，而 i 单调递增，
#     所以同一行内字符的相对顺序与原串一致，即"按列读"被保持。
#
# （4）行间顺序
#     最终按行号 0, 1, ..., numRows-1 拼接，对应 Z 字形从上到下的行。
#
# 综合（1）~（4）：算法输出与定义完全一致。证毕。
#
#
# 周期与下标关系（数学周期法）：
# ────────────────────────────────────────────────────────
#   T = 2*numRows - 2
#   mod = i % T
#   字符 s[i] 所在行 =
#       mod          , 当 mod < numRows
#       T - mod      , 当 mod >= numRows
#   整个映射等价于方向标志法中 curRow 的轨迹，只是它不维护状态而
#   是用模运算直接算出当前行号；避免了显式的方向判断。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 未初始化 idx：双重 while 循环中 `idx` 必须在外层 while 之前
#    初始化为 0，否则运行时会报 UnboundLocalError。
#
# 2. 斜上阶段行号下标算错：常见错误是写成 numRows - j - 1，
#    会导致末行被重复访问或漏掉次末行。正确写法是 numRows - j - 2。
#
# 3. 边界 numRows == 1：当 numRows == 1 时 T = 0，方向标志法会
#    死循环（curRow 在 0 处反复翻转但永远是 0）；数学周期法 T = 0
#    也需要特判。两种解法都应该在函数开头直接返回 s。
#
# 4. 边界 numRows >= len(s)：这种情况每行最多一个字符，输出与
#    原串相同，提前返回可省去后续无意义的循环。
#
# 5. 字符串拼接性能：在 Python 中字符串是不可变的，substrs[i] += ch
#    实际上是新建字符串并赋值。字符很多时开销很大，更推荐用 list
#    append + join（见 convert_concise）。
#
# 6. 方向标志初始值误设为 True：若 goingDown 初始为 True，
#    首字符会直接放到第 1 行而不是第 0 行，输出全错。
#
# 7. 周期法拼接两段等差数列：把行 k 的下标拆成
#    "i ≡ k (mod T)" 和 "i ≡ T-k (mod T)" 两段再简单拼接，会丢
#    失行内顺序（同一行字符在原串中的相对位置）。应按 i 从小到大
#    遍历并直接分桶。
# ══════════════════════════════════════════════════════════
