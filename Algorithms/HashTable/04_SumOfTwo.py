"""
1. 两数之和（Two Sum）

题目描述：
给定一个整数数组 nums 和一个整数目标值 target，
请你在该数组中找出和为目标值 target 的那两个整数，并返回它们的数组下标。

你可以假设每种输入只会对应一个答案，并且你不能使用两次相同的元素。
你可以按任意顺序返回答案。

输入描述：
整数数组 nums 和目标值 target。
2 <= nums.length <= 10^4，-10^9 <= nums[i] <= 10^9，-10^9 <= target <= 10^9。

输出描述：
返回两个下标 [i, j]，使得 nums[i] + nums[j] == target。

输入示例 1：
nums = [2, 7, 11, 15], target = 9
输出示例 1：
[0, 1]
解释：nums[0] + nums[1] = 2 + 7 = 9，返回 [0, 1]。

输入示例 2：
nums = [3, 2, 4], target = 6
输出示例 2：
[1, 2]

输入示例 3：
nums = [3, 3], target = 6
输出示例 3：
[0, 1]

════════════════════════════════════════════════════════════════════════
核心概念：哈希表 — 一次遍历 + 互补查询
════════════════════════════════════════════════════════════════════════

两数之和的核心洞察：
    对于 nums[i]，需要找到 complement = target - nums[i] 是否在数组中。
    用哈希表存储「已遍历的数字 → 下标」，O(1) 查找互补数。

关键：先查后存
    必须先查找 complement 是否在表中，再存入当前数字。
    否则 nums = [3, 3], target = 6 时会使用同一个元素两次。

    i=0, num=3, complement=3: 查 3 → 不在表中 → 存 {3: 0}
    i=1, num=3, complement=3: 查 3 → 在表中（下标 0）→ 返回 [0, 1] ✓

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
暴力双重循环                  O(n²)           O(1)            ⭐⭐ 直观
哈希表（一次遍历）            O(n)            O(n)            ⭐⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想（哈希表）：
────────────────────────────────────────────────────────────────────────
遍历数组，用字典 seen 存储已遍历的数字及其下标。
对每个 nums[i]，查找 complement = target - nums[i] 是否在 seen 中。
若在，返回 [seen[complement], i]；若不在，存入 seen[nums[i]] = i。
"""


# ══════════════════════════════════════════════════════════
# 解法一：哈希表（一次遍历）⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def twoSum(nums: list[int], target: int) -> list[int]:
    """哈希表（一次遍历）⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    用字典 seen 存储「已遍历数字 → 下标」。
    对每个 nums[i]，先查 complement = target - nums[i] 是否在 seen 中。
    先查后存，避免同一元素使用两次。

    算法步骤：
    1. seen = {}。
    2. 遍历 nums，对每个 i, num：
       a. complement = target - num。
       b. 若 complement in seen，返回 [seen[complement], i]。
       c. 否则 seen[num] = i。

    时间复杂度：O(n) — 遍历一次，每次 O(1) 查找。
    空间复杂度：O(n) — 最坏存 n 个元素。

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [2, 7, 11, 15], target = 9

    i=0, num=2, complement=7: 7 不在 seen → seen={2:0}
    i=1, num=7, complement=2: 2 在 seen（下标0）→ 返回 [0, 1] ✓

    nums = [3, 3], target = 6
    i=0, num=3, complement=3: 3 不在 seen → seen={3:0}
    i=1, num=3, complement=3: 3 在 seen（下标0）→ 返回 [0, 1] ✓
    """
    seen: dict[int, int] = {}
    for i, num in enumerate(nums):
        complement = target - num
        if complement in seen:
            return [seen[complement], i]
        seen[num] = i  # 先查后存，避免使用同一元素两次

    return []  # 题目保证有解，不会执行到此处


# ══════════════════════════════════════════════════════════
# 解法二：暴力双重循环 ⭐⭐
# ══════════════════════════════════════════════════════════


def twoSum_bruteforce(nums: list[int], target: int) -> list[int]:
    """暴力双重循环 ⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    枚举所有 i < j 的下标对，检查 nums[i] + nums[j] == target。
    i < j 保证不重复检查、不使用同一元素。

    算法步骤：
    1. for i in range(n):
    2.   for j in range(i+1, n):
    3.     if nums[i] + nums[j] == target: return [i, j]

    时间复杂度：O(n²) — 检查 n*(n-1)/2 个下标对。
    空间复杂度：O(1) — 不用额外空间。

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [2, 7, 11, 15], target = 9

    i=0, j=1: 2+7=9 == 9 → 返回 [0, 1] ✓
    """
    for i in range(len(nums)):
        for j in range(i + 1, len(nums)):
            if nums[i] + nums[j] == target:
                return [i, j]

    return []


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、哈希表法的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：哈希表法在遍历到答案的第二个元素时必定返回正确结果。
#
# 证明：
# （1）设答案为 (i, j)，i < j，nums[i] + nums[j] = target。
# （2）遍历到 i 时，complement = target - nums[i] = nums[j]。
#     nums[j] 还未被遍历（j > i），不在 seen 中，存入 seen[nums[i]] = i。
# （3）遍历到 j 时，complement = target - nums[j] = nums[i]。
#     nums[i] 已在 seen 中（下标 i），返回 [i, j]。✓
# （4）先查后存保证不会使用同一元素：
#     处理 i 时 seen 中没有 nums[i] 本身，只存不返回。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 先存后查：
#    seen[num] = i 先执行，再查 complement。
#    nums = [3, 3], target = 6 时，i=0 存入 {3:0}，
#    立即查 complement=3 → 找到自己 → 返回 [0, 0]，错误！
#    正确做法是先查后存。
#
# 2. 排序后双指针：
#    排序会丢失原始下标信息。若要排序需额外保存下标。
#    两数之和用哈希表更直接。
#
# 3. 暴力法内层循环从 0 开始：
#    for j in range(0, n) 会导致 i==j 和重复检查。
#    应从 i+1 开始。
#
# 4. 字典存数字而非下标：
#    seen 只存数字不存下标，则找到 complement 也无法返回下标。
#    应存 {数字: 下标}。
# ══════════════════════════════════════════════════════════
