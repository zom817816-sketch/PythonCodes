"""
202. 快乐数（Happy Number）

题目描述：
编写一个算法来判断一个数 n 是否是快乐数。

对于一个正整数，每一次将该数替换为它每个位置上的数字的平方和，
重复这个过程：
    - 如果最终得到 1，那么 n 就是快乐数。
    - 如果进入一个始终无法到达 1 的无限循环，那么 n 不是快乐数。

输入描述：
一个正整数 n。1 <= n <= 2^31 - 1。

输出描述：
如果 n 是快乐数，返回 True，否则返回 False。

输入示例 1：
n = 19
输出示例 1：
True
解释：1² + 9² = 82 → 8² + 2² = 68 → 6² + 8² = 100 → 1² + 0² + 0² = 1

输入示例 2：
n = 2
输出示例 2：
False
解释：2 → 4 → 16 → 37 → 58 → 89 → 145 → 42 → 20 → 4 → ...（进入循环）

════════════════════════════════════════════════════════════════════════
核心概念：哈希集合检测环 vs 快慢指针检测环
════════════════════════════════════════════════════════════════════════

快乐数问题本质上是一个"序列是否有环"的问题。

    n → f(n) → f(f(n)) → ... → 1（快乐数）
    n → f(n) → f(f(n)) → ... → 循环（非快乐数）

其中 f(n) = n 的各位数字平方和。

两种检测环的方法：
    1. 哈希集合：记录所有出现过的数，重复出现说明有环。
    2. 快慢指针：slow 走 1 步，fast 走 2 步，相遇说明有环。

    哈希集合法更直观，快慢指针法空间更优。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
哈希集合记录状态              O(log n)        O(log n)        ⭐⭐⭐⭐⭐ 推荐
快慢指针检测环                O(log n)        O(1)            ⭐⭐⭐⭐ 空间最优
────────────────────────────────────────────────────────────────────────

核心思想（哈希集合）：
────────────────────────────────────────────────────────────────────────
每次计算 f(n) 前检查 n 是否已在集合中。
    - n == 1 → 快乐数
    - n 已在集合中 → 进入循环，非快乐数
"""


# ══════════════════════════════════════════════════════════
# 解法一：哈希集合记录状态 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def isHappy(n: int) -> bool:
    """哈希集合记录状态 ⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    用集合 seen 记录所有出现过的数。每次计算平方和前检查：
    - n == 1 → 返回 True
    - n in seen → 进入循环，返回 False

    算法步骤：
    1. while n != 1 and n not in seen:
       a. seen.add(n)
       b. n = 各位数字平方和
    2. 返回 n == 1。

    时间复杂度：O(log n) — 状态数有限（见证明）。
    空间复杂度：O(log n) — 集合存储中间状态。

    图解示例：
    ────────────────────────────────────────────────────────
    n = 19

    步骤  n    平方和计算         seen
    1     19   1+81=82           {19}
    2     82   64+4=68           {19, 82}
    3     68   36+64=100         {19, 82, 68}
    4     100  1+0+0=1           {19, 82, 68, 100}
    5     1    → 退出循环

    n == 1 → True ✓
    """
    def digit_square_sum(num: int) -> int:
        """计算 num 的各位数字平方和"""
        return sum(int(d) ** 2 for d in str(num))

    seen: set[int] = set()
    while n != 1 and n not in seen:
        seen.add(n)  # 记录当前状态
        n = digit_square_sum(n)  # 转移到下一个状态

    return n == 1


# ══════════════════════════════════════════════════════════
# 解法二：快慢指针检测环 ⭐⭐⭐⭐
# ══════════════════════════════════════════════════════════


def isHappy_fast_slow(n: int) -> bool:
    """快慢指针检测环 ⭐⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    把数字序列看成链表：每个数字指向 f(n)。
    slow 每次走 1 步，fast 每次走 2 步。
    - fast == 1 → 快乐数
    - slow == fast → 检测到环（非快乐数）

    算法步骤：
    1. slow = n, fast = f(n)。
    2. while fast != 1 and slow != fast:
       a. slow = f(slow)
       b. fast = f(f(fast))
    3. 返回 fast == 1。

    时间复杂度：O(log n) — 状态数有限。
    空间复杂度：O(1) — 只用两个指针。

    图解示例：
    ────────────────────────────────────────────────────────
    n = 19（快乐数）
    slow: 19 → 82 → 68 → 100 → 1
    fast: 82 → 100 → 1 → 1
    fast == 1 → True ✓

    n = 2（非快乐数）
    slow: 2 → 4 → 16 → 37 → ...
    fast: 4 → 37 → ...
    slow == fast（在环中相遇）→ False ✓
    """
    def digit_square_sum(num: int) -> int:
        """计算 num 的各位数字平方和"""
        return sum(int(d) ** 2 for d in str(num))

    slow = n
    fast = digit_square_sum(n)

    while fast != 1 and slow != fast:
        slow = digit_square_sum(slow)  # 慢指针走 1 步
        fast = digit_square_sum(digit_square_sum(fast))  # 快指针走 2 步

    return fast == 1


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、为什么状态数有限（不会无限增长）：
# ────────────────────────────────────────────────────────
#
# 定理：对于 n <= 2^31 - 1（最多 10 位），f(n) <= 10 * 9² = 810。
#
# 证明：
# （1）2^31 - 1 = 2147483647，最多 10 位数字。
# （2）每位数字最大 9，平方最大 81。
# （3）f(n) <= 10 * 81 = 810。
# （4）因此所有状态都在 [1, 810] 范围内，状态数有限。
# （5）有限状态 + 确定性转移 = 一定进入循环或到达 1。
#
#
# 二、哈希集合法的正确性：
# ────────────────────────────────────────────────────────
#
# 定理：哈希集合法返回 True 当且仅当 n 是快乐数。
#
# 证明：
# （1）若 n 是快乐数，序列最终到达 1，n == 1 退出循环，返回 True。
# （2）若 n 不是快乐数，序列进入不含 1 的循环。
#     循环中的某个数会第二次出现，被 seen 检测到，返回 False。
# （3）不会无限循环：状态数有限，seen 集合在有限步内必然检测到重复。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 不检测环：只判断 n == 1，非快乐数会无限循环。
#
# 2. 集合法的记录时机：
#    应在转移前记录 seen.add(n)，不能只记录结果而遗漏初始状态。
#
# 3. 快慢指针的终止条件：
#    要同时处理 fast == 1（成功）和 slow == fast（有环）。
#
# 4. digit_square_sum 不要命名为 next：
#    next 是 Python 内置函数，遮蔽会导致问题。
# ══════════════════════════════════════════════════════════
