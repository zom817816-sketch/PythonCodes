"""
# 202. 快乐数（Happy Number）

## 题目描述

编写一个算法来判断一个数 `n` 是否是快乐数。

对于一个正整数，每一次将它替换为它每个位置上的数字的平方和，重复这个过程：

    n -> 各位数字平方和 -> 各位数字平方和 -> ...

如果这个过程最终得到 `1`，那么 `n` 就是快乐数；如果进入一个始终无法到达 `1`
的无限循环，那么 `n` 不是快乐数。

例如：

    19 -> 1² + 9² = 82
       -> 8² + 2² = 68
       -> 6² + 8² = 100
       -> 1² + 0² + 0² = 1

因此 `19` 是快乐数。

- 输入：正整数 `n`
- 输出：如果 `n` 是快乐数，返回 `True`，否则返回 `False`
- 题目链接：https://leetcode.cn/problems/happy-number/

## 解法总览

### 解法一：哈希集合记录状态

把每一次出现过的数字放入集合 `seen`。如果下一次计算得到的数字已经在集合中，
说明序列出现了环，之后会重复之前的过程，不可能再到达 `1`。

状态转移图可以抽象为：

    当前数字 --各位数字平方和--> 下一个数字
       |                              |
       +-------- 重复出现 <-----------+

### 解法二：快慢指针检测环

把数字序列看成链表：每个数字指向“各位数字平方和”的结果。

- 慢指针每次走一步；
- 快指针每次走两步；
- 如果快指针到达 `1`，说明是快乐数；
- 如果快慢指针相遇，说明存在环，且这个环不是以 `1` 结束。

解法一更直观，解法二不需要保存所有已经访问过的数字。
"""


def if_happy_num_1(n: int) -> bool:
    """使用哈希集合判断 `n` 是否是快乐数。

    算法步骤：
    1. 计算当前数字各位数字的平方和。
    2. 如果结果为 `1`，返回 `True`。
    3. 如果当前数字已经出现过，说明进入循环，返回 `False`。
    4. 否则记录当前数字并继续迭代。

    复杂度：设输入有 `d` 位，实际经历了 `T` 次状态转移。每次计算需要
    `O(d)` 时间，因此总时间复杂度为 `O(dT)`；由于后续状态会迅速落入有限范围，
    在本题通常记为 `O(log n)`。集合最多保存 `T` 个状态，空间复杂度为 `O(T)`，
    通常记为 `O(log n)`。
    """

    def digit_square_sum(num: int) -> int:
        """返回 `num` 的各位数字平方和。"""
        return sum(int(digit) ** 2 for digit in str(num))

    seen = set()
    while n != 1 and n not in seen:
        # 先记录当前状态，再计算下一个状态，避免环中的状态被重复处理。
        seen.add(n)
        n = digit_square_sum(n)

    # 退出循环的两种情况分别是 n == 1 和 n 已经出现过。
    return n == 1


def if_happy_num_2(n: int) -> bool:
    """使用快慢指针判断 `n` 是否是快乐数。

    令 `f(x)` 表示 `x` 的各位数字平方和。慢指针每次执行一次 `f`，快指针
    每次执行两次 `f`。若序列形成环，两个指针最终一定相遇；若快指针先到达
    `1`，则说明序列能够结束于 `1`。

    复杂度：设输入有 `d` 位，实际经历了 `T` 次状态转移，总时间复杂度为
    `O(dT)`，本题通常记为 `O(log n)`；只使用有限个指针变量，空间复杂度为
    `O(1)`。
    """

    def digit_square_sum(num: int) -> int:
        """返回 `num` 的各位数字平方和。"""
        return sum(int(digit) ** 2 for digit in str(num))

    slow = n
    fast = digit_square_sum(n)

    # fast == 1：到达成功终点；fast == slow：检测到非 1 环。
    while fast != 1 and slow != fast:
        slow = digit_square_sum(slow)
        fast = digit_square_sum(digit_square_sum(fast))

    return fast == 1


# 正确性证明
#
# 设 f(x) 为 x 的各位数字平方和。算法一每轮都把当前状态 x 加入 seen，
# 然后转移到 f(x)。如果最终 n == 1，根据题目定义，原数是快乐数，算法返回 True。
# 如果某个状态重复出现，则确定存在环；之后的状态会按相同顺序重复，不可能首次到达 1，
# 算法返回 False。因此算法一正确。
#
# 对算法二，所有状态都按 f 连接成一条序列。若序列到达 1，快指针最终会到达 1；
# 若序列进入不包含 1 的环，快慢指针在环中每轮的相对距离改变 1，必然相遇。
# 所以算法二在且仅在序列到达 1 时返回 True，也正确。
#
# 易错点：
# 1. 必须检测“状态是否重复”，仅检测当前值是否为 1 会在非快乐数上无限循环。
# 2. 集合方案应在转移前记录状态，不能只记录结果而遗漏初始状态。
# 3. 快慢指针的终止条件要同时处理 `fast == 1` 和 `slow == fast`。
# 4. `digit_square_sum` 不应命名为 `next`，否则会遮蔽 Python 的内置函数 `next`。
