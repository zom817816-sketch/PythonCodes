"""
349. 两个数组的交集 / 350. 两个数组的交集 II（Intersection of Two Arrays）

题目描述：
给定两个整数数组 nums1 和 nums2，返回它们的交集。

LC 349（去重交集）：结果中每个元素只出现一次。
LC 350（重复交集）：结果中每个元素出现的次数等于两数组中出现次数的较小值。

输入描述：
两个整数数组 nums1 和 nums2。
1 <= nums1.length, nums2.length <= 1000，0 <= nums[i] <= 1000。

输出描述：
返回交集数组，元素顺序不作要求。

输入示例 1（LC 349）：
nums1 = [1, 2, 2, 1], nums2 = [2, 2]
输出示例 1：
[2]

输入示例 2（LC 350）：
nums1 = [1, 2, 2, 1], nums2 = [2, 2]
输出示例 2：
[2, 2]

════════════════════════════════════════════════════════════════════════
核心概念：集合 vs 频次表
════════════════════════════════════════════════════════════════════════

两种交集定义的区别：
    LC 349（去重）：只关心元素是否存在 → 用集合
    LC 350（重复）：关心出现次数 → 用频次表（Counter 或 dict）

    nums1 = [1, 2, 2, 1], nums2 = [2, 2]
    去重交集：{1,2} & {2} = {2} → [2]
    重复交集：{1:2, 2:2} & {2:2} = {2:2} → [2, 2]

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
集合交集（去重）              O(n+m)          O(n+m)          ⭐⭐⭐⭐⭐ LC 349
Counter 交集（重复）          O(n+m)          O(n+m)          ⭐⭐⭐⭐⭐ LC 350
字典频次法（重复）            O(n+m)          O(n)            ⭐⭐⭐⭐ 不依赖 Counter
────────────────────────────────────────────────────────────────────────

核心思想：
────────────────────────────────────────────────────────────────────────
LC 349：set(nums1) & set(nums2)，集合交集天然去重。
LC 350：Counter(nums1) & Counter(nums2)，Counter 的 & 取 min 频次。
"""

from collections import Counter


# ══════════════════════════════════════════════════════════
# 解法一：集合交集（LC 349 去重）⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def intersection(nums1: list[int], nums2: list[int]) -> list[int]:
    """集合交集（去重）⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    将两个数组转为集合，用集合的 & 操作取交集，天然去重。

    算法步骤：
    1. set1 = set(nums1), set2 = set(nums2)。
    2. return list(set1 & set2)。

    时间复杂度：O(n+m) — 构建两个集合。
    空间复杂度：O(n+m) — 两个集合。

    图解示例：
    ────────────────────────────────────────────────────────
    nums1 = [1, 2, 2, 1] → set1 = {1, 2}
    nums2 = [2, 2]       → set2 = {2}
    set1 & set2 = {2} → [2] ✓
    """
    return list(set(nums1) & set(nums2))


# ══════════════════════════════════════════════════════════
# 解法二：Counter 交集（LC 350 重复）⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def intersect(nums1: list[int], nums2: list[int]) -> list[int]:
    """Counter 交集（保留重复）⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    用 Counter 统计两个数组的频次，& 操作对相同键取 min 频次。
    elements() 按频次展开为列表。

    算法步骤：
    1. counts1 = Counter(nums1), counts2 = Counter(nums2)。
    2. common = counts1 & counts2（每个键取 min 频次）。
    3. return list(common.elements())。

    时间复杂度：O(n+m) — 构建两个 Counter。
    空间复杂度：O(n+m) — 两个 Counter。

    图解示例：
    ────────────────────────────────────────────────────────
    nums1 = [1, 2, 2, 1] → Counter({1: 2, 2: 2})
    nums2 = [2, 2]       → Counter({2: 2})
    & 操作 → Counter({2: 2})  (min(2,2)=2)
    elements() → [2, 2] ✓
    """
    counts1 = Counter(nums1)
    counts2 = Counter(nums2)
    common = counts1 & counts2  # 对相同键取 min 频次
    return list(common.elements())


# ══════════════════════════════════════════════════════════
# 解法三：字典频次法（LC 350 重复）⭐⭐⭐⭐
# ══════════════════════════════════════════════════════════


def intersect_dict(nums1: list[int], nums2: list[int]) -> list[int]:
    """字典频次法（保留重复）⭐⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    用字典统计 nums1 的频次，遍历 nums2 时查找并消耗频次。
    不依赖 Counter，展示底层逻辑。

    算法步骤：
    1. 用字典 counts 统计 nums1 中每个数字的出现次数。
    2. 遍历 nums2，若 counts[num] > 0，加入结果并减一。
    3. 返回结果列表。

    时间复杂度：O(n+m) — 遍历两遍。
    空间复杂度：O(n) — 只需一个字典。

    图解示例：
    ────────────────────────────────────────────────────────
    nums1 = [1, 2, 2, 1] → counts = {1: 2, 2: 2}
    nums2 = [2, 2]
      2: counts[2]=2>0 → 加入结果, counts[2]=1
      2: counts[2]=1>0 → 加入结果, counts[2]=0
    结果: [2, 2] ✓
    """
    counts: dict[int, int] = {}
    for num in nums1:
        counts[num] = counts.get(num, 0) + 1

    result: list[int] = []
    for num in nums2:
        if counts.get(num, 0) > 0:
            result.append(num)
            counts[num] -= 1

    return result


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、Counter 交集法的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：Counter & 操作的结果恰好是多重集交集。
#
# 证明：
# （1）Counter(nums1)[x] = x 在 nums1 中的出现次数。
# （2）Counter 的 & 操作对键 x 取 min(count1[x], count2[x])。
# （3）x 能在交集中出现的最大次数 = min(两数组中的出现次数)。
# （4）elements() 按频次展开，结果恰好是多重集交集。✓
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 混淆 349 和 350：
#    349 要求去重（每个元素最多一次），用集合。
#    350 要求保留重复（取较小频次），用 Counter 或字典。
#
# 2. 用集合解决 350：
#    set 会丢失频次信息，set([1,2,2]) = {1,2}，
#    无法表示 2 出现了两次。
#
# 3. Counter.elements() 返回迭代器：
#    必须用 list() 转换才能得到列表结果。
#
# 4. 字典法中忘记减一：
#    counts[num] -= 1 是关键，否则同一元素会被重复使用超出供应。
# ══════════════════════════════════════════════════════════
