# 解法二：排序 + 哈希表 ⭐⭐⭐
# ══════════════════════════════════════════════════════════


def threeSum_hashset(nums: list[int]) -> list[list[int]]:
    """排序 + 哈希表 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    排序后固定 nums[i]，在 [i+1, n-1] 中用哈希表找两数之和 = -nums[i]。
    遍历 j 时，target = -nums[i] - nums[j]，检查 target 是否在 seen 中。

    时间复杂度：O(n²) — 外层 n，内层 n。
    空间复杂度：O(n) — 哈希表。

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [-1, 0, 1, 2, -1, -4]
    排序后: [-4, -1, -1, 0, 1, 2]

    i=1, nums[i]=-1:
      j=2, nums[j]=-1, target=2: 2 不在 seen → seen={-1}
      j=3, nums[j]=0,  target=1: 1 不在 seen → seen={-1,0}
      j=4, nums[j]=1,  target=0: 0 在 seen → 记录 [-1,0,1], seen.remove(0)
      j=5, nums[j]=2,  target=-1: -1 在 seen → 记录 [-1,-1,2], seen.remove(-1)
    """
    nums.sort()
    result: list[list[int]] = []
    n = len(nums)

    for i in range(n - 2):
        if nums[i] > 0:
            break
        if i > 0 and nums[i] == nums[i - 1]:
            continue

        seen: set[int] = set()
        for j in range(i + 1, n):
            # 内层去重
            if j > i + 1 and nums[j] == nums[j - 1]:
                continue

            target = -nums[i] - nums[j]
            if target in seen:
                result.append([nums[i], target, nums[j]])
                seen.remove(target)  # 避免重复使用
            else:
                seen.add(nums[j])

    return result


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、排序 + 双指针的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：排序 + 双指针能找到所有不重复的和为 0 的三元组。
#
# 证明：
# （1）完备性：对任意满足 a+b+c=0 的三元组（排序后 a<=b<=c），
#     当外层固定到 a 时，双指针一定能在 [b, c] 之间找到 b 和 c。
#     因为双指针不会跳过可行解：
#     - sum < 0 时只有增大 left 才可能到 0（right 已是最大）。
#     - sum > 0 时只有减小 right 才可能到 0。
#
# （2）不重复：外层跳过重复 nums[i] 保证 a 不重复；
#     命中后跳过重复 left/right 保证同一 a 下的 (b,c) 不重复。
#
# （3）剪枝正确性：nums[i] > 0 时，因为排序后 nums[i] <= nums[j] <= nums[k]，
#     三数之和 >= 3*nums[i] > 0，不可能为 0，可以 break。
#     注意是 > 0 不是 >= 0，因为 [0,0,0] 也是合法答案。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 剪枝用 >= 0 而非 > 0：
#    nums[i] == 0 时 [0,0,0] 是合法答案，不能 break。
#
# 2. 只外层去重，不内层去重：
#    找到答案后不跳过 left/right 的重复值，会产生重复三元组。
#
# 3. 去重条件用 nums[i] == nums[i+1]：
#    这会跳过同一值的第一个出现，漏掉 [-1,-1,2] 这种答案。
#    正确做法：nums[i] == nums[i-1]（跳过第二个及之后的重复）。
#
# 4. 哈希表法中 seen 的时机：
#    必须先查 target 再加入 nums[j]，否则可能使用同一元素。
#    命中后 seen.remove(target) 避免重复输出。
# ══════════════════════════════════════════════════════════
