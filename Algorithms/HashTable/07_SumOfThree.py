"""
15. 三数之和（3Sum）

题目描述：
给你一个整数数组 nums，判断是否存在三元组 [nums[i], nums[j], nums[k]] 满足
i != j、i != k 且 j != k，同时还满足 nums[i] + nums[j] + nums[k] == 0。
请你返回所有和为 0 且不重复的三元组。

注意：答案中不可以包含重复的三元组。

输入描述：
整数数组 nums。3 <= nums.length <= 3000，-10^5 <= nums[i] <= 10^5。

输出描述：
所有和为 0 的不重复三元组列表。

输入示例 1：
nums = [-1, 0, 1, 2, -1, -4]
输出示例 1：
[[-1, -1, 2], [-1, 0, 1]]
解释：排序后为 [-4, -1, -1, 0, 1, 2]，两个三元组满足条件。

输入示例 2：
nums = [0, 1, 1]
输出示例 2：
[]

输入示例 3：
nums = [0, 0, 0]
输出示例 3：
[[0, 0, 0]]

════════════════════════════════════════════════════════════════════════
核心概念：排序 + 双指针 + 去重
════════════════════════════════════════════════════════════════════════

三数之和的关键：
    1. 排序：使双指针移动有方向性（小了右移 left，大了左移 right）。
    2. 固定一个数：nums[i]，在 [i+1, n-1] 中用双指针找两数之和 = -nums[i]。
    3. 去重：外层跳过重复的 nums[i]，找到答案后跳过重复的 left 和 right。

    排序后: [-4, -1, -1, 0, 1, 2]
             i   L           R
             固定  →  双指针搜索

为什么不用哈希表？
    哈希表也能做（固定 i，在剩余部分用哈希表找两数之和），
    但去重逻辑更复杂，且空间 O(n)。
    排序 + 双指针去重更自然，空间 O(1)。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
排序 + 双指针                  O(n²)           O(1)            ⭐⭐⭐⭐⭐ 推荐
排序 + 哈希表                  O(n²)           O(n)            ⭐⭐⭐ 去重复杂
────────────────────────────────────────────────────────────────────────

核心思想（排序 + 双指针）：
────────────────────────────────────────────────────────────────────────
排序后固定 nums[i]，在 [i+1, n-1] 中用 left 和 right 双指针。
    - sum < 0 → left 右移（增大）
    - sum > 0 → right 左移（减小）
    - sum = 0 → 记录答案，跳过左右重复值
"""


# ══════════════════════════════════════════════════════════
# 解法一：排序 + 双指针 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def threeSum(nums: list[int]) -> list[list[int]]:
    """排序 + 双指针 ⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    排序后固定 nums[i]，在右侧用双指针找两数之和 = -nums[i]。
    利用排序的单调性，O(n) 完成双指针搜索。
    通过跳过重复值避免重复三元组。

    算法步骤：
    1. nums.sort()。
    2. for i in range(n-2):
       a. nums[i] > 0 → break（排序后最小值 > 0 不可能和为 0）。
       b. 跳过重复的 nums[i]。
       c. left = i+1, right = n-1，双指针搜索。
       d. sum < 0 → left++，sum > 0 → right--。
       e. sum = 0 → 记录，跳过左右重复，left++ right--。

    时间复杂度：O(n²) — 外层 n，内层双指针 n。
    空间复杂度：O(1) — 不计结果和排序。

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [-1, 0, 1, 2, -1, -4]
    排序后: [-4, -1, -1, 0, 1, 2]

    i=0, nums[i]=-4, left=1(-1), right=5(2)
      -4+(-1)+2=-3 < 0 → left++
      -4+0+2=-2 < 0 → left++
      -4+1+2=-1 < 0 → left++
      left >= right → 无解

    i=1, nums[i]=-1, left=2(-1), right=5(2)
      -1+(-1)+2=0 → 记录 [-1,-1,2], 跳过重复, left=3 right=4
      -1+0+1=0 → 记录 [-1,0,1], left=4 right=3
      left >= right → 结束

    i=2, nums[i]=-1 (重复, 跳过)

    结果: [[-1,-1,2], [-1,0,1]] ✓
    """
    nums.sort()
    result: list[list[int]] = []
    n = len(nums)

    for i in range(n - 2):
        # 剪枝：排序后最小值 > 0，不可能和为 0
        if nums[i] > 0:
            break

        # 外层去重：跳过重复的 nums[i]
        if i > 0 and nums[i] == nums[i - 1]:
            continue

        left, right = i + 1, n - 1
        while left < right:
            total = nums[i] + nums[left] + nums[right]

            if total < 0:
                left += 1  # 和太小，增大 left
            elif total > 0:
                right -= 1  # 和太大，减小 right
            else:
                result.append([nums[i], nums[left], nums[right]])

                # 跳过 left 重复值
                while left < right and nums[left] == nums[left + 1]:
                    left += 1
                # 跳过 right 重复值
                while left < right and nums[right] == nums[right - 1]:
                    right -= 1

                left += 1  # 移动到下一个不同的值
                right -= 1

    return result


