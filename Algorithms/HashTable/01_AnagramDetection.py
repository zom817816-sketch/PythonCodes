"""
# 题目：有效的字母异位词（Valid Anagram）

给定两个字符串 `s` 和 `t`，判断 `t` 是否是 `s` 的字母异位词。
字母异位词指：两个字符串包含完全相同的字符，且每个字符出现的次数也相同，
但字符排列顺序可以不同。

## 示例

```text
输入：s = "anagram", t = "nagaram"
输出：True
解释：两个字符串都包含 a、g、m、n、r，各字符出现次数完全相同。

输入：s = "rat", t = "car"
输出：False
解释：两个字符串中的字符及其出现次数不相同。
```

## 核心概念

1. **频次统计**：异位词的本质是两个字符串的字符频次表相等。
2. **长度剪枝**：长度不同，不可能是异位词，可以立即返回 `False`。
3. **差分计数**：遍历两个字符串时，一个加一、一个减一，最后所有计数为零
   就说明每种字符都恰好抵消。
4. **哈希表**：当字符集不限定为 26 个小写字母时，可以用 `Counter` 统计任意字符。

## 复杂度总览

| 解法 | 思路 | 时间复杂度 | 额外空间复杂度 | 适用场景 |
| --- | --- | --- | --- | --- |
| `if_anagram_1` | 26 位数组差分计数 | O(n) | O(1) | 仅有小写英文字母 |
| `is_anagram_2` | `Counter` 统计频次 | O(n) | O(k) | 字符集范围不确定 |

其中 `n` 为字符串长度，`k` 为不同字符的数量。表格中的空间复杂度不包含输入
字符串本身；在固定 26 个字符的前提下，O(26) 可视为 O(1)。

## 约定

本文件中的数组解法遵循题目“只包含小写英文字母”的约束。若输入可能包含大写字母、
数字、空格或 Unicode 字符，请使用 `is_anagram_2`。
"""

from collections import Counter


def if_anagram_1(s: str, t: str) -> bool:
    """使用固定长度数组判断两个字符串是否为字母异位词。

    步骤：
        1. 若两个字符串长度不同，直接返回 `False`。
        2. 创建 26 个计数槽位，分别对应 `a` 到 `z`。
        3. 同时遍历 `s` 和 `t`：在 `s` 的字符位置加一，在 `t` 的字符位置减一。
        4. 若最终所有槽位均为零，则两边每个字母出现次数相同。

    图解（以 `s = "ab"`、`t = "ba"` 为例）：

    ```text
    字符       a    b    c ... z
    读取 s     +1   +1    0 ... 0
    读取 t     -1   -1    0 ... 0
    最终        0    0    0 ... 0  -> True
    ```

    Args:
        s: 只包含小写英文字母的第一个字符串。
        t: 只包含小写英文字母的第二个字符串。

    Returns:
        如果 `t` 是 `s` 的字母异位词，返回 `True`；否则返回 `False`。

    Complexity:
        时间复杂度 O(n)，空间复杂度 O(1)（计数数组固定为 26 个元素）。

    Note:
        如果输入不满足小写英文字母约束，字符转下标可能越界或得到错误结果；
        此时应使用 `is_anagram_2`。
    """
    if len(s) != len(t):
        return False

    counts = [0] * 26
    for source_char, target_char in zip(s, t):
        # ord(char) - ord("a") 将小写字母映射到 0～25。
        counts[ord(source_char) - ord("a")] += 1
        counts[ord(target_char) - ord("a")] -= 1

    # 只要有一个计数不为零，就代表某个字符的频次不相等。
    return all(count == 0 for count in counts)


def is_anagram_2(s: str, t: str) -> bool:
    """使用哈希表统计频次，判断两个字符串是否为字母异位词。

    步骤：
        1. 分别统计 `s` 和 `t` 中每个字符出现的次数。
        2. 比较两个频次表；键和值都相同才是异位词。

    图解：

    ```text
    s = "aabb"  -> {a: 2, b: 2}
    t = "baba"  -> {a: 2, b: 2}
    两个 Counter 相等 ----------------> True
    ```

    Args:
        s: 第一个字符串，可以包含任意可哈希字符。
        t: 第二个字符串，可以包含任意可哈希字符。

    Returns:
        如果两个字符串的字符频次完全相同，返回 `True`；否则返回 `False`。

    Complexity:
        时间复杂度 O(n)，空间复杂度 O(k)，其中 `k` 是两个字符串中不同字符的总数。
    """
    # Counter 能正确处理大小写、数字、空格以及一般 Unicode 字符。
    return Counter(s) == Counter(t)


# 更符合常见命名习惯的兼容别名；保留原函数名以兼容已有调用方。
is_anagram_1 = if_anagram_1


