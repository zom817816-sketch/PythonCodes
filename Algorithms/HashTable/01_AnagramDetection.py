"""
242. 有效的字母异位词（Valid Anagram）

题目描述：
给定两个字符串 s 和 t，判断 t 是否是 s 的字母异位词。
字母异位词指：两个字符串包含完全相同的字符，且每个字符出现的次数也相同，
但字符排列顺序可以不同。

输入描述：
两个字符串 s 和 t。1 <= s.length, t.length <= 5 * 10^4，
字符串只包含小写英文字母。

输出描述：
如果 t 是 s 的字母异位词，返回 True，否则返回 False。

输入示例 1：
s = "anagram", t = "nagaram"
输出示例 1：
True

输入示例 2：
s = "rat", t = "car"
输出示例 2：
False

════════════════════════════════════════════════════════════════════════
核心概念：频次统计与差分计数
════════════════════════════════════════════════════════════════════════

异位词的本质：两个字符串的字符频次表完全相等。

差分计数法：
    遍历 s 时对应字符计数 +1，遍历 t 时对应字符计数 -1。
    最终所有计数为零 → 每种字符恰好抵消 → 是异位词。

    字符       a    b    c ... z
    读取 s     +1   +1    0 ... 0
    读取 t     -1   -1    0 ... 0
    最终        0    0    0 ... 0  → True

两种解法对比：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
26 位数组差分计数              O(n)            O(1)            ⭐⭐⭐⭐⭐ 推荐
Counter 频次比较              O(n)            O(k)            ⭐⭐⭐ 通用字符集
────────────────────────────────────────────────────────────────────────

核心思想（数组差分计数）：
────────────────────────────────────────────────────────────────────────
用长度 26 的数组 counts 记录每个字符的频次差。
s 的字符 +1，t 的字符 -1，最终全零则返回 True。
长度不等直接返回 False（剪枝）。
"""

from collections import Counter


# ══════════════════════════════════════════════════════════
# 解法一：26 位数组差分计数 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def isAnagram(s: str, t: str) -> bool:
    """26 位数组差分计数 ⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    用长度 26 的数组记录频次差。s 的字符 +1，t 的字符 -1。
    最终全零说明两个字符串的字符频次完全相同。

    算法步骤：
    1. 长度不同，直接返回 False。
    2. 创建 counts[26]，全初始化为 0。
    3. 同时遍历 s 和 t：s 的字符 +1，t 的字符 -1。
    4. 检查 counts 是否全零。

    时间复杂度：O(n) — 遍历一次。
    空间复杂度：O(1) — 固定 26 个元素。

    图解示例：
    ────────────────────────────────────────────────────────
    s = "anagram", t = "nagaram"

    字符       a    g    m    n    r   ... 其他
    读取 s     +3   +1   +1   +1   +1   ... 0
    读取 t     -3   -1   -1   -1   -1   ... 0
    最终        0    0    0    0    0   ... 0  → True ✓
    """
    if len(s) != len(t):
        return False

    counts = [0] * 26
    for sc, tc in zip(s, t):
        counts[ord(sc) - ord("a")] += 1  # s 的字符加一
        counts[ord(tc) - ord("a")] -= 1  # t 的字符减一

    return all(c == 0 for c in counts)


# ══════════════════════════════════════════════════════════
# 解法二：Counter 频次比较 ⭐⭐⭐
# ══════════════════════════════════════════════════════════


def isAnagram_counter(s: str, t: str) -> bool:
    """Counter 频次比较 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    用 Counter 分别统计两个字符串的字符频次，直接比较是否相等。
    适用于任意字符集（Unicode、大写字母、数字等）。

    算法步骤：
    1. 统计 s 的频次：Counter(s)。
    2. 统计 t 的频次：Counter(t)。
    3. 比较两个 Counter 是否相等。

    时间复杂度：O(n) — 遍历两次。
    空间复杂度：O(k) — k 为不同字符数。

    图解示例：
    ────────────────────────────────────────────────────────
    s = "aabb" → Counter({'a': 2, 'b': 2})
    t = "baba" → Counter({'a': 2, 'b': 2})
    两个 Counter 相等 → True ✓
    """
    return Counter(s) == Counter(t)


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、差分计数法的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：差分计数法返回 True 当且仅当 s 和 t 是字母异位词。
#
# 证明：
# （1）counts[c] = (s 中 c 的出现次数) - (t 中 c 的出现次数)。
# （2）若 s 和 t 是异位词，每个字符在两边出现次数相同，
#     因此 counts 全为零，返回 True。
# （3）若 counts 全为零，每个字符在两边的出现次数相同，
#     满足异位词定义，返回 True 正确。
# （4）长度不同时直接返回 False，因为不同长度不可能频次相同。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 用集合比较：set(s) == set(t) 会丢失重复次数信息。
#    如 s="ab", t="aab" 集合都是 {'a','b'} 但不是异位词。
#
# 2. 数组解法用于非小写字母：ord(char) - ord('a') 对大写字母
#    或 Unicode 字符会越界或得到错误下标，应使用 Counter 解法。
#
# 3. 长度不同时不剪枝：虽然 Counter 比较也能正确处理，
#    但差分计数法要求 zip 配对，长度不同会少算字符。
#
# 4. 排序后比较：sorted(s) == sorted(t) 是 O(n log n)，
#    比哈希表 O(n) 慢，但也是正确的解法。
# ══════════════════════════════════════════════════════════
