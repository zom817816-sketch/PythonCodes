# 正确性证明
# ----------
# 对 if_anagram_1：每处理一对字符，counts[c] 表示字符 c 在 s 中的出现次数
# 减去在 t 中的出现次数。遍历结束后，所有 counts[c] 都为 0，当且仅当每个
# 字符在两个字符串中的出现次数相同。因此函数返回 True 当且仅当两者是异位词。
#
# 对 is_anagram_2：Counter(s) 和 Counter(t) 分别准确记录两个字符串的字符频次。
# 两个 Counter 相等当且仅当每个字符的频次相等，而这正是字母异位词的定义，
# 所以该函数也能且只能在异位词情况下返回 True。

# 易错点
# ------
# 1. 只比较排序后的字符串或字符集合是不够的：集合会丢失重复次数。
