"""
18. 四数之和（4Sum）

题目描述：
给你一个由 n 个整数组成的数组 nums，和一个目标值 target。
请你找出并返回满足下述全部条件且不重复的四元组
[nums[a], nums[b], nums[c], nums[d]]
（若两个四元组元素一一对应，则认为两个四元组重复）：

    0 <= a, b, c, d < n
    a、b、c、d 互不相同
    nums[a] + nums[b] + nums[c] + nums[d] == target

返回不重复的四元组列表。

输入描述：
整数数组 nums 和目标值 target。
1 <= nums.length <= 200，-10^9 <= nums[i] <= 10^9，-10^9 <= target <= 10^9。

输出描述：
所有和为 target 的不重复四元组列表。

输入示例 1：
nums = [1, 0, -1, 0, -2, 2], target = 0
输出示例 1：
[[-2, -1, 1, 2], [-2, 0, 0, 2], [-1, 0, 0, 1]]

输入示例 2：
nums = [2, 2, 2, 2, 2], target = 8
输出示例 2：
[[2, 2, 2, 2]]

════════════════════════════════════════════════════════════════════════
核心概念：排序 + 两层枚举 + 双指针 + 剪枝
════════════════════════════════════════════════════════════════════════

四数之和是三数之和的扩展：
    在三数之和的外面再固定一个数。

    排序后: [a, ..., b, ..., left, ..., right]
             ↑固定    ↑固定    ↑双指针搜索

两层固定 + 双指针搜索：
    1. 外层固定 a（跳过重复）。
    2. 内层固定 b（跳过重复）。
    3. 在 [b+1, n-1] 中用双指针找两数之和 = target - nums[a] - nums[b]。

剪枝优化：
    - a 层最小和 > target → break（后续 a 更大，不可能更小）。
    - a 层最大和 < target → continue（当前 a 太小，尝试下一个）。
    - b 层同理。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
排序 + 两层枚举 + 双指针      O(n³)           O(1)            ⭐⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想：
────────────────────────────────────────────────────────────────────────
排序后两层固定 a 和 b，在 [b+1, n-1] 中双指针搜索剩余两数。
利用排序的单调性进行剪枝和去重。
"""


# ══════════════════════════════════════════════════════════
# 解法一：排序 + 两层枚举 + 双指针 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def fourSum(nums: list[int], target: int) -> list[list[int]]:
    """排序 + 两层枚举 + 双指针 ⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    排序后固定 a 和 b，在 [b+1, n-1] 中用双指针找剩余两数。
    利用排序单调性进行剪枝和去重。

    算法步骤：
    1. nums.sort()。
    2. for a in range(n-3):
       a. 剪枝：最小四数和 > target → break；最大四数和 < target → continue。
       b. 跳过重复 a。
       c. for b in range(a+1, n-2):
          i. 剪枝。
          ii. 跳过重复 b。
          iii. left=b+1, right=n-1，双指针搜索。
          iv. sum < target → left++，sum > target → right--。
          v. sum = target → 记录，跳过重复，left++ right--。

    时间复杂度：O(n³) — 两层枚举 O(n²) × 双指针 O(n)。
    空间复杂度：O(1) — 不计结果和排序。

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [1, 0, -1, 0, -2, 2], target = 0
    排序后: [-2, -1, 0, 0, 1, 2]

    a=0(-2), b=1(-1), left=2(0), right=5(2)
      -2+(-1)+0+2=-1 < 0 → left++
      -2+(-1)+0+2=-1 < 0 → left++
      -2+(-1)+1+2=0 → 记录 [-2,-1,1,2]

    a=0(-2), b=2(0), left=3(0), right=5(2)
      -2+0+0+2=0 → 记录 [-2,0,0,2]

    a=0(-2), b=3(0) 跳过重复

    a=1(-1), b=2(0), left=3(0), right=5(2)
      -1+0+0+1=0 → 记录 [-1,0,0,1]

    结果: [[-2,-1,1,2], [-2,0,0,2], [-1,0,0,1]] ✓
    """
    nums.sort()
    result: list[list[int]] = []
    n = len(nums)

    if n < 4:
        return result

    for a in range(n - 3):
        # 剪枝：a 层最小四数和已超过 target
        if nums[a] + nums[a + 1] + nums[a + 2] + nums[a + 3] > target:
            break
        # 剪枝：a 层最大四数和仍不足 target
        if nums[a] + nums[n - 3] + nums[n - 2] + nums[n - 1] < target:
            continue

        # 外层去重
        if a > 0 and nums[a] == nums[a - 1]:
            continue

        for b in range(a + 1, n - 2):
            # 剪枝
            if nums[a] + nums[b] + nums[b + 1] + nums[b + 2] > target:
                break
            if nums[a] + nums[b] + nums[n - 2] + nums[n - 1] < target:
                continue

            # 内层去重
            if b > a + 1 and nums[b] == nums[b - 1]:
                continue

            left, right = b + 1, n - 1
            while left < right:
                total = nums[a] + nums[b] + nums[left] + nums[right]

                if total < target:
                    left += 1
                elif total > target:
                    right -= 1
                else:
                    result.append([nums[a], nums[b], nums[left], nums[right]])

                    # 跳过 left 重复值
                    while left < right and nums[left] == nums[left + 1]:
                        left += 1
                    # 跳过 right 重复值
                    while left < right and nums[right] == nums[right - 1]:
                        right -= 1

                    left += 1
                    right -= 1

    return result


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、排序 + 双指针的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：排序 + 两层枚举 + 双指针能找到所有不重复的四元组。
#
# 证明：
# （1）完备性：对任意满足 a+b+c+d=target 的四元组（排序后 a<=b<=c<=d），
#     外层枚举到 a 和 b 时，双指针一定能在 [b+1, n-1] 中找到 c 和 d。
#     因为双指针不跳过可行解（单调性保证）。
#
# （2）不重复：外层跳过重复 a，内层跳过重复 b，
#     命中后跳过重复 left/right，保证每个数值组合只输出一次。
#
# （3）剪枝正确性：
#     - 最小四数和 = nums[a]+nums[a+1]+nums[a+2]+nums[a+3]，
#       这是固定 a 后能取到的最小和。若 > target，后续 a 更大，break。
#     - 最大四数和 = nums[a]+nums[n-3]+nums[n-2]+nums[n-1]，
#       这是固定 a 后能取到的最大和。若 < target，当前 a 太小，continue。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 去重条件错误：
#    a > 0 and nums[a] == nums[a-1]（跳过重复），
#    不是 a >= 0 and nums[a] == nums[a+1]（会跳过第一个）。
#    b > a+1 and nums[b] == nums[b-1]，不是 b > a+1 and nums[b] == nums[b+1]。
#
# 2. 剪枝用 nums[a] > target（仅适用于 target=0 的三数之和）：
#    四数之和的 target 不一定是 0，nums[a] > target 不代表无解
#    （后面可能有负数抵消）。应使用最小/最大四数和判断。
#
# 3. 元素不重复使用 vs 数值不重复：
#    四个 2 可以组成 [2,2,2,2]，只要数组中有四个 2。
#    "不重复使用"指下标不同，不是数值不同。
#
# 4. 整数溢出（其他语言）：
#    Python 整数不溢出，但 C++/Java 中四个 10^9 相加会溢出，
#    需要用 long 或先转 long 再相加。
# ══════════════════════════════════════════════════════════
