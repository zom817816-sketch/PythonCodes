"""
# 454. 四数相加 II（4Sum II）

## 题目描述

给定四个整数数组 `A`、`B`、`C`、`D`，其中每个数组的长度都为 `n`，请计算满足

    A[i] + B[j] + C[k] + D[l] == 0

的元组 `(i, j, k, l)` 的数量。

其中，`i`、`j`、`k`、`l` 分别是四个数组中的下标。下标来自不同数组，因此即使
数组中的数值相同，只要下标组合不同，也应分别计数。

典型约束：

- `0 <= n <= 500`
- 数组中的整数范围较大
- 最终答案适合 32 位有符号整数

## 解法总览：分组 + 哈希表

直接枚举四个下标需要 `O(n^4)`，在 `n = 500` 时不可接受。

将等式改写为：

    A[i] + B[j] == -(C[k] + D[l])

可以把四个数组拆成两组：

1. 枚举 `A` 和 `B` 的所有数值对，统计每个和出现的次数。
2. 枚举 `C` 和 `D` 的所有数值对，查找其相反数在第一组中出现了多少次。

如果 `A[i] + B[j]` 出现了 `x` 次，那么每找到一个满足
`C[k] + D[l] == -(A[i] + B[j])` 的组合，就能贡献 `x` 个完整元组。

### 图解

假设第一组的部分和频次如下：

    A + B：  2 -> 3 次，  5 -> 1 次

枚举第二组时：

    C + D = -2  -> 查找 A + B =  2，答案增加 3
    C + D = -5  -> 查找 A + B =  5，答案增加 1

也就是用哈希表把四数问题转化为“两组二数和”的匹配问题。

## 正确性证明

设哈希表 `sum_count[s]` 表示所有满足 `A[i] + B[j] == s` 的下标对 `(i, j)`
数量。

对于任意固定的下标对 `(k, l)`，其对应的部分和为 `C[k] + D[l]`。完整元组
满足总和为零，当且仅当：

    A[i] + B[j] = -(C[k] + D[l])

因此，与 `(k, l)` 配对的 `(i, j)` 数量，恰好是
`sum_count[-(C[k] + D[l])]`。算法对所有 `(k, l)` 求和，所以：

- 每个被统计的组合都满足四数之和为零；
- 每个满足条件的下标元组都会在枚举其 `(k, l)` 时被统计一次；
- 不同下标组合会按频次分别计数，不会因数值重复而丢失。

所以算法返回的结果正好是符合条件的元组总数。

## 复杂度分析

设四个数组长度均为 `n`：

- 时间复杂度：`O(n^2)`，分别枚举 `A、B` 和 `C、D` 的所有数对。
- 空间复杂度：`O(n^2)`，哈希表最多保存 `n^2` 个不同的部分和。

## 易错点

1. **必须累加出现次数**：不能只记录某个和是否出现，否则重复值对应的不同下标组合会被漏算。
2. **查询相反数**：第二组的部分和是 `c + d`，应查询 `-(c + d)`，而不是直接查询 `c + d`。
3. **统计的是下标元组**：数组中数值相同并不意味着组合相同。
4. **空数组要能处理**：当 `n == 0` 时，两个循环都不会执行，答案自然为 `0`。
5. **不要使用四重循环**：虽然逻辑直观，但复杂度为 `O(n^4)`，无法通过大规模数据。
"""


def four_sum_count(A, B, C, D):
    """返回满足 ``A[i] + B[j] + C[k] + D[l] == 0`` 的元组数量。

    参数:
        A, B, C, D: 四个可迭代的整数序列。按照题目约束，它们长度相同。

    返回:
        `int`: 满足条件的下标元组 `(i, j, k, l)` 数量。

    核心不变量:
        `sum_count[s]` 始终等于已经枚举过的所有 `(i, j)` 中，
        `A[i] + B[j] == s` 的组合数。
    """
    sum_count = {}

    # 记录 A[i] + B[j] 的频次，而不是只记录是否出现过。
    # 例如 A=[1, 1]、B=[2] 时，和 3 应记录为 2。
    for a in A:
        for b in B:
            pair_sum = a + b
            sum_count[pair_sum] = sum_count.get(pair_sum, 0) + 1

    answer = 0

    # 对每个 C[k] + D[l]，寻找能与它抵消的 A[i] + B[j]。
    for c in C:
        for d in D:
            answer += sum_count.get(-(c + d), 0)

    return answer
