"""
454. 四数相加 II（4Sum II）

题目描述：
给定四个整数数组 nums1、nums2、nums3、nums4，数组长度都为 n，
计算有多少个元组 (i, j, k, l) 满足：
    nums1[i] + nums2[j] + nums3[k] + nums4[l] == 0

输入描述：
四个整数数组，长度均为 n。0 <= n <= 200，-2^28 <= nums[i] <= 2^28。

输出描述：
返回满足条件的元组数量。

输入示例 1：
nums1 = [1, 2], nums2 = [-2, -1], nums3 = [-1, 2], nums4 = [0, 2]
输出示例 1：
2
解释：两个元组为 (0, 0, 0, 1) → 1+(-2)+(-1)+2=0, (1, 1, 0, 0) → 2+(-1)+(-1)+0=0

════════════════════════════════════════════════════════════════════════
核心概念：分组 + 哈希表
════════════════════════════════════════════════════════════════════════

四数相加 II 的关键洞察：
    将 A[i] + B[j] + C[k] + D[l] == 0 改写为：
    A[i] + B[j] == -(C[k] + D[l])

    分成两组：AB 组和 CD 组。
    1. 枚举 A×B 的所有 n² 个和，用哈希表记录每个和出现的次数。
    2. 枚举 C×D 的所有 n² 个和，查找 -(c+d) 在哈希表中的次数并累加。

为什么这与三数之和/四数之和不同？
    三数之和/四数之和要求在同一数组中找不重复的三/四元组，需要排序去重。
    四数相加 II 是四个独立数组，只需计数，不需要去重，用哈希表最直接。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
暴力四重循环                  O(n⁴)           O(1)            ⭐ 超时
分组 + 哈希表                 O(n²)           O(n²)           ⭐⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想（分组 + 哈希表）：
────────────────────────────────────────────────────────────────────────
第一阶段：枚举 A×B 的所有 n² 个和，存入哈希表 sum_count[sum] = 出现次数。
第二阶段：枚举 C×D 的所有 n² 个和，对每个和 s 查找 -s 的出现次数并累加。
"""


# ══════════════════════════════════════════════════════════
# 解法一：分组 + 哈希表 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def fourSumCount(
    nums1: list[int], nums2: list[int], nums3: list[int], nums4: list[int]
) -> int:
    """分组 + 哈希表 ⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    将四数之和拆成两组两数之和。
    AB 组的和存入哈希表（记录频次），CD 组的和查相反数。

    算法步骤：
    1. sum_count = {}。
    2. 枚举 nums1 × nums2：sum_count[a+b] += 1。
    3. 枚举 nums3 × nums4：answer += sum_count.get(-(c+d), 0)。
    4. 返回 answer。

    时间复杂度：O(n²) — 两次双重循环。
    空间复杂度：O(n²) — 哈希表最多 n² 个不同和。

    图解示例：
    ────────────────────────────────────────────────────────
    nums1=[1,2], nums2=[-2,-1], nums3=[-1,2], nums4=[0,2]

    第一阶段：枚举 A+B
      1+(-2)=-1, 1+(-1)=0, 2+(-2)=0, 2+(-1)=1
      sum_count = {-1: 1, 0: 2, 1: 1}

    第二阶段：枚举 C+D，查 -(c+d)
      (-1)+0=-1 → 查 1: count=1 → answer=1
      (-1)+2=1  → 查 -1: count=1 → answer=2
      2+0=2     → 查 -2: count=0
      2+2=4     → 查 -4: count=0

    answer = 2 ✓
    """
    sum_count: dict[int, int] = {}

    # 第一阶段：统计 A[i] + B[j] 的频次
    for a in nums1:
        for b in nums2:
            s = a + b
            sum_count[s] = sum_count.get(s, 0) + 1

    # 第二阶段：查找 -(C[k] + D[l]) 的频次并累加
    answer = 0
    for c in nums3:
        for d in nums4:
            answer += sum_count.get(-(c + d), 0)

    return answer


# ══════════════════════════════════════════════════════════
# 解法二：暴力四重循环 ⭐（仅参考，会超时）
# ══════════════════════════════════════════════════════════


def fourSumCount_bruteforce(
    nums1: list[int], nums2: list[int], nums3: list[int], nums4: list[int]
) -> int:
    """暴力四重循环 ⭐

    核心思想：
    ────────────────────────────────────────────────────────
    枚举所有 (i, j, k, l) 组合，检查和是否为零。

    时间复杂度：O(n⁴) — n=200 时约 16 亿次，会超时。
    空间复杂度：O(1)。

    图解示例：
    ────────────────────────────────────────────────────────
    nums1=[1,2], nums2=[-2,-1], nums3=[-1,2], nums4=[0,2]
    枚举 2×2×2×2=16 种组合，找到 2 个和为 0 的元组。
    """
    count = 0
    for a in nums1:
        for b in nums2:
            for c in nums3:
                for d in nums4:
                    if a + b + c + d == 0:
                        count += 1
    return count


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、分组哈希表法的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：分组哈希表法返回的值恰好是满足条件的元组总数。
#
# 证明：
# （1）sum_count[s] = 所有满足 A[i]+B[j]==s 的 (i,j) 对数。
# （2）对于固定的 (k,l)，需要 A[i]+B[j] = -(C[k]+D[l])。
#     满足条件的 (i,j) 数量 = sum_count[-(C[k]+D[l])]。
# （3）对所有 (k,l) 累加，得到满足条件的 (i,j,k,l) 总数。
# （4）每个元组被恰好统计一次（在枚举其 (k,l) 时）。✓
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 只记录是否出现，不记录频次：
#    sum_count 只存 set 而非 dict，则重复值的不同下标组合会被漏算。
#    如 A=[1,1], B=[2] 时和 3 出现 2 次，必须记录频次。
#
# 2. 查询时用 c+d 而非 -(c+d)：
#    需要 A[i]+B[j] = -(C[k]+D[l])，应查 -(c+d) 的频次。
#
# 3. 统计的是下标元组数，不是数值组合数：
#    四个数组中数值相同不代表组合相同，不同下标分别计数。
#
# 4. 使用四重循环：
#    O(n⁴) 在 n=200 时约 16 亿次运算，会超时。
#    分组法 O(n²) 在 n=200 时仅 4 万次，高效。
# ══════════════════════════════════════════════════════════
