# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理（动态规划正确性）：
#     按照子串长度从小到大填充 dp 表，对于任意 i≤j，dp[i][j] 正确反映
#     s[i:j+1] 是否为回文。
#
# 证明（数学归纳法）：
# （1）基例：length=1 时，单字符天然是回文，dp[i][i]=True ✓
#           length=2 时，两字符相等即回文，dp[i][i+1]=(s[i]==s[i+1]) ✓
# （2）归纳假设：所有长度 < L 的子串的 dp 值都正确。
# （3）归纳步骤：考察长度为 L（L≥3）的子串 s[i:j+1]。
#      此时 dp[i+1][j-1] 对应的子串长度为 L-2 < L，由归纳假设其值正确。
#      dp[i][j] = (s[i]==s[j]) ∧ (长度≤2 ∨ dp[i+1][j-1])
#      若 s[i]≠s[j]，显然不是回文 ✓
#      若 s[i]==s[j]，则 s[i:j+1] 是回文当且仅当内部 s[i+1:j] 是回文，
#      而这正是 dp[i+1][j-1] 的语义 ✓
# （4）综上，由数学归纳法，所有 dp[i][j] 正确。
#
#
# 中心扩展法 vs 动态规划法对比：
# ────────────────────────────────────────────────────────
#        方法        │  时间  │ 空间  │ 代码量 │  易出错点
# ───────────────────────────┼────────┼───────┼───────┼───────────────
#  二维动态规划      │  O(n²) │ O(n²) │  中等  │ 遍历顺序、返回子串而非长度
#  一维动态规划      │  O(n²) │  O(n) │  较难  │ i和j都必须逆序、dp[j-1]语义
#  中心扩展法        │  O(n²) │  O(1) │  简洁  │ 忘记处理偶数长度回文
#  Manacher          │  O(n)  │  O(n) │  复杂  │ 预处理、半径换算还原
#
# 一维DP为什么 i 和 j 都必须逆序？
#     dp[j]（当前i行）依赖 dp[j-1]（上一轮i+1行）。
#     若 i 升序，dp 整体会是 i-1 行而非 i+1 行，方向完全错误。
#     若 j 升序，在处理 j 之前 dp[j-1] 已被同一轮覆盖为"i行"新值，
#     我们需要的"i+1行"旧值丢失，导致依赖关系被破坏。
#     所以 i 和 j 必须同时逆序遍历。
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 返回最长长度而不是子串本身 → 应同时记录起点/终点或直接切片保存
# 2. 空串和长度1未特判 → 函数开头加 if n<=1: return s
# 3. 中心扩展法只考虑了奇数长度 → 需同时调用 expand(i,i) 和 expand(i,i+1)
# 4. expand 函数退出时忘记回退指针 → 返回 l+1, r-1 而不是 l, r
# 5. 二维DP按 i 从小到大遍历而非按 length → dp[i+1][j-1] 还未计算
# 6. 一维DP按 i 或 j 升序遍历 → dp[j-1] 被覆盖导致错误，必须i和j同时逆序
# 7. Manacher半径换算错误 → 原长度 = p[i]，起点 = (i - p[i]) // 2
# ══════════════════════════════════════════════════════════


