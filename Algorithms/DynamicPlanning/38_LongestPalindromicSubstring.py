# 解法四：中心扩展法（双指针）
# ══════════════════════════════════════════════════════════


def longestPalindrome_center(s: str) -> str:
    """
    中心扩展法⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    回文天然具有"中心对称性"，可以以每个字符（奇数长度回文）或每对相邻字符
    （偶数长度回文）为中心，向左右扩展直到不再相等，记录最长的一次。
    这种方法直观简洁，空间最优，面试中最推荐使用。

    算法步骤：
    1. 特判空串或长度≤1的情况
    2. 定义辅助函数 expand(l, r)：以 s[l]~s[r] 为初始中心，向左右扩展，返回最长回文
    3. 遍历每个位置 i：
       a. 以 i 为中心调用 expand(i, i) → 奇数长度回文
       b. 以 (i, i+1) 为中心调用 expand(i, i+1) → 偶数长度回文
    4. 在所有扩展结果中选择最长的返回

    时间复杂度：O(n²) — 每个中心点最多扩展 O(n) 步，共 O(n) 个中心点
    空间复杂度：O(1) — 只使用常量级指针变量，空间最优

    图解示例：
    ────────────────────────────────────────────────────────
    s = "babad"

    奇数长度扩展（单中心）：
    i=0 中心'b': l=0,r=0 → l-1=-1停止, 回文"b" len=1
    i=1 中心'a': l=1,r=1 → l=0,r=2 s[0]='b'==s[2]='b' → l=-1停止, 回文"bab" len=3 ✓
    i=2 中心'b': l=2,r=2 → l=1,r=3 s[1]='a'==s[3]='a' → l=0,r=4 s[0]='b'≠s[4]='d'停止, 回文"aba" len=3 ✓
    i=3 中心'a': l=3,r=3 → l=2,r=4 s[2]='b'≠s[4]='d'停止, 回文"a" len=1
    i=4 中心'd': l=4,r=4 → 停止, 回文"d" len=1

    偶数长度扩展（双中心）：
    i=0 中心'ba': s[0]='b'≠s[1]='a' → 无
    i=1 中心'ab': s[1]='a'≠s[2]='b' → 无
    i=2 中心'ba': s[2]='b'≠s[3]='a' → 无
    i=3 中心'ad': s[3]='a'≠s[4]='d' → 无

    最长结果："bab"（或 "aba"）len=3 ✓

    s = "cbbd" 的偶数情况演示：
    i=1 中心'bb': s[1]='b'==s[2]='b' → l=0,r=3 s[0]='c'≠s[3]='d'停止, 回文"bb" len=2 ✓
    """
    n = len(s)
    if n <= 1:
        return s

    def expand(l: int, r: int) -> tuple[int, int]:
        """
        以 s[l:r+1] 为初始中心向左右扩展，返回最长回文的 (起点, 终点)
        注意：初始时需要保证 s[l]==s[r]，否则会返回空区间
        """
        while l >= 0 and r < n and s[l] == s[r]:
            l -= 1
            r += 1
        # 循环退出时多走了一步，所以回退一格：实际回文是 [l+1, r-1]
        return l + 1, r - 1

    max_length = 1
    result = s[0]

    for i in range(n):
        # 奇数长度回文：以 s[i] 为中心
        l1, r1 = expand(i, i)
        len1 = r1 - l1 + 1
        if len1 > max_length:
            max_length = len1
            result = s[l1:r1 + 1]

        # 偶数长度回文：以 s[i] 和 s[i+1] 为中心
        if i + 1 < n:
            l2, r2 = expand(i, i + 1)
            len2 = r2 - l2 + 1
            if len2 > max_length:
                max_length = len2
                result = s[l2:r2 + 1]

    return result


