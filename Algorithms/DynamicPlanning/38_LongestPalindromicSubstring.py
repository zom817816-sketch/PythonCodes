# 解法五：Manacher 算法（马拉车算法）
# ══════════════════════════════════════════════════════════


def longestPalindrome_manacher(s: str) -> str:
    """
    Manacher（马拉车）算法⭐⭐⭐⭐⭐ 时间最优

    核心思想：
    ────────────────────────────────────────────────────────
    巧妙利用回文的对称性，在线性时间内求出最长回文子串。
    核心技巧：
    1. 在字符间插入特殊分隔符（如'#'），将奇数/偶数长度回文统一为奇数长度处理
       例："cbbd" → "^#c#b#b#d#$"（^和$为哨兵，避免边界判断）
    2. 维护当前已知的"最右回文"边界 [L, R]，利用对称点的信息跳过不必要的扩展
       若当前位置 i 在 R 内，则其关于中心 C 的镜像点 j=2C-i 的 p[j] 值可直接复用，
       只需从 min(p[j], R-i) 开始扩展即可

    算法步骤：
    1. 对原字符串进行预处理，插入'#'分隔符和首尾哨兵
    2. 初始化 p 数组（p[i] 表示以 t[i] 为中心的最长回文半径）、中心 C、右边界 R
    3. 遍历每个位置 i：
       a. 计算镜像点 mirror = 2*C - i
       b. 若 i < R，则 p[i] = min(R - i, p[mirror])（利用对称性跳过已匹配部分）
       c. 以 i 为中心继续向左右扩展，更新 p[i]
       d. 若扩展后 i+p[i] > R，更新 C 和 R
    4. 找到 p 数组中最大值对应的中心，还原回原字符串的子串位置

    时间复杂度：O(n) — 每个位置最多被扩展访问一次，R 单调递增保证线性
    空间复杂度：O(n) — 需要长度为 2n+3 的预处理字符串和 p 数组

    图解示例：
    ────────────────────────────────────────────────────────
    s = "babad"
    预处理 t = "^#b#a#b#a#d#$"（索引 0-12）

    关键步骤（摘取几步）：
    i=3(t='#'): mirror=2*2-3=1, i<R=5 → p[3]=min(5-3=2, p[1]=0)=0
                 扩展: t[2]='b'==t[4]='b'(+1), t[1]='#'==t[5]='#'(+1), t[0]='^'≠t[6]='a'停止
                 p[3]=2, i+p[i]=5 ≤ R=5, 不更新
    i=4(t='b'): mirror=2*2-4=0, i<R=5 → p[4]=min(5-4=1, p[0]=0)=0
                 扩展: t[3]='#'==t[5]='#'(+1), t[2]='b'==t[6]='a'✗停止
                 p[4]=1, i+p[i]=5 ≤ R=5
    i=5(t='#'): i==R=5 → p[5]=0, 不使用对称性
                 扩展: t[4]='b'==t[6]='a'✗停止, p[5]=0
                 i+p[i]=5 ≤ R=5
    i=6(t='a'): i>R=5 → p[6]=0, 不使用对称性
                 扩展: t[5]='#'==t[7]='#'(+1), t[4]='b'==t[8]='b'(+1), t[3]='#'==t[9]='#'(+1),
                       t[2]='b'==t[10]='d'✗停止
                 p[6]=3, i+p[i]=9 > R=5 → 更新 C=6, R=9

    最终 p 数组中最大值为 p[3]=4（对应中心 'a'，半径4）或 p[5]=4（对应中心 'b'）
    还原：半径4 → 原长度=4，起始位置 (3-4)/2=0.5？不对
    实际上最大 p[i]=4，中心位置 i，原长度 = p[i]，起始 = (i - p[i]) // 2
    结果：s[0:3] = "bab" 或 s[1:4] = "aba" ✓
    """
    n = len(s)
    if n <= 1:
        return s

    # 预处理：在每个字符间插入 '#'，首尾添加不同哨兵避免边界判断
    # '^' 和 '$' 不相等，因此扩展时自然不会越界
    t = '^#' + '#'.join(s) + '#$'
    m = len(t)  # m = 2*n + 3

    # p[i] 表示以 t[i] 为中心的最长回文"半径"（包含中心，即回文长度为 2*p[i]+1 时半径为 p[i]）
    # 注意：这里实现的 p[i] 含义是"单边扩展长度"，即中心到一端的字符数（不含中心）
    # 所以以 t[i] 为中心的最长回文长度 = 2*p[i] + 1
    p = [0] * m
    center = 0      # 当前已知最右回文的中心
    right = 0       # 当前已知最右回文的右边界（不含右边界本身）

    for i in range(1, m - 1):
        # 当前位置 i 关于 center 的镜像点
        mirror = 2 * center - i

        # 核心优化：如果 i 在当前最右回文内部，利用镜像点信息赋予初始值
        if i < right:
            p[i] = min(right - i, p[mirror])

        # 以 i 为中心继续向左右扩展（跳过上面已经确定的 p[i] 步）
        while t[i + 1 + p[i]] == t[i - 1 - p[i]]:
            p[i] += 1

        # 如果当前扩展出的右边界超过了已知的 right，更新 center 和 right
        if i + p[i] > right:
            center = i
            right = i + p[i]

    # 找到最大半径及其对应的中心位置
    max_radius = 0
    center_idx = 0
    for i in range(1, m - 1):
        if p[i] > max_radius:
            max_radius = p[i]
            center_idx = i

    # 将预处理字符串中的中心和半径还原为原字符串的子串
    # 原字符串中起点 = (center_idx - max_radius) // 2
    # 原字符串中长度 = max_radius（因为 # 的数量刚好抵消了长度换算）
    start = (center_idx - max_radius) // 2
    return s[start:start + max_radius]


