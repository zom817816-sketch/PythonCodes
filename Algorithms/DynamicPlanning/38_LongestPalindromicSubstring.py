"""
最长回文子串（Longest Palindromic Substring）

题目描述：
给你一个字符串 s，找到 s 中最长的 回文 子串。

输入描述：
一个字符串 s，长度范围 [0, 1000]

输出描述：
s 中最长的回文子串

输入示例：
示例 1：s = "babad"
输出示例："bab"（"aba" 同样是符合题意的答案）

示例 2：s = "cbbd"
输出示例："bb"

════════════════════════════════════════════════════════════════════════
核心概念：回文子串 vs 回文子序列
════════════════════════════════════════════════════════════════════════

┌─────────────────┬─────────────────────────────────────────────────────┐
│ 概念            │ 说明                                                │
├─────────────────┼─────────────────────────────────────────────────────┤
│ 回文子串        │ 连续的字符序列，正读和反读相同，如 "bab"             │
│ 回文子序列      │ 不要求连续，只需相对顺序保持，如 "aab" 的子序列 "aa"  │
│ 中心对称        │ 回文的本质性质，可围绕一个或两个字符对称展开         │
└─────────────────┴─────────────────────────────────────────────────────┘

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
回溯/暴力搜索法                 O(n³)            O(1)             ⭐⭐   基础理解
动态规划法（二维）              O(n²)            O(n²)            ⭐⭐⭐ 经典DP
动态规划法（一维优化）          O(n²)            O(n)             ⭐⭐⭐ 空间优化
中心扩展法                      O(n²)            O(1)             ⭐⭐⭐⭐ 推荐，简洁
Manacher算法                    O(n)             O(n)             ⭐⭐⭐⭐⭐ 最优
────────────────────────────────────────────────────────────────────────

核心思想（动态规划）：
────────────────────────────────────────────────────────────────────────
如果一个长度 > 2 的字符串是回文，那么去掉首尾字符后，剩下的子串也一定是回文。

状态定义：
    dp[i][j]：表示字符串 s 中从索引 i 到 j（闭区间）的子串是否为回文

状态转移：
    dp[i][j] = (s[i] == s[j]) and (j - i < 2 or dp[i+1][j-1])
    即：首尾字符相同，且（子串长度≤2 或 去掉首尾后的子串是回文）

初始条件：
    - 长度为1的子串一定是回文：dp[i][i] = True
    - 长度为2的子串：dp[i][i+1] = (s[i] == s[i+1])

最终答案：
    所有 dp[i][j] = True 中，最长的 s[i:j+1]
"""


# ══════════════════════════════════════════════════════════
# 解法一：回溯/暴力搜索法
# ══════════════════════════════════════════════════════════


def longestPalindrome_backtrack(s: str) -> str:
    """
    回溯/暴力搜索法⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    枚举所有可能的子串（即枚举所有起点i和终点j），逐一判断是否为回文，
    记录最长的那个。本质是两次嵌套循环枚举区间 + 一次循环判断回文。

    算法步骤：
    1. 若字符串为空或长度≤1，直接返回
    2. 外层循环 i 枚举子串的起始位置
    3. 内层循环 j 枚举子串的结束位置（j >= i）
    4. 对每个子串 s[i:j+1]，调用辅助函数判断是否为回文
    5. 若是回文且长度超过当前最大值，则更新结果

    时间复杂度：O(n³) — 枚举子串O(n²)，每个子串判断回文O(n)
    空间复杂度：O(1) — 只使用常量级额外空间

    图解示例：
    ────────────────────────────────────────────────────────
    s = "babad"
    i=0: j=0 "b"✓ len=1; j=1 "ba"✗; j=2 "bab"✓ len=3; j=3 "baba"✗; j=4 "babad"✗
    i=1: j=1 "a"✓ len=1; j=2 "ab"✗; j=3 "aba"✓ len=3; j=4 "abad"✗
    i=2: j=2 "b"✓ len=1; j=3 "ba"✗; j=4 "bad"✗
    i=3: j=3 "a"✓ len=1; j=4 "ad"✗
    i=4: j=4 "d"✓ len=1
    最长为 "bab"（或 "aba"），长度 3 ✓

    适用场景：帮助理解问题本质，不适合大数据量
    """
    n = len(s)
    if n <= 1:
        return s

    def is_palindrome(l: int, r: int) -> bool:
        """判断 s[l:r+1] 是否为回文（双指针对撞）"""
        while l < r:
            if s[l] != s[r]:
                return False
            l += 1
            r -= 1
        return True

    max_len = 1
    result = s[0]

    # 枚举所有子串的起点 i 和终点 j
    for i in range(n):
        for j in range(i + 1, n):
            if is_palindrome(i, j):
                length = j - i + 1
                if length > max_len:
                    max_len = length
                    result = s[i:j + 1]

    return result


# ══════════════════════════════════════════════════════════
# 解法二：动态规划法（二维数组）
# ══════════════════════════════════════════════════════════


def longestPalindrome_dp(s: str) -> str:
    """
    动态规划法（二维）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    利用回文的最优子结构：长回文的"内部子串"也必然是回文。
    用 dp[i][j] 记录 s[i:j+1] 是否为回文，避免暴力法中重复判断内部子串。

    算法步骤：
    1. 特判空串或长度≤1的情况
    2. 初始化 n×n 的二维布尔数组 dp，dp[i][i] = True（单字符天然是回文）
    3. 按子串长度从小到大遍历（length = 1, 2, ..., n），保证求 dp[i][j] 时 dp[i+1][j-1] 已算好
    4. 对每个长度，遍历所有起点 i，计算终点 j = i + length - 1
    5. 若 s[i]==s[j] 且（length<3 或 dp[i+1][j-1]），则 dp[i][j]=True，更新最长结果
    6. 返回记录的最长回文子串

    时间复杂度：O(n²) — 双层循环填充 n×n 的 dp 表，每个位置O(1)判断
    空间复杂度：O(n²) — 需要 n×n 的二维数组

    图解示例：
    ────────────────────────────────────────────────────────
    s = "babad"（索引 0-4）

    dp 表填充顺序（按子串长度）：
    length=1: (0,0)=T, (1,1)=T, (2,2)=T, (3,3)=T, (4,4)=T
    length=2: (0,1) b-a=F, (1,2) a-b=F, (2,3) b-a=F, (3,4) a-d=F
    length=3: (0,2) b-a-b: s[0]==s[2]且dp[1][1]=T → T ✓ 结果"bab"
             (1,3) a-b-a: s[1]==s[3]且dp[2][2]=T → T ✓ 结果"aba"
             (2,4) b-a-d: s[2]≠s[4] → F
    length=4: (0,3) b-a-b-a: s[0]==s[3]但dp[1][2]=F → F
             (1,4) a-b-a-d: s[1]≠s[4] → F
    length=5: (0,4) b-a-b-a-d: s[0]≠s[4] → F

    结果："bab" 或 "aba"，长度 3 ✓
    """
    n = len(s)
    if n <= 1:
        return s

    # dp[i][j] 表示 s[i:j+1] 是否为回文
    dp = [[False] * n for _ in range(n)]
    max_length = 1
    result = s[0]

    # 按子串长度从小到大遍历，保证依赖的子问题已求解
    for length in range(1, n + 1):
        for i in range(n - length + 1):
            j = i + length - 1
            # 核心状态转移：首尾相等 + （长度≤2 或 内部子串是回文）
            if s[i] == s[j] and (length < 3 or dp[i + 1][j - 1]):
                dp[i][j] = True
                if length > max_length:
                    max_length = length
                    result = s[i:j + 1]

    return result


# ══════════════════════════════════════════════════════════
# 解法三：动态规划法（一维空间优化）
# ══════════════════════════════════════════════════════════


def longestPalindrome_dp1d(s: str) -> str:
    """
    动态规划法（一维空间优化）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    观察二维DP的状态转移：dp[i][j] 只依赖于 dp[i+1][j-1]（即"左下角"位置）。
    因此可以将二维表压缩为一维数组，只保留当前"行"的信息。
    需要逆序遍历起点 i，避免覆盖下次迭代还需要的 dp[j-1]（原 dp[i+1][j-1]）。

    算法步骤：
    1. 特判空串或长度≤1的情况
    2. 初始化一维布尔数组 dp，长度为 n
    3. 逆序遍历起点 i（从 n-1 到 0），保证求 dp 时保存的是上一轮 i+1 的值
    4. 对每个 i，逆序遍历终点 j（从 n-1 到 i），保证 dp[j] 依赖 dp[j-1] 时 dp[j-1] 未被覆盖
    5. 若 s[i]==s[j] 且（j-i<2 或 dp[j-1]），则 dp[j]=True，更新最长结果
       注意：此处 dp[j-1] 实际对应二维中的 dp[i+1][j-1]
    6. 返回记录的最长回文子串

    时间复杂度：O(n²) — 仍为双层循环，时间与二维DP相同
    空间复杂度：O(n) — 只使用一维数组，相比二维节省了 O(n) 空间

    图解示例：
    ────────────────────────────────────────────────────────
    s = "babad"，n=5

    逆序遍历 i，同时 j 也逆序遍历（关键！否则 dp[j-1] 会被覆盖）：
    i=4: j=4 s[4]='d', j-i<2 → dp[4]=T, 结果"d"
    i=3: j=4 s[3]='a'≠s[4]='d' → dp[4]=F
         j=3 s[3]='a' → dp[3]=T
    i=2: j=4 s[2]='b'≠s[4]='d' → dp[4]=F
         j=3 s[2]='b'≠s[3]='a' → dp[3]=F
         j=2 s[2]='b' → dp[2]=T
    i=1: j=4 s[1]='a'≠s[4]='d' → dp[4]=F
         j=3 s[1]='a'==s[3]='a'且dp[2]==T → dp[3]=T, 结果"aba" len=3 ✓
         j=2 s[1]='a'≠s[2]='b' → dp[2]=F
         j=1 s[1]='a' → dp[1]=T
    i=0: j=4 s[0]='b'≠s[4]='d' → dp[4]=F
         j=3 s[0]='b'≠s[3]='a' → dp[3]=F
         j=2 s[0]='b'==s[2]='b'且dp[1]==T → dp[2]=T, 结果"bab" len=3 ✓
         j=1 s[0]='b'≠s[1]='a' → dp[1]=F
         j=0 s[0]='b' → dp[0]=T

    最终结果："bab" 或 "aba" ✓
    """
    n = len(s)
    if n <= 1:
        return s

    # 一维 dp 数组，最终 dp[j] 保存当前 i 下 s[i:j+1] 是否为回文
    # 每次外循环开始时，dp 整体保存的是"上一轮 i+1 行"的结果
    dp = [False] * n
    max_length = 1
    result = s[0]

    # i 必须逆序，保证求 dp[j] 时 dp 中尚未修改的部分对应 i+1 行
    for i in range(n - 1, -1, -1):
        # j 也必须逆序！因为 dp[j] 依赖 dp[j-1]
        # 若 j 正序，dp[j-1] 在本次循环中会先被覆盖为"i行"的值，破坏依赖
        for j in range(n - 1, i - 1, -1):
            # s[i]==s[j] 且（长度≤2 或 内部子串是回文，dp[j-1] 仍是 i+1 行的值）
            if s[i] == s[j] and (j - i < 2 or dp[j - 1]):
                dp[j] = True
                if j - i + 1 > max_length:
                    max_length = j - i + 1
                    result = s[i:j + 1]
            else:
                dp[j] = False

    return result


