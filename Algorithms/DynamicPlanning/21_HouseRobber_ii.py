"""
打家劫舍 II（House Robber II）

题目描述：
你是一个专业的小偷，计划偷窃沿街的房屋，每间房内都藏有一定的现金。
这个地方所有的房屋都 围成一圈 ，这意味着第一个房屋和最后一个房屋是紧挨着的。
同时，相邻的房屋装有相互连通的防盗系统，如果两间相邻的房屋在同一晚上被小偷闯入，
系统会自动报警。

给定一个代表每个房屋存放金额的非负整数数组，计算你 在不触动警报装置的情况下 ，
今晚能够偷窃到的最高金额。

示例 1：
输入：nums = [2,3,2]
输出：3
解释：你不能先偷窃 1 号房屋（金额 = 2），然后偷窃 3 号房屋（金额 = 2）, 因为他们是相邻的。

示例 2：
输入：nums = [1,2,3,1]
输出：4
解释：你可以先偷窃 1 号房屋（金额 = 1），然后偷窃 3 号房屋（金额 = 3）。
     偷窃到的最高金额 = 1 + 3 = 4 。

示例 3：
输入：nums = [1,2,3]
输出：3

════════════════════════════════════════════════════════════════════════
核心联系：本题与打家劫舍 I 的关系
════════════════════════════════════════════════════════════════════════

维度              打家劫舍 I（线性）              打家劫舍 II（环形）
────────────────────────────────────────────────────────────────────────
房屋排列          线性排列，首尾不相邻            环形排列，首尾相邻
递推公式          dp[i] = max(dp[i-1], dp[i-2]+nums[i])  与 I 相同
关键区别          无首尾限制                      不能同时偷第一个和最后一个
解法思路          直接 DP 求解                    拆分为两个线性问题求解
────────────────────────────────────────────────────────────────────────

为什么本题需要拆分为两个子问题？
────────────────────────────────────────────────────────────────────────
由于房屋围成一圈，第一个和最后一个房屋相邻，不能同时偷窃。因此：
1. 如果偷第一个房屋，就不能偷最后一个房屋 → 问题转化为偷 [0..n-2]
2. 如果不偷第一个房屋，就可以偷最后一个房屋 → 问题转化为偷 [1..n-1]
取两种情况的最大值即为答案。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
动态规划（环形问题）           O(n)            O(1)            ⭐⭐⭐⭐⭐ 
───────────────────────────────────────────────────────────────────────

核心思想（动态规划）：
────────────────────────────────────────────────────────────────────────
关键洞察：
1. 环形问题 → 拆分为两个线性问题
2. 问题1：偷 [0..n-2]（不偷最后一个）
3. 问题2：偷 [1..n-1]（不偷第一个）
4. 答案 = max(问题1的解, 问题2的解)

状态定义（一维 DP，线性问题）：
    dp[i] = 前 i+1 间房屋（nums[0..i]）能偷窃到的最高金额

状态转移（线性问题）：
    dp[i] = max(dp[i - 1], dp[i - 2] + nums[i])

初始条件（线性问题）：
    dp[0] = nums[0]（只有一间房屋，只能偷它）
    dp[1] = max(nums[0], nums[1])（两间房屋，偷金额较大的）

最终答案（环形问题）：
    max(rob_linear(nums[0..n-2]), rob_linear(nums[1..n-1]))
"""


def rob_linear_dp(nums: list[int]) -> int:
    """
    动态规划解法（Bottom-Up DP）⭐⭐⭐⭐⭐ 最优空间 — 线性问题，滚动变量

    核心思想：
    ────────────────────────────────────────────────────────
    观察到状态转移只依赖 dp[i-1] 和 dp[i-2]，可以用两个变量代替数组。

    算法步骤：
    1. 使用两个变量 prev_prev（dp[i-2]）和 prev（dp[i-1]）
    2. 遍历每个房屋，更新当前最大值 curr
    3. 滚动更新 prev_prev 和 prev

    时间复杂度：O(n) — 单循环
    空间复杂度：O(1) — 常数空间

    状态定义：
    - prev_prev = dp[i-2] = 前 i-1 间房屋能偷窃的最高金额
    - prev = dp[i-1] = 前 i 间房屋能偷窃的最高金额
    - curr = dp[i] = 前 i+1 间房屋能偷窃的最高金额

    状态转移：
    - curr = max(prev, prev_prev + nums[i])

    初始条件：
    - prev_prev = nums[0]（第 0 间房屋）
    - prev = max(nums[0], nums[1])（前 2 间房屋）

    最终答案：
    - prev（遍历结束后，prev 就是 dp[n-1]）
    """
    n = len(nums)
    if n == 0:                   # 特殊情况：没有房屋
        return 0
    if n == 1:                   # 特殊情况：只有一间房屋
        return nums[0]

    prev_prev = nums[0]          # dp[0]：第 0 间房屋
    prev = max(nums[0], nums[1])  # dp[1]：前 2 间房屋的最大值

    for i in range(2, n):        # 遍历从第 2 间到第 n-1 间房屋
        # 当前最大值 = max(不偷当前房屋, 偷当前房屋)
        curr = max(prev, prev_prev + nums[i])
        prev_prev = prev         # 滚动更新：dp[i-2] = dp[i-1]
        prev = curr              # 滚动更新：dp[i-1] = dp[i]

    return prev  # 返回前 n 间房屋能偷窃的最高金额


# ══════════════════════════════════════════════════════════
# 解法五：动态规划（Bottom-Up DP）— 环形问题，最终解法
# ══════════════════════════════════════════════════════════


def rob_circular(nums: list[int]) -> int:
    """
    动态规划解法（Bottom-Up DP）⭐⭐⭐⭐⭐ 最终解法 — 环形问题

    核心思想：
    ────────────────────────────────────────────────────────
    将环形问题拆分为两个线性问题求解。
    由于第一个和最后一个房屋相邻，不能同时偷窃，因此：
    1. 偷 [0..n-2]（不偷最后一个）
    2. 偷 [1..n-1]（不偷第一个）
    取两种情况的最大值即为答案。

    算法步骤：
    1. 如果只有一间房屋，直接返回 nums[0]
    2. 计算不偷最后一个房屋时的最高金额：rob_linear_dp(nums[:-1])
    3. 计算不偷第一个房屋时的最高金额：rob_linear_dp(nums[1:])
    4. 返回两种情况的最大值

    时间复杂度：O(n) — 两个线性 DP，各 O(n)
    空间复杂度：O(1) — 滚动变量优化

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [2, 3, 2]

    情况1：偷 [0..1] = [2, 3] → 最大值 = max(2, 3) = 3
    情况2：偷 [1..2] = [3, 2] → 最大值 = max(3, 2) = 3
    答案：max(3, 3) = 3 ✓

    nums = [1, 2, 3, 1]

    情况1：偷 [0..2] = [1, 2, 3] → 最大值 = max(max(1,2), 1+3) = max(2, 4) = 4
    情况2：偷 [1..3] = [2, 3, 1] → 最大值 = max(max(2,3), 2+1) = max(3, 3) = 3
    答案：max(4, 3) = 4 ✓

    状态定义：
    - 复用 rob_linear_dp 的状态定义

    状态转移：
    - 复用 rob_linear_dp 的状态转移

    初始条件：
    - 复用 rob_linear_dp 的初始条件

    最终答案：
    - max(rob_linear_dp(nums[:-1]), rob_linear_dp(nums[1:]))
    """
    n = len(nums)
    if n == 0:                   # 特殊情况：没有房屋
        return 0
    if n == 1:                   # 特殊情况：只有一间房屋（环形不影响）
        return nums[0]

    # 情况1：不偷最后一个房屋，偷 [0..n-2]
    result1 = rob_linear_dp(nums[:-1])

    # 情况2：不偷第一个房屋，偷 [1..n-1]
    result2 = rob_linear_dp(nums[1:])

    # 返回两种情况的最大值
    return max(result1, result2)


# ══════════════════════════════════════════════════════════
# 重要说明：算法正确性说明与易错点提醒
# ══════════════════════════════════════════════════════════
#
# 算法正确性说明：
# ────────────────────────────────────────────────────────
# 1. 环形问题拆分为线性问题的正确性：
#    - 由于房屋围成一圈，第一个和最后一个不能同时偷
#    - 枚举所有可能的合法情况：
#      * 偷第一个 → 不能偷最后一个 → 问题转化为偷 [0..n-2]
#      * 不偷第一个 → 可以偷最后一个 → 问题转化为偷 [1..n-1]
#    - 这两种情况覆盖了所有合法的偷窃方案
#    - 取最大值即为最优解
#
# 2. 线性问题动态规划的正确性：
#    - dp[i] 表示前 i+1 间房屋能偷窃的最高金额
#    - 对于第 i 间房屋，有两种选择：
#      * 不偷：最高金额等于前 i 间的最高金额，即 dp[i-1]
#      * 偷：最高金额等于前 i-1 间的最高金额 + 当前金额，即 dp[i-2] + nums[i]
#    - 取两种选择的最大值，得到 dp[i]
#
# 3. 滚动变量优化的正确性：
#    - 状态转移只依赖 dp[i-1] 和 dp[i-2]，用两个变量保存即可
#    - 每次迭代后，prev_prev 和 prev 分别向前滚动
#    - 最终 prev 就是 dp[n-1]，即答案
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 忘记处理边界情况
#    - 错误：不检查 n == 0 或 n == 1
#    - 后果：当 nums 为空时会导致索引越界；当只有一间房屋时，环形无意义
#    - 正确：先处理特殊情况，再进行正常逻辑
#
# 2. 错误地认为需要同时考虑三个情况
#    - 错误：分别计算"偷第一个不偷最后一个"、"不偷第一个偷最后一个"、"都不偷"
#    - 后果：增加不必要的计算，"都不偷"的情况已被包含在前两种情况中
#    - 正确：只需要计算两种情况：[0..n-2] 和 [1..n-1]
#
# 3. 拆分问题时索引错误
#    - 错误：nums[:n-1] 写成 nums[:n]（包含了最后一个房屋）
#    - 后果：可能同时偷第一个和最后一个，违反环形约束
#    - 正确：nums[:-1] 表示不包含最后一个元素，nums[1:] 表示不包含第一个元素
#
# 4. 状态转移方程错误
#    - 错误：dp[i] = dp[i-1] + nums[i]（偷当前房屋，但忘记不能偷相邻的）
#    - 后果：可能偷了相邻的房屋，违反题目约束
#    - 正确：dp[i] = max(dp[i-1], dp[i-2] + nums[i])
#
# 5. 初始条件错误
#    - 错误：dp[1] = nums[1]（只考虑偷第 2 间房屋）
#    - 后果：忽略了偷第 1 间房屋可能更优的情况
#    - 正确：dp[1] = max(nums[0], nums[1])
#
# 6. 滚动变量更新顺序错误
#    - 错误：先更新 prev，再更新 prev_prev
#    - 后果：prev_prev 会被覆盖，丢失 dp[i-2] 的值
#    - 正确：先更新 prev_prev = prev，再更新 prev = curr
#
# 7. 混淆房屋索引
#    - 错误：认为 dp[i] 表示第 i 间房屋的金额
#    - 正确：dp[i] 表示前 i+1 间房屋（nums[0..i]）能偷窃的最高金额
#
# 8. 回溯算法中遗漏选择
#    - 错误：只考虑偷或只考虑不偷
#    - 后果：无法枚举所有可能的组合
#    - 正确：两种选择都要尝试，取最大值
# ══════════════════════════════════════════════════════════
