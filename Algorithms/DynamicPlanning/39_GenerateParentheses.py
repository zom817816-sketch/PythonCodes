"""
括号生成（Generate Parentheses）

题目描述：
数字 n 代表生成括号的对数，请你设计一个函数，能够生成所有可能的并且
有效的括号组合。

输入描述：
一个整数 n，表示括号的对数。

输出描述：
返回所有可能的有效括号组合，顺序不限。

输入示例：
n = 3
输出示例：
["((()))","(()())","(())()","()(())","()()()"]

输入示例：
n = 1
输出示例：
["()"]

════════════════════════════════════════════════════════════════════════
核心概念：什么是「有效括号」？
════════════════════════════════════════════════════════════════════════

有效括号必须同时满足两条规则：
────────────────────────────────────────────────────────────────────────
规则                          含义                         反例
────────────────────────────────────────────────────────────────────────
1. 左右括号数量相等            最终 left == right == n      "))((" ✗
2. 任意前缀中，左括号数 ≥ 右括号数  不会出现「先关后开」        "())(" ✗
────────────────────────────────────────────────────────────────────────

示例推演（n = 2）：
────────────────────────────────────────────────────────────────────────
"()()"  ✓  任意前缀：'(', '()', '()(', '()()'  左≥右 始终成立
"(())"  ✓
")("    ✗  第一个字符就是 ')'，左 < 右
"(()"   ✗  最终数量不等（少一个 ')'）
"())("  ✗  前缀 "())" 时右括号已经多于左括号

与卡塔兰数的关系：
────────────────────────────────────────────────────────────────────────
合法括号序列的个数恰好是第 n 个卡塔兰数：
    C(n) = (1/(n+1)) × C(2n, n) = (2n)! / ((n+1)! × n!)

    C(1)=1, C(2)=2, C(3)=5, C(4)=14, C(5)=42, ...

本题不仅要求「个数」，还要求「枚举所有合法序列」。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
回溯（DFS + 剪枝）             O(4^n/√n)       O(n)            ⭐⭐⭐⭐ 推荐
动态规划（按结构拆分）         O(4^n/√n)       O(4^n/√n)       ⭐⭐⭐  与卡塔兰递推
────────────────────────────────────────────────────────────────────────
注：答案个数本身是卡塔兰数 Θ(4^n/n^{3/2})，输出规模决定了时间下界。

核心思想（回溯）：
────────────────────────────────────────────────────────────────────────
在长度为 2n 的字符串上做 DFS，每一步选 '(' 或 ')'，用两条剪枝保证合法：
    - left < n 时才能放 '('（左括号最多 n 个）
    - right < left 时才能放 ')'（右括号不能超过已有的左括号）

核心思想（动态规划）：
────────────────────────────────────────────────────────────────────────
任意合法括号串可唯一拆成：
    "(" + 【内部合法串 A】 + ")" + 【右侧合法串 B】

若整串用了 i 对括号，则 A 用 j 对，B 用 i-j-1 对（j = 0..i-1）。

状态定义：
    dp[i] = 使用 i 对括号能生成的所有合法序列列表

状态转移：
    dp[i] = { "(" + left + ")" + right
              | j ∈ [0, i), left ∈ dp[j], right ∈ dp[i-j-1] }

初始条件：
    dp[0] = [""]   （0 对括号：空串，便于拼接）

最终答案：
    dp[n]
"""


# ══════════════════════════════════════════════════════════
# 解法一：回溯（DFS + 剪枝）
# ══════════════════════════════════════════════════════════


def generateParenthesis_backtrack(n: int) -> list[str]:
    """
    回溯解法（DFS + 剪枝）⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    从空串开始，每次追加一个括号；用 left / right 计数剪枝，
    保证生成的每一个长度为 2n 的串都是合法的。

    算法步骤：
    1. 若当前串长度 == 2n，收进答案并返回
    2. 若 left < n，尝试追加 '('，递归
    3. 若 right < left，尝试追加 ')'，递归
    4. （回溯：用参数传字符串，无需显式撤销）

    时间复杂度：O(4^n / √n) — 与卡塔兰数同阶，需枚举所有合法串
    空间复杂度：O(n) — 递归深度最多 2n；不计答案列表时为 O(n)

    图解示例（n = 2）：
    ────────────────────────────────────────────────────────
                    ""
                   /
                 "("          left=1, right=0
                /   \\
             "(("    "()"
             /         \\
          "(()"       "()("
            |            |
          "(())"       "()()"
            ✓            ✓

    决策点说明：
    - 在 "(" 处：left=1<2，可加 '('；right=0<1，也可加 ')'
    - 在 "((" 处：left=2，不能再加 '('；right=0<2，只能加 ')'
    - 在 "()" 处：left=1<2，可加 '('；right=1==left，不能加 ')'

    结果：["(())", "()()"] ✓
    """
    if n <= 0:
        return []

    result: list[str] = []

    def backtrack(s: str, left: int, right: int) -> None:
        # 已放满 2n 个字符，当前路径一定合法
        if len(s) == 2 * n:
            result.append(s)
            return

        # 左括号尚未用完 → 可以继续放 '('
        if left < n:
            backtrack(s + "(", left + 1, right)

        # 右括号少于左括号 → 可以放 ')'（保证任意前缀左 ≥ 右）
        if right < left:
            backtrack(s + ")", left, right + 1)

    backtrack("", 0, 0)
    return result


# ══════════════════════════════════════════════════════════
# 解法二：动态规划（按括号结构拆分）
# ══════════════════════════════════════════════════════════


def generateParenthesis(n: int) -> list[str]:
    """
    动态规划解法（结构拆分）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    合法括号串的唯一标准形：
        S = "(" + A + ")" + B
    其中 A、B 仍是合法括号串（可以为空）。
    枚举 A 用掉的括号对数 j，B 用掉 i-j-1 对，组合得到 dp[i]。

    算法步骤：
    1. 初始化 dp[0] = [""]
    2. 对 i = 1..n：
         对 j = 0..i-1：
           遍历 left ∈ dp[j]、right ∈ dp[i-j-1]
           拼出 "(" + left + ")" + right 加入 dp[i]
    3. 返回 dp[n]

    时间复杂度：O(4^n / √n) — 生成全部卡塔兰数量级的串
    空间复杂度：O(4^n / √n) — 需存下所有中间规模的合法串

    图解示例（n = 3）：
    ────────────────────────────────────────────────────────
    dp[0] = [""]

    i=1, j=0：A∈dp[0], B∈dp[0]
        → "(" + "" + ")" + "" = "()"
    dp[1] = ["()"]

    i=2：
        j=0：A="", B∈dp[1] → "()" + "()" = "()()"
        j=1：A∈dp[1], B="" → "(" + "()" + ")" = "(())"
    dp[2] = ["()()", "(())"]

    i=3：
        j=0：A="", B∈dp[2]
            → "()" + "()()" = "()()()"
            → "()" + "(())" = "()(())"
        j=1：A∈dp[1], B∈dp[1]
            → "(" + "()" + ")" + "()" = "(())()"
        j=2：A∈dp[2], B=""
            → "(" + "()()" + ")" = "(()())"
            → "(" + "(())" + ")" = "((()))"
    dp[3] = ["()()()", "()(())", "(())()", "(()())", "((()))"]

    结果：5 个合法串，与 C(3)=5 一致 ✓
    """
    if n <= 0:
        return []

    # dp[i]：恰好使用 i 对括号的所有合法序列
    dp: list[list[str]] = [[] for _ in range(n + 1)]
    dp[0] = [""]  # 空串：便于作为 A 或 B

    for i in range(1, n + 1):
        # j = A 使用的括号对数；B 使用 i - j - 1 对
        for j in range(i):
            for left in dp[j]:
                for right in dp[i - j - 1]:
                    # 标准形： ( A ) B
                    dp[i].append("(" + left + ")" + right)

    return dp[n]


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明（回溯）：
# ────────────────────────────────────────────────────────
#
# 定理：回溯剪枝生成的串集合 = 全部合法括号串集合。
#
# 证明：
# （1）合法性（生成的都合法）
#     - left ≤ n、right ≤ left 保证全程：右括号数 ≤ 左括号数 ≤ n
#     - 结束时长度 = 2n 且 left = right = n，故数量相等
#     - 任意前缀均满足左 ≥ 右 → 合法
#
# （2）完备性（合法的都能生成）
#     - 任意合法串可从左到右读出；每一步追加的括号都满足上述剪枝条件
#     - DFS 会尝试所有满足剪枝的分支 → 覆盖全部合法串
#
# （3）无重复
#     - 每一步只在当前末尾追加一个字符，路径由字符序列唯一决定
#     - 不同路径对应不同字符串
#
#
# 算法正确性证明（动态规划）：
# ────────────────────────────────────────────────────────
#
# 定理：任意非空合法括号串可唯一写成 "(" + A + ")" + B，
#       其中 A、B 合法（可为空）；且该拆分与卡塔兰递推一致。
#
# 证明：
# （1）存在性：找与第一个 '(' 匹配的那个 ')'，中间为 A，右侧为 B
# （2）唯一性：匹配位置唯一（括号匹配唯一）
# （3）递推：A 用 j 对、B 用 i-j-1 对，对 j 求和即得 |dp[i]| = C(i)
# （4）归纳：假设更小规模的 dp 正确，则按标准形组合得到全部 i 对合法串
#
#
# 回溯 vs DP 怎么选？
# ────────────────────────────────────────────────────────
# - 面试首选回溯：代码短、剪枝直观、额外空间小
# - DP 适合理解「合法括号 ↔ 卡塔兰结构」；与 Unique BST 同一递推骨架
# - 两者答案个数相同，只是枚举方式不同（路径扩展 vs 结构拼接）
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 剪枝写成 right < n
#    错误：只保证数量 ≤ n，仍可能生成 ")(" 这类非法串
#    正确：必须 right < left（任意时刻左括号不少于右括号）
#
# 2. 忘记 left < n 的限制
#    错误：会生成过多左括号，如 n=1 时得到 "(("
#    正确：left < n 才允许追加 '('
#
# 3. DP 转移漏掉空串 / 下标算错
#    错误：dp[0] 不初始化为 [""]，或 B 用成 dp[i-j]
#    正确：dp[0]=[""]，B 对应 dp[i-j-1]（最外层那一对占掉 1 对）
#
# 4. 把「合法括号判断」做成事后过滤
#    错误：先生成全部 2^{2n} 种再筛，指数爆炸且多余
#    正确：生成过程中剪枝，只走合法分支
#
# 5. 混淆「生成」与「判断」题
#    - 本题：Generate Parentheses（枚举）
#    - 相关：Valid Parentheses（判断单串是否合法，用栈即可）
# ══════════════════════════════════════════════════════════
