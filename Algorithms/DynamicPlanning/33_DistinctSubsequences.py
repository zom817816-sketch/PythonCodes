"""
不同的子序列（Distinct Subsequences）

题目描述：
给你两个字符串 s 和 t ，统计并返回在 s 的 子序列 中 t 出现的个数。
测试用例保证结果在 32 位有符号整数范围内。

输入描述：
两个字符串 s 和 t。

输出描述：
输出一个整数，表示在 s 的子序列中 t 出现的个数。

输入示例：
示例 1：
s = "rabbbit", t = "rabbit"
输出：3
解释：有 3 种可以从 s 中得到 "rabbit" 的方案。

示例 2：
s = "babgbag", t = "bag"
输出：5
解释：有 5 种可以从 s 中得到 "bag" 的方案。

════════════════════════════════════════════════════════════════════════
核心概念：子序列匹配的计数问题
════════════════════════════════════════════════════════════════════════

维度              子序列匹配问题                  子序列计数问题
────────────────────────────────────────────────────────────────────────
问题描述          t 是否是 s 的子序列            s 的子序列中 t 出现多少次
示例              s="abcde", t="ace"            s="rabbbit", t="rabbit"
                  → 返回 True                    → 返回 3
核心思想          双指针贪心匹配                  DP 计数（选或不选）
时间复杂度        O(m + n)                      O(m*n)
空间复杂度        O(1)                          O(n)（优化后）
────────────────────────────────────────────────────────────────────────

本题的关键洞察：
────────────────────────────────────────────────────────────────────────
对于每个字符 s[i] 和 t[j]，有两种选择：
1. 如果 s[i] == t[j]：可以选择匹配（同时前进两个指针），也可以选择不匹配（只前进 s 的指针）
2. 如果 s[i] != t[j]：只能不匹配（只前进 s 的指针）

这是一个典型的"选或不选"的 DP 问题，但目标是计数而非求最优解。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
回溯算法（暴力）              O(2^m)           O(m)            ⭐⭐⭐  直观但超时
回溯 + 记忆化                 O(m*n)           O(m*n)          ⭐⭐⭐⭐ 递归版 DP
动态规划（二维）              O(m*n)           O(m*n)          ⭐⭐⭐⭐ 清晰直观
动态规划（一维优化）          O(m*n)           O(n)            ⭐⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想（动态规划）：
────────────────────────────────────────────────────────────────────────
状态定义：
    dp[i][j] = s 的前 i 个字符（s[0..i-1]）中，t 的前 j 个字符（t[0..j-1]）出现的次数

状态转移：
    如果 s[i-1] == t[j-1]:
        dp[i][j] = dp[i-1][j-1] + dp[i-1][j]
        （选：用 s[i-1] 匹配 t[j-1]，加上不选：跳过 s[i-1]）
    如果 s[i-1] != t[j-1]:
        dp[i][j] = dp[i-1][j]
        （只能不选：跳过 s[i-1]）

初始条件：
    dp[i][0] = 1（空字符串是任何字符串的子序列，只有 1 种方式）
    dp[0][j] = 0（空字符串中不可能有非空 t，j > 0 时）

最终答案：
    dp[m][n]（m = len(s), n = len(t)）

空间优化：
    观察状态转移，dp[i][j] 只依赖 dp[i-1][j-1] 和 dp[i-1][j]
    可以用一维数组 dp[j]，从后往前更新（避免覆盖需要的值）
"""


# ══════════════════════════════════════════════════════════
# 解法一：回溯算法（暴力）
# ══════════════════════════════════════════════════════════


def numDistinct_backtrack(s: str, t: str) -> int:
    """
    回溯算法（暴力解法）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    遍历 s 的每个字符，对每个字符有两种选择：选或不选。
    选择的条件是当前字符与 t 的当前位置匹配。

    算法步骤：
    1. 用双指针 s_idx（遍历 s）和 t_idx（匹配 t）
    2. 如果 s[s_idx] == t[t_idx]，可以选择匹配（同时前进）或不匹配（只前进 s）
    3. 如果不匹配，只能不选（只前进 s）
    4. 终止条件：t 全部匹配完（找到一种方案）或 s 遍历完（无方案）

    时间复杂度：O(2^m) — 每个字符有两种选择，m 是 s 的长度
    空间复杂度：O(m)   — 递归栈深度

    图解示例：
    ────────────────────────────────────────────────────────
    s = "rabbbit", t = "rabbit"（m=7, n=6）

    递归树示意（只展示关键路径）：
    backtrack(0, 0)
        ├── s[0]='r' == t[0]='r' → backtrack(1, 1)
        │       ├── s[1]='a' == t[1]='a' → backtrack(2, 2)
        │       │       ├── s[2]='b' == t[2]='b' → backtrack(3, 3)
        │       │       │       ├── s[3]='b' == t[3]='b' → backtrack(4, 4)
        │       │       │       │       ├── s[4]='b' != t[4]='i' → backtrack(5, 4)
        │       │       │       │       │       ├── s[5]='i' == t[4]='i' → backtrack(6, 5)
        │       │       │       │       │       │       ├── s[6]='t' == t[5]='t' → ✅ 计数+1
        │       │       │       │       │       │       └── 不选 → backtrack(7, 5) → 返回
        │       │       │       │       │       └── 不选 → backtrack(6, 4) → 返回
        │       │       │       │       └── 不选 → backtrack(5, 4)（重复路径）
        │       │       │       └── 不选 → backtrack(4, 3) → ...
        │       │       └── 不选 → backtrack(3, 2) → ...
        │       └── 不选 → backtrack(2, 1) → ...
        └── 不选 → backtrack(1, 0) → ...

    结果：3 ✓

    问题：存在大量重复子问题，如 backtrack(5, 4) 会被多次计算，导致超时。
    """
    m, n = len(s), len(t)
    
    def backtrack(s_idx: int, t_idx: int) -> int:
        # 终止条件：t 已经全部匹配，找到一种方案
        if t_idx == n:
            return 1
        # s 已经遍历完但 t 还没匹配完，无方案
        if s_idx == m:
            return 0
        
        count = 0
        # 如果当前字符匹配，可以选择匹配（同时前进两个指针）
        if s[s_idx] == t[t_idx]:
            count += backtrack(s_idx + 1, t_idx + 1)
        
        # 不选择当前字符（只前进 s 的指针）
        count += backtrack(s_idx + 1, t_idx)
        
        return count
    
    return backtrack(0, 0)


# ══════════════════════════════════════════════════════════
# 解法二：回溯 + 记忆化（递归版 DP）
# ══════════════════════════════════════════════════════════


def numDistinct_memo(s: str, t: str) -> int:
    """
    回溯 + 记忆化（递归版动态规划）⭐⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    在暴力回溯的基础上，用 memo[s_idx][t_idx] 缓存已计算的结果，
    避免重复计算相同的子问题。

    算法步骤：
    1. 创建二维记忆数组 memo[m+1][n+1]
    2. 如果 memo[s_idx][t_idx] 已计算，直接返回
    3. 否则按回溯逻辑计算，并存入 memo

    时间复杂度：O(m*n) — 每个状态只计算一次，共 m*n 个状态
    空间复杂度：O(m*n) — memo 数组 + 递归栈

    图解示例：
    ────────────────────────────────────────────────────────
    s = "babgbag", t = "bag"（m=7, n=3）

    memo 缓存示意（部分）：
    memo[7][3] = 1（t 已匹配完）
    memo[i][3] = 1（所有 i，t 已匹配完）
    memo[7][j] = 0（j < 3，s 已遍历完）
    
    memo[6][2]: s[6]='g' == t[2]='g'
        = memo[5][1] + memo[5][2]
    
    memo[5][1]: s[5]='a' == t[1]='a'
        = memo[4][0] + memo[4][1]
        = 1 + memo[4][1]
    
    ...

    结果：5 ✓
    """
    m, n = len(s), len(t)
    # memo[s_idx][t_idx] = s[s_idx:] 中 t[t_idx:] 出现的次数
    memo = [[-1] * (n + 1) for _ in range(m + 1)]
    
    def backtrack(s_idx: int, t_idx: int) -> int:
        # 终止条件：t 已经全部匹配
        if t_idx == n:
            return 1
        # s 已经遍历完但 t 还没匹配完
        if s_idx == m:
            return 0
        
        # 如果已计算过，直接返回缓存
        if memo[s_idx][t_idx] != -1:
            return memo[s_idx][t_idx]
        
        count = 0
        # 如果当前字符匹配，可以选择匹配
        if s[s_idx] == t[t_idx]:
            count += backtrack(s_idx + 1, t_idx + 1)
        
        # 不选择当前字符
        count += backtrack(s_idx + 1, t_idx)
        
        # 缓存结果
        memo[s_idx][t_idx] = count
        return count
    
    return backtrack(0, 0)


# ══════════════════════════════════════════════════════════
# 解法三：动态规划（二维 DP 数组）
# ══════════════════════════════════════════════════════════


def numDistinct_dp(s: str, t: str) -> int:
    """
    动态规划（二维 DP 数组）⭐⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    dp[i][j] 表示 s 的前 i 个字符中，t 的前 j 个字符出现的次数。
    根据 s[i-1] 和 t[j-1] 是否相等进行状态转移。

    算法步骤：
    1. 初始化 dp[m+1][n+1]，dp[i][0] = 1（空字符串是任何字符串的子序列）
    2. 遍历 s 和 t，按状态转移方程更新 dp
    3. 返回 dp[m][n]

    时间复杂度：O(m*n) — 双重循环
    空间复杂度：O(m*n) — dp 数组

    图解示例：
    ────────────────────────────────────────────────────────
    s = "rabbbit", t = "rabbit"（m=7, n=6）

    初始化：
      "" r a b b i t
    "" 1 0 0 0 0 0 0
     r 1 ? ? ? ? ? ?
     a 1 ? ? ? ? ? ?
     b 1 ? ? ? ? ? ?
     b 1 ? ? ? ? ? ?
     b 1 ? ? ? ? ? ?
     i 1 ? ? ? ? ? ?
     t 1 ? ? ? ? ? ?

    填充过程：
    i=1, s[0]='r':
        j=1, t[0]='r': s[0]==t[0]
            dp[1][1] = dp[0][0] + dp[0][1] = 1 + 0 = 1
    
    i=2, s[1]='a':
        j=1, t[0]='r': s[1]!=t[0]
            dp[2][1] = dp[1][1] = 1
        j=2, t[1]='a': s[1]==t[1]
            dp[2][2] = dp[1][1] + dp[1][2] = 1 + 0 = 1
    
    ... 逐步填充 ...

    最终：dp[7][6] = 3 ✓
    """
    m, n = len(s), len(t)
    
    # dp[i][j] = s 的前 i 个字符中，t 的前 j 个字符出现的次数
    dp = [[0] * (n + 1) for _ in range(m + 1)]
    
    # 初始条件：空字符串是任何字符串的子序列，只有 1 种方式
    for i in range(m + 1):
        dp[i][0] = 1
    
    # 初始条件：空字符串中不可能有非空 t（已初始化为 0，无需额外设置）
    
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            if s[i - 1] == t[j - 1]:
                # 当前字符匹配：选（用 s[i-1] 匹配 t[j-1]）+ 不选（跳过 s[i-1]）
                dp[i][j] = dp[i - 1][j - 1] + dp[i - 1][j]
            else:
                # 当前字符不匹配：只能不选（跳过 s[i-1]）
                dp[i][j] = dp[i - 1][j]
    
    return dp[m][n]


# ══════════════════════════════════════════════════════════
# 解法四：动态规划（空间优化，一维 DP 数组）⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def numDistinct(s: str, t: str) -> int:
    """
    动态规划（空间优化，一维 DP 数组）⭐⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    观察二维 DP 的状态转移：
    dp[i][j] 只依赖 dp[i-1][j-1] 和 dp[i-1][j]
    可以用一维数组 dp[j]，从后往前更新，避免覆盖需要的值。

    为什么要从后往前？
    ────────────────────────────────────────────────────────
    如果从前往后更新：
    dp[j] = dp[j-1] + dp[j] 会先用新的 dp[j-1] 覆盖旧值，
    导致后续 dp[j+1] 需要的 dp[j-1]（上一轮的值）丢失。

    从后往前更新：
    先更新 dp[j]，此时 dp[j-1] 还是上一轮的值，不会被覆盖。

    算法步骤：
    1. 初始化 dp[n+1]，dp[0] = 1
    2. 遍历 s 的每个字符
    3. 从后往前遍历 t 的每个字符（j 从 n 到 1）
    4. 如果 s[i] == t[j-1]，更新 dp[j] = dp[j] + dp[j-1]
    5. 返回 dp[n]

    时间复杂度：O(m*n) — 双重循环
    空间复杂度：O(n)   — 一维 dp 数组

    图解示例：
    ────────────────────────────────────────────────────────
    s = "babgbag", t = "bag"（m=7, n=3）

    初始化：dp = [1, 0, 0, 0]

    i=0, s[0]='b':
        j=3: 'b' != 'g' → 不变
        j=2: 'b' != 'a' → 不变
        j=1: 'b' == 'b' → dp[1] = dp[1] + dp[0] = 0 + 1 = 1
        dp = [1, 1, 0, 0]

    i=1, s[1]='a':
        j=3: 'a' != 'g' → 不变
        j=2: 'a' == 'a' → dp[2] = dp[2] + dp[1] = 0 + 1 = 1
        j=1: 'a' != 'b' → 不变
        dp = [1, 1, 1, 0]

    i=2, s[2]='b':
        j=3: 'b' != 'g' → 不变
        j=2: 'b' != 'a' → 不变
        j=1: 'b' == 'b' → dp[1] = dp[1] + dp[0] = 1 + 1 = 2
        dp = [1, 2, 1, 0]

    i=3, s[3]='g':
        j=3: 'g' == 'g' → dp[3] = dp[3] + dp[2] = 0 + 1 = 1
        j=2: 'g' != 'a' → 不变
        j=1: 'g' != 'b' → 不变
        dp = [1, 2, 1, 1]

    i=4, s[4]='b':
        j=3: 'b' != 'g' → 不变
        j=2: 'b' != 'a' → 不变
        j=1: 'b' == 'b' → dp[1] = dp[1] + dp[0] = 2 + 1 = 3
        dp = [1, 3, 1, 1]

    i=5, s[5]='a':
        j=3: 'a' != 'g' → 不变
        j=2: 'a' == 'a' → dp[2] = dp[2] + dp[1] = 1 + 3 = 4
        j=1: 'a' != 'b' → 不变
        dp = [1, 3, 4, 1]

    i=6, s[6]='g':
        j=3: 'g' == 'g' → dp[3] = dp[3] + dp[2] = 1 + 4 = 5
        j=2: 'g' != 'a' → 不变
        j=1: 'g' != 'b' → 不变
        dp = [1, 3, 4, 5]

    结果：dp[3] = 5 ✓
    """
    m, n = len(s), len(t)
    
    # 特殊情况：t 为空字符串，返回 1
    if n == 0:
        return 1
    # 特殊情况：s 比 t 短，不可能匹配
    if m < n:
        return 0
    
    # dp[j] = 到目前为止，t 的前 j 个字符出现的次数
    # dp[0] = 1：空字符串是任何字符串的子序列
    dp = [0] * (n + 1)
    dp[0] = 1
    
    for i in range(m):
        # 从后往前遍历，避免覆盖需要的 dp[j-1]（上一轮的值）
        # 如果从前往后，dp[j-1] 会被本轮更新后的值覆盖
        for j in range(n, 0, -1):
            if s[i] == t[j - 1]:
                # 当前字符匹配：
                # dp[j] = 不选 s[i] 的方案数（原来的 dp[j]）
                #       + 选 s[i] 的方案数（dp[j-1]，用 s[i] 匹配 t[j-1]）
                dp[j] += dp[j - 1]
    
    return dp[n]


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、动态规划的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：dp[i][j] = s[0..i-1] 的子序列中 t[0..j-1] 出现的次数。
#
# 证明：
# （1）状态完备性：
#     任何匹配方案都可以通过"选或不选"每个 s 中的字符来构造，
#     dp[i][j] 覆盖了所有可能的选择组合。
#
# （2）状态转移的正确性：
#     - 当 s[i-1] == t[j-1]：
#       选 s[i-1]：方案数为 dp[i-1][j-1]（用 s[i-1] 匹配 t[j-1]）
#       不选 s[i-1]：方案数为 dp[i-1][j]（跳过 s[i-1]）
#       总方案数 = 选 + 不选 = dp[i-1][j-1] + dp[i-1][j]
#
#     - 当 s[i-1] != t[j-1]：
#       只能不选 s[i-1]，方案数 = dp[i-1][j]
#
# （3）初始条件的正确性：
#     dp[i][0] = 1：空字符串是任何字符串的子序列，只有 1 种方式（什么都不选）
#     dp[0][j] = 0（j > 0）：空字符串中不可能有非空的 t
#
# （4）最终答案：
#     dp[m][n] 表示 s[0..m-1] 的子序列中 t[0..n-1] 出现的次数，即题目要求。
#
#
# 二、一维 DP 的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：从后往前更新的一维 dp[j] 与二维 dp[i][j] 等价。
#
# 证明：
# 对于第 i 轮（处理 s[i]），更新前 dp[j] 等于二维的 dp[i-1][j]。
#
# 当从后往前更新时：
#   dp[j] += dp[j-1]
#   此时 dp[j-1] 还是上一轮的值（dp[i-1][j-1]），
#   所以 dp[j] 变成 dp[i-1][j] + dp[i-1][j-1]，与二维完全一致。
#
# 如果从前往后更新：
#   dp[j] += dp[j-1]
#   此时 dp[j-1] 已经被本轮更新过（变成 dp[i][j-1]），
#   导致 dp[j] = dp[i-1][j] + dp[i][j-1]，这是错误的。
#
# 因此，从后往前更新是正确的。
#
#
# 三、为什么不能从前往后更新一维 DP？
# ────────────────────────────────────────────────────────
#
# 核心原因：状态转移中，dp[j] 需要的是上一轮的 dp[j-1]，
#          如果从前往后更新，dp[j-1] 会被本轮更新后的值覆盖，
#          导致 dp[j] 使用了错误的值。
#
# 反例：s = "aa", t = "aa"（正确答案应该是 1）
#
# 从后往前更新（正确）：
#   初始：dp = [1, 0, 0]
#
#   处理 s[0]='a'：
#     j=2: 'a' == 'a' → dp[2] = 0 + dp[1]=0 = 0（使用上一轮的 dp[1]）
#     j=1: 'a' == 'a' → dp[1] = 0 + dp[0]=1 = 1（使用上一轮的 dp[0]）
#     dp = [1, 1, 0]
#
#   处理 s[1]='a'：
#     j=2: 'a' == 'a' → dp[2] = 0 + dp[1]=1 = 1（使用上一轮的 dp[1]）
#     j=1: 'a' == 'a' → dp[1] = 1 + dp[0]=1 = 2（使用上一轮的 dp[0]）
#     dp = [1, 2, 1]
#
#   结果：dp[2] = 1 ✓
#
# 从前往后更新（错误）：
#   初始：dp = [1, 0, 0]
#
#   处理 s[0]='a'：
#     j=1: 'a' == 'a' → dp[1] = 0 + dp[0]=1 = 1（使用上一轮的 dp[0]，正确）
#     j=2: 'a' == 'a' → dp[2] = 0 + dp[1]=1 = 1（使用本轮刚更新的 dp[1]，错误！）
#     dp = [1, 1, 1]  ← 错误：此时 dp[2] 已经是 1
#
#   处理 s[1]='a'：
#     j=1: 'a' == 'a' → dp[1] = 1 + dp[0]=1 = 2（使用上一轮的 dp[0]，正确）
#     j=2: 'a' == 'a' → dp[2] = 1 + dp[1]=2 = 3（使用本轮刚更新的 dp[1]，错误！）
#     dp = [1, 2, 3]
#
#   结果：dp[2] = 3 ✗（正确答案应该是 1）
#
# 结论：从前往后更新会导致错误结果，必须从后往前更新。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 状态定义错误——dp[i][j] 定义为 s[i:] 和 t[j:] 的匹配次数：
#    这不是错误，但容易混淆边界条件。更直观的定义是 dp[i][j] 表示前 i/j 个字符。
#    正确：dp[i][j] = s[0..i-1] 中 t[0..j-1] 出现的次数。
#
# 2. 初始条件错误——忘记 dp[i][0] = 1：
#    空字符串是任何字符串的子序列，这是基础情况，必须设置。
#    否则所有结果都会少算。
#
# 3. 一维 DP 从前往后更新：
#    从前往后更新会导致错误结果，因为 dp[j] 需要上一轮的 dp[j-1]，
#    但从前往后会先用本轮更新的值覆盖 dp[j-1]。
#    反例：s="aa", t="aa"，从前往后得到 3（错误），从后往前得到 1（正确）。
#    正确：从后往前更新（j 从 n 到 1）。
#
# 4. 特殊情况未处理——t 为空字符串：
#    t 为空时，答案应该是 1（空字符串是任何字符串的子序列）。
#    如果未处理，一维 DP 中 dp[0]=1 已经隐含了这个情况。
#
# 5. 特殊情况未处理——s 比 t 短：
#    s 的长度小于 t 时，不可能匹配，应直接返回 0。
#    虽然 DP 会正确计算为 0，但提前返回可以节省时间。
#
# 6. 递归回溯版本中未加记忆化：
#    不加记忆化的回溯会有大量重复计算，时间复杂度 O(2^m)，
#    对于较长的字符串会超时。必须加记忆化才能通过测试。
#
# 7. 混淆子序列和子数组：
#    子序列不需要连续，子数组需要连续。
#    本题是子序列问题，不能用滑动窗口等子数组方法。
#
# 8. 方向错误——从 t 中构建子序列去匹配 s：
#    题目要求的是在 s 的子序列中统计 t 出现的次数，
#    应该从 s 出发去匹配 t，而不是反过来。
#    错误示例：从 t 中选字符组合去匹配 s（完全搞反了）。
