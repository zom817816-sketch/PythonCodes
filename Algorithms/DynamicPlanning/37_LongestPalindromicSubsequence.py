"""
最长回文子序列（Longest Palindromic Subsequence, LPS）

题目描述：
给你一个字符串 s ，找出其中最长的回文子序列，并返回该序列的长度。
子序列定义为：不改变剩余字符顺序的情况下，删除某些字符或者不删除任何字符形成的一个序列。

输入描述：
一个字符串 s。

输出描述：
输出一个整数，表示最长回文子序列的长度。

输入示例：
示例 1：
s = "bbbab"
输出：4
解释：一个可能的最长回文子序列为 "bbbb"。

示例 2：
s = "cbbd"
输出：2
解释：一个可能的最长回文子序列为 "bb"。

════════════════════════════════════════════════════════════════════════
核心概念：回文子序列 vs 回文子串 vs 最长公共子序列
════════════════════════════════════════════════════════════════════════

维度                最长回文子序列（LPS）          最长回文子串（LPSst）          最长公共子序列（LCS）
────────────────────────────────────────────────────────────────────────────────────────────────────────
问题描述          最长的回文子序列              最长的回文子串                  两个字符串的最长公共子序列
元素位置          可以不连续                      必须连续                        可以不连续（在各自串中）
示例              s="bbbab"                     s="cbbd"                       s1="abcde", s2="ace"
                  → 4 ("bbbb")                  → 2 ("bb")                     → 3 ("ace")
DP 状态           dp[i][j] = s[i..j] 的 LPS 长度   dp[i][j] = s[i..j] 是否回文   dp[i][j] = s1[0..i] 和 s2[0..j] 的 LCS 长度
状态转移          s[i]==s[j]: dp[i+1][j-1]+2        s[i]==s[j] 且内层回文          s1[i]==s2[j]: dp[i-1][j-1]+1
                  否则: max(dp[i+1][j], dp[i][j-1]) 则 dp[i][j]=True          否则: max(dp[i-1][j], dp[i][j-1])
时间复杂度        O(n²)                           O(n²) 或 O(n)（Manacher）      O(m*n)
空间复杂度        O(n²) → O(n)                   O(n²) → O(1)（中心扩展）       O(m*n) → O(min(m,n))
────────────────────────────────────────────────────────────────────────────────────────────────────────

关键洞察：LPS 与 LCS 的关系
────────────────────────────────────────────────────────────────────────
最长回文子序列 = 字符串与其反转的最长公共子序列
    LPS(s) = LCS(s, reversed(s))

为什么成立？
    回文串 = 正着读和反着读一样。
    s 的回文子序列 ↔ s 和 reversed(s) 的公共子序列。

示例：s = "bbbab", reversed(s) = "babbb"
    LCS("bbbab", "babbb") = 4 ("bbbb") = LPS("bbbab") ✓

迭代方向的区别：
────────────────────────────────────────────────────────────────────────
LPS 的区间 DP 需要 i 从 n-1 到 0（逆序），因为 dp[i][j] 依赖 dp[i+1][j-1]。
LCS 的迭代方向通常是正序，因为 dp[i][j] 依赖 dp[i-1][j-1]。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
区间 DP（直接）                O(n²)           O(n²)           ⭐⭐⭐⭐ 直观清晰
LCS 转换                       O(n²)           O(n²)→O(n)      ⭐⭐⭐⭐⭐ 推荐，巧妙转换
空间优化区间 DP                O(n²)           O(n)            ⭐⭐⭐⭐ 进阶优化
────────────────────────────────────────────────────────────────────────

核心思想（区间 DP）：
────────────────────────────────────────────────────────────────────────
状态定义：
    dp[i][j] = s[i..j]（包含两端点）中最长回文子序列的长度

状态转移：
    如果 s[i] == s[j]：
        dp[i][j] = dp[i+1][j-1] + 2
        （两端字符相同，构成回文的两端，加上内部区间的 LPS）
    如果 s[i] != s[j]：
        dp[i][j] = max(dp[i+1][j], dp[i][j-1])
        （去掉左端点 或 去掉右端点，取较大值）

初始条件：
    dp[i][i] = 1（单个字符本身就是回文，长度为 1）
    dp[i][j] = 0（i > j，空区间，无字符）

迭代顺序：
    i 从 n-1 到 0（逆序，因为 dp[i][j] 依赖 dp[i+1][j-1] 和 dp[i+1][j]）
    j 从 i+1 到 n-1（正序，因为 dp[i][j] 依赖 dp[i][j-1]）

最终答案：
    dp[0][n-1]（整个字符串的最长回文子序列长度）
"""


# ══════════════════════════════════════════════════════════
# 解法一：区间 DP（直接解法，二维数组）
# ══════════════════════════════════════════════════════════


def longestPalindromeSubseq_dp(s: str) -> int:
    """
    区间 DP（直接解法）⭐⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    定义 dp[i][j] = s[i..j] 中最长回文子序列的长度。
    从两端向中间收缩：若 s[i] == s[j]，则 dp[i][j] = dp[i+1][j-1] + 2；
    否则取 max(dp[i+1][j], dp[i][j-1])。

    算法步骤：
    1. 初始化 dp[n][n]，所有元素为 0
    2. dp[i][i] = 1（单字符回文）
    3. i 从 n-1 到 0 逆序遍历
    4. j 从 i+1 到 n-1 正序遍历
    5. 按状态转移方程更新 dp[i][j]
    6. 返回 dp[0][n-1]

    时间复杂度：O(n²) — 双重循环
    空间复杂度：O(n²) — dp 数组

    图解示例：
    ────────────────────────────────────────────────────────
    s = "bbbab"（n=5）

    初始化（对角线为 1）：
        b b b b a
    b [ 1 0 0 0 0 ]
    b [ 0 1 0 0 0 ]
    b [ 0 0 1 0 0 ]
    b [ 0 0 0 1 0 ]
    a [ 0 0 0 0 1 ]

    i=3, s[3]='b':
        j=4: s[3]='b' != s[4]='a'
            dp[3][4] = max(dp[4][4], dp[3][3]) = max(1, 1) = 1

    i=2, s[2]='b':
        j=3: s[2]='b' == s[3]='b'
            dp[2][3] = dp[3][2] + 2 = 0 + 2 = 2
        j=4: s[2]='b' != s[4]='a'
            dp[2][4] = max(dp[3][4], dp[2][3]) = max(1, 2) = 2

    i=1, s[1]='b':
        j=2: s[1]='b' == s[2]='b'
            dp[1][2] = dp[2][1] + 2 = 0 + 2 = 2
        j=3: s[1]='b' == s[3]='b'
            dp[1][3] = dp[2][2] + 2 = 1 + 2 = 3
        j=4: s[1]='b' != s[4]='a'
            dp[1][4] = max(dp[2][4], dp[1][3]) = max(2, 3) = 3

    i=0, s[0]='b':
        j=1: s[0]='b' == s[1]='b'
            dp[0][1] = dp[1][0] + 2 = 0 + 2 = 2
        j=2: s[0]='b' == s[2]='b'
            dp[0][2] = dp[1][1] + 2 = 1 + 2 = 3
        j=3: s[0]='b' == s[3]='b'
            dp[0][3] = dp[1][2] + 2 = 2 + 2 = 4
        j=4: s[0]='b' != s[4]='a'
            dp[0][4] = max(dp[1][4], dp[0][3]) = max(3, 4) = 4

    最终 dp 矩阵：
        b b b b a
    b [ 1 2 3 4 4 ]
    b [ 0 1 2 3 3 ]
    b [ 0 0 1 2 2 ]
    b [ 0 0 0 1 1 ]
    a [ 0 0 0 0 1 ]

    结果：dp[0][4] = 4 ✓
    对应回文子序列："bbbb"（选择所有 'b'，跳过 'a'）
    """
    n = len(s)
    if n == 0:
        return 0
    if n == 1:
        return 1

    # dp[i][j] = s[i..j] 中最长回文子序列的长度
    dp = [[0] * n for _ in range(n)]

    # 初始条件：每个字符自身构成长度为 1 的回文子序列
    for i in range(n):
        dp[i][i] = 1

    # i 从 n-2 到 0 逆序（因为 dp[i][j] 依赖 dp[i+1][j-1] 和 dp[i+1][j]）
    for i in range(n - 2, -1, -1):
        # j 从 i+1 到 n-1 正序（因为 dp[i][j] 依赖 dp[i][j-1]）
        for j in range(i + 1, n):
            if s[i] == s[j]:
                # 两端字符相同：回文长度 = 内部区间的长度 + 2（两端）
                dp[i][j] = dp[i + 1][j - 1] + 2
            else:
                # 两端字符不同：去掉左端点 或 去掉右端点，取较大值
                dp[i][j] = max(dp[i + 1][j], dp[i][j - 1])

    return dp[0][n - 1]


# ══════════════════════════════════════════════════════════
# 解法二：LCS 转换法 ⭐⭐⭐⭐⭐ 推荐
# ══════════════════════════════════════════════════════════


def longestPalindromeSubseq_lcs(s: str) -> int:
    """
    LCS 转换法（推荐）⭐⭐⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    最长回文子序列 = 原字符串 与 反转字符串 的最长公共子序列
    即：LPS(s) = LCS(s, reversed(s))

    为什么成立？
    ────────────────────────────────────────────────────────
    回文串：正着读和反着读完全相同。
    如果一个子序列是回文，那么它必然同时出现在 s 和 reversed(s) 中。
    反之，s 和 reversed(s) 的任何公共子序列都可以匹配成回文。

    因此，最长回文子序列 = s 和 reversed(s) 的最长公共子序列。

    算法步骤：
    1. 计算 t = reversed(s)
    2. 求 s 和 t 的 LCS 长度
    3. 返回 LCS 长度

    LCS 的 DP 状态：
        dp[i][j] = s[0..i-1] 和 t[0..j-1] 的 LCS 长度
        s[i-1] == t[j-1]: dp[i][j] = dp[i-1][j-1] + 1
        s[i-1] != t[j-1]: dp[i][j] = max(dp[i-1][j], dp[i][j-1])

    时间复杂度：O(n²) — LCS 的时间复杂度
    空间复杂度：O(n)   — 优化后只用一维数组

    图解示例：
    ────────────────────────────────────────────────────────
    s = "bbbab" = s[0..4]
    t = reversed(s) = "babbb"

    LCS 过程（简化，只展示关键值）：
    i=1, s[0]='b'（与 t 中的 'b' 匹配）
        → dp[1] = [0, 1, 1, 1, 1, 1]

    i=2, s[1]='b'
        t[0]='b': 匹配 → dp[2][1] = 1
        t[1]='a': 不匹配 → dp[2][2] = max(dp[1][2], dp[2][1]) = 1
        t[2]='b': 匹配 → dp[2][3] = dp[1][2] + 1 = 2
        ...

    最终 LCS 长度 = 4
    对应公共子序列 "bbbb"，也是 s 的最长回文子序列 ✓
    """
    n = len(s)
    if n <= 1:
        return n

    t = s[::-1]  # 反转字符串
    # dp[j] = s[0..i] 和 t[0..j-1] 的 LCS 长度（空间优化版）
    dp = [0] * (n + 1)

    for i in range(1, n + 1):
        # prev = dp[i-1][j-1]，即上一轮、前一列的值
        prev = 0
        for j in range(1, n + 1):
            # 保存更新前的 dp[j]（上一轮的 dp[i-1][j]），
            # 因为它会成为下一个 j 的 prev（即 dp[i][j+1] 需要的 dp[i-1][j]）
            temp = dp[j]
            if s[i - 1] == t[j - 1]:
                # 字符匹配：dp[i][j] = dp[i-1][j-1] + 1
                dp[j] = prev + 1
            else:
                # 不匹配：dp[i][j] = max(dp[i-1][j], dp[i][j-1])
                dp[j] = max(dp[j], dp[j - 1])
            # prev 滚动更新：为下一个 j 准备 dp[i-1][j]
            prev = temp

    return dp[n]


# ══════════════════════════════════════════════════════════
# 解法三：区间 DP + 空间优化（一维数组）
# ══════════════════════════════════════════════════════════


def longestPalindromeSubseq(s: str) -> int:
    """
    区间 DP + 空间优化（一维数组）⭐⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    二维区间 DP 中，dp[i][j] 只依赖：
    - dp[i+1][j]（同一列的下面一行）
    - dp[i][j-1]（同一行的左边一列）
    - dp[i+1][j-1]（左下对角）

    当 i 从大到小遍历时，i+1 行已经计算完成，
    可以用一维数组 dp[j]，每次迭代 i 时从 j-1 的新值恢复 "左下对角"。

    具体做法：
    - prev：保存 dp[i+1][j-1]（更新前的 dp[j-1]）
    - temp：保存更新前的 dp[j]（即 dp[i+1][j]）
    - 计算后 dp[j] 变成 dp[i][j]

    算法步骤：
    1. 初始化 dp[n] = [1, 1, ..., 1]（每个单字符的 LPS 长度为 1）
    2. i 从 n-2 到 0 逆序遍历
    3. 每轮开始时 prev = 0，遍历 j 从 i+1 到 n-1
    4. 按状态转移更新 dp[j]，同时保存 prev 和 temp

    时间复杂度：O(n²) — 双重循环
    空间复杂度：O(n)   — 一维 dp 数组

    图解示例：
    ────────────────────────────────────────────────────────
    s = "cbbd"（n=4）

    初始化：dp = [1, 1, 1, 1]（每个单字符回文长度为 1）

    i=2, s[2]='b':
        j=3, s[3]='d':
            prev = dp[2] = 1（此时 prev 初始为 0，第一次迭代后更新）
            等等，重新梳理：
            初始 prev = 0
            j=3: temp = dp[3]=1
                 s[2]='b' != s[3]='d': dp[3] = max(dp[3]=1, dp[2]=1) = 1
                 prev = temp = 1
            dp = [1, 1, 1, 1] （不变）

    i=1, s[1]='b':
        prev = 0
        j=2: temp = dp[2] = 1
             s[1]='b' == s[2]='b': dp[2] = prev(0) + 2 = 2
             prev = 1
        j=3: temp = dp[3] = 1
             s[1]='b' != s[3]='d': dp[3] = max(dp[3]=1, dp[2]=2) = 2
             prev = 1
        dp = [1, 1, 2, 2]

    i=0, s[0]='c':
        prev = 0
        j=1: temp = dp[1] = 1
             s[0]='c' != s[1]='b': dp[1] = max(dp[1]=1, dp[0]=1) = 1
             prev = 1
        j=2: temp = dp[2] = 2
             s[0]='c' != s[2]='b': dp[2] = max(dp[2]=2, dp[1]=1) = 2
             prev = 2
        j=3: temp = dp[3] = 2
             s[0]='c' != s[3]='d': dp[3] = max(dp[3]=2, dp[2]=2) = 2
             prev = 2
        dp = [1, 1, 2, 2]

    结果：dp[3] = 2 ✓
    对应回文子序列："bb"（选择两个 'b'，跳过 'c' 和 'd'）
    """
    n = len(s)
    if n <= 1:
        return n

    # dp[j] = 上一轮（i+1）计算的区间 s[i+1..j] 的 LPS 长度
    # 初始化：相当于 i = n-1 时，dp[j] = 1（单字符）
    dp = [1] * n

    # i 从 n-2 到 0 逆序遍历
    for i in range(n - 2, -1, -1):
        # prev 保存 dp[i+1][j-1]，即 "左下对角" 的值
        # 初始 prev=0：当 j=i+1 时，dp[i+1][j-1] = dp[i+1][i] = 0（i > j 的空区间）
        prev = 0
        for j in range(i + 1, n):
            # 保存更新前的 dp[j]，它是 dp[i+1][j]，
            # 同时它将成为下一个 j 的 prev（即 dp[i+1][j]）
            temp = dp[j]
            if s[i] == s[j]:
                # 两端相同：dp[i][j] = dp[i+1][j-1] + 2
                # prev 就是 dp[i+1][j-1]（上一轮的 dp[j-1]）
                dp[j] = prev + 2
            else:
                # 两端不同：dp[i][j] = max(dp[i+1][j], dp[i][j-1])
                # dp[j]（未更新）= dp[i+1][j]，dp[j-1]（已更新）= dp[i][j-1]
                dp[j] = max(dp[j], dp[j - 1])
            # prev 滚动：为下一个 j 保存 dp[i+1][j]
            prev = temp

    return dp[n - 1]


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 一、区间 DP 的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：dp[i][j] 正确记录了 s[i..j] 中最长回文子序列的长度。
#
# 证明（对区间长度 len = j - i + 1 归纳）：
# （1）len = 1 时：dp[i][i] = 1，单字符本身就是回文，长度为 1。正确。
#
# （2）假设对所有 len' < len 的区间，dp 都正确。
#     考虑 len = j - i + 1 的区间 s[i..j]：
#
#     情况 a：s[i] == s[j]
#         s[i] 和 s[j] 可以同时作为回文的两端。
#         中间的 s[i+1..j-1] 必须是回文子序列（归纳假设已正确），
#         所以 dp[i][j] = dp[i+1][j-1] + 2。正确。
#
#     情况 b：s[i] != s[j]
#         s[i] 和 s[j] 不能同时出现在回文中（否则它们作为两端字符不同，不是回文）。
#         最优解要么不包含 s[i]（dp[i+1][j]），要么不包含 s[j]（dp[i][j-1]），
#         取较大值。正确。
#
#     由归纳法，对所有区间 dp[i][j] 正确。
#
# （3）最终答案：dp[0][n-1] = s[0..n-1] 的最长回文子序列长度，即题目要求。■
#
#
# 二、LCS 转换法的正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：字符串 s 的最长回文子序列长度 = LCS(s, reversed(s))。
#
# 证明（双向包含）：
# （1）LPS(s) ⊆ LCS(s, reversed(s))：
#     设 P 是 s 的一个回文子序列。因为 P 是回文，所以 reversed(P) = P。
#     P 在 s 中以顺序 p1 < p2 < ... < pk 出现。
#     P 在 reversed(s) 中也以顺序 n-pk < n-p(k-1) < ... < n-p1 出现。
#     所以 P 是 s 和 reversed(s) 的公共子序列。
#     因此 LPS(s) 的长度 ≤ LCS(s, reversed(s)) 的长度。
#
# （2）LCS(s, reversed(s)) ⊆ LPS(s)：
#     设 C 是 s 和 reversed(s) 的公共子序列。
#     C 在 s 中以位置 a1 < a2 < ... < ak 出现。
#     C 在 reversed(s) 中以位置 b1 < b2 < ... < bk 出现，对应 s 中的位置 n-b1 > n-b2 > ... > n-bk。
#     注意：{a1,...,ak} 和 {n-b1,...,n-bk} 都是 s 中的递增位置序列，
#     但它们未必相同。实际上，C 在 s 中有两种递增位置序列可以表示它：
#     原始位置 (a1,...,ak) 和 反转对应的位置 (n-b1 > ... > n-bk)。
#     由于 LCS 选择的是同时出现在两边的子序列，存在一个 k 使得
#     a_i = n - b_{k+1-i} 对所有 i 成立（这是 LCS 的对称性导致的）。
#     因此 C 是回文（因为它在 s 中有互为反转的两组位置）。
#     所以 C 是 s 的回文子序列。
#     因此 LCS(s, reversed(s)) 的长度 ≤ LPS(s) 的长度。
#
# 由（1）和（2）：LPS(s) = LCS(s, reversed(s))。■
#
#
# 三、为什么 LPS 的区间 DP 要 i 逆序遍历？
# ────────────────────────────────────────────────────────
#
# 状态转移方程：
#   s[i] == s[j]: dp[i][j] = dp[i+1][j-1] + 2
#   s[i] != s[j]: dp[i][j] = max(dp[i+1][j], dp[i][j-1])
#
# dp[i][j] 依赖 dp[i+1][j-1]、dp[i+1][j]、dp[i][j-1]。
# - dp[i+1][j-1] 和 dp[i+1][j]：来自"下一行"（i+1），需要先计算好
# - dp[i][j-1]：来自"左边"（j-1），在同一行内，随 j 正序自动可用
#
# 因此：i 从 n-2 到 0 逆序（保证 i+1 行已计算完成），
#       j 从 i+1 到 n-1 正序（保证 j-1 已在当前行计算好）。
#
# 如果 i 正序遍历，dp[i+1][j-1] 和 dp[i+1][j] 还没算出来，会用到初始值 0，结果错误。
