# 原代码（37_LongestPalindromicSubsequence.py）的问题：
#
# Bug 1：解决了错误的问题（子串 vs 子序列）
# ────────────────────────────────────────────────────────
# 原代码用布尔 dp[i][j] 表示 s[i..j] 是否为回文，这是在做"最长回文子串"，
# 而题目要求的是"最长回文子序列"。
#
# 反例：s = "bbbab"
# - 最长回文子串："bb" 或 "bb"，长度 2
# - 最长回文子序列："bbbb"，长度 4
# 原代码会返回 2，但正确答案是 4。
#
# Bug 2：状态转移方向错误（dp[i-1][j-1] vs dp[i+1][j-1]）
# ────────────────────────────────────────────────────────
# 原代码：s[i] == s[j] and (length < 3 or dp[i-1][j-1])
# 正确（子串解法）：s[i] == s[j] and (length < 3 or dp[i+1][j-1])
#
# dp[i-1][j-1] 引用的是"左上"位置，但 i=0 时会变成 dp[-1][j-1]（Python 负索引会包装到最后一行），
# 导致错误结果。正确应该是引用"左下"位置 dp[i+1][j-1]。
#
# Bug 3：迭代方向与状态转移不匹配
# ────────────────────────────────────────────────────────
# 原代码按 length 正序遍历，对"最长回文子串"没问题（子串转移只依赖更短的子串）。
# 但对于"最长回文子序列"，状态转移是从大区间到小区间的反向依赖，
# 不能用 length 正序。
#
# 总结对比：
# ┌──────────────────┬─────────────────────────────┬──────────────────────────────┐
# │                  │ 最长回文子串（Substring）     │ 最长回文子序列（Subsequence） │
# ├──────────────────┼─────────────────────────────┼──────────────────────────────┤
# │ dp[i][j] 含义    │ s[i..j] 是否为回文（bool）   │ s[i..j] 的 LPS 长度（int）    │
# │ 状态转移         │ s[i]==s[j] 且内层回文        │ s[i]==s[j]: 内层+2           │
# │                  │ dp[i][j] = dp[i+1][j-1]      │ 否则: max(去左/去右)          │
# │ 迭代方向         │ length 正序 或 中心扩展     │ i 逆序，j 正序               │
# │ 时间复杂度       │ O(n²) 或 O(n)（Manacher）    │ O(n²)                        │
# │ 空间复杂度       │ O(n²) → O(1)                 │ O(n²) → O(n)                 │
# └──────────────────┴─────────────────────────────┴──────────────────────────────┘
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 混淆子串和子序列（最常见）：
#    子串必须连续，子序列可以不连续。
#    最长回文子序列的解法绝不能用布尔 dp 表示"是否回文"，
#    必须用整数 dp 记录最长长度，因为可以跳过一些字符。
#
# 2. 状态转移方向错写成 dp[i-1][j-1]：
#    区间 DP 从两端向中间收缩，应该依赖"内部"区间 dp[i+1][j-1]，
#    而不是依赖"外部"的 dp[i-1][j-1]。
#    特别注意 i=0 时 dp[-1][j-1] 在 Python 中不会报错（负索引包装），
#    但会产生错误结果，难以排查。
#
# 3. i 正序遍历导致依赖未计算：
#    dp[i][j] 依赖 dp[i+1][j-1] 和 dp[i+1][j]（i+1 行），
#    i 必须逆序遍历。如果正序，i+1 行还没算好，会用到初始值。
#
# 4. 迭代方向与二维数组初始化方式不匹配：
#    如果先填对角线 dp[i][i] = 1，再 i 逆序、j 正序，是正确的。
#    如果尝试按 length 正序填（像最长回文子串那样），会错，
#    因为子序列的转移不是"更短区间 → 更长区间"的直接依赖。
#
# 5. 空间优化版本忘记 prev 的滚动：
#    空间优化时，prev 保存 dp[i+1][j-1]，每次迭代后要更新 prev = temp。
#    如果忘记更新，所有位置都会用同一个 prev 值，结果全错。
#
# 6. LCS 转换法中 i 和 j 的对应关系搞反：
#    s[i-1] == t[j-1] 还是 s[i-1] == s[n-j]？
#    推荐直接用 t = s[::-1]，保持 t[j-1] 和 s[i-1] 的对齐关系，不易出错。
#
# 7. 特殊情况未处理——s 为空或单字符：
