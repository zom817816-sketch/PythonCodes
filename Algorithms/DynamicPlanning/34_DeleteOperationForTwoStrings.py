"""
两个字符串的删除操作（Delete Operation for Two Strings）

题目描述：
给定两个单词 word1 和 word2，返回使得 word1 和 word2 相同所需的最小步数。
每步可以删除任意一个字符串中的一个字符。

输入描述：
两个字符串 word1 和 word2，由小写英文字母组成。

输出描述：
输出一个整数，表示最小删除步数。

输入示例：
word1 = "sea", word2 = "eat"
输出示例：
2

════════════════════════════════════════════════════════════════════════
核心概念：删除操作与最长公共子序列的关系
════════════════════════════════════════════════════════════════════════

关键洞察：
────────────────────────────────────────────────────────────────────────
本题的本质是：找到两个字符串的"最长公共子序列（LCS）"，
然后删除不在 LCS 中的字符。

为什么？
    - 最终相同的字符串一定是 word1 和 word2 的"公共子序列"
    - 要删除的字符数最少，就要保留最长的公共子序列
    - 因此：最小删除步数 = (len(word1) - LCS长度) + (len(word2) - LCS长度)
                      = len(word1) + len(word2) - 2 * LCS长度

示例验证：
    word1 = "sea", word2 = "eat"
    LCS = "ea", 长度 = 2
    删除步数 = 3 + 3 - 2 * 2 = 2 ✓

    另一种思路（直接 DP）：
    ────────────────────────────────────────────────────────
    定义 dp[i][j] = 使 word1[:i] 和 word2[:j] 相同的最小删除步数
    - 如果 word1[i-1] == word2[j-1]，则无需删除，dp[i][j] = dp[i-1][j-1]
    - 否则，要么删除 word1[i-1]（+1步），要么删除 word2[j-1]（+1步）
      即 dp[i][j] = 1 + min(dp[i-1][j], dp[i][j-1])

这两种思路殊途同归，核心都是"最长公共子序列"。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                                      时间复杂度       空间复杂度           说明
────────────────────────────────────────────────────────────────────────
回溯法（暴力递归）                          O(2^(m+n))      O(m+n)              ⭐
回溯 + 记忆化搜索（自顶向下 DP）            O(m*n)          O(m*n)              ⭐⭐⭐
动态规划（LCS 二维数组）                    O(m*n)          O(m*n)              ⭐⭐⭐
动态规划（LCS 滚动数组优化）                O(m*n)          O(min(m,n))         ⭐⭐⭐⭐ 推荐
直接 DP（最小删除步数）                    O(m*n)          O(m*n)              ⭐⭐⭐  更直观
────────────────────────────────────────────────────────────────────────

核心思想（回溯法）：
────────────────────────────────────────────────────────────────────────
关键洞察：用双指针同步遍历两字符串，逐字符决策

递归函数 dfs(i, j)：
    - 返回使 word1[i:] 和 word2[j:] 相同的最小删除步数
    - 字符匹配 → 无需删除，跳过（i+1, j+1）
    - 字符不匹配 → 尝试删 word1 或删 word2，取最小值

这形成一棵二叉搜索树，每个不匹配产生 2 个分支。

核心思想（动态规划求 LCS）：
────────────────────────────────────────────────────────────────────────
关键洞察：两字符串删除到相同 → 找最长公共子序列（LCS）

状态定义：
    dp[i][j] = word1 的前 i 个字符与 word2 的前 j 个字符的 LCS 长度

状态转移：
    dp[i][j] = dp[i-1][j-1] + 1                    如果 word1[i-1] == word2[j-1]
    dp[i][j] = max(dp[i-1][j], dp[i][j-1])         如果 word1[i-1] != word2[j-1]

初始条件：
    dp[0][j] = 0 且 dp[i][0] = 0（空字符串与任意字符串的 LCS 为 0）

最终答案：
    m + n - 2 * dp[m][n]（总长度减去两倍 LCS 长度）
"""


# ══════════════════════════════════════════════════════════
# 解法一：回溯法（暴力递归）
# ══════════════════════════════════════════════════════════


def minDistance_backtrack(word1: str, word2: str) -> int:
    """
    回溯法（暴力递归）⭐

    核心思想：
    ────────────────────────────────────────────────────────
    用指针 i 和 j 分别遍历 word1 和 word2，逐字符比较：
    - 如果字符相等，两个指针同时前移（无需删除）
    - 如果字符不等，尝试两种选择：
      ① 删除 word1 的当前字符（i+1, j），步数 +1
      ② 删除 word2 的当前字符（i, j+1），步数 +1
      取两种选择的最小值
    - 当某个字符串遍历完时，需删除另一个字符串的所有剩余字符

    这是一个典型的回溯搜索问题，搜索树中每个节点最多有 2 个分支，
    树的深度最多为 m + n，因此是指数级时间复杂度。

    算法步骤：
    1. 定义递归函数 dfs(i, j)，返回使 word1[i:] 和 word2[j:] 相同的最小步数
    2. 如果 i == m，需删除 word2 剩余的 n-j 个字符
    3. 如果 j == n，需删除 word1 剩余的 m-i 个字符
    4. 如果 word1[i] == word2[j]，无需删除，递归 dfs(i+1, j+1)
    5. 否则，取 1 + min(dfs(i+1, j), dfs(i, j+1))
    6. 从 dfs(0, 0) 开始搜索

    时间复杂度：O(2^(m+n)) — 每层最多 2 个分支，最大深度 m+n
    空间复杂度：O(m+n) — 递归栈的深度

    图解示例：
    ────────────────────────────────────────────────────────
    word1 = "sea", word2 = "eat"

    递归搜索树（只展示关键分支）：

    dfs(0,0) "s" vs "e" 不相等
    ├── 删 word1: 1 + dfs(1,0)
    │   └── dfs(1,0) "e" vs "e" 相等
    │       └── dfs(2,1) "a" vs "a" 相等
    │           └── dfs(3,2) i=m, 返回 n-j=1
    │               删除 word2 剩余 't'，总计删除次数 = 1 + 0 + 0 + 1 = 2
    └── 删 word2: 1 + dfs(0,1)
        └── dfs(0,1) "s" vs "a" 不相等
            ├── 删 word1: 1 + dfs(1,1) ... 后续步数更多
            └── 删 word2: 1 + dfs(0,2) ... 后续步数更多

    最优路径：删 's'(word1) + 删 't'(word2) = 2 步
    结果：最小删除步数 = 2 ✓
    """
    m, n = len(word1), len(word2)

    def dfs(i: int, j: int) -> int:
        """返回使 word1[i:] 和 word2[j:] 相同的最小删除步数"""
        # 边界情况：某个字符串已遍历完，需删除另一个的全部剩余字符
        if i == m:
            return n - j
        if j == n:
            return m - i

        if word1[i] == word2[j]:
            # 字符匹配，无需删除，直接比较下一个字符
            return dfs(i + 1, j + 1)
        else:
            # 字符不匹配，尝试两种删除方案，取最小值
            # 删除 word1[i]：消耗 1 步，继续比较 word1[i+1] 和 word2[j]
            # 删除 word2[j]：消耗 1 步，继续比较 word1[i] 和 word2[j+1]
            return 1 + min(dfs(i + 1, j), dfs(i, j + 1))

    return dfs(0, 0)


