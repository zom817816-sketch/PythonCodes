# 解法二：回溯 + 记忆化搜索（自顶向下 DP）
# ══════════════════════════════════════════════════════════


def minDistance_memo(word1: str, word2: str) -> int:
    """
    回溯 + 记忆化搜索（自顶向下 DP）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    暴力回溯中存在大量重复计算 —— 不同的删除顺序可能到达相同的 (i, j) 子问题。

    例如 word1="sea", word2="eat"：
      - 先删 word1 的 's' 再删 word2 的 't' → dfs(3,3)
      - 先删 word2 的 't' 再删 word1 的 's' → dfs(3,3)
    两条路径到达完全相同的子问题，但暴力回溯会重复计算两次。

    解决方法：用一个缓存（二维数组或字典）保存已计算的 (i, j) 结果，
    下次遇到相同的子问题时直接返回缓存值（剪枝）。

    记忆化搜索本质上是自顶向下的动态规划，与自底向上的 DP 本质相同，
    只是计算顺序不同 —— 一个从大问题递归分解到小问题，另一个从小问题迭代到大问题。

    算法步骤：
    1. 创建 (m+1) × (n+1) 的缓存（初始化为 -1 表示未计算）
    2. 在 dfs 中，如果 memo[i][j] != -1，直接返回缓存值
    3. 计算完结果后存入缓存
    4. 其余逻辑与暴力回溯相同

    时间复杂度：O(m*n) — 最多 (m+1)*(n+1) 个子问题，每个 O(1)
    空间复杂度：O(m*n) — 缓存数组 + 递归栈

    图解示例：
    ────────────────────────────────────────────────────────
    word1 = "sea", word2 = "eat", m=3, n=3

    缓存 memo 内容（最终状态）：

            j=0  j=1  j=2  j=3
            ""   's'  'e'  'a'
    i=0 ""  [3,   2,   1,   2]
    i=1 'e' [2,   2,   1,   2]
    i=2 'a' [1,   1,   2,   2]
    i=3 't' [0,   0,   0,   0]

    memo[0][0] = 最小删除步数 = 2 ✓
    注：memo[i][j] 表示使 word1[i:] 和 word2[j:] 相同的最小步数

    计算过程（自顶向下递归 + 缓存）：
    dfs(0,0): "s"≠"e", 计算 1+min(dfs(1,0), dfs(0,1))
    ├─ dfs(1,0): "e"=="e" → dfs(2,1)
    │   └─ dfs(2,1): "a"=="a" → dfs(3,2)=1, 缓存 memo[2][1]=1
    │       返回 1, 缓存 memo[1][0]=1
    └─ dfs(0,1): "s"≠"a", 计算 1+min(dfs(1,1), dfs(0,2))
        ├─ dfs(1,1): "e"≠"a", 计算 1+min(dfs(2,1)✓, dfs(1,2))
        │   ├─ dfs(2,1): 已缓存 = 1  ← 剪枝！
        │   └─ dfs(1,2): "e"≠"t", 计算 1+min(dfs(2,2), dfs(1,3))...
        └─ dfs(0,2): "s"≠"t", ...

    由于 memo 缓存，每个 (i, j) 只计算一次，大幅减少重复计算。
    """
    m, n = len(word1), len(word2)

    # 创建缓存，初始化为 -1 表示未计算
    # memo[i][j] = 使 word1[i:] 和 word2[j:] 相同的最小步数
    memo = [[-1] * (n + 1) for _ in range(m + 1)]

    def dfs(i: int, j: int) -> int:
        """返回使 word1[i:] 和 word2[j:] 相同的最小删除步数（带记忆化）"""
        # 边界情况：某个字符串已遍历完，需删除另一个的全部剩余字符
        if i == m:
            return n - j
        if j == n:
            return m - i

        # 如果已经计算过，直接返回缓存值
        if memo[i][j] != -1:
            return memo[i][j]

        if word1[i] == word2[j]:
            # 字符匹配，无需删除，直接比较下一个字符
            memo[i][j] = dfs(i + 1, j + 1)
        else:
            # 字符不匹配，尝试两种删除方案，取最小值
            memo[i][j] = 1 + min(dfs(i + 1, j), dfs(i, j + 1))

        return memo[i][j]

    return dfs(0, 0)


# ══════════════════════════════════════════════════════════
# 解法三：动态规划（LCS 二维数组）
# ══════════════════════════════════════════════════════════


def minDistance_lcs(word1: str, word2: str) -> int:
    """
    动态规划求 LCS（二维数组）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    先求最长公共子序列（LCS）的长度，再用总长度减去两倍 LCS 长度。
    LCS 问题用二维 DP 求解。

    算法步骤：
    1. 创建 (m+1) × (n+1) 的二维 DP 表
    2. 遍历 word1 和 word2 的每个字符
    3. 若字符相等，LCS 长度 +1；否则取上方和左方的较大值
    4. 最终 dp[m][n] 即最长公共子序列长度
    5. 返回 m + n - 2 * dp[m][n]

    时间复杂度：O(m*n) — 双循环遍历两个字符串
    空间复杂度：O(m*n) — 二维 DP 表

    图解示例：
    ────────────────────────────────────────────────────────
    word1 = "sea", word2 = "eat", m=3, n=3

    DP 表（行=word2"eat"，列=word1"sea"）：

                    j=0  j=1  j=2  j=3
                    ""   's'  'e'  'a'
        i=0  ""    [0,   0,   0,   0]
        i=1  'e'   [0,   0,   1,   1]
        i=2  'a'   [0,   0,   1,   2]
        i=3  't'   [0,   0,   1,   2]

    逐步推演：
    i=1 (word2='e'), j=1 (word1='s'): 'e'≠'s' → dp[1][1] = max(0,0) = 0
    i=1 (word2='e'), j=2 (word1='e'): 'e'=='e' → dp[1][2] = dp[0][1] + 1 = 1
    i=1 (word2='e'), j=3 (word1='a'): 'e'≠'a' → dp[1][3] = max(1,0) = 1
    i=2 (word2='a'), j=1 (word1='s'): 'a'≠'s' → dp[2][1] = max(0,0) = 0
    i=2 (word2='a'), j=2 (word1='e'): 'a'≠'e' → dp[2][2] = max(1,0) = 1
    i=2 (word2='a'), j=3 (word1='a'): 'a'=='a' → dp[2][3] = dp[1][2] + 1 = 2
    i=3 (word2='t'), j=1~3: 't'与's','e','a'都不等 → 均为上方/左方较大值

    LCS 长度 = dp[3][3] = 2
    最小删除步数 = 3 + 3 - 2 * 2 = 2 ✓
    """
    m, n = len(word1), len(word2)

    # 创建 (n+1) × (m+1) 的 DP 表
    # dp[i][j] 表示 word1[:j] 和 word2[:i] 的 LCS 长度
    dp = [[0] * (m + 1) for _ in range(n + 1)]

    # 遍历 word2（行）和 word1（列）
    for i in range(1, n + 1):          # i 对应 word2 的索引
        for j in range(1, m + 1):      # j 对应 word1 的索引
            if word1[j - 1] == word2[i - 1]:
                # 字符匹配，LCS 长度 +1
                dp[i][j] = dp[i - 1][j - 1] + 1
            else:
                # 字符不匹配，取上方或左方的 LCS 较大值
                dp[i][j] = max(dp[i - 1][j], dp[i][j - 1])

    # 最小删除步数 = 总长度 - 2 × LCS 长度
    return m + n - 2 * dp[n][m]


# ══════════════════════════════════════════════════════════
# 解法四：动态规划（LCS 滚动数组优化）
# ══════════════════════════════════════════════════════════


def minDistance_lcs_optimized(word1: str, word2: str) -> int:
    """
    动态规划求 LCS（滚动数组优化）⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    观察 DP 表可以发现，dp[i][j] 只依赖三格的值：
        dp[i-1][j-1]（左上角）、dp[i-1][j]（上方）、dp[i][j-1]（左方）
    因此不需要完整二维表，只需保存"上一行"和"当前行"即可。

    优化后空间从 O(m*n) 降至 O(min(m, n))。

    算法步骤：
    1. 选择较短的字符串作为列方向，以减少空间使用
    2. 用两个一维数组（上一行和当前行）代替二维表
    3. 遍历时，用变量 prev 保存左上角的值（dp[i-1][j-1]）
    4. 其余逻辑与标准 LCS 相同

    时间复杂度：O(m*n) — 双循环遍历两个字符串
    空间复杂度：O(min(m, n)) — 滚动数组

    图解示例：
    ────────────────────────────────────────────────────────
    word1 = "sea", word2 = "eat"
    取较短者 word2="eat" 作为列方向，长度为 3

    初始状态：prev_row = [0, 0, 0, 0]（表示 word1 为空时的 LCS）

    word1 的第 1 个字符 's'：
        prev = 0  （左上角）
        j=1 ('e'): 's'≠'e' → cur[1] = max(cur[0]=0, prev_row[1]=0) = 0, prev=0
        j=2 ('a'): 's'≠'a' → cur[2] = max(cur[1]=0, prev_row[2]=0) = 0, prev=0
        j=3 ('t'): 's'≠'t' → cur[3] = max(cur[2]=0, prev_row[3]=0) = 0, prev=0
        cur = [0, 0, 0, 0]，更新 prev_row = cur

    word1 的第 2 个字符 'e'：
        prev = 0
        j=1 ('e'): 'e'=='e' → cur[1] = prev + 1 = 1, prev=0
        j=2 ('a'): 'e'≠'a' → cur[2] = max(cur[1]=1, prev_row[2]=0) = 1, prev=0
        j=3 ('t'): 'e'≠'t' → cur[3] = max(cur[2]=1, prev_row[3]=0) = 1, prev=0
        cur = [0, 1, 1, 1]，更新 prev_row = cur

    word1 的第 3 个字符 'a'：
        prev = 0
        j=1 ('e'): 'a'≠'e' → cur[1] = max(cur[0]=0, prev_row[1]=1) = 1, prev=1
        j=2 ('a'): 'a'=='a' → cur[2] = prev + 1 = 2, prev=1
        j=3 ('t'): 'a'≠'t' → cur[3] = max(cur[2]=2, prev_row[3]=1) = 2, prev=1
        cur = [0, 1, 2, 2]

    LCS 长度 = prev_row[n] = 2
    最小删除步数 = 3 + 3 - 2 * 2 = 2 ✓
    """
    # 确保 word1 是较短的字符串，以优化空间
    if len(word1) > len(word2):
        word1, word2 = word2, word1

    m, n = len(word1), len(word2)  # m 是较短字符串长度

    # 只用两个一维数组：上一行和当前行
    prev_row = [0] * (n + 1)  # 上一行（dp[i-1]）
    cur_row = [0] * (n + 1)   # 当前行（dp[i]）

    for i in range(1, m + 1):          # 遍历较短的字符串 word1
        for j in range(1, n + 1):      # 遍历较长的字符串 word2
            if word1[i - 1] == word2[j - 1]:
                # 字符匹配：左上角（prev_row[j-1]）+ 1
                # 使用独立的 prev_row 数组，可直接访问上一行的值
                cur_row[j] = prev_row[j - 1] + 1
            else:
                # 字符不匹配：取上方（prev_row[j]）或左方（cur_row[j-1]）的较大值
                cur_row[j] = max(prev_row[j], cur_row[j - 1])
        # 当前行变为下一轮的上一行
        prev_row, cur_row = cur_row, [0] * (n + 1)

    return m + n - 2 * prev_row[n]


# ══════════════════════════════════════════════════════════
# 解法五：直接 DP（不经过 LCS，直接求最小删除步数）
# ══════════════════════════════════════════════════════════


def minDistance_direct(word1: str, word2: str) -> int:
    """
    直接 DP 求最小删除步数 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    不通过 LCS，直接定义最小删除步数的状态转移方程。
    相比 LCS 解法，这种思路更直观——直接在删除操作上做 DP。

    状态定义：
        dp[i][j] = 使 word1[:i] 和 word2[:j] 相同的最小删除步数

    状态转移：
        dp[i][j] = dp[i-1][j-1]                         如果 word1[i-1] == word2[j-1]
        dp[i][j] = 1 + min(dp[i-1][j], dp[i][j-1])     如果 word1[i-1] != word2[j-1]

    初始条件：
        dp[0][j] = j（word1 为空，需删除 word2 的所有字符）
        dp[i][0] = i（word2 为空，需删除 word1 的所有字符）

    最终答案：
        dp[m][n]

    时间复杂度：O(m*n) — 双循环遍历两个字符串
    空间复杂度：O(m*n) — 二维 DP 表

    图解示例：
    ────────────────────────────────────────────────────────
    word1 = "sea", word2 = "eat", m=3, n=3

    DP 表（行=word1，列=word2）：

                    j=0   j=1   j=2   j=3
                    ""    'e'   'a'   't'
        i=0  ""   [ 0,    1,    2,    3 ]
        i=1  's'  [ 1,    2,    3,    4 ]
        i=2  'e'  [ 2,    1,    2,    3 ]
        i=3  'a'  [ 3,    2,    1,    2 ]

    逐步推演：
    dp[0][*] 和 dp[*][0] 用初始条件填充

    i=1 (word1='s'), j=1 (word2='e'): 's'≠'e' → 1+min(1,1)=2
    i=1 (word1='s'), j=2 (word2='a'): 's'≠'a' → 1+min(2,1)=2
    i=1 (word1='s'), j=3 (word2='t'): 's'≠'t' → 1+min(3,2)=3

    i=2 (word1='e'), j=1 (word2='e'): 'e'=='e' → dp[1][0]=1
    i=2 (word1='e'), j=2 (word2='a'): 'e'≠'a' → 1+min(1,2)=2
    i=2 (word1='e'), j=3 (word2='t'): 'e'≠'t' → 1+min(2,2)=3

    i=3 (word1='a'), j=1 (word2='e'): 'a'≠'e' → 1+min(2,1)=2
    i=3 (word1='a'), j=2 (word2='a'): 'a'=='a' → dp[2][1]=2
    i=3 (word1='a'), j=3 (word2='t'): 'a'≠'t' → 1+min(2,2)=3

    最小删除步数 = dp[3][3] = 2 ✓
    """
    m, n = len(word1), len(word2)

    # 创建 (m+1) × (n+1) 的 DP 表
    # dp[i][j] 表示使 word1[:i] 和 word2[:j] 相同的最小删除步数
    dp = [[0] * (n + 1) for _ in range(m + 1)]

    # 初始化边界条件
    for i in range(1, m + 1):
        dp[i][0] = i  # word2 为空，需删除 word1 的所有 i 个字符
    for j in range(1, n + 1):
        dp[0][j] = j  # word1 为空，需删除 word2 的所有 j 个字符

    # 填充 DP 表
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            if word1[i - 1] == word2[j - 1]:
                # 字符相同，无需删除，继承左上角的结果
                dp[i][j] = dp[i - 1][j - 1]
            else:
                # 字符不同，取删除 word1 或删除 word2 中较小的步数
                dp[i][j] = 1 + min(dp[i - 1][j], dp[i][j - 1])

    return dp[m][n]


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：对于任意两个字符串 word1 和 word2，
#      最小删除步数 = m + n - 2 × LCS(word1, word2)，
#      其中 LCS 为最长公共子序列的长度。
#
# 证明：
# （1）最终相同的字符串 S 必须是 word1 和 word2 的公共子序列：
#     - 从 word1 删除若干字符得到 S → S 是 word1 的子序列
#     - 从 word2 删除若干字符得到 S → S 是 word2 的子序列
#     - 因此 S 是 word1 和 word2 的公共子序列
#
# （2）总删除步数 = (len(word1) - |S|) + (len(word2) - |S|)
#                 = m + n - 2|S|
#     要使删除步数最小，就要使 |S| 最大
#
# （3）所以求最小删除步数等价于求最长公共子序列长度
#
# （4）LCS 的 DP 正确性：
#     - 最优子结构：如果 word1[i-1] == word2[j-1]，则该字符一定在 LCS 中
#       否则 LCS 要么来自 word1 前 i-1 个字符与 word2 前 j 个字符的比较，
#       要么来自 word1 前 i 个字符与 word2 前 j-1 个字符的比较
#     - 无后效性：dp[i][j] 只依赖 dp[i-1][j-1]、dp[i-1][j]、dp[i][j-1]
#
#
# 回溯法的正确性分析：
# ────────────────────────────────────────────────────────
#
# 回溯法的核心是穷举所有可能的删除序列。对于任意两个字符串，
# 能达到相同的最终字符串的删除操作序列是有限的，回溯法能遍历所有可能，
# 因此一定能找到最优解。
#
# 为什么回溯法能保证找到最小步数？
# （1）完全性：回溯法枚举了所有可能的删除决策（删除 word1[i] 或删除 word2[j]），
#     不存在遗漏
# （2）最优性：在每个决策点取最小值 min(删word1, 删word2)，通过递归层层传递，
#     最终得到的 dfs(0,0) 就是全局最优解
# （3）边界正确性：当 i=m 或 j=n 时，必须删除另一个字符串的全部剩余字符，
#     这个步数是唯一可能，没有更优选择
#
# 记忆化搜索的正确性：
# 由于子问题 dfs(i, j) 的结果只与 i、j 有关，与到达路径无关（无后效性），
# 因此缓存 (i, j) 的结果不会影响正确性，只是避免了重复计算。
#
# 从回溯到 DP 的优化路程：
# ────────────────────────────────────────────────────────
# 暴力回溯  →  记忆化搜索  →  自底向上 DP  →  空间优化 DP
# O(2^(m+n))   O(m*n)        O(m*n)          O(min(m,n))
#
# 记忆化搜索和自底向上 DP 本质上是同一个算法的两种写法：
#   - 记忆化搜索：从大问题出发，递归分解，缓存中间结果（"我不用知道怎么来的，算过就存"）
#   - 自底向上 DP：从小问题出发，迭代构建，逐步扩大（"先解决最简单的，再组合成复杂的"）
#
#
# 两种 DP 思路的内在联系：
# ────────────────────────────────────────────────────────
# 本题有两种 DP 思路：
#
# 思路 A（LCS 法）：dp[i][j] = LCS 长度
#   转移：相等 → dp[i-1][j-1] + 1
#        不等 → max(dp[i-1][j], dp[i][j-1])
#
# 思路 B（直接法）：dp[i][j] = 最小删除步数
#   转移：相等 → dp[i-1][j-1]
#        不等 → 1 + min(dp[i-1][j], dp[i][j-1])
#
# 二者关系：思路 B 的 dp_direct[i][j] = i + j - 2 × dp_lcs[i][j]
# 证明：对 i 和 j 进行数学归纳即可
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 混淆"子序列"和"子串"：
#    子序列（Subsequence）可以不连续，如 "sea" 和 "eat" 的 LCS 是 "ea"
#    子串（Substring）必须连续，如 "sea" 和 "eat" 的公共子串仅有 "e"、"a"、"t"
#    本题是子序列问题，不是子串问题！
#
# 2. LCS 解法中 DP 表维度搞反：
#    dp[i][j] 的 i 对应哪个字符串、j 对应哪个，要保持一致
#    不一致会导致索引错误
#
# 3. LCS 解法边界条件忘记初始化：
#    dp[0][j] = 0 和 dp[i][0] = 0 是 Python 列表初始化自动填充的，
#    但如果用不同方式创建 DP 表可能会遗漏
#
# 4. 直接 DP 解法中边界初始化错误：
#    dp[0][j] = j（不是 0），dp[i][0] = i（不是 0）
#    这表示一个字符串为空时，必须删除另一个字符串的全部字符
#
# 5. 滚动数组优化时忘记保存左上角值：
#    一维数组会覆盖左上角 dp[i-1][j-1] 的值，
#    需要用变量 prev 在其被覆盖前保存
#
# 6. 认为"只能删除相同位置的字符"：
#    实际上可以删除任意位置的字符，只要最终两个字符串相同即可。
#    删除不同位置的字符操作是独立的。
#
# 7. 回溯递归时忘记处理边界条件：
#    递归函数 dfs(i, j) 必须先判断 i==m 或 j==n 的情况，
#    否则会导致索引越界或无限递归。
#
# 8. 记忆化搜索中缓存键设计错误：
#    缓存应该用 (i, j) 二元组作为键，而不是只用 i 或只用 j。
#    因为子问题需要两个字符串的剩余部分共同决定。
