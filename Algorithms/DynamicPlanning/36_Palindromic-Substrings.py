"""
回文子串（Palindromic Substrings）

题目描述：
给你一个字符串 s，请你统计并返回这个字符串中 回文子串 的数目。
回文字符串 是正着读和倒过来读一样的字符串。
子字符串 是字符串中的由连续字符组成的一个序列。

输入描述：
一个字符串 s，由小写英文字母组成。

输出描述：
输出一个整数，表示回文子串的数目。

输入示例：
s = "abc"
输出示例：
3

════════════════════════════════════════════════════════════════════════
核心概念：回文串判定与回文系列题目对比
════════════════════════════════════════════════════════════════════════

关键洞察：
────────────────────────────────────────────────────────────────────────
回文串的最大特征是"中心对称"：从中心向两边扩展，两侧字符一一对应相等。

判断 s[i..j] 是否为回文，可以递推：
    s[i..j] 是回文  ⟺  s[i] == s[j] 且 s[i+1..j-1] 是回文
这就是区间 DP 的基础。

系列题目对比：
────────────────────────────────────────────────────────────────────────
题目                         要求                   核心方法           答案
────────────────────────────────────────────────────────────────────────
最长回文子串（LC 5）         子串必须连续           中心扩展/区间DP     最长长度
回文子串（LC 647，本题）     子串必须连续           中心扩展/区间DP     回文个数
最长回文子序列（LC 516）     子序列可跳跃           区间DP             最长长度
────────────────────────────────────────────────────────────────────────
注意：本题统计的是"子串"（必须连续），与 LC 516 的"子序列"（可跳跃）不同！

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度           说明
────────────────────────────────────────────────────────────────────────
暴力枚举（判断所有子串）        O(n³)           O(1)                ⭐ 仅用于理解
动态规划（区间 DP）            O(n²)           O(n²)               ⭐⭐⭐
中心扩展法                     O(n²)           O(1)                ⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想（动态规划）：
────────────────────────────────────────────────────────────────────────
状态定义：
    dp[i][j] = 子串 s[i..j] 是否为回文（布尔值）

状态转移：
    dp[i][j] = True  如果 s[i] == s[j] 且 (j - i < 2 或 dp[i+1][j-1] == True)
    dp[i][j] = False 否则

初始条件：
    dp[i][i] = True（长度为 1 的子串恒为回文）

最终答案：
    统计所有 dp[i][j] == True 的个数

遍历顺序（关键！）：
    必须按子串长度从小到大遍历。
    因为 dp[i][j] 依赖内部更短的子串 dp[i+1][j-1]（长度减 2），
    只有短子串先算完，长子串才能正确递推。
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力枚举（判断所有子串）
# ══════════════════════════════════════════════════════════


def countSubstrings_brute(s: str) -> int:
    """
    暴力枚举 ⭐

    核心思想：
    ────────────────────────────────────────────────────────
    枚举所有子串 s[i..j]（共 n(n+1)/2 个），逐个判断是否为回文。
    判断回文用双指针从两端向中间扫描。

    算法步骤：
    1. 双重循环枚举子串起点 i 和终点 j
    2. 对每个子串用双指针判断是否回文
    3. 统计回文子串个数

    时间复杂度：O(n³) — 枚举 O(n²) 个子串 × 每个判断 O(n)
    空间复杂度：O(1) — 只用常数空间

    图解示例：
    ────────────────────────────────────────────────────────
    s = "abc"，全部子串：
      (0,0)"a" 回文 ✓     (0,1)"ab" a≠b ✗    (0,2)"abc" a≠c ✗
      (1,1)"b" 回文 ✓     (1,2)"bc" b≠c ✗
      (2,2)"c" 回文 ✓

    回文子串共 3 个
    结果：3 ✓
    """
    n = len(s)
    count = 0

    # 枚举所有子串的起点和终点
    for i in range(n):
        for j in range(i, n):
            left, right = i, j
            # 双指针从两端向中间扫描，判断是否回文
            while left < right and s[left] == s[right]:
                left += 1
                right -= 1
            # 若指针相遇或越过，说明两侧字符全部匹配，是回文
            if left >= right:
                count += 1

    return count


# ══════════════════════════════════════════════════════════
# 解法二：动态规划（区间 DP）
# ══════════════════════════════════════════════════════════


def countSubstrings_dp(s: str) -> int:
    """
    动态规划（区间 DP）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    用二维布尔表记录每个子串是否回文。
    回文判定递推：s[i..j] 回文 ⟺ s[i] == s[j] 且内部 s[i+1..j-1] 回文。

    关键：按子串长度从小到大遍历，
    保证计算 dp[i][j] 时，内部的 dp[i+1][j-1]（长度小 2）已计算完成。

    算法步骤：
    1. 创建 n×n 的布尔 DP 表，dp[i][j] 表示 s[i..j] 是否回文
    2. 按长度 length 从 1 到 n 遍历
    3. 对每个长度，枚举所有起点 i，终点 j = i + length - 1
    4. 若 s[i] == s[j] 且（长度 < 3 或内部子串回文），标记为回文并计数
    5. 返回总数

    时间复杂度：O(n²) — 双重循环遍历所有子串
    空间复杂度：O(n²) — 二维 DP 表

    图解示例：
    ────────────────────────────────────────────────────────
    s = "abcba"，n = 5

    按长度依次处理：
    length=1: "a"✓ "b"✓ "c"✓ "b"✓ "a"✓    → +5，累计 5
    length=2: "ab"✗ "bc"✗ "cb"✗ "ba"✗     → +0，累计 5
    length=3: "abc" a≠c ✗
              "bcb" b==b 且 length<3 → ✓  → +1，累计 6
              "cba" c≠a ✗
    length=4: "abcb" a≠b ✗  "bcba" b≠a ✗  → +0，累计 6
    length=5: "abcba" a==a 且 dp[1][3]("bcb")=True → ✓  → +1，累计 7

    结果：7 ✓
    """
    n = len(s)
    # dp[i][j] 表示子串 s[i..j] 是否为回文，初始全部为 False
    dp = [[False] * n for _ in range(n)]
    result = 0

    # 按子串长度从小到大遍历（关键！保证内部子串先被计算）
    for length in range(1, n + 1):
        # 枚举起点 i，终点 j 由起点和长度唯一确定
        for i in range(n - length + 1):
            j = i + length - 1
            # 首尾字符相同才可能是回文；长度 1、2 直接判定，长度 ≥ 3 需内部子串也是回文
            if s[i] == s[j] and (length < 3 or dp[i + 1][j - 1]):
                dp[i][j] = True
                result += 1  # 找到一个回文子串，计数 +1

    return result


# ══════════════════════════════════════════════════════════
# 解法三：中心扩展法（推荐）
# ══════════════════════════════════════════════════════════


def countSubstrings(s: str) -> int:
    """
    中心扩展法 ⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    每个回文串都有唯一的"中心"：
    - 奇数长度回文：中心是 1 个字符
    - 偶数长度回文：中心是 2 个字符之间的空隙
    因此 n 个字符共有 2n - 1 个中心。

    从每个中心出发向两边扩展，只要两侧字符相等就构成新的回文，
    每扩展成功一次，回文计数 +1。

    算法步骤：
    1. 枚举全部 2n - 1 个中心
    2. 用 left、right 表示当前回文的左右边界
    3. 只要 s[left] == s[right] 就向外扩展并计数
    4. 返回总数

    时间复杂度：O(n²) — 每个中心最多向外扩展 O(n) 次
    空间复杂度：O(1) — 只用常数空间

    图解示例：
    ────────────────────────────────────────────────────────
    s = "abcba"，n = 5，共 2×5-1 = 9 个中心

    中心序号   left,right    扩展过程                        计数
    ─────────────────────────────────────────────────────────
    0         0,0           "a" ✓ → 越界停止                  1
    1         0,1           "ab" a≠b 停止                     0
    2         1,1           "b" ✓ → "bc" b≠c 停止             1
    3         1,2           "bc" b≠c 停止                     0
    4         2,2           "c" ✓ → "bcb" ✓ → "abcba" ✓ 越界  3
    5         2,3           "cb" c≠b 停止                     0
    6         3,3           "b" ✓ → "ba" b≠a 停止             1
    7         3,4           "ba" b≠a 停止                     0
    8         4,4           "a" ✓ → 越界停止                  1

    总计：1+0+1+0+3+0+1+0+1 = 7
    结果：7 ✓
    """
    n = len(s)
    result = 0

    # 2n-1 个中心：偶数下标 → 单字符中心；奇数下标 → 两字符之间的中心
    for center in range(2 * n - 1):
        # 奇数中心（center 为偶数）：left = right = center // 2
        # 偶数中心（center 为奇数）：left = center // 2, right = left + 1
        left = center // 2
        right = left + center % 2

        # 从中心向两边扩展，两侧字符相等就构成回文并计数
        while left >= 0 and right < n and s[left] == s[right]:
            result += 1
            left -= 1
            right += 1

    return result


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：动态规划（或中心扩展法）返回的数字等于字符串 s 中回文子串的总数。
#
# 证明（以动态规划为例）：
# （1）状态完备性：
#     任意子串 s[i..j]（0 ≤ i ≤ j < n）都对应唯一的 dp[i][j]，
#     dp 表覆盖了所有 n(n+1)/2 个子串，无遗漏。
#
# （2）回文判定的递推正确性（数学归纳法）：
#     归纳基础：长度为 1 的子串恒为回文（dp[i][i] = True）；
#               长度为 2 的子串回文当且仅当 s[i] == s[j]。
#     归纳假设：所有长度 < L 的子串的回文性已被正确判定。
#     归纳步骤：对长度 L 的子串 s[i..j]（j - i + 1 = L）：
#       - 若 s[i] != s[j]，首尾不同，一定不是回文；
#       - 若 s[i] == s[j]，则 s[i..j] 回文 ⟺ 内部 s[i+1..j-1] 回文
#         （内部长度 L-2 < L，由归纳假设已被正确判定）。
#     因此 dp 表正确标记了所有子串的回文性。
#
# （3）遍历顺序保证递推可用：
#     按长度从小到大遍历，计算 dp[i][j]（长度 L）时，
#     其依赖的 dp[i+1][j-1]（长度 L-2）必然已经计算完成。
#
# （4）计数正确性：
#     每个回文子串在其被判定为回文的那一刻计数 +1，且只计数一次，
#     因此总数正确。
#
# 中心扩展法的正确性：
# （1）每个回文子串都有唯一的中心（奇数长度中心为 1 个字符，
#     偶数长度中心为两字符之间），因此 2n-1 个中心覆盖全部回文子串；
# （2）从中心向两端扩展时，遇到第一个不相等字符即停止，
#     恰好枚举出该中心产生的全部回文子串（长度逐次 +2）；
# （3）不同中心产生的回文子串互不重复（中心唯一），计数无重叠。
#
#
# 为什么 DP 必须按"长度"遍历，而不是按"起点"遍历？
# ────────────────────────────────────────────────────────
# dp[i][j] 依赖 dp[i+1][j-1]，即"内部子串"。
# 如果按起点 i 从 0 到 n-1、终点 j 从 i 到 n-1 遍历：
#   计算 dp[0][4] 时需要 dp[1][3]，但第 1 行还未开始计算，
#   dp[1][3] 仍是初始值 False，导致漏判。
# 例如 s = "abcba"：按起点遍历时 dp[0][4] 会在 dp[1][3] 之前被求值，
# 从而漏掉 "abcba" 这个回文子串。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 遍历顺序错误（最常见的错误）：
#    按"起点 i 从小到大"遍历，导致内部子串未计算就先被使用。
#    正确做法：按子串长度从小到大遍历，或让 i 从大到小遍历。
#
# 2. 忘记处理长度为 1、2 的边界：
#    长度 ≥ 3 才需要查内部 dp[i+1][j-1]；
#    长度 1、2 直接根据字符相等判断，否则会下标越界或误判。
#
# 3. 混淆"子串"与"子序列"：
#    本题是连续子串；回文子序列（LC 516）允许跳跃，解法不同。
#
# 4. 中心扩展法中中心数量搞错：
#    中心共有 2n-1 个（n 个单字符中心 + n-1 个间隙中心），
#    不是 n 个，否则会漏掉偶数长度的回文。
#
# 5. 忘记空字符串特判：
#    虽然上述三种实现天然处理了空串（返回 0），
#    但若实现中直接用 s[0] 等索引，必须先判断 n == 0。
#
# 6. 计数方式重复或遗漏：
#    应在"判定为回文的那一刻"计数；若最后再遍历 dp 表统计，
#    结果相同但会多一次 O(n²) 遍历。
# ══════════════════════════════════════════════════════════
