"""
编辑距离（Edit Distance）

题目描述：
给你两个单词 word1 和 word2，请返回将 word1 转换成 word2 所使用的最少操作数。

你可以对一个单词进行如下三种操作：
- 插入一个字符
- 删除一个字符
- 替换一个字符

输入描述：
两个字符串 word1 和 word2，由小写英文字母组成。

输出描述：
输出一个整数，表示将 word1 转换成 word2 的最少操作数。

输入示例：
word1 = "horse", word2 = "ros"
输出示例：
3
解释：
horse -> rorse (将 'h' 替换为 'r')
rorse -> rose (删除 'r')
rose -> ros (删除 'e')

输入示例 2：
word1 = "intention", word2 = "execution"
输出示例 2：
5
解释：
intention -> inention (删除 't')
inention -> enention (将 'i' 替换为 'e')
enention -> exention (将 'n' 替换为 'x')
exention -> exection (将 'n' 替换为 'c')
exection -> execution (插入 'u')

════════════════════════════════════════════════════════════════════════
核心概念：字符串动态规划家族 —— 编辑距离是集大成者
════════════════════════════════════════════════════════════════════════

本题属于"两个字符串的动态规划"系列问题，与同系列题目关系密切：

题目                          状态定义                              核心操作                关键差异
──────────────────────────────────────────────────────────────────────────────────────────────────────
32 判断子序列                dp[i][j] = 匹配到的长度               只有匹配/不匹配          单向匹配、无额外代价
33 不同的子序列              dp[i][j] = 出现次数（计数）            匹配时"选/不选"         计数问题，两个分支
34 两个字符串的删除操作      dp[i][j] = 最小删除步数               只有删除                 可转化为 LCS 问题
35 编辑距离（本题）          dp[i][j] = 最小编辑距离               删除 + 插入 + 替换       三种操作，最综合、最经典
──────────────────────────────────────────────────────────────────────────────────────────────────────

关键洞察：
────────────────────────────────────────────────────────────────────────
1. 三种操作的本质是对"两个字符串的尾字符"做决策：
   - 删除：word1 少一个字符（吃掉 word1 的尾字符，代价 1）
   - 插入：word2 少一个字符（吃掉 word2 的尾字符，代价 1）
   - 替换：两个都少一个字符（代价 1）
   - 若两尾字符相等：两个都少一个字符（代价 0，免费跳过）
2. 因此 dp[i][j] 只依赖三个子状态 dp[i-1][j]、dp[i][j-1]、dp[i-1][j-1]，
   具有"最优子结构 + 无后效性"，完美契合动态规划。
3. 掌握了编辑距离，就能"降维打击"同系列题目：
   - 去掉"替换"操作 → 34 两个字符串的删除操作（LeetCode 583）
   - 去掉"插入"操作 → 32 判断子序列（LeetCode 392）
   - 变换状态含义（计数）→ 33 不同的子序列（LeetCode 115）

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                              时间复杂度       空间复杂度            说明
────────────────────────────────────────────────────────────────────────
回溯法（暴力递归）                  O(3^(m+n))      O(m+n)               ⭐ 理解搜索过程
回溯 + 记忆化搜索（自顶向下 DP）    O(m*n)          O(m*n)               ⭐⭐⭐
动态规划（二维数组）                O(m*n)          O(m*n)               ⭐⭐⭐ 最经典
动态规划（滚动数组优化）            O(m*n)          O(min(m,n))          ⭐⭐⭐⭐ 推荐
0-1 BFS（最短路径视角）             O(m*n)          O(m*n)               ⭐⭐⭐ 思维拓展
────────────────────────────────────────────────────────────────────────

核心思想（动态规划 - 二维数组）：
────────────────────────────────────────────────────────────────────────

状态定义：
    dp[i][j] = 将 word1 的前 i 个字符转换成 word2 的前 j 个字符所需的最少操作数
              （即 word1[:i] → word2[:j] 的编辑距离）

状态转移：
    dp[i][j] = dp[i-1][j-1]                                       如果 word1[i-1] == word2[j-1]
    dp[i][j] = 1 + min(dp[i-1][j], dp[i][j-1], dp[i-1][j-1])      如果 word1[i-1] != word2[j-1]

    三种操作的直观解释（以计算 dp[i][j] 为例）：
    - dp[i-1][j] + 1：删除 word1[i-1]（word1 少一个字符，word2 不变）
    - dp[i][j-1] + 1：在 word1 末尾插入 word2[j-1]（word2 少一个字符，word1 不变）
    - dp[i-1][j-1] + 1：将 word1[i-1] 替换成 word2[j-1]（两个各少一个字符）

初始条件：
    dp[0][j] = j：word1 为空，只能逐个插入 word2 的 j 个字符
    dp[i][0] = i：word2 为空，只能逐个删除 word1 的 i 个字符

最终答案：
    dp[m][n]（m、n 分别为 word1、word2 的长度）
"""

from collections import deque  # 用于解法五（0-1 BFS）的双端队列


# ══════════════════════════════════════════════════════════
# 解法一：回溯法（暴力递归）
# ══════════════════════════════════════════════════════════


def minDistance_backtrack(word1: str, word2: str) -> int:
    """
    回溯法（暴力递归）⭐

    核心思想：
    ────────────────────────────────────────────────────────
    用指针 i 和 j 分别遍历 word1 和 word2，逐字符决策：
    - 如果字符相等：无需操作，两个指针同时前移
    - 如果字符不等：尝试三种操作，取最小代价
      ① 删除 word1[i]    → (i+1, j)，代价 1
      ② 在 word1 中插入 word2[j] → (i, j+1)，代价 1
      ③ 将 word1[i] 替换为 word2[j] → (i+1, j+1)，代价 1
    - 当某个字符串遍历完时，只能对另一个串做"插入剩余字符"或"删除剩余字符"

    这是一个典型的回溯搜索问题：字符不等时每个节点有 3 个分支，
    搜索树深度最多为 m + n，因此最坏情况下是指数级时间复杂度。

    算法步骤：
    1. 定义递归函数 dfs(i, j)，返回将 word1[i:] 转换成 word2[j:] 的最少操作数
    2. 如果 i == m，需插入 word2 剩余的 n-j 个字符
    3. 如果 j == n，需删除 word1 剩余的 m-i 个字符
    4. 如果 word1[i] == word2[j]，无需操作，递归 dfs(i+1, j+1)
    5. 否则，取 1 + min(dfs(i+1, j), dfs(i, j+1), dfs(i+1, j+1))
    6. 从 dfs(0, 0) 开始搜索

    时间复杂度：O(3^(m+n)) — 每个不匹配节点最多 3 个分支，最大深度 m+n
    空间复杂度：O(m+n) — 递归栈的深度

    图解示例：
    ────────────────────────────────────────────────────────
    word1 = "ab", word2 = "b"

    递归搜索树（dfs(i, j) 表示将 word1[i:] 变成 word2[j:]）：

    dfs(0,0): 'a' vs 'b' 不相等 → 1 + min(删, 插, 替)
    ├── 删除 'a': 1 + dfs(1,0)
    │   └── dfs(1,0): 'b'=='b' → dfs(2,1) = 0     ⇒ 总 1 步
    ├── 插入 'b': 1 + dfs(0,1)
    │   └── dfs(0,1): word2 已遍历完 → 删剩余 2 个字符 ⇒ 总 3 步
    └── 替换 'a'→'b': 1 + dfs(1,1)
        └── dfs(1,1): word2 已遍历完 → 删剩余 1 个字符 ⇒ 总 2 步

    最优路径：删除 'a' = 1 步
    结果：最小编辑距离 = 1 ✓
    """
    m, n = len(word1), len(word2)

    def dfs(i: int, j: int) -> int:
        """返回将 word1[i:] 转换成 word2[j:] 的最少操作数"""
        # 边界情况：word1 已处理完，只能逐个插入 word2 剩余的字符
        if i == m:
            return n - j
        # 边界情况：word2 已处理完，只能逐个删除 word1 剩余的字符
        if j == n:
            return m - i

        if word1[i] == word2[j]:
            # 字符相等：无需任何操作，直接比较下一个字符
            return dfs(i + 1, j + 1)
        else:
            # 字符不相等：尝试三种操作，取最小代价
            delete = dfs(i + 1, j)        # ① 删除 word1[i]，代价 1
            insert = dfs(i, j + 1)        # ② 插入 word2[j]，代价 1
            replace = dfs(i + 1, j + 1)   # ③ 替换 word1[i] 为 word2[j]，代价 1
            return 1 + min(delete, insert, replace)

    return dfs(0, 0)


# ══════════════════════════════════════════════════════════
# 解法二：回溯 + 记忆化搜索（自顶向下 DP）
# ══════════════════════════════════════════════════════════


def minDistance_memo(word1: str, word2: str) -> int:
    """
    回溯 + 记忆化搜索（自顶向下 DP）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    暴力回溯中存在大量重复计算 —— 不同的操作顺序可能到达相同的 (i, j) 子问题。

    例如 word1="ab", word2="b"：
      - 先删 'a' 再匹配 'b'  → 到达 dfs(2,1)
      - 先替换 'a' 再删 'b'  → 也到达 dfs(2,1)
    两条路径到达完全相同的子问题，但暴力回溯会重复计算。

    解决方法：用一个缓存保存已计算的 (i, j) 结果，
    下次遇到相同子问题时直接返回缓存值（剪枝）。

    记忆化搜索本质上是自顶向下的动态规划：从大问题递归分解到小问题。
    它与自底向上的 DP 只是计算顺序不同，转移方程完全等价。

    算法步骤：
    1. 创建 (m+1) × (n+1) 的缓存（初始化为 -1 表示未计算）
    2. 在 dfs 中，若 memo[i][j] != -1，直接返回缓存值
    3. 计算完结果后存入缓存
    4. 其余逻辑与暴力回溯相同

    时间复杂度：O(m*n) — 最多 (m+1)*(n+1) 个子问题，每个 O(1)
    空间复杂度：O(m*n) — 缓存数组 + 递归栈

    图解示例：
    ────────────────────────────────────────────────────────
    word1 = "ab", word2 = "b", m=2, n=1

    缓存 memo 内容（最终状态，memo[i][j] = word1[i:] → word2[j:] 的最小操作数）：

            j=0  j=1
            ""   'b'
    i=0 "" [ 1,   2 ]
    i=1 'a' [ 0,   1 ]
    i=2 'b' [ 1,   0 ]

    计算过程（自顶向下递归 + 缓存）：
    dfs(0,0): 'a'≠'b'，计算 1+min(dfs(1,0), dfs(0,1), dfs(1,1))
    ├─ dfs(1,0): 'b'=='b' → dfs(2,1) = 0 → 缓存 memo[1][0] = 0
    ├─ dfs(0,1): j==n → 返回 2（删除剩余 2 字符）
    └─ dfs(1,1): j==n → 返回 1（删除剩余 1 字符）

    dfs(0,0) = 1 + min(0, 2, 1) = 1 ✓
    由于 memo 缓存，每个 (i, j) 只计算一次，指数级搜索被剪枝为多项式级。
    """
    m, n = len(word1), len(word2)

    # 创建缓存，初始化为 -1 表示未计算
    # memo[i][j] = 将 word1[i:] 转换成 word2[j:] 的最少操作数
    memo = [[-1] * (n + 1) for _ in range(m + 1)]

    def dfs(i: int, j: int) -> int:
        """返回将 word1[i:] 转换成 word2[j:] 的最少操作数（带记忆化）"""
        # 边界情况：word1 已处理完，只能逐个插入 word2 剩余的字符
        if i == m:
            return n - j
        # 边界情况：word2 已处理完，只能逐个删除 word1 剩余的字符
        if j == n:
            return m - i

        # 如果已经计算过，直接返回缓存值（剪枝）
        if memo[i][j] != -1:
            return memo[i][j]

        if word1[i] == word2[j]:
            # 字符相等：无需操作，缓存下一个子问题的结果
            memo[i][j] = dfs(i + 1, j + 1)
        else:
            # 字符不相等：三种操作各试一次，取最小值
            memo[i][j] = 1 + min(dfs(i + 1, j), dfs(i, j + 1), dfs(i + 1, j + 1))

        return memo[i][j]

    return dfs(0, 0)


# ══════════════════════════════════════════════════════════
# 解法三：动态规划（二维数组，自底向上）—— 本题最经典的解法
# ══════════════════════════════════════════════════════════


def minDistance(word1: str, word2: str) -> int:
    """
    动态规划（二维数组）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    自底向上地填充 (m+1) × (n+1) 的 DP 表：
    - dp[i][j] 表示 word1[:i] → word2[:j] 的编辑距离
    - 转移只需看"尾字符"是否相等，分两种情况讨论
    - 计算顺序：按行从左到右，保证依赖的三个子状态都已算出

    相比回溯/记忆化，自底向上 DP 不需要递归栈，实现直观、不易写错，
    是面试中最常要求手写的解法。

    算法步骤：
    1. 创建 (m+1) × (n+1) 的二维 DP 表
    2. 初始化边界：dp[i][0] = i，dp[0][j] = j
    3. 双重循环填充表格：
       - 尾字符相等 → 继承左上角 dp[i-1][j-1]
       - 尾字符不等 → 1 + min(上, 左, 左上)
    4. 返回 dp[m][n]

    时间复杂度：O(m*n) — 双重循环遍历两个字符串
    空间复杂度：O(m*n) — 二维 DP 表

    图解示例：
    ────────────────────────────────────────────────────────
    word1 = "horse", word2 = "ros", m=5, n=3

    DP 表（行=word1 的前 i 个字符，列=word2 的前 j 个字符）：

                ""    'r'   'o'   's'
    ""   ""   [ 0,    1,    2,    3 ]
    i=1  'h'  [ 1,    1,    2,    3 ]
    i=2  'o'  [ 2,    2,    1,    2 ]
    i=3  'r'  [ 3,    2,    2,    2 ]
    i=4  's'  [ 4,    3,    3,    2 ]
    i=5  'e'  [ 5,    4,    4,    3 ]

    逐步推演（关键格子）：
    ① 初始化：dp[0][*] = 0,1,2,3；dp[*][0] = 0,1,2,3,4,5
    ② dp[2][2]：word1[1]='o' == word2[1]='o' → dp[1][1] = 1（继承左上角）
    ③ dp[3][1]：word1[2]='r' == word2[0]='r' → dp[2][0] = 2
    ④ dp[4][3]：word1[3]='s' == word2[2]='s' → dp[3][2] = 2
    ⑤ 其余格子：取 min(上, 左, 左上) + 1，例如
       dp[5][3]：'e'≠'s' → min(dp[4][3]=2, dp[5][2]=4, dp[4][2]=3) + 1 = 3

    最小编辑距离 = dp[5][3] = 3 ✓
    """
    m, n = len(word1), len(word2)

    # 创建 (m+1) × (n+1) 的 DP 表，默认全 0
    # dp[i][j] 表示将 word1 的前 i 个字符转换成 word2 的前 j 个字符的最少操作数
    dp = [[0] * (n + 1) for _ in range(m + 1)]

    # 初始化边界条件
    for i in range(1, m + 1):
        dp[i][0] = i  # word2 为空，只能删除 word1 的全部 i 个字符
    for j in range(1, n + 1):
        dp[0][j] = j  # word1 为空，只能插入 word2 的全部 j 个字符

    # 自底向上填充 DP 表
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            if word1[i - 1] == word2[j - 1]:
                # 尾字符相等：无需操作，直接继承左上角的结果
                dp[i][j] = dp[i - 1][j - 1]
            else:
                # 尾字符不等：三种操作中取最小代价
                # dp[i-1][j]   → 删除 word1[i-1]
                # dp[i][j-1]   → 插入 word2[j-1]
                # dp[i-1][j-1] → 替换 word1[i-1] 为 word2[j-1]
                dp[i][j] = 1 + min(dp[i - 1][j], dp[i][j - 1], dp[i - 1][j - 1])

    return dp[m][n]


# ══════════════════════════════════════════════════════════
# 解法四：动态规划（滚动数组 / 一维数组空间优化）
# ══════════════════════════════════════════════════════════


def minDistance_optimized(word1: str, word2: str) -> int:
    """
    动态规划（滚动数组优化）⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    观察二维 DP 表：dp[i][j] 只依赖三格的值
        dp[i-1][j]（上方）、dp[i][j-1]（左方）、dp[i-1][j-1]（左上角）
    因此不需要保留完整的二维表，只需一个一维数组：
    - dp[j] 在更新前保存"上一行"的值 dp[i-1][j]（上方）
    - dp[j-1] 已经是"当前行"的值 dp[i][j-1]（左方）
    - 用变量 prev 保存"左上角" dp[i-1][j-1]（在覆盖 dp[j] 前先暂存）

    空间从 O(m*n) 降至 O(min(m, n))，时间不变。

    算法步骤：
    1. 交换两串，使较短的字符串作为 word2，最小化数组长度
    2. 初始化一维数组 dp = [0, 1, ..., n]（即第一行 dp[0][j] = j）
    3. 每行开始：prev = dp[0]（保存 dp[i-1][0]），dp[0] = i（更新 dp[i][0]）
    4. 内层循环：先用 temp 暂存旧 dp[j]（= dp[i-1][j]），再按转移方程更新
    5. 更新完 dp[j] 后，prev = temp（为下一个 j 准备好左上角）
    6. 返回 dp[n]

    时间复杂度：O(m*n) — 双重循环遍历两个字符串
    空间复杂度：O(min(m, n)) — 一维滚动数组

    图解示例：
    ────────────────────────────────────────────────────────
    word1 = "horse", word2 = "ros"
    len(word1)=5 >= len(word2)=3，无需交换。m=5, n=3

    初始：dp = [0, 1, 2, 3]（表示第 0 行，即 word1 为空）

    第 1 行（word1='h'）:   prev 暂存左上角 dp[i-1][j-1]
        j=1 'r': 'h'≠'r' → dp[1] = min(旧dp[1]=1, dp[0]=1, prev=0)+1 = 1
        j=2 'o': 'h'≠'o' → dp[2] = min(2, 1, 1)+1 = 2
        j=3 's': 'h'≠'s' → dp[3] = min(3, 2, 2)+1 = 3
        dp = [1, 1, 2, 3]

    第 2 行（word1='o'）:
        j=1 'r': 'o'≠'r' → dp[1] = min(1, 2, 1)+1 = 2
        j=2 'o': 'o'=='o' → dp[2] = prev(上一轮 j=1 保存的旧 dp[1]=1) = 1
        j=3 's': 'o'≠'s' → dp[3] = min(3, 1, 2)+1 = 2
        dp = [2, 2, 1, 2]

    第 3 行（word1='r'）:
        j=1 'r': 'r'=='r' → dp[1] = prev = 2
        j=2 'o': 'r'≠'o' → dp[2] = min(1, 2, 2)+1 = 2
        j=3 's': 'r'≠'s' → dp[3] = min(2, 2, 1)+1 = 2
        dp = [3, 2, 2, 2]

    第 4 行（word1='s'）:
        j=1 'r': 's'≠'r' → dp[1] = min(2, 4, 3)+1 = 3
        j=2 'o': 's'≠'o' → dp[2] = min(2, 3, 2)+1 = 3
        j=3 's': 's'=='s' → dp[3] = prev = 2
        dp = [4, 3, 3, 2]

    第 5 行（word1='e'）:
        j=1 'r': 'e'≠'r' → dp[1] = min(3, 5, 4)+1 = 4
        j=2 'o': 'e'≠'o' → dp[2] = min(3, 4, 3)+1 = 4
        j=3 's': 'e'≠'s' → dp[3] = min(2, 4, 3)+1 = 3
        dp = [5, 4, 4, 3]

    最小编辑距离 = dp[3] = 3 ✓（与二维 DP 的结果一致）
    """
    # 交换两串，使 word2 为较短的串，从而最小化一维数组的长度
    if len(word1) < len(word2):
        word1, word2 = word2, word1

    m, n = len(word1), len(word2)  # m >= n

    # 一维滚动数组：dp[j] 表示当前行的第 j 列
    # 初始化即第 0 行：dp[0][j] = j
    dp = list(range(n + 1))

    for i in range(1, m + 1):
        # prev 保存"左上角" dp[i-1][j-1]，初始为 dp[i-1][0]
        prev = dp[0]
        # 更新当前行的第 0 列：dp[i][0] = i
        dp[0] = i

        for j in range(1, n + 1):
            # temp 暂存旧值 dp[i-1][j]（即"上方"的格子），之后会用作下一轮的 prev
            temp = dp[j]
            if word1[i - 1] == word2[j - 1]:
                # 尾字符相等：继承左上角 dp[i-1][j-1]
                dp[j] = prev
            else:
                # 尾字符不等：min(上方 dp[j], 左方 dp[j-1], 左上 prev) + 1
                dp[j] = 1 + min(dp[j], dp[j - 1], prev)
            # 当前 j 的旧值成为下一个 j 的左上角
            prev = temp

    return dp[n]


# ══════════════════════════════════════════════════════════
# 解法五：0-1 BFS（最短路径视角，思维拓展）
# ══════════════════════════════════════════════════════════


def minDistance_bfs(word1: str, word2: str) -> int:
    """
    0-1 BFS（最短路径视角）⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    把编辑过程看成在 (m+1) × (n+1) 网格上的"寻路"问题：
    - 起点 (0, 0)，终点 (m, n)
    - 向下走到 (i+1, j) = 删除 word1[i]，代价 1
    - 向右走到 (i, j+1) = 插入 word2[j]，代价 1
    - 斜向走到 (i+1, j+1) = 替换（代价 1）；若 word1[i]==word2[j] 则代价 0（免费跳过）

    由于斜向边代价可能是 0，普通 BFS（边权均匀为 1）不适用，
    需要使用 0-1 BFS：边权 0 入队首，边权 1 入队尾，配合 dist 数组松弛。
    0-1 BFS 的性质保证：节点按距离非递减顺序出队，
    因此第一次弹出终点 (m, n) 时，其距离就是最小编辑距离。

    算法步骤：
    1. 初始化 dist 数组为无穷大，dist[0][0] = 0
    2. 双端队列初始含起点 (0, 0)
    3. 循环：弹出队首 (i, j)，尝试三种移动
       - 删除/插入（代价 1）→ 更新后入队尾
       - 斜向（代价 0 或 1）→ 代价 0 入队首，代价 1 入队尾
    4. 第一次弹出 (m, n) 时直接返回其距离

    时间复杂度：O(m*n) — 每个格子最多被松弛常数次
    空间复杂度：O(m*n) — dist 数组 + 队列

    图解示例：
    ────────────────────────────────────────────────────────
    word1 = "ab", word2 = "b"，网格 3 × 2

    dist 网格（dist[i][j] = 从 (0,0) 到 (i,j) 的最小代价）：

            j=0  j=1
    i=0   [ 0,   1 ]
    i=1   [ 1,   1 ]
    i=2   [ 2,   1 ]

    推演过程：
    (0,0)=0
    (1,0)：删 'a'，0+1=1
    (0,1)：插 'b'，0+1=1
    (1,1)：替 'a'→'b'，0+1=1（从 (1,0) 插 'b' 为 2，取小）
    (2,0)：删 'b'，(1,0)+1=2
    (2,1)：从 (1,1) 斜向走，word1[1]='b'==word2[0]='b'，代价 0 → 1+0=1
           （从 (2,0) 插 'b' 为 3，取小）

    终点 (2,1) 的最小代价 = 1 ✓
    """
    m, n = len(word1), len(word2)

    # dist[i][j] = 从 (0,0) 到 (i,j) 的最少操作数
    # 编辑距离上界为 m + n，用 m + n + 1 充当"无穷大"（且保持整数类型）
    dist = [[m + n + 1] * (n + 1) for _ in range(m + 1)]
    dist[0][0] = 0

    # 双端队列：代价 0 的边入队首，代价 1 的边入队尾
    dq = deque([(0, 0)])

    while dq:
        i, j = dq.popleft()
        d = dist[i][j]

        # 0-1 BFS 节点按距离非递减出队，第一次弹出终点即最短距离
        if i == m and j == n:
            return d

        # 操作 1：删除 word1[i]（向下移动），代价 1
        if i < m and d + 1 < dist[i + 1][j]:
            dist[i + 1][j] = d + 1
            dq.append((i + 1, j))

        # 操作 2：插入 word2[j]（向右移动），代价 1
        if j < n and d + 1 < dist[i][j + 1]:
            dist[i][j + 1] = d + 1
            dq.append((i, j + 1))

        # 操作 3：替换 / 免费跳过相等字符（斜向移动）
        if i < m and j < n:
            cost = 0 if word1[i] == word2[j] else 1
            if d + cost < dist[i + 1][j + 1]:
                dist[i + 1][j + 1] = d + cost
                if cost == 0:
                    dq.appendleft((i + 1, j + 1))  # 代价 0，入队首
                else:
                    dq.append((i + 1, j + 1))      # 代价 1，入队尾

    # 理论上不会走到这里（终点一定可达），兜底返回
    return dist[m][n]


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：对于任意两个字符串 word1 和 word2，
#      二维 DP 求出的 dp[m][n] 即为将 word1 转换成 word2 所需的最少操作数。
#
# 证明（对 i + j 进行数学归纳）：
# （1）基础情形（i = 0 或 j = 0）：
#     - dp[0][j] = j：word1 为空时，只能逐个插入 word2 的 j 个字符，
#       恰好 j 步，且不可能更少（每个字符都必须被插入）
#     - dp[i][0] = i：word2 为空时，只能逐个删除 word1 的 i 个字符，
#       恰好 i 步，且不可能更少
#
# （2）归纳假设：所有更小的子问题 (i-1, j)、(i, j-1)、(i-1, j-1) 已求出最优值
#
# （3）考察 word1[:i] → word2[:j] 的任意一个最优操作序列，
#     其"最后一次操作"必然是以下三类之一：
#     - 删除 word1 的最后一个字符：此前状态为 word1[:i-1] → word2[:j]，
#       总代价 = dp[i-1][j] + 1
#     - 插入 word2 的最后一个字符：此前状态为 word1[:i] → word2[:j-1]，
#       总代价 = dp[i][j-1] + 1
#     - 替换（或相等时免费跳过）最后一个字符：此前状态为 word1[:i-1] → word2[:j-1]，
#       总代价 = dp[i-1][j-1] + (word1[i-1] != word2[j-1])
#
#     任意最优解的最后一步必然属于上述三类之一（完备性），
#     且这三类各自给出一个可行方案（可达性），
#     因此对三者取最小值恰好等于 dp[i][j] 的最优值。
#
# （4）由数学归纳法，规模最大的子问题 dp[m][n] 即为所求的最小编辑距离。
#
#
# 回溯法的正确性分析：
# ────────────────────────────────────────────────────────
#
# （1）完全性：字符不等时穷举了"删除 / 插入 / 替换"全部分支，不存在遗漏；
#     字符相等时"不操作"是唯一不会更差的选择（替换为相同字符是无意义操作）
# （2）最优性：每个决策点取三种操作的最小值，通过递归层层传递，
#     最终 dfs(0, 0) 就是全局最优解
# （3）边界正确性：i == m 或 j == n 时，只能对另一串逐字符操作，
#     步数是唯一可能，没有更优选择
#
# 记忆化搜索的正确性：
# 递归子问题 dfs(i, j) 的结果只与 i、j 有关，与到达该子问题的"路径"无关
# （无后效性），因此缓存 (i, j) 的结果不会改变答案，只是避免重复计算。
#
# 0-1 BFS 的正确性：
# 网格中的每条边恰好对应一次操作（插入 / 删除 / 替换），
# 边的代价即操作代价，因此"从 (0,0) 到 (m,n) 的最短路径长度"
# 就等于最小编辑距离。0-1 BFS 保证节点按距离非递减出队，
# 第一次弹出终点时距离即为最短（该性质由入队首/入队尾的规则维持）。
#
#
# 从暴力到最优的优化路程：
# ────────────────────────────────────────────────────────
# 暴力回溯  →  记忆化搜索  →  自底向上 DP  →  滚动数组优化
# O(3^(m+n))   O(m*n)        O(m*n)          O(min(m,n))
#
# 回溯与 DP 是同一问题的两种视角：
#   - 回溯（自顶向下）："从前往后"逐字符决策，对应 word1[i:] → word2[j:]
#   - 自底向上 DP：    "从后往前"反推，对应 word1[:i] → word2[:j]
#   两者状态一一对应：dfs(i, j) ⇔ dp[m-i][n-j]，转移方程本质相同。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 忘记初始化边界 dp[0][j] = j 和 dp[i][0] = i：
#    Python 列表默认初始化为 0，若漏掉边界初始化，
#    所有"与空串转换"的结果都会错误地算成 0。
#
# 2. 三个操作的方向对应关系搞混：
#    - 删除 word1 的字符 → 状态 (i-1, j)，即"上方的格子"
#    - 插入 word2 的字符 → 状态 (i, j-1)，即"左方的格子"
#    - 替换 → 状态 (i-1, j-1)，即"左上角的格子"
#    方向一旦写反，结果会错且很难排查。
#
# 3. 字符相等时仍然执行 min(...) + 1：
#    相等时直接继承左上角 dp[i-1][j-1] 即可，
#    此时"不操作"是免费的，任何 +1 的操作都不可能更优。
#
# 4. 滚动数组优化时丢失左上角的值：
#    一维数组更新 dp[j] 前，必须先用临时变量保存旧值 dp[i-1][j]，
#    并用 prev 变量维护 dp[i-1][j-1]，否则对角信息会丢失，
#    导致"相等继承"和"替换"两个转移全部算错。
#
# 5. 递归解法中两个边界返回值写反：
#    i == m 时返回 n - j（插入剩余字符），j == n 时返回 m - i（删除剩余字符）。
#    方向一旦写反，空串边界的结果就会出错。
#
# 6. 混淆"子序列"与"子串"：
#    编辑距离 DP 中字符相等时"直接跳过"，隐含了子序列式的匹配（允许不连续），
#    与"最长公共子串"这类要求连续匹配的问题是完全不同的。
