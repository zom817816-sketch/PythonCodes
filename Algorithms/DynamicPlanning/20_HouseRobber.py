"""
打家劫舍（House Robber）

题目描述：
你是一个专业的小偷，计划偷窃沿街的房屋。每间房内都藏有一定的现金，
影响你偷窃的唯一制约因素就是相邻的房屋装有相互连通的防盗系统，
如果两间相邻的房屋在同一晚上被小偷闯入，系统会自动报警。

给定一个代表每个房屋存放金额的非负整数数组，计算你 不触动警报装置的情况下 ，
一夜之内能够偷窃到的最高金额。

示例 1：
输入：[1,2,3,1]
输出：4
解释：偷窃 1 号房屋 (金额 = 1) ，然后偷窃 3 号房屋 (金额 = 3)。
     偷窃到的最高金额 = 1 + 3 = 4 。

示例 2：
输入：[2,7,9,3,1]
输出：12
解释：偷窃 1 号房屋 (金额 = 2), 偷窃 3 号房屋 (金额 = 9)，接着偷窃 5 号房屋 (金额 = 1)。
     偷窃到的最高金额 = 2 + 9 + 1 = 12 。

════════════════════════════════════════════════════════════════════════
核心联系：本题与动态规划的关系
════════════════════════════════════════════════════════════════════════

维度              一般动态规划问题                  打家劫舍（本题）
────────────────────────────────────────────────────────────────────────
问题本质          求最优解（最大/最小值）           求最大金额
递推公式          dp[i] = f(dp[i-1], dp[i-2])     dp[i] = max(dp[i-1], dp[i-2]+nums[i])
初始条件          dp[0] = ..., dp[1] = ...         dp[0] = nums[0], dp[1] = max(nums[0], nums[1])
最终答案          dp[n-1] 的值                     dp[n-1] 的值
────────────────────────────────────────────────────────────────────────

为什么本题是动态规划问题？
────────────────────────────────────────────────────────────────────────
每个房屋有两种选择：偷或不偷。选择依赖于前一个房屋的状态，
具有最优子结构和重叠子问题特征，适合用动态规划解决。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                          时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
回溯算法                       O(2^n)          O(n)            超时，仅用于理解
记忆化搜索（Top-Down DP）       O(n)            O(n)            ⭐⭐
动态规划（Bottom-Up DP）        O(n)            O(n)            ⭐⭐⭐⭐  推荐
动态规划（滚动变量优化）         O(n)            O(1)            ⭐⭐⭐⭐⭐ 最优空间
───────────────────────────────────────────────────────────────────────

核心思想（动态规划）：
────────────────────────────────────────────────────────────────────────
关键洞察：
1. 对于第 i 间房屋，有两种选择：偷或不偷
2. 如果偷第 i 间，就不能偷第 i-1 间，最大金额 = dp[i-2] + nums[i]
3. 如果不偷第 i 间，最大金额 = dp[i-1]
4. 取两种选择的最大值：dp[i] = max(dp[i-1], dp[i-2] + nums[i])

状态定义（一维 DP）：
    dp[i] = 前 i+1 间房屋（nums[0..i]）能偷窃到的最高金额

状态转移：
    dp[i] = max(dp[i - 1], dp[i - 2] + nums[i])

    含义：
    - dp[i-1]：不偷第 i 间，最高金额等于前 i 间的最高金额
    - dp[i-2] + nums[i]：偷第 i 间，最高金额等于前 i-1 间的最高金额 + 当前房屋金额

初始条件：
    dp[0] = nums[0]（只有一间房屋，只能偷它）
    dp[1] = max(nums[0], nums[1])（两间房屋，偷金额较大的）

最终答案：
    dp[n-1]（n = len(nums)）
"""


# ══════════════════════════════════════════════════════════
# 解法一：回溯算法（Brute Force）
# ══════════════════════════════════════════════════════════


def rob_backtrack(nums: list[int]) -> int:
    """
    回溯算法（Brute Force）

    核心思路：
    ────────────────────────────────────────────────────────
    枚举每一种偷窃组合，记录最大金额。

    算法步骤：
    1. 使用回溯枚举每个房屋的选择（偷或不偷）
    2. 维护当前房屋索引 index 和当前金额 current_sum
    3. 如果 index >= n，更新最大金额
    4. 如果偷当前房屋，下一个只能从 index+2 开始
    5. 如果不偷当前房屋，下一个从 index+1 开始

    时间复杂度：O(2^n) — 每个房屋有两种选择，共 2^n 种组合
    空间复杂度：O(n)   — 递归调用栈深度

    问题分析：
    ────────────────────────────────────────────────────────
    对于 n = 20，递归树非常庞大（2^20 ≈ 100万），效率极低。
    仅用于理解问题本质。
    """
    n = len(nums)
    max_sum = float("-inf")

    def backtrack(index: int, current_sum: int) -> None:
        nonlocal max_sum
        if index >= n:           # 所有房屋都处理完了
            max_sum = max(max_sum, current_sum)  # 更新最大金额
            return

        # 选择不偷当前房屋，处理下一间
        backtrack(index + 1, current_sum)

        # 选择偷当前房屋，跳过下一间
        backtrack(index + 2, current_sum + nums[index])

    backtrack(0, 0)  # 从第 0 间房屋开始，当前金额为 0
    return max_sum


# ══════════════════════════════════════════════════════════
# 解法二：记忆化搜索（Top-Down DP）
# ══════════════════════════════════════════════════════════


def rob_memo(nums: list[int]) -> int:
    """
    记忆化搜索解法（Top-Down DP）⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    在回溯的基础上，添加缓存避免重复计算。

    算法步骤：
    1. 创建缓存 memo[index]，表示从第 index 间房屋开始能偷窃的最高金额
    2. 使用递归 + 缓存求解
    3. 对于每个房屋，有两种选择：偷或不偷

    时间复杂度：O(n) — 每个状态只计算一次
    空间复杂度：O(n) — 缓存 + 递归调用栈

    状态定义：
    - memo[index] = 从第 index 间房屋开始能偷窃的最高金额

    状态转移：
    - memo[index] = max(偷当前房屋, 不偷当前房屋)
                  = max(nums[index] + memo[index+2], memo[index+1])

    初始条件：
    - index >= n 时返回 0（没有房屋可偷）
    """
    n = len(nums)
    memo = {}  # 缓存：存储从第 index 间房屋开始能偷窃的最高金额

    def dfs(index: int) -> int:
        if index >= n:           # 没有房屋可偷，返回 0
            return 0
        if index in memo:        # 如果已计算过，直接返回缓存值
            return memo[index]

        # 选择不偷当前房屋，去下一间
        option1 = dfs(index + 1)

        # 选择偷当前房屋，去下下间
        option2 = nums[index] + dfs(index + 2)

        memo[index] = max(option1, option2)  # 缓存结果
        return memo[index]

    return dfs(0)  # 从第 0 间房屋开始递归


# ══════════════════════════════════════════════════════════
# 解法三：动态规划（Bottom-Up DP）— 写法一：完整DP数组
# ══════════════════════════════════════════════════════════


def rob_dp_v1(nums: list[int]) -> int:
    """
    动态规划解法（Bottom-Up DP）⭐⭐⭐⭐ 推荐 — 写法一

    核心思想：
    ────────────────────────────────────────────────────────
    标准的动态规划解法。
    通过一维数组记录前 i+1 间房屋能偷窃的最高金额。

    算法步骤：
    1. 创建一维 DP 数组 dp[n]
    2. 初始化 dp[0] = nums[0]，dp[1] = max(nums[0], nums[1])
    3. 遍历每个房屋（从第 2 间到第 n-1 间）
    4. 对于每个房屋，取两种选择的最大值

    时间复杂度：O(n) — 单循环
    空间复杂度：O(n) — 一维 DP 数组

    图解示例：
    ────────────────────────────────────────────────────────
    nums = [2, 7, 9, 3, 1]

    dp = [2, 7, 0, 0, 0]

    i=2: dp[2] = max(dp[1], dp[0]+nums[2]) = max(7, 2+9) = max(7, 11) = 11
         dp = [2, 7, 11, 0, 0]

    i=3: dp[3] = max(dp[2], dp[1]+nums[3]) = max(11, 7+3) = max(11, 10) = 11
         dp = [2, 7, 11, 11, 0]

    i=4: dp[4] = max(dp[3], dp[2]+nums[4]) = max(11, 11+1) = max(11, 12) = 12
         dp = [2, 7, 11, 11, 12]

    结果：dp[4] = 12 ✓

    状态定义：
    - dp[i] = 前 i+1 间房屋（nums[0..i]）能偷窃到的最高金额

    状态转移：
    - dp[i] = max(dp[i-1], dp[i-2] + nums[i])
      - dp[i-1]：不偷第 i 间
      - dp[i-2] + nums[i]：偷第 i 间

    初始条件：
    - dp[0] = nums[0]（只有一间房屋，只能偷它）
    - dp[1] = max(nums[0], nums[1])（两间房屋，偷金额较大的）

    最终答案：
    - dp[n-1]（n = len(nums)）
    """
    n = len(nums)
    if n == 0:                   # 特殊情况：没有房屋
        return 0
    if n == 1:                   # 特殊情况：只有一间房屋
        return nums[0]

    dp = [0] * n                 # 创建 DP 数组
    dp[0] = nums[0]              # 第 0 间房屋：只能偷它
    dp[1] = max(nums[0], nums[1])  # 第 1 间房屋：偷金额较大的

    for i in range(2, n):        # 遍历从第 2 间到第 n-1 间房屋
        # 状态转移：取"不偷当前房屋"和"偷当前房屋"的最大值
        dp[i] = max(dp[i - 1], dp[i - 2] + nums[i])

    return dp[n - 1]  # 返回前 n 间房屋能偷窃的最高金额


# ══════════════════════════════════════════════════════════
# 解法四：动态规划（Bottom-Up DP）— 写法二：滚动变量优化空间
# ══════════════════════════════════════════════════════════


def rob_dp_v2(nums: list[int]) -> int:
    """
    动态规划解法（Bottom-Up DP）⭐⭐⭐⭐⭐ 最优空间 — 写法二

    核心思想：
    ────────────────────────────────────────────────────────
    观察到状态转移只依赖 dp[i-1] 和 dp[i-2]，可以用两个变量代替数组。

    算法步骤：
    1. 使用两个变量 prev_prev（dp[i-2]）和 prev（dp[i-1]）
    2. 遍历每个房屋，更新当前最大值 curr
    3. 滚动更新 prev_prev 和 prev

    时间复杂度：O(n) — 单循环
    空间复杂度：O(1) — 常数空间

    状态定义：
    - prev_prev = dp[i-2] = 前 i-1 间房屋能偷窃的最高金额
    - prev = dp[i-1] = 前 i 间房屋能偷窃的最高金额
    - curr = dp[i] = 前 i+1 间房屋能偷窃的最高金额

    状态转移：
    - curr = max(prev, prev_prev + nums[i])

    初始条件：
    - prev_prev = nums[0]（第 0 间房屋）
    - prev = max(nums[0], nums[1])（前 2 间房屋）

    最终答案：
    - prev（遍历结束后，prev 就是 dp[n-1]）

    为什么可以优化空间？
    ────────────────────────────────────────────────────────
    状态转移方程 dp[i] = max(dp[i-1], dp[i-2] + nums[i]) 只依赖于
    dp[i-1] 和 dp[i-2]，不需要保存整个数组，用两个变量即可。
    """
    n = len(nums)
    if n == 0:                   # 特殊情况：没有房屋
        return 0
    if n == 1:                   # 特殊情况：只有一间房屋
        return nums[0]

    prev_prev = nums[0]          # dp[0]：第 0 间房屋
    prev = max(nums[0], nums[1])  # dp[1]：前 2 间房屋的最大值

    for i in range(2, n):        # 遍历从第 2 间到第 n-1 间房屋
        # 当前最大值 = max(不偷当前房屋, 偷当前房屋)
        curr = max(prev, prev_prev + nums[i])
        prev_prev = prev         # 滚动更新：dp[i-2] = dp[i-1]
        prev = curr              # 滚动更新：dp[i-1] = dp[i]

    return prev  # 返回前 n 间房屋能偷窃的最高金额


# ══════════════════════════════════════════════════════════
# 重要说明：算法正确性说明与易错点提醒
# ══════════════════════════════════════════════════════════
#
# 算法正确性说明：
# ────────────────────────────────────────────────────────
# 1. 动态规划解法的正确性：
#    - dp[i] 表示前 i+1 间房屋能偷窃的最高金额
#    - 对于第 i 间房屋，有两种选择：
#      * 不偷：最高金额等于前 i 间的最高金额，即 dp[i-1]
#      * 偷：最高金额等于前 i-1 间的最高金额 + 当前金额，即 dp[i-2] + nums[i]
#    - 取两种选择的最大值，得到 dp[i]
#    - 这是最优子结构的体现：问题的最优解包含子问题的最优解
#
# 2. 记忆化搜索的正确性：
#    - memo[index] 表示从第 index 间房屋开始能偷窃的最高金额
#    - 递归尝试两种选择：偷或不偷
#    - 缓存避免了重复计算，将时间复杂度从 O(2^n) 降到 O(n)
#
# 3. 滚动变量优化的正确性：
#    - 状态转移只依赖 dp[i-1] 和 dp[i-2]，用两个变量保存即可
#    - 每次迭代后，prev_prev 和 prev 分别向前滚动
#    - 最终 prev 就是 dp[n-1]，即答案
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 忘记处理边界情况
#    - 错误：不检查 n == 0 或 n == 1
#    - 后果：当 nums 为空时会导致索引越界
#    - 正确：先处理特殊情况，再进行正常逻辑
#
# 2. 状态转移方程错误
#    - 错误：dp[i] = dp[i-1] + nums[i]（偷当前房屋，但忘记不能偷相邻的）
#    - 后果：可能偷了相邻的房屋，违反题目约束
#    - 正确：dp[i] = max(dp[i-1], dp[i-2] + nums[i])
#
# 3. 初始条件错误
#    - 错误：dp[1] = nums[1]（只考虑偷第 2 间房屋）
#    - 后果：忽略了偷第 1 间房屋可能更优的情况
#    - 正确：dp[1] = max(nums[0], nums[1])
#
# 4. 滚动变量更新顺序错误
#    - 错误：先更新 prev，再更新 prev_prev
#    - 后果：prev_prev 会被覆盖，丢失 dp[i-2] 的值
#    - 正确：先更新 prev_prev = prev，再更新 prev = curr
#
# 5. 混淆房屋索引
#    - 错误：认为 dp[i] 表示第 i 间房屋的金额
#    - 正确：dp[i] 表示前 i+1 间房屋（nums[0..i]）能偷窃的最高金额
#
# 6. 回溯算法中遗漏选择
#    - 错误：只考虑偷或只考虑不偷
#    - 后果：无法枚举所有可能的组合
#    - 正确：两种选择都要尝试，取最大值
#
# 7. 记忆化搜索中忘记缓存
#    - 错误：每次递归都重新计算
#    - 后果：时间复杂度仍然是 O(2^n)，会超时
#    - 正确：将计算结果存入 memo，下次直接返回
# ══════════════════════════════════════════════════════════
