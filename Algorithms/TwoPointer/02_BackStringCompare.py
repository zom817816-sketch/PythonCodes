"""
844. 比较含退格的字符串（Backspace String Compare）

题目描述：
给定 s 和 t 两个字符串，当它们分别被输入到空白的文本编辑器后，
如果两者相等，返回 True；否则返回 False。# 代表退格字符。

注意：如果对空文本输入退格字符，文本仍然为空。

输入描述：
    s 和 t 只包含小写英文字母以及字符 #。

输出描述：
    如果退格处理后的两个字符串相等，返回 True；否则返回 False。

输入示例：
    示例 1：s = "ab#c", t = "ad#c"
    示例 2：s = "ab##", t = "c#d#"
    示例 3：s = "a#c", t = "b"

输出示例：
    示例 1：True，两个字符串都变成 "ac"
    示例 2：True，两个字符串都变成 ""
    示例 3：False，s 变成 "c"，t 仍为 "b"

════════════════════════════════════════════════════════════════════════
核心概念：退格操作具有“后进先出”的特征
════════════════════════════════════════════════════════════════════════

遇到普通字符时，它会出现在当前文本末尾；遇到 # 时，删除当前文本末尾的字符。
因此，# 的作用类似栈的 pop，但当使用双指针从后向前扫描时，可以进一步做到
不额外保存处理后的字符串。

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                  时间复杂度       空间复杂度       说明
────────────────────────────────────────────────────────────────────────
栈模拟法              O(m + n)          O(m + n)          直观易懂
双指针逆向扫描        O(m + n)          O(1)              ⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想（双指针逆向扫描）：
────────────────────────────────────────────────────────────────────────
分别从 s 和 t 的末尾开始向前扫描，并用 skip 记录尚未抵消的退格数量：

1. 遇到 #：skip 加 1，表示前面有一个字符将被删除。
2. 遇到普通字符且 skip > 0：跳过该字符，并让 skip 减 1。
3. 遇到普通字符且 skip == 0：它是退格后的有效字符，与另一字符串的
   当前有效字符进行比较。
4. 两个字符串都扫描完毕后，才算相等。

例如 s = "ab#c"：
    从后向前依次看到 c、#、b、a。
    # 会跳过 b，所以最终有效字符序列为 a、c，即 "ac"。
"""


# ══════════════════════════════════════════════════════════
# 解法一：栈模拟法
# ══════════════════════════════════════════════════════════


def backspace_compare_stack(s: str, t: str) -> bool:
    """
    栈模拟法 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    用列表模拟文本编辑器。普通字符入栈，# 删除栈顶字符；
    最后比较两个栈是否相同。

    算法步骤：
    1. 依次处理字符串中的每个字符。
    2. 普通字符入栈；遇到 # 且栈非空时弹出栈顶。
    3. 比较两个字符串处理后的栈内容。

    时间复杂度：O(m + n) — 每个字符最多入栈和出栈一次。
    空间复杂度：O(m + n) — 需要保存两个处理后的字符串。

    图解示例：
    ────────────────────────────────────────────────────────
    s = "ab#c"：
        a -> [a]
        b -> [a, b]
        # -> [a]
        c -> [a, c]
    最终结果为 "ac"。
    """

    def build(text: str) -> list[str]:
        stack: list[str] = []  # 保存退格处理后的字符
        for char in text:
            if char != "#":
                stack.append(char)  # 普通字符添加到文本末尾
            elif stack:
                stack.pop()  # 有字符时，# 删除最后一个字符
        return stack

    return build(s) == build(t)


# ══════════════════════════════════════════════════════════
# 解法二：双指针逆向扫描
# ══════════════════════════════════════════════════════════


def backspace_compare(s: str, t: str) -> bool:
    """
    双指针逆向扫描 ⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    从字符串末尾向前查找“退格处理后仍然有效”的字符。
    不需要真正构造结果字符串，因此额外空间复杂度为 O(1)。

    算法步骤：
    1. 分别将两个指针放在 s 和 t 的末尾。
    2. 使用 skip 统计当前字符串中待跳过的字符数量。
    3. 找到两个字符串各自的下一个有效字符；若只有一方有字符，
       或两个有效字符不同，则返回 False。
    4. 两个指针都越过字符串后，返回 True。

    时间复杂度：O(m + n) — 每个字符最多被指针访问一次。
    空间复杂度：O(1) — 只使用指针和计数器。

    图解示例：
    ────────────────────────────────────────────────────────
    s = "ab#c"，t = "ad#c"：
        两个指针先比较末尾 c，相同；
        遇到 # 后分别跳过 b 和 d；
        再比较 a，相同；
        两个字符串同时扫描结束，结果为 True ✓。
    """

    def next_valid_index(text: str, index: int) -> tuple[int, int]:
        """从 index 开始向前查找有效字符，返回（下标，新的 skip）。"""
        skip = 0
        while index >= 0:
            if text[index] == "#":
                skip += 1  # 退格数量增加
            elif skip > 0:
                skip -= 1  # 当前字符被退格抵消
            else:
                break  # 找到退格后的有效字符
            index -= 1
        return index, skip

    s_index = len(s) - 1
    t_index = len(t) - 1

    while s_index >= 0 or t_index >= 0:
        s_index, _ = next_valid_index(s, s_index)
        t_index, _ = next_valid_index(t, t_index)

        # 一方已经没有有效字符，另一方还有有效字符。
        if s_index < 0 or t_index < 0:
            return s_index == t_index

        # 当前有效字符不同，处理后的字符串必然不同。
        if s[s_index] != t[t_index]:
            return False

        s_index -= 1  # 继续比较前一个有效字符
        t_index -= 1

    return True


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：双指针逆向扫描返回 True，当且仅当退格处理后的 s 和 t 相等。
#
# 证明：
# （1）从后向前扫描时，skip 会准确记录右侧 # 对左侧字符的抵消数量；
#     因此 next_valid_index 找到的字符正是退格处理后的下一个有效字符。
# （2）每次比较的都是两个处理后字符串中相同位置的有效字符。
#     如果字符不同，两个结果必然不同，返回 False 正确。
# （3）如果所有有效字符都逐一相同，且两个指针同时结束，则两个处理后的
#     字符串长度相同且每个位置都相同，因此返回 True 正确。
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 遇到 # 时无条件 pop：空文本继续退格仍为空，必须先判断栈是否为空。
# 2. 双指针只跳过一个字符：连续的 "##" 需要让 skip 持续生效。
# 3. 只比较原字符串：例如 "a#c" 和 "b" 原字符串不同，但处理后也确实
#    不同；而 "ab#c" 和 "ad#c" 原字符串不同，处理后却相同，必须先处理退格。
# 4. 一方没有有效字符时仍访问下标：比较前要检查指针是否已经小于 0。
# ══════════════════════════════════════════════════════════