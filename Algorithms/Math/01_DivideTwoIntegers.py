"""
29. 两数相除（Divide Two Integers）

题目描述：
给你两个整数，被除数 dividend 和除数 divisor。将两数相除，要求不使用
乘法、除法和取余运算。

整数除法应向零截断，即截去小数部分。例如，8.345 截断为 8，-2.7335 截断为 -2。
返回 dividend 除以 divisor 得到的商。

注意：假设环境只能存储 32 位有符号整数，数值范围是 [−2^31, 2^31 − 1]。
若商严格大于 2^31 − 1，返回 2^31 − 1；若商严格小于 −2^31，返回 −2^31。

输入描述：
    dividend 和 divisor 均为 32 位有符号整数，divisor ≠ 0。

输出描述：
    返回向零截断后的整数商，并满足溢出截断规则。

输入示例：
    示例 1：dividend = 10, divisor = 3
    示例 2：dividend = 7, divisor = -3
    示例 3：dividend = -2147483648, divisor = -1

输出示例：
    示例 1：3，因为 10 / 3 = 3.333...，向零截断后为 3
    示例 2：-2，因为 7 / -3 = -2.333...，向零截断后为 -2
    示例 3：2147483647，商会溢出，按题意返回 INT_MAX

════════════════════════════════════════════════════════════════════════
核心概念：用加减与位运算模拟整数除法
════════════════════════════════════════════════════════════════════════

除法本质是「被除数里最多能减掉多少个除数」。
暴力做法是一次减一个除数；优化做法是利用倍增（左移），每次尽量减去
尽可能大的 2^k * divisor，从而把线性扫描加速到对数级。

关键约束对比：
────────────────────────────────────────────────────────────────────────
维度                说明
────────────────────────────────────────────────────────────────────────
禁止运算            不能使用 *、/、%
截断方向            向零截断（与 Python 地板除 // 不同）
溢出边界            INT_MIN / -1 会超出 32 位有符号整数范围
符号处理            先统一成正数运算，最后再恢复符号
────────────────────────────────────────────────────────────────────────

解题思路总览：
────────────────────────────────────────────────────────────────────────
解法                  时间复杂度           空间复杂度       说明
────────────────────────────────────────────────────────────────────────
暴力反复减法          O(|dividend/divisor|) O(1)            直观但会超时
倍增位运算            O(log² N)             O(1)            ⭐⭐⭐⭐ 推荐
────────────────────────────────────────────────────────────────────────

核心思想（倍增位运算）：
────────────────────────────────────────────────────────────────────────
1. 先处理唯一会溢出的情况：INT_MIN / -1 → INT_MAX。
2. 用异或确定结果符号，再对绝对值做运算。
3. 外层循环：只要剩余被除数 a >= 除数 b，就继续。
4. 内层倍增：找到最大的 temp = b * 2^k，使得 a >= temp，
   然后 a -= temp，商加上 2^k。
5. 根据符号返回最终结果。

例如 10 / 3：
    3 << 1 = 6，还能再倍增吗？6 << 1 = 12 > 10，停止。
    10 - 6 = 4，商 += 2；
    4 >= 3，再减一次 3，商 += 1；
    最终商 = 3。
"""


# ══════════════════════════════════════════════════════════
# 解法一：暴力反复减法
# ══════════════════════════════════════════════════════════


def divide_subtract(dividend: int, divisor: int) -> int:
    """
    暴力反复减法 ⭐⭐⭐

    核心思想：
    ────────────────────────────────────────────────────────
    不断从被除数中减去一个除数，每减一次商加 1。
    思路最直观，但当商很大时会超时。

    算法步骤：
    1. 处理溢出边界 INT_MIN / -1。
    2. 确定符号，并取绝对值。
    3. 反复减法，统计能减多少次。
    4. 按符号返回结果。

    时间复杂度：O(|quotient|) — 商有多大，循环就做多少次。
    空间复杂度：O(1) — 只用常数额外变量。

    图解示例：
    ────────────────────────────────────────────────────────
    dividend = 10, divisor = 3
        10 - 3 = 7，result = 1
         7 - 3 = 4，result = 2
         4 - 3 = 1，result = 3
         1 < 3，停止
    结果：3 ✓
    """
    int_min, int_max = -(2**31), 2**31 - 1

    # 唯一会溢出的情况：-2^31 / -1 = 2^31，超出 32 位有符号范围
    if dividend == int_min and divisor == -1:
        return int_max

    # 异或：两数符号不同则为负
    sign = -1 if (dividend > 0) ^ (divisor > 0) else 1
    a, b = abs(dividend), abs(divisor)

    result = 0
    while a >= b:
        a -= b  # 每次只减一个除数
        result += 1

    return result if sign == 1 else -result


# ══════════════════════════════════════════════════════════
# 解法二：倍增位运算
# ══════════════════════════════════════════════════════════


def divide(dividend: int, divisor: int) -> int:
    """
    倍增位运算 ⭐⭐⭐⭐ 推荐

    核心思想：
    ────────────────────────────────────────────────────────
    不一次只减一个 divisor，而是不断把 divisor 左移倍增，
    每次减去当前能减掉的最大 2^k * divisor，从而快速逼近商。

    算法步骤：
    1. 处理 INT_MIN / -1 的溢出。
    2. 用异或确定符号，再转成正数运算。
    3. 外层：只要 a >= b，就进入倍增过程。
    4. 内层：持续 temp <<= 1、multiple <<= 1，找到最大可减倍数。
    5. a 减去该倍数对应的值，result 累加该倍数。
    6. 恢复符号并返回。

    时间复杂度：O(log² N) — 外层最多 O(log N) 次，内层每次最多 O(log N)。
    空间复杂度：O(1) — 只用常数额外变量。

    图解示例：
    ────────────────────────────────────────────────────────
    dividend = 10, divisor = 3
        第 1 轮：
            temp = 3, multiple = 1
            3 << 1 = 6 <= 10，继续倍增 → temp = 6, multiple = 2
            6 << 1 = 12 > 10，停止
            a = 10 - 6 = 4，result = 2
        第 2 轮：
            temp = 3, multiple = 1
            3 << 1 = 6 > 4，停止
            a = 4 - 3 = 1，result = 3
        a < b，结束
    结果：3 ✓
    """
    int_min, int_max = -(2**31), 2**31 - 1

    # 唯一会溢出的情况：-2^31 / -1 = 2^31，超出 32 位有符号范围
    if dividend == int_min and divisor == -1:
        return int_max

    # 异或：两数符号不同则为负
    sign = -1 if (dividend > 0) ^ (divisor > 0) else 1
    a, b = abs(dividend), abs(divisor)

    result = 0
    while a >= b:
        multiple = 1  # 当前 temp 对应的倍数，初始为 1 倍
        temp = b  # 当前可减掉的最大值，初始为一个除数

        # 不断倍增，找到不超过 a 的最大 2^k * b
        while a >= (temp << 1):
            temp <<= 1  # 被减数翻倍：b, 2b, 4b, ...
            multiple <<= 1  # 对应商翻倍：1, 2, 4, ...

        a -= temp  # 减去这一大块
        result += multiple  # 累加对应的商

    return result if sign == 1 else -result


# ══════════════════════════════════════════════════════════
# 重要说明：算法的正确性证明和易错点提示
# ══════════════════════════════════════════════════════════
#
# 算法正确性证明：
# ────────────────────────────────────────────────────────
#
# 定理：倍增位运算法返回的结果等于 dividend / divisor 向零截断后的商
#      （并在溢出时按题意截断到 32 位有符号整数边界）。
#
# 证明：
# （1）溢出特判：唯一超出范围的情况是 INT_MIN / -1，直接返回 INT_MAX，
#     满足题目约束。
# （2）符号分离：商的绝对值只依赖 |dividend| 与 |divisor|；符号由两数
#     是否同号决定。先算正数商再恢复符号，等价于向零截断的整数除法。
# （3）倍增正确性：内层循环找到最大的 k，使得 b * 2^k <= a。
#     减去 b * 2^k 后，等价于商累加 2^k。由于每次都取当前最大可行块，
#     最终 result = floor(a / b)，再按符号得到正确商。
# （4）终止性：每次至少减去 b，a 严格减小，循环必然结束。
#
#
# 为什么不是 O(log N) 而是 O(log² N)：
# ────────────────────────────────────────────────────────
# 外层循环次数与商的二进制位数有关，最多约 O(log N) 次；
# 每次内层又要从 b 重新倍增到接近当前剩余值，最多 O(log N)。
# 两者相乘得到 O(log² N)。
#
#
# 常见错误：
# ────────────────────────────────────────────────────────
# 1. 忘记溢出特判：INT_MIN / -1 必须单独处理，否则结果会超出范围。
# 2. 与 Python // 混淆：Python 的 // 是向负无穷取整，例如 -7 // 3 = -3；
#    本题要求向零截断，应为 -2。
# 3. 倍增条件写成 a >= temp：应判断 a >= (temp << 1)，否则可能多移一位。
# 4. 符号判断错误：应用异或或分别判断正负，不要直接用 dividend * divisor，
#    因为本题禁止乘法，且乘法本身也可能溢出。
# 5. 只做暴力减法：当 |dividend| 很大且 |divisor| = 1 时会严重超时。
# ══════════════════════════════════════════════════════════
